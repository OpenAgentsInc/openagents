/* Platform effects for `openagents dictate` (GitHub #12667). Effects only:
   which backend, which recorder arguments, what a key means, when audio is
   late, how segments are cut and what is printed are all Coax
   (dictate.coax, dictate-rules.coax, apps/shared/dictation*.coax).

   - cxdict_now_ms: the monotonic clock.
   - cxdict_control_*: stdin as control bytes (raw and unechoed on a
     terminal, restored on close and exit) plus SIGINT/SIGTERM as a cancel.
   - cxdict_arg / cxdict_capture_spawn / cxdict_capture_read / _close: the
     recorder Coax named (pw-record, parec or arecord), its stdout read as
     little-endian f32 mono in memory. Nothing is written to disk.
   - cxdict_mac_*: CoreAudio capture (dictate-mac.m); stubs elsewhere.
   - cxdict_dct_*: the one shared dictation controller of this process
     (apps/shared/dictation.coax, compiled as its own library unit as Coder
     for Mac links it), its 60-second clip in memory here.
   - cxdict_model_*: the resident Parakeet engine (psionic-parakeet.h) on one
     worker thread, so a cancel never waits for a running model call.
   Views are borrowed for the call only (Coax spec 7.1). */
