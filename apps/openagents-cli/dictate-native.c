int64_t cxdict_now_ms(void) {
  struct timespec t; clock_gettime(CLOCK_MONOTONIC, &t);
  return (int64_t)t.tv_sec * 1000 + t.tv_nsec / 1000000;
}

/* ---- control: stdin bytes and signals ---- */
static struct termios saved_tty;
static int tty_raw, stdin_open = 1, wake[2] = {-1, -1};
static volatile sig_atomic_t cancelled;
static void on_signal(int signo) {
  (void)signo; cancelled = 1;
  if (wake[1] >= 0) { int e = errno; ssize_t w = write(wake[1], "x", 1); (void)w; errno = e; }
}
static void restore_tty(void) { if (tty_raw) { tcsetattr(STDIN_FILENO, TCSANOW, &saved_tty); tty_raw = 0; } }
int64_t cxdict_control_open(void) {
  if (wake[0] < 0) {
    if (pipe(wake) != 0) return -1;
    fcntl(wake[0], F_SETFL, O_NONBLOCK); fcntl(wake[1], F_SETFL, O_NONBLOCK);
  }
  struct sigaction a; memset(&a, 0, sizeof a); a.sa_handler = on_signal; sigemptyset(&a.sa_mask);
  if (sigaction(SIGINT, &a, NULL) || sigaction(SIGTERM, &a, NULL)) return -1;
  signal(SIGPIPE, SIG_IGN);
  if (isatty(STDIN_FILENO) && tcgetattr(STDIN_FILENO, &saved_tty) == 0) {
    struct termios raw = saved_tty;
    raw.c_lflag &= ~(tcflag_t)(ICANON | ECHO);   /* ISIG stays: Ctrl-C is SIGINT */
    raw.c_cc[VMIN] = 0; raw.c_cc[VTIME] = 0;
    if (tcsetattr(STDIN_FILENO, TCSANOW, &raw) == 0) { tty_raw = 1; atexit(restore_tty); }
    return 1;
  }
  return 0;
}
/* The next control byte (0..255), -1 none before the timeout, -2 stdin has
   ended (then never watched again), -3 a signal asked to cancel. */
int64_t cxdict_control_poll(int64_t timeout_ms) {
  if (cancelled) return -3;
  struct pollfd p[2]; int n = 0;
  p[n].fd = wake[0]; p[n].events = POLLIN; n++;
  if (stdin_open) { p[n].fd = STDIN_FILENO; p[n].events = POLLIN; n++; }
  int r = poll(p, (nfds_t)n, timeout_ms < 0 ? 0 : (int)timeout_ms);
  if (cancelled) return -3;
  if (r <= 0 || n < 2 || !(p[1].revents & (POLLIN | POLLHUP | POLLERR))) return -1;
  unsigned char c;
  ssize_t got = read(STDIN_FILENO, &c, 1);
  if (got == 1) return c;
  if (got == 0 || (got < 0 && errno != EAGAIN && errno != EINTR)) { stdin_open = 0; return -2; }
  return -1;
}
int64_t cxdict_control_close(void) { restore_tty(); return 0; }

/* ---- the recorder subprocess ---- */
enum { ARGS = 24, ARG_BYTES = 8192 };
static char arg_bytes[ARG_BYTES]; static int arg_used, argc_n; static char *argv_p[ARGS + 1];
static pid_t child = -1; static int child_out = -1, child_status = -1;
static unsigned char carry[4]; static int carry_n;
int64_t cxdict_arg(coax_v_u8 a) {
  if (argc_n >= ARGS || a.count < 0 || arg_used + a.count + 1 > ARG_BYTES) return -1;
  for (int64_t i = 0; i < a.count; i++) if (a.data[i] == 0) return -1;
  memcpy(arg_bytes + arg_used, a.data, (size_t)a.count); arg_bytes[arg_used + a.count] = 0;
  argv_p[argc_n++] = arg_bytes + arg_used; arg_used += (int)a.count + 1; argv_p[argc_n] = NULL;
  return 0;
}
/* 0 running, 7 the program is not installed, 3 it could not start. */
int64_t cxdict_capture_spawn(void) {
  if (argc_n < 1 || child >= 0) return 3;
  int out[2], status[2];
  if (pipe(out) != 0) return 3;
  if (pipe(status) != 0) { close(out[0]); close(out[1]); return 3; }
  fcntl(status[1], F_SETFD, FD_CLOEXEC);
  pid_t pid = fork();
  if (pid < 0) { close(out[0]); close(out[1]); close(status[0]); close(status[1]); return 3; }
  if (pid == 0) {
#if defined(__linux__)
    prctl(PR_SET_PDEATHSIG, SIGTERM);
#endif
    signal(SIGINT, SIG_IGN);   /* the parent decides what Ctrl-C means */
    int null = open("/dev/null", O_RDONLY);
    if (null >= 0) { dup2(null, STDIN_FILENO); close(null); }
    dup2(out[1], STDOUT_FILENO); close(out[0]); close(out[1]); close(status[0]);
    execvp(argv_p[0], argv_p);
    int e = errno; ssize_t w = write(status[1], &e, sizeof e); (void)w; _exit(127);
  }
  close(out[1]); close(status[1]);
  int e = 0; ssize_t got;
  do { got = read(status[0], &e, sizeof e); } while (got < 0 && errno == EINTR);
  close(status[0]);
  if (got == (ssize_t)sizeof e) { close(out[0]); waitpid(pid, NULL, 0); return e == ENOENT ? 7 : 3; }
  child = pid; child_out = out[0]; carry_n = 0; child_status = -1;
  fcntl(child_out, F_SETFL, O_NONBLOCK);
  return 0;
}
static int64_t pipe_read(coax_v_f32 out, int64_t timeout_ms) {
  if (child_out < 0 || out.count < 1) return -1;
  struct pollfd p = {child_out, POLLIN, 0};
  int r = poll(&p, 1, timeout_ms < 0 ? 0 : (int)timeout_ms);
  if (r == 0) return 0;
  if (r < 0) return errno == EINTR ? 0 : -1;
  unsigned char buf[16384];
  size_t want = (size_t)out.count * 4; if (want > sizeof buf - 4) want = sizeof buf - 4;
  memcpy(buf, carry, (size_t)carry_n);
  ssize_t got = read(child_out, buf + carry_n, want - (size_t)carry_n);
  if (got < 0) return (errno == EAGAIN || errno == EINTR) ? 0 : -1;
  if (got == 0) {   /* the recorder ended */
    int st = 0; if (waitpid(child, &st, 0) == child) child_status = st;
    close(child_out); child_out = -1; child = -1; return -1;
  }
  size_t have = (size_t)carry_n + (size_t)got, whole = have / 4;
  for (size_t i = 0; i < whole; i++) { uint32_t u = (uint32_t)buf[4*i] | (uint32_t)buf[4*i+1] << 8 | (uint32_t)buf[4*i+2] << 16 | (uint32_t)buf[4*i+3] << 24; float f; memcpy(&f, &u, 4); out.data[i] = f; }
  carry_n = (int)(have - whole * 4); memcpy(carry, buf + whole * 4, (size_t)carry_n);
  memset(buf, 0, sizeof buf);
  return (int64_t)whole;
}

