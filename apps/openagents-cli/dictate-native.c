/* Mono f32 samples now: >0 how many, 0 none before the timeout, -1 the
   capture ended or failed. */
int64_t cxdict_capture_read(coax_v_f32 out, int64_t timeout_ms) {
  if (cxdict_mac_active()) return cxdict_mac_read(out, timeout_ms);
  return pipe_read(out, timeout_ms);
}
int64_t cxdict_capture_rate(void) { return cxdict_mac_active() ? cxdict_mac_rate() : 48000; }
int64_t cxdict_capture_close(void) {
  if (cxdict_mac_active()) return cxdict_mac_close();
  if (child >= 0) {
    kill(child, SIGTERM);
    int st = 0; for (int i = 0; i < 100; i++) { if (waitpid(child, &st, WNOHANG) == child) { child = -1; break; } usleep(10000); }
    if (child >= 0) { kill(child, SIGKILL); waitpid(child, &st, 0); child = -1; }
  }
  if (child_out >= 0) { close(child_out); child_out = -1; }
  carry_n = 0; memset(carry, 0, sizeof carry);
  return 0;
}

/* ---- the resident model on one worker thread ---- */
enum { TEXT = 8193, MAX_SAMPLES = 327520 };
static psionic_parakeet *engine;
static pthread_mutex_t job_lock = PTHREAD_MUTEX_INITIALIZER;
static pthread_cond_t job_done = PTHREAD_COND_INITIALIZER;
static int job_state;   /* 0 idle, 1 running, 2 done, 3 failed */
static float *job_audio; static int64_t job_n; static char job_text[TEXT], job_error[512];
/* memset, kept by an empty asm that may read *p (explicit_bzero's method). */
static void wipe(void *p, size_t n) { if (p && n) { memset(p, 0, n); __asm__ __volatile__("" : : "r"(p) : "memory"); } }
static void *job_run(void *unused) {
  (void)unused;
  char text[TEXT], err[512]; text[0] = 0; err[0] = 0;
  int ok = psionic_parakeet_text(engine, job_audio, job_n, text, sizeof text, err, sizeof err);
  pthread_mutex_lock(&job_lock);
  memcpy(job_text, text, sizeof text); memcpy(job_error, err, sizeof err);
  wipe(job_audio, MAX_SAMPLES * sizeof *job_audio);
  job_state = ok ? 2 : 3; pthread_cond_broadcast(&job_done);
  pthread_mutex_unlock(&job_lock);
  wipe(text, sizeof text);
  return NULL;
}
/* 0 open; else the engine's reason in err (NUL-free, truncated to err.count). */
int64_t cxdict_model_open(coax_v_u8 dir, int64_t gpu, coax_v_u8 err) {
  char path[4096], e[512]; e[0] = 0;
  if (engine) return 0;
  if (dir.count < 1 || (size_t)dir.count >= sizeof path) return -1;
  memcpy(path, dir.data, (size_t)dir.count); path[dir.count] = 0;
  job_audio = calloc(MAX_SAMPLES, sizeof *job_audio);
  if (!job_audio) return -1;
  engine = psionic_parakeet_open(path, gpu ? 1 : 0, e, sizeof e);
  if (engine) return 0;
  int64_t n = (int64_t)strlen(e); if (n > err.count) n = err.count;
  memcpy(err.data, e, (size_t)n);
  return -(n + 1);
}
int64_t cxdict_model_start(coax_v_f32 samples) {
  if (!engine || samples.count < 320 || samples.count > MAX_SAMPLES) return -1;
  pthread_mutex_lock(&job_lock);
  if (job_state == 1) { pthread_mutex_unlock(&job_lock); return -1; }
  memcpy(job_audio, samples.data, (size_t)samples.count * sizeof *job_audio); job_n = samples.count;
  job_state = 1; wipe(job_text, sizeof job_text);
  pthread_t t; pthread_attr_t at; pthread_attr_init(&at); pthread_attr_setdetachstate(&at, PTHREAD_CREATE_DETACHED);
  int bad = pthread_create(&t, &at, job_run, NULL);
  pthread_attr_destroy(&at);
  if (bad) { job_state = 0; wipe(job_audio, MAX_SAMPLES * sizeof *job_audio); }
  pthread_mutex_unlock(&job_lock);
  return bad ? -1 : 0;
}
/* -1 still running after the timeout; n >= 0, the text's n bytes copied
   into out; or -(2 + n), the call failed and its n-byte reason is in out
   (-2 with no reason when out is too short). */
int64_t cxdict_model_poll(coax_v_u8 out, int64_t timeout_ms) {
  pthread_mutex_lock(&job_lock);
  if (job_state == 1 && timeout_ms > 0) {
    struct timespec until; clock_gettime(CLOCK_REALTIME, &until);
    until.tv_sec += timeout_ms / 1000; until.tv_nsec += (timeout_ms % 1000) * 1000000;
    if (until.tv_nsec >= 1000000000) { until.tv_sec++; until.tv_nsec -= 1000000000; }
    while (job_state == 1) { if (pthread_cond_timedwait(&job_done, &job_lock, &until) != 0) break; }
  }
  int64_t r = -1;
  if (job_state == 2 || job_state == 3) {
    const char *s = job_state == 2 ? job_text : job_error;
    int64_t n = (int64_t)strlen(s);
    if (n > out.count) r = -2;
    else { memcpy(out.data, s, (size_t)n); r = job_state == 2 ? n : -(2 + n); }
    wipe(job_text, sizeof job_text); wipe(job_error, sizeof job_error); job_state = 0;
  }
  pthread_mutex_unlock(&job_lock);
  return r;
}
/* Discard the engine's resident utterance work (psionic_parakeet_clear). */
int64_t cxdict_model_clear(void) { return engine && psionic_parakeet_clear(engine) ? 0 : -1; }
int64_t cxdict_model_close(void) {
  pthread_mutex_lock(&job_lock); int busy = job_state == 1; pthread_mutex_unlock(&job_lock);
  /* A cancelled call still running ends with the process; its audio goes with it. */
  if (engine && !busy) { psionic_parakeet_close(engine); engine = NULL; }
  return 0;
}

/* ---- the shared dictation controller (one per process) ---- */
enum { CLIP = 960000 };
static coax_t_DctState *dct; static float *dct_clip;
static coax_v_t_DctState dv(void) { return (coax_v_t_DctState){dct, 1}; }
/* Consent (this command), activity and readiness (model and input ready). */
int64_t cxdict_dct_reset(void) {
  if (!dct) { dct = calloc(1, sizeof *dct); dct_clip = calloc(CLIP, sizeof *dct_clip); if (!dct || !dct_clip) return -1; }
  coax_default_t_DctState(dct); dct->clip = (coax_v_f32){dct_clip, CLIP};
  dct_set_enabled(dv(), 1); dct_set_active(dv(), 1); dct_set_ready(dv(), 1);
  return 0;
}
/* Withdrawing consent clears the clip, the warm ring and the text. */
int64_t cxdict_dct_clear(void) { if (dct) { dct_set_enabled(dv(), 0); wipe(dct_clip, CLIP * sizeof *dct_clip); } return 0; }
int64_t cxdict_dct_start(int64_t now) { return dct ? (int64_t)dct_start(dv(), now) : 0; }
int64_t cxdict_dct_end(int64_t now) { if (dct) dct_end(dv(), now); return 0; }
