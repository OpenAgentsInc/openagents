#!/usr/bin/env python3
# Turns a recorded `claude --output-format stream-json` turn into the Coax
# fixture the session tests feed (claude_fixture.coax): scrubs it first (the
# recording's folder becomes /tmp/demo, the account's name "you", the init
# frame's lists of the machine's servers, commands, agents, skills, plugins
# and memory are emptied) and drops the frames the transcript never reads
# (hooks, thinking-token counts, status, rate limits, signatures, all but
# two tool-input deltas) and the bulky members it never reads (the init's
# tool and capability lists, the CLI's copies of tool inputs and results,
# per-message usage and diagnostics), so the Coax test's interpreted feed
# stays within its step budget; what is left is as it came.
#   fixture.py RECORDED.jsonl PROJECT_DIR > claude-tools.jsonl
#   fixture.py --coax claude-tools.jsonl > ../claude_fixture.coax
import json, sys

def scrub(path, project):
    kept, json_deltas = [], 0
    for line in open(path):
        j = json.loads(line)
        t, st = j.get("type"), j.get("subtype", "")
        if t == "rate_limit_event" or (t == "system" and st != "init"):
            continue
        ev = j.get("event") if t == "stream_event" else None
        if ev:
            dt = (ev.get("delta") or {}).get("type", "")
            if dt == "signature_delta":
                continue
            if dt == "input_json_delta":
                json_deltas += 1
                if json_deltas > 2:
                    continue
        for k in ("wire_tool_inputs", "tool_use_result", "tool_result_meta", "model_usage_since_last_result", "request_id", "timestamp", "api_message_id"):
            j.pop(k, None)
        if t == "assistant" and isinstance(j.get("message"), dict):
            for k in ("usage", "diagnostics", "context_management", "input_transformations", "container", "stop_details"):
                j["message"].pop(k, None)
            for c in j["message"].get("content", []):
                c.pop("caller", None)
                c.pop("signature", None)
        if t == "result":
            j["usage"] = {k: j["usage"][k] for k in ("input_tokens", "output_tokens", "cache_read_input_tokens", "cache_creation_input_tokens") if k in j["usage"]}
        if t == "system" and st == "init":
            for k in ("tools", "capabilities"):
                if k in j: j[k] = []
            for k in ("mcp_servers", "slash_commands", "agents", "skills", "plugins", "memory_paths", "terminal_slash_commands"):
                if k in j: j[k] = []
            j["messaging_socket_path"] = ""
        # the members a reader looks for first lead (JSON objects are unordered)
        lead = {k: j[k] for k in ("type", "subtype", "parent_tool_use_id", "event", "message") if k in j}
        j = {**lead, **{k: v for k, v in j.items() if k not in lead}}
        s = json.dumps(j, ensure_ascii=False, separators=(",", ":"))
        s = s.replace(project, "/tmp/demo").replace("christopherdavid", "you")
        kept.append(s)
    return kept

def coax(path):
    lines = [l.rstrip("\n") for l in open(path) if l.strip()]
    out = ["// Generated by fixtures/fixture.py from fixtures/claude-tools.jsonl: a real",
           "// claude-haiku-5-5 turn (Bash, Read, Grep, Edit, a failed Bash, thinking and",
           "// a Markdown answer), scrubbed. Do not edit by hand.", "",
           "CLAUDE_FIXTURE :: [%d] string.[" % len(lines)]
    for i, l in enumerate(lines):
        e = l.replace("\\", "\\\\").replace("\"", "\\\"").replace("\t", "\\t").replace("\r", "\\r")
        out.append("  \"%s\"%s" % (e, "," if i + 1 < len(lines) else ""))
    out.append("];")
    return "\n".join(out) + "\n"

if __name__ == "__main__":
    if sys.argv[1] == "--coax":
        sys.stdout.write(coax(sys.argv[2]))
    else:
        for s in scrub(sys.argv[1], sys.argv[2]): print(s)
