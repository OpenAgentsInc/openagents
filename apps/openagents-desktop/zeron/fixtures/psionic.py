#!/usr/bin/env python3
# Records real Psionic Responses streams for the Coax tests (psionic_fixture.coax):
# the body lines of POST /v1/responses as the server sent them, for the same
# request shape psionic.coax sends (its instructions with the working folder
# /tmp/demo, its three tools). The key comes from PSIONIC_API_KEY (or the
# secrets file) and is never written; the stream holds none.
#   psionic.py record URL > psionic-turns.sse        (needs PSIONIC_API_KEY)
#   psionic.py record URL --owned-fixture > ...       (the fixture server, psionic/lib/responses/
#     fixture-host.coax: its owned continuations answer any tool list with a
#     {"city":"Paris"} call to the first tool, so the call turn offers its
#     owned weather tool and the text turn sets tool_choice none)
#   psionic.py --coax psionic-turns.sse > ../psionic_fixture.coax
import json, os, re, sys, urllib.request
from pathlib import Path

TOOLS = json.loads(re.search(r'^PS_TOOLS :: "(.*)";$', (Path(__file__).parent.parent / "psionic.coax").read_text(), re.M).group(1).encode().decode("unicode_escape"))
INSTRUCTIONS = ("You are gpt-oss-20b on OpenAgents' own Psionic engine, chatting in the OpenAgents Mac app. Answer in Markdown."
                " Use the tools only when the request needs the user's files or a command. Working folder: /tmp/demo")

def key():
    if os.environ.get("PSIONIC_API_KEY"):
        return os.environ["PSIONIC_API_KEY"]
    for line in (Path.home() / "work/.secrets/psionic-responses.env").read_text().splitlines():
        if line.startswith("PSIONIC_API_KEY="):
            return line.split("=", 1)[1].strip()
    sys.exit("no PSIONIC_API_KEY")

WEATHER = [{"type": "function", "name": "weather", "description": "The weather in a city.",
            "parameters": {"type": "object", "properties": {"city": {"type": "string"}}, "required": ["city"]}}]

def post(url, items, effort="low", tools=None, choice="auto"):
    body = {"model": "gpt-oss-20b", "stream": True, "store": False, "max_output_tokens": 512, "reasoning": {"effort": effort},
            "instructions": INSTRUCTIONS, "tools": tools or TOOLS, "tool_choice": choice, "input": items}
    req = urllib.request.Request(url.rstrip("/") + "/v1/responses", json.dumps(body).encode(), method="POST",
                                 headers={"Authorization": "Bearer " + key(), "Content-Type": "application/json"})
    lines, done = [], None
    with urllib.request.urlopen(req, timeout=300) as r:
        for raw in r:
            line = raw.decode().rstrip("\n").rstrip("\r")
            lines.append(line)
            if line.startswith("data: ") and '"type":"response.completed"' in line:
                done = json.loads(line[6:])["response"]
    return lines, done

def user(text):
    return {"type": "message", "role": "user", "content": text}

def record(url, owned):
    # turn one: plain text; turn two: a call (list the folder)
    out = []
    a, done = post(url, [user("In one sentence: what is a GPU?")], choice="none" if owned else "auto")
    out += ["# turn: text"] + a
    items = [user("In one sentence: what is a GPU?")] + [i for i in done["output"] if i["type"] != "reasoning"]
    items.append(user("List the folder /tmp/demo with your tool."))
    b, done = post(url, items, tools=WEATHER if owned else None)
    out += ["# turn: call"] + b
    print("\n".join(out))

def coax(path):
    turns, name = {}, None
    for line in open(path):
        line = line.rstrip("\n")
        if line.startswith("# turn: "):
            name = line[8:].upper(); turns[name] = []; continue
        turns[name].append(line)
    print("// Generated by fixtures/psionic.py from fixtures/psionic-turns.sse: streams")
    print("// from the Psionic Responses server (psionic/platform/responses-server.c, the")
    print("// same Coax wire code), the body lines as sent: a text answer with reasoning,")
    print("// then a function call. Do not edit by hand.")
    for name, lines in turns.items():
        print(f"\nPSIONIC_{name} :: [{len(lines)}] string.[")
        print(",\n".join("  " + json.dumps(l, ensure_ascii=False) for l in lines))
        print("];")

if __name__ == "__main__":
    if sys.argv[1] == "record": record(sys.argv[2], "--owned-fixture" in sys.argv)
    elif sys.argv[1] == "--coax": coax(sys.argv[2])
