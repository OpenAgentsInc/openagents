#!/usr/bin/env bash
# Bakes a project's commit history into Coax for its page's tree:
#   apps/openagents-web/project/commits.sh coax > apps/openagents-web/project/coax/commits.coax
# One row per commit touching the folder, oldest first:
#   short hash | date | branch | author | subject
# The branch is the subfolder most of the commit's files are in (src, web,
# book, ...), "spec" for the folder's own top-level files.
set -euo pipefail
folder="${1:?folder}"
cd "$(dirname "$0")/../../.."
git log --reverse --date=short --name-only --format='@@%h|%ad|%an|%s' -- "$folder" | awk -v f="$folder/" '
  function flush() {
    if (head == "") return
    best = "spec"; most = 0
    for (k in n) if (n[k] > most || (n[k] == most && k < best)) { most = n[k]; best = k }
    split(head, p, "|")
    subject = substr(head, length(p[1]) + length(p[2]) + length(p[3]) + 4)
    gsub(/[\\"|]/, "", subject); if (length(subject) > 72) subject = substr(subject, 1, 69) "..."
    rows = rows p[1] "|" p[2] "|" best "|" p[3] "|" subject "\\n"
    count++; delete n; head = ""
  }
  /^@@/ { flush(); head = substr($0, 3); next }
  index($0, f) == 1 {
    rest = substr($0, length(f) + 1)
    k = (index(rest, "/") > 0) ? substr(rest, 1, index(rest, "/") - 1) : "spec"
    n[k]++
  }
  END {
    flush()
    print "// Generated by apps/openagents-web/project/commits.sh: do not edit."
    print "// Every commit to " f ", oldest first: hash|date|branch|author|subject."
    printf "PROJECT_COMMITS :: %d;\n", count
    printf "PROJECT_HISTORY :: \"%s\";\n", rows
  }'
printf 'PROJECT_AUTHORS :: %d;\n' "$(git log --format=%ae -- "$folder" | sort -u | wc -l)"
printf 'PROJECT_FILES :: %d;\n' "$(git ls-files -- "$folder" | wc -l)"
printf 'PROJECT_LINES :: %d;\n' "$(git ls-files -z -- "$folder" | xargs -0 cat 2>/dev/null | wc -l)"
