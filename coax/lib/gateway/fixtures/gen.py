#!/usr/bin/env python3
# Writes ../fixtures.coax from the recorded streams in this folder: each
# .sse file becomes an array of its lines, byte for byte (a trailing \r
# stays; the SSE reader drops it). Run after adding or replacing a recording:
#   python3 coax/lib/gateway/fixtures/gen.py
import os, sys

here = os.path.dirname(os.path.abspath(__file__))
names = sorted(f for f in os.listdir(here) if f.endswith(".sse"))

def esc(s):
    out = []
    for ch in s:
        if ch == "\\": out.append("\\\\")
        elif ch == '"': out.append('\\"')
        elif ch == "\t": out.append("\\t")
        elif ch == "\r": out.append("\\r")
        elif ch == "\0": out.append("\\0")
        else: out.append(ch)
    return "".join(out)

lines = ["// Generated by fixtures/gen.py from fixtures/*.sse (real recorded",
         "// streams; see fixtures/README.md). Do not edit by hand.", ""]
for f in names:
    text = open(os.path.join(here, f), encoding="utf-8").read()
    rows = text.split("\n")
    if rows and rows[-1] == "": rows.pop()
    const = "GW_FX_" + f[:-4].upper().replace("-", "_").replace(".", "_")
    lines.append(f"{const} :: [{len(rows)}] string.[")
    for r in rows: lines.append(f'  "{esc(r)}",')
    lines.append("];")
    lines.append("")
open(os.path.join(here, "..", "fixtures.coax"), "w", encoding="utf-8").write("\n".join(lines))
print(f"wrote fixtures.coax: {len(names)} streams")
