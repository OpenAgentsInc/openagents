#!/usr/bin/env python3
"""Pins a JSONTestSuite subset (github.com/nst/JSONTestSuite, test_parsing/)
as Coax constants for json.coax's tests: every y_ (must parse) and n_ (must
refuse) case that a Coax string literal can hold. Left out, and listed in
the output: cases over 4 KiB, cases whose bytes are not UTF-8 (a .coax file
is UTF-8 text; json.coax's own tests cover bad UTF-8 byte by byte), and
cases with control bytes a Coax literal has no escape for. i_ cases
(implementation-defined) are not pinned.

  python3 -I json_suite.py SUITE_DIR > json_suite.coax
"""
import hashlib, os, subprocess, sys

suite = sys.argv[1]
commit = subprocess.run(["git", "-C", suite, "rev-parse", "HEAD"], capture_output=True, text=True, check=True).stdout.strip()
d = os.path.join(suite, "test_parsing")
kept, left = [], []
ESC = {0x0A: "\\n", 0x09: "\\t", 0x0D: "\\r", 0x00: "\\0", 0x5C: "\\\\", 0x22: '\\"'}
for name in sorted(os.listdir(d)):
    if not (name.startswith("y_") or name.startswith("n_")):
        continue
    b = open(os.path.join(d, name), "rb").read()
    why = ""
    if len(b) > 4096:
        why = "over 4 KiB"
    else:
        try:
            b.decode("utf-8")
        except UnicodeDecodeError:
            why = "not UTF-8"
    if not why and any(c < 0x20 and c not in ESC for c in b):
        why = "a control byte with no Coax escape"
    if why:
        left.append((name, why))
        continue
    lit = "".join(ESC.get(c, "") or chr(c) if c < 0x80 else "" for c in b) if all(c < 0x80 for c in b) else None
    if lit is None:
        s = b.decode("utf-8")
        lit = "".join(ESC.get(ord(ch), ch) if ord(ch) < 0x80 else ch for ch in s)
    kept.append((name, lit, name.startswith("y_"), hashlib.sha256(b).hexdigest()[:16]))

out = [f"// Generated by coax/lib/nostr/fixtures/json_suite.py from JSONTestSuite {commit}",
       "// (test_parsing/, MIT): y_ cases must parse, n_ cases must be refused.",
       f"// {len(kept)} cases pinned; each line's comment is the file name and the first 16 hex of its SHA-256.",
       "// Left out:"]
out += [f"//   {n}: {w}" for n, w in left]
out.append(f"JSON_SUITE_N :: {len(kept)};")
out.append(f"JSON_SUITE_TEXT :: [JSON_SUITE_N] string.[")
out += [f'  "{lit}",   // {n} {h}' for n, lit, _, h in kept]
out.append("];")
out.append(f"JSON_SUITE_VALID :: [JSON_SUITE_N] bool.[")
out += [f"  {'true' if ok else 'false'},   // {n}" for n, _, ok, _ in kept]
out.append("];")
out.append(f"JSON_SUITE_NAMES :: [JSON_SUITE_N] string.[")
out += [f'  "{n}",' for n, _, _, _ in kept]
out.append("];")
print("\n".join(out))
