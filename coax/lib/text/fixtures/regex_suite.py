#!/usr/bin/env python3
"""Pins regex.coax's answers to Python's re over bytes, whose \\d \\w \\s are
ASCII and whose . skips only a newline, as regex.coax's are. Patterns are
drawn from every atom, bracket class, escape, quantifier and anchor in the
subset, against texts drawn from the bytes at each class's edges. Patterns
outside the subset are pinned as refused. Texts leave out the vertical tab
and form feed, which a Coax literal cannot spell; regex.coax's own tests
cover them.

  python3 -I regex_suite.py > regex_suite.coax
"""
import random, re

random.seed(20261031)
ATOMS = ["a", "b", "z", "_", "-", "1", ".", "\\.", "\\\\", "\\*", "\\+", "\\?", "\\[", "\\]", "\\(", "\\)",
         "\\{", "\\}", "\\|", "\\^", "\\$", "\\-", "\\/", "\\d", "\\D", "\\w", "\\W", "\\s", "\\S",
         "[a-c]", "[^a-c]", "[]a]", "[a-]", "[\\d_]", "[\\]x]", "[^\\]]", "[\\.-\\/]", "[0-9]", "[A-Z]",
         "[\\s]", "[\\W]", "[x\\-z]", "[^]]", "[\\D]", "[\\w-]", "[\\S]", "[a\\]-c]", "[!-\\/]", "[`-b]", "[Z-a]", "[!-\\.-0]", "[!-\\.x]", "[a-]", "[a]"]
CHARS = list("abcxz-./09:@AZ[]`{_ !\\*+?()^$|}") + ["\t", "\n", "\r"]
REFUSED = ["(a)", "a|b", "a{2}", "a{2,3}", "a*?", "a+?", "a??", "a**", "a*+", "*a", "+a", "?a", "a\\", "\\q",
           "\\1", "[a", "[[:alpha:]]", "a^", "$a", "a$b", "[\\", "[\\q]", "(?=a)", "a{", "{", "}", "|", ")", "[a-\\q]", "^*", "a\\b", "(a", "[", "[^", "[]", "[^]"]

def esc(s):
    out = ""
    for ch in s:
        out += {"\n": "\\n", "\t": "\\t", "\r": "\\r", "\\": "\\\\", '"': '\\"'}.get(ch, ch)
    return out

cases = []
seen = set()
while len(cases) < 900:
    p = random.choice(["", "", "^"]) + "".join(random.choice(ATOMS) + random.choice(["", "", "*", "+", "?"]) for _ in range(random.randint(1, 4))) + random.choice(["", "", "$"])
    t = "".join(random.choice(CHARS) for _ in range(random.randint(0, 6)))
    if (p, t) in seen: continue
    seen.add((p, t))
    want = 1 if re.search(p.encode(), t.encode()) else 0
    cases.append((p, t, want))
# every atom alone against every char, so each class edge is pinned
for a in ATOMS:
    for ch in CHARS:
        p = "^" + a + "$"
        cases.append((p, ch, 1 if re.search(p.encode(), ch.encode()) else 0))
# ^ and $ alone, and the empty pattern
for p in ["^", "$", "^$", ""]:
    for t in ["", "x"]:
        cases.append((p, t, 1 if re.search(p.encode(), t.encode()) else 0))
for p in REFUSED:
    cases.append((p, "a", -1))

print("// Generated by coax/lib/text/fixtures/regex_suite.py: regex.coax's answers pinned to Python's re over")
print("// bytes (1 a match, 0 none, -1 refused as outside the subset). %d cases." % len(cases))
print("RxCase :: struct { p: string; t: string; want: int; }")
print("RX_SUITE :: [%d] RxCase.[" % len(cases))
print(",\n".join('  RxCase.{p = "%s", t = "%s", want = %d}' % (esc(p), esc(t), w) for p, t, w in cases))
print("];")
