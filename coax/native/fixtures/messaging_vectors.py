# Firm reason: 2 (independent protocol fixture using the existing Python signing oracle).
"""One public list head for custody/read-barrier checks. Never publishes it."""
import hashlib
import importlib.util
import json
from pathlib import Path

root = Path(__file__).resolve().parents[3]
source = root / 'coax/tests/nostr/event_sign_vectors.py'
spec = importlib.util.spec_from_file_location('event_fixture_oracle', source)
oracle = importlib.util.module_from_spec(spec)
spec.loader.exec_module(oracle)
public = oracle.point_mul(oracle.d0)[0].to_bytes(32, 'big')
created = 1730000000
tags = [['relay', 'wss://inbox.example'], ['x-future', 'leave me', 'extra']]
content = 'opaque-encrypted-content'
dump = lambda value: json.dumps(value, separators=(',', ':'), ensure_ascii=False)
preimage = dump([0, public.hex(), created, 10050, tags, content]).encode()
event_id = hashlib.sha256(preimage).digest()
actual_public, signature = oracle.sign(event_id)
assert public == actual_public
assert oracle.schnorr_verify(event_id, public, signature)
event = dict(id=event_id.hex(), pubkey=public.hex(), created_at=created,
             kind=10050, tags=tags, content=content, sig=signature.hex())
array = lambda value: '[32]u8.[' + ','.join(str(byte) for byte in value) + ']'
text = '\n'.join([
    '// Generated by messaging_vectors.py with the existing independent Python oracle.',
    'NMS_LIST_EVENT :: ' + json.dumps(dump(event)) + ';',
    'NMS_LIST_ID :: ' + array(event_id) + ';',
    'NMS_LIST_ID_HEX :: ' + json.dumps(event_id.hex()) + ';',
    'NMS_LIST_PUB :: ' + json.dumps(public.hex()) + ';',
    'NMS_LIST_AT :: ' + str(created) + ';',
]) + '\n'
Path(__file__).with_suffix('.coax').write_text(text)

# Complete-send inboxes for the publicly known BIP-340 test keys. Their
# private scalars are test inputs only and never identify a real account.
inboxes = {}
for name, scalar in [('SELF', 1), ('PEER', oracle.d0)]:
    pub = oracle.point_mul(scalar)[0].to_bytes(32, 'big')
    tags = [['relay', 'wss://relay.openagents.com']]
    digest = hashlib.sha256(dump([0, pub.hex(), created, 10050, tags, '']).encode()).digest()
    _, signature = oracle.sign(digest, secret=scalar)
    signed = dict(id=digest.hex(), pubkey=pub.hex(), created_at=created,
                  kind=10050, tags=tags, content='', sig=signature.hex())
    inboxes[pub.hex()] = signed
    text += f'NMS_INBOX_{name} :: ' + json.dumps(dump(signed)) + ';\n'
Path(__file__).with_suffix('.coax').write_text(text)
fixture = root / 'apps/openagents-ios/StarterTests/nostr-inboxes.json'
fixture.write_text(json.dumps(inboxes, sort_keys=True, separators=(',', ':')) + '\n')

# A current-identity AUTH and a follows list beyond the relay's 256-tag quota.
for name, kind, event_tags in [
    ('AUTH', 22242, [['relay', 'wss://relay.example'], ['challenge', 'fixture']]),
    ('FOLLOWS', 3, [['p', f'{index:064x}'] for index in range(300)]),
]:
    digest = hashlib.sha256(dump([0, public.hex(), created, kind, event_tags, '']).encode()).digest()
    _, signature = oracle.sign(digest)
    signed = dict(id=digest.hex(), pubkey=public.hex(), created_at=created,
                  kind=kind, tags=event_tags, content='', sig=signature.hex())
    text += f'NMS_{name}_EVENT :: ' + json.dumps(dump(signed)) + ';\n'
Path(__file__).with_suffix('.coax').write_text(text)

# A signed public event that leaves history while its outgoing receipt stays pending.
exp_tags = [['expiration', str(created + 10)]]
exp_content = 'public expiry test'
exp_id = hashlib.sha256(dump([0, public.hex(), created, 1, exp_tags, exp_content]).encode()).digest()
_, exp_sig = oracle.sign(exp_id)
exp_event = dict(id=exp_id.hex(), pubkey=public.hex(), created_at=created, kind=1,
                 tags=exp_tags, content=exp_content, sig=exp_sig.hex())
text += 'NMS_EXPIRING_EVENT :: ' + json.dumps(dump(exp_event)) + ';\n'
text += 'NMS_EXPIRING_ID :: ' + array(exp_id) + ';\n'
# A correctly signed AUTH for a different public test key, with otherwise
# identical relay/challenge/time. Later AUTH guards cannot mask an owner bug.
other_pub = oracle.point_mul(1)[0].to_bytes(32, 'big')
other_tags = [['relay', 'wss://relay.example'], ['challenge', 'fixture']]
other_id = hashlib.sha256(dump([0, other_pub.hex(), created, 22242, other_tags, '']).encode()).digest()
_, other_sig = oracle.sign(other_id, secret=1)
other_event = dict(id=other_id.hex(), pubkey=other_pub.hex(), created_at=created,
                   kind=22242, tags=other_tags, content='', sig=other_sig.hex())
assert oracle.schnorr_verify(other_id, other_pub, other_sig)
text += 'NMS_AUTH_OTHER_EVENT :: ' + json.dumps(dump(other_event)) + ';\n'
Path(__file__).with_suffix('.coax').write_text(text)
