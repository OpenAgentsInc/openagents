import struct
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[3]
COMPILER = Path(os.environ.get("COAX_TEST_COMPILER", ROOT / "coax/bin/coax"))
FIXTURE = ROOT / "bitcoin/fixtures/block-files-core.json"
MAGIC = 0xDAB5BFFA
MAX_BODY = 1 << 25
OK, END, TORN, BAD_MAGIC, SIZE, CHECKSUM, ARGUMENT, CAPACITY = range(8)


def sha256d(b):
    return hashlib.sha256(hashlib.sha256(b).digest()).digest()


def xor(b, key, at=0):
    return bytes(c ^ key[(at + i) % 8] for i, c in enumerate(b))


def frame(body, kind=0, previous=bytes(32), key=bytes(8), at=0):
    raw = struct.pack("<II", MAGIC, len(body)) + body
    if kind:
        raw += sha256d(previous + body)
    return xor(raw, key, at)


def reference(raw, kind, key):
    """Independent strict framing recovery; no consensus or undo validation."""
    at = count = 0
    while at < len(raw):
        head = xor(raw[at:at + 8], key, at)
        expected = struct.pack("<I", MAGIC)
        code = OK
        if head[:4] != expected[:len(head[:4])]:
            code = BAD_MAGIC
        elif len(head) < 8:
            return OK, at, count, True
        else:
            n = struct.unpack_from("<I", head, 4)[0]
            if not (1 if kind else 81) <= n <= MAX_BODY:
                code = SIZE
            else:
                end = at + 8 + n + (32 if kind else 0)
                if end > len(raw):
                    return OK, at, count, True
                at, count = end, count + 1
        if code:
            return (OK, at, count, True) if not any(raw[at:]) else (code, at, count, False)
    return OK, at, count, False


class View(C.Structure):
    _fields_ = [("data", C.POINTER(C.c_uint8)), ("count", C.c_int64)]


class Recovery(C.Structure):
    _fields_ = [("code", C.c_int64), ("keep", C.c_int64), ("records", C.c_int64), ("cut", C.c_bool)]


def view(b):
    return View(C.cast(b, C.POINTER(C.c_uint8)), len(b))


def array(data):
    return (C.c_uint8 * len(data)).from_buffer_copy(data)


def run(cmd, **kw):
    p = subprocess.run([str(c) for c in cmd], capture_output=True, text=True, timeout=180, **kw)
    if p.returncode:
        raise AssertionError(f"command failed ({p.returncode}): {p.stderr[-4000:]} {p.stdout[-1000:]}")
    return p.stdout


def capture(directory):
    src = directory / "blk00000.dat"
    key = (directory / "xor.dat").read_bytes()
    assert len(key) == 8
    records, at = [], 0
    with src.open("rb") as f:
        for _ in range(3):
            head = f.read(8)
            magic, n = struct.unpack("<II", xor(head, key, at))
            assert magic == MAGIC and 81 <= n <= MAX_BODY
            encoded = head + f.read(n)
            body = xor(encoded, key, at)[8:]
            records.append({"stored_hex": encoded.hex(), "block_hash": sha256d(body[:80])[::-1].hex()})
            at += len(encoded)
    return {"source": "Bitcoin Core 32.1 regtest blk00000.dat, generated by chapter 72's live check on 2026-11-03",
            "xor_hex": key.hex(), "records": records}


def codec(lib, sample):
    write = lib.bf_write_vartime
    read = lib.bf_read_vartime
    write.argtypes = [C.c_int64, C.c_uint32, C.c_uint64, C.c_int64, View, View, View]
    read.argtypes = [View, C.c_int64, C.c_int64, C.c_uint32, C.c_uint64, View, View]
    write.restype = read.restype = C.c_int64
    recover = lib.bf_recover_vartime
    recover.argtypes = [View, C.c_int64, C.c_uint32, C.c_uint64]
    recover.restype = Recovery
    rng = random.Random(61)
    cases = 0
    for kind in (0, 1):
        sizes = [81, 82, 255, 256, 4095, 4096, 4097, (1 << 20) + 1]
        if kind:
            sizes += [1, 31, 32, 33, 63, 64, 65]
        for n in sizes:
            body = rng.randbytes(n)
            previous = rng.randbytes(32)
            key = rng.randbytes(8)
            at = rng.randrange(10000)
            expected = frame(body, kind, previous, key, at)
            inp, prev, out = array(body), array(previous), array(bytes([165]) * (len(expected) + 1))
            assert write(kind, MAGIC, int.from_bytes(key, "little"), at, view(inp), view(prev), view(out)) == len(expected)
            assert bytes(out) == expected + b"\xa5"
            encoded, decoded = array(expected), array(bytes([165]) * (n + 1))
            assert read(view(encoded), at, kind, MAGIC, int.from_bytes(key, "little"), view(prev), view(decoded)) == n
            assert bytes(decoded) == body + b"\xa5"
            # Every checksum byte and the previous-block binding are checked independently.
            if kind:
                for j in range(32):
                    bad = bytearray(expected)
                    bad[-32 + j] ^= 1
                    damaged, sentinel = array(bad), array(bytes([165]) * n)
                    assert read(view(damaged), at, kind, MAGIC, int.from_bytes(key, "little"), view(prev), view(sentinel)) == -CHECKSUM
                    assert bytes(sentinel) == bytes([165]) * n
            cases += 1
        bodies = [rng.randbytes(81 + i) for i in range(3)]
        key = rng.randbytes(8)
        data = b""
        for body in bodies:
            data += frame(body, kind, key=key, at=len(data))
        for end in range(len(data) + 1):
            raw = data[:end]
            inp = array(raw)
            r = recover(view(inp), kind, MAGIC, int.from_bytes(key, "little"))
            assert (r.code, r.keep, r.records, r.cut) == reference(raw, kind, key), (kind, end)
            cases += 1
        for j in range(len(data)):
            raw = bytearray(data)
            raw[j] ^= 1
            inp = array(raw)
            r = recover(view(inp), kind, MAGIC, int.from_bytes(key, "little"))
            assert (r.code, r.keep, r.records, r.cut) == reference(raw, kind, key), (kind, j)
            cases += 1
    key = bytes.fromhex(sample["xor_hex"])
    raw = bytes.fromhex(sample["records"][0]["stored_hex"])
    for record in sample["records"][1:]:
        raw += bytes.fromhex(record["stored_hex"])
    inp = array(raw + bytes(128))
    r = recover(view(inp), 0, MAGIC, int.from_bytes(key, "little"))
    assert (r.code, r.keep, r.records, r.cut) == (OK, len(raw), 3, True)
    return cases


def file_checks(tool, directory, sample, core_dir=None):
    key = bytes.fromhex(sample["xor_hex"])
    encoded = b"".join(bytes.fromhex(r["stored_hex"]) for r in sample["records"])
    path, keyfile = directory / "blk.dat", directory / "xor.dat"
    path.write_bytes(encoded + bytes(128))
    keyfile.write_bytes(key)
    def call(action, kind="block", src=path, *tail, ok=True):
        p = subprocess.run([str(tool), action, kind, str(src), "fabfb5da", *map(str, tail), "--xor", str(keyfile)], capture_output=True, text=True, timeout=120)
        assert (p.returncode == 0) == ok, p.stderr + p.stdout
        assert "AddressSanitizer" not in p.stderr and "runtime error:" not in p.stderr, p.stderr
        return p.stdout
    assert "3 records" in call("scan")
    imported = directory / "imported.dat"
    call("import", "block", path, imported)
    plain = xor(encoded, key)
    assert imported.read_bytes() == plain
    assert path.read_bytes() == encoded + bytes(128)  # import is read-only
    at = 0
    for i, record in enumerate(sample["records"]):
        n = len(bytes.fromhex(record["stored_hex"]))
        output = directory / f"block-{i}.bin"
        call("read", "block", path, at + 8, output)
        assert output.read_bytes() == plain[at + 8:at + n]
        assert sha256d(output.read_bytes()[:80])[::-1].hex() == record["block_hash"]
        at += n
    # Actual ftruncate at every byte of an append, then append and read again.
    body = directory / "body.bin"
    body.write_bytes(plain[8:len(bytes.fromhex(sample["records"][0]["stored_hex"]))])
    first = len(frame(body.read_bytes()))
    second = frame(body.read_bytes(), key=key, at=first)
    one = frame(body.read_bytes(), key=key)
    for cut in range(len(second)):
        path.write_bytes(one + second[:cut])
        call("recover")
        assert path.read_bytes() == one
    call("append", "block", path, body)
    assert path.read_bytes() == one + second
    # Corruption is not truncated, including a zero prefix before nonzero data.
    bad = one + b"\0" * 12 + b"x"
    path.write_bytes(bad)
    call("recover", ok=False)
    assert path.read_bytes() == bad
    # Undo roundtrip and wrong-binding refusal leave no output file.
    undo, source, dest = directory / "rev.dat", directory / "undo.bin", directory / "undo-read.bin"
    source.write_bytes(b"\x00")  # serialized empty CBlockUndo
    previous = bytes(range(32))
    call("append", "undo", undo, source, "--prev", previous.hex())
    assert undo.read_bytes() == frame(b"\x00", 1, previous, key)
    call("read", "undo", undo, 8, dest, "--prev", previous.hex())
    assert dest.read_bytes() == b"\x00"
    dest.unlink()
    call("read", "undo", undo, 8, dest, "--prev", bytes(32).hex(), ok=False)
    assert not dest.exists()
    if core_dir:
        src = core_dir / "blk00000.dat"
        corekey = (core_dir / "xor.dat").read_bytes()
        output = directory / "core-import.dat"
        command = [str(tool), "import", "block", str(src), "fabfb5da", str(output), "--xor", str(core_dir / "xor.dat")]
        report = run(command)
        raw = src.read_bytes()
        result = reference(raw, 0, corekey)
        assert result[0] == OK
        assert output.read_bytes() == xor(raw[:result[1]], corekey)
        print("Core 32.1 full-file import:", report.strip())
    return len(second)


def effect_checks(directory):
    """The new native effect cannot extend, create or follow a symlink."""
    binary = directory / "effects.dylib"
    run(["cc", "-std=c11", "-D_DARWIN_C_SOURCE", "-shared", "-fPIC",
         ROOT / "coax/platform/store-file-native.c", "-o", binary])
    lib = C.CDLL(str(binary))
    lib.cxfs_path_push.argtypes = [C.c_int64]
    lib.cxfs_truncate.argtypes = [C.c_int64]
    lib.cxfs_truncate.restype = C.c_int64
    def truncate(path, n):
        for byte in os.fsencode(path):
            assert lib.cxfs_path_push(byte) == 0
        return lib.cxfs_truncate(n)
    path = directory / "effect.bin"
    path.write_bytes(b"original")
    assert truncate(path, -1) == -1 and path.read_bytes() == b"original"
    assert truncate(path, 9) == -1 and path.read_bytes() == b"original"
    assert truncate(path, 8) == 0 and path.read_bytes() == b"original"
    link = directory / "effect-link"
    link.symlink_to(path)
    assert truncate(link, 0) == -1 and path.read_bytes() == b"original"
    missing = directory / "effect-missing"
    assert truncate(missing, 0) == -1 and not missing.exists()
    assert truncate(directory, 0) == -1
    assert truncate(path, 3) == 0 and path.read_bytes() == b"ori"
    print("native truncate: seven shorten/refusal cases passed")


def main():
    parser = argparse.ArgumentParser(__doc__)
    parser.add_argument("--record-core", type=Path)
    parser.add_argument("--core-dir", type=Path)
    parser.add_argument("--mode", choices=("debug", "release", "all"), default="all")
    parser.add_argument("--codec-only", action="store_true")
    parser.add_argument("--effects-only", action="store_true")
    args = parser.parse_args()
    if args.effects_only:
        with tempfile.TemporaryDirectory(prefix="coax-blockfiles-effects-") as tmp:
            effect_checks(Path(tmp))
        return
    if args.record_core:
        FIXTURE.write_text(json.dumps(capture(args.record_core), indent=2) + "\n")
        print("captured three Core records")
        return
    sample = json.loads(FIXTURE.read_text())
    # Bind reference observations to the repository's already pinned Core source.
    pins = json.loads((ROOT / "coax/tests/vectors/manifest.json").read_text())
    source = ROOT / "coax/tests/vectors/upstream/bitcoin-core/blockstorage.cpp"
    assert any(v.get("sha256") == hashlib.sha256(source.read_bytes()).hexdigest() for v in pins["files"])
    text = source.read_text()
    for statement in ("fileout << GetParams().MessageStart() << block_size;", "hasher << block.pprev->GetBlockHash() << blockundo;", "fileout << blockundo << hasher.GetHash();"):
        assert statement in text
    with tempfile.TemporaryDirectory(prefix="coax-blockfiles-") as tmp:
        tmp = Path(tmp)
        modes = (False, True) if args.mode == "all" else (args.mode == "release",)
        for release in modes:
            mode = "release" if release else "debug"
            cfile, binary = tmp / f"codec-{mode}.c", tmp / f"codec-{mode}.dylib"
            command = [COMPILER, "c", ROOT / "coax/lib/bitcoin/blockfiles.coax", "--library"]
            if release:
                command.append("--release")
            cfile.write_text(run(command))
            run(["cc", "-std=c11", "-O2", "-shared", "-fPIC", cfile, "-o", binary, "-lm"])
            count = codec(C.CDLL(str(binary)), sample)
            print(f"{'release' if release else 'debug'}: {count} independent codec/recovery cases")
        if args.codec_only:
            return
        toolc, tool = tmp / "tool.c", tmp / "block-files"
        toolc.write_text(run([COMPILER, "c", ROOT / "bitcoin/examples/live/block-files.coax", "--library"]))
        platform = ROOT / "coax/platform"
        run(["cc", "-std=c11", "-D_DARWIN_C_SOURCE", "-O1", "-g", "-fsanitize=address,undefined", "-fno-omit-frame-pointer", "-I", platform,
             toolc, platform / "tool-native.c", platform / "store-file-native.c", "-o", tool, "-lpthread", "-lm"])
        count = file_checks(tool, tmp, sample, args.core_dir)
        print(f"ASan/UBSan: Core import/read, {count} real-file tail cuts, durable append, recovery and undo binding passed")
        effect_checks(tmp)


if __name__ == "__main__":
    main()
