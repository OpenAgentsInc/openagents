#!/usr/bin/env python3
# Firm reason: 2 (independent oracle: copies published vectors outside Coax)
"""Writes coax/tests/bitcoin/address_vectors.coax for Bitcoin chapter 29 from
files pinned in coax/tests/vectors/upstream/:

  python3 -I coax/tests/bitcoin/make_address_vectors.py

- bitcoin-core/key_io_valid.json: the 54 addresses (22 Base58 and 32
  segwit), each with its chain, scriptPubKey and whether its other case is
  valid too. The 16 WIF keys are chapter 26's;
- bip86/bip-0086.mediawiki: the 3 key-path Taproot outputs, each internal
  key with its output key, scriptPubKey and address;
- bip341/wallet-test-vectors.json: the one scriptPubKey case with no script
  tree, with its tweak, output key, scriptPubKey and address;
- bip84/bip-0084.mediawiki: the 3 P2WPKH keys and addresses;
- bip49/bip-0049.mediawiki: the P2SH-P2WPKH key, key hash, redeem script,
  script hash and testnet address.

Each file's SHA-256 must equal its pin below, so a changed file refuses
instead of silently changing the checks. Nothing here hashes, tweaks or
encodes: every key, script and address is copied. key_io_invalid.json's 70
strings are already in bech32m_vectors.coax (SW_KEY_IO_INVALID), which the
chapter's checks load too."""
import hashlib, json, re
from pathlib import Path

UPSTREAM = Path(__file__).resolve().parents[1] / 'vectors/upstream'
PINS = {
    'bitcoin-core/key_io_valid.json': '90bd1d35d12763e0d00c5400b2c9fe551e532a821e1e466c20cad3aced70a7fe',
    'bip86/bip-0086.mediawiki': 'd8d01dee331da07c2562615bc1f064c1868ec3fce61184973da76d1196c7f5b0',
    'bip341/wallet-test-vectors.json': '403e19fb81dd1f31e745699216308f61fb403774b2aafa87b631b8f7c042d37f',
    'bip84/bip-0084.mediawiki': '1900feec6cafca65b8c09906ca0658d2d742b4c9b44cb15678996985b6bfe627',
    'bip49/bip-0049.mediawiki': '307b62faf7b9927233b5112e93d591272ba0c48303b5dbb6f0bbfbaf2347e695',
}
CHAINS = {'main': 'SW_MAINNET', 'testnet4': 'SW_TESTNET', 'signet': 'SW_TESTNET', 'regtest': 'SW_REGTEST'}


def read(name):
    data = (UPSTREAM / name).read_bytes()
    assert hashlib.sha256(data).hexdigest() == PINS[name], name
    return data


def pre(text):
    """The test-vector <pre> block of a BIP's text."""
    start = text.index('==Test vectors==')
    return text[start:text.index('</pre>', start)]


def tables():
    keyio = []
    for t, spk, meta in json.loads(read('bitcoin-core/key_io_valid.json')):
        if meta['isPrivkey']:
            continue
        assert '"' not in t and re.fullmatch('[0-9a-f]+', spk)
        keyio.append((t, CHAINS[meta['chain']], spk, 'true' if meta.get('tryCaseFlip') else 'false', meta['chain']))
    assert len(keyio) == 54 and sum(r[3] == 'true' for r in keyio) == 32

    b86 = pre(read('bip86/bip-0086.mediawiki').decode())
    bip86 = re.findall(r'internal_key = ([0-9a-f]{64})\noutput_key   = ([0-9a-f]{64})\n'
                       r'scriptPubKey = ([0-9a-f]{68})\naddress      = (bc1p[0-9a-z]+)\n', b86)
    paths = re.findall(r"^// Account 0, (.+) = (m/\S+)$", b86, re.M)[1:]
    assert len(bip86) == 3 and len(paths) == 3

    keypath = [s for s in json.loads(read('bip341/wallet-test-vectors.json'))['scriptPubKey']
               if s['given']['scriptTree'] is None]
    assert len(keypath) == 1
    k = keypath[0]
    bip341 = (k['given']['internalPubkey'], k['intermediary']['tweak'], k['intermediary']['tweakedPubkey'],
              k['expected']['scriptPubKey'], k['expected']['bip350Address'])

    b84 = pre(read('bip84/bip-0084.mediawiki').decode())
    bip84 = re.findall(r'pubkey  = ([0-9a-f]{66})\n  address = (bc1q[0-9a-z]+)\n', b84)
    assert len(bip84) == 3

    b49 = pre(read('bip49/bip-0049.mediawiki').decode())
    field = lambda name: re.search(name + r' = (?:0x)?([0-9a-zA-Z]+)', b49).group(1)
    bip49 = (field('account0recvPublicKeyHex'), field(r'keyhash = HASH160\(account0recvPublicKeyHex\)'),
             field(r'scriptSig = <0 <keyhash>>'), field(r'addressBytes = HASH160\(scriptSig\)'),
             field(r'address = base58check\(prefix \| addressBytes\)'))
    assert len(bip49[0]) == 66 and len(bip49[1]) == 40 and len(bip49[2]) == 44 and len(bip49[3]) == 40
    return keyio, bip86, paths, bip341, bip84, bip49


def render(keyio, bip86, paths, bip341, bip84, bip49):
    out = ['// Generated by make_address_vectors.py from Bitcoin Core\'s key_io_valid.json,',
           '// BIP-86, BIP-341\'s wallet-test-vectors.json, BIP-84 and BIP-49, pinned in',
           '// coax/tests/vectors/upstream/ (see SOURCES.md there). Published values,',
           '// copied, not computed. Test data only.',
           '// Every address of key_io_valid.json: its network (testnet4 and signet',
           '// are SW_TESTNET), its scriptPubKey, and whether its other case is valid.',
           'AdKeyIo :: struct {text:string;network:int;script:string;flip:bool;}',
           'AD_KEY_IO :: [%d] AdKeyIo.[' % len(keyio)]
    for i, (t, net, spk, flip, chain) in enumerate(keyio):
        out.append('  AdKeyIo.{text="%s",network=%s,script="%s",flip=%s}%s  // %s'
                   % (t, net, spk, flip, ',' if i + 1 < len(keyio) else '];', chain))
    out += ['// BIP-86: internal key, output key, scriptPubKey and address.',
            'AdTaproot :: struct {internal:string;output:string;script:string;address:string;}',
            'AD_BIP86 :: [3] AdTaproot.[']
    for i, ((ik, ok, spk, addr), (_what, path)) in enumerate(zip(bip86, paths)):
        out.append('  AdTaproot.{internal="%s",output="%s",script="%s",address="%s"}%s  // %s'
                   % (ik, ok, spk, addr, ',' if i < 2 else '];', path))
    out += ['// BIP-341\'s scriptPubKey case with no script tree, and its TapTweak hash.',
            'AD_BIP341 :: AdTaproot.{internal="%s",output="%s",script="%s",address="%s"};'
            % (bip341[0], bip341[2], bip341[3], bip341[4]),
            'AD_BIP341_TWEAK :: "%s";' % bip341[1],
            '// BIP-84: P2WPKH keys and their mainnet addresses.',
            'AdKey :: struct {key:string;address:string;}',
            'AD_BIP84 :: [3] AdKey.[']
    for i, (key, addr) in enumerate(bip84):
        out.append('  AdKey.{key="%s",address="%s"}%s' % (key, addr, ',' if i < 2 else '];'))
    out += ['// BIP-49: a P2SH-P2WPKH key, its HASH160, the redeem script, that',
            '// script\'s HASH160 and the testnet address.',
            'AD_BIP49_KEY :: "%s";' % bip49[0],
            'AD_BIP49_KEYHASH :: "%s";' % bip49[1],
            'AD_BIP49_REDEEM :: "%s";' % bip49[2],
            'AD_BIP49_HASH :: "%s";' % bip49[3],
            'AD_BIP49_ADDRESS :: "%s";' % bip49[4]]
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    Path(__file__).with_name('address_vectors.coax').write_text(render(*tables()))
