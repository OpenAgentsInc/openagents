#!/usr/bin/env python3
# Firm reason: 2 (independent oracle: copies published vectors outside Coax)
"""Writes coax/tests/bitcoin/base58_vectors.coax for Bitcoin chapter 26 from
three Bitcoin Core files and the BIP-32 text, all pinned in
coax/tests/vectors/upstream/:

  python3 -I coax/tests/bitcoin/make_base58_vectors.py

- base58_encode_decode.json: every (hex, Base58) pair;
- key_io_valid.json: every entry that is not a Bech32 address (P2PKH and
  P2SH addresses and WIF private keys), with its chain, its kind and the
  script or key Bitcoin Core gives for it;
- key_io_invalid.json: every string, all of which must refuse;
- bip-0032.mediawiki: the extended public key of every test vector.

Each file's SHA-256 must equal its pin below, so a changed file refuses
instead of silently changing the checks. Nothing here encodes, decodes or
hashes Base58: every string, script and key is copied."""
import hashlib, json, re
from pathlib import Path

UPSTREAM = Path(__file__).resolve().parents[1] / 'vectors/upstream'
PINS = {
    'bitcoin-core/base58_encode_decode.json': '20d51011f49339714c28b9244cc5238f4c78bb9206dc8fc61500aed6fc2682ca',
    'bitcoin-core/key_io_valid.json': '90bd1d35d12763e0d00c5400b2c9fe551e532a821e1e466c20cad3aced70a7fe',
    'bitcoin-core/key_io_invalid.json': 'c3ca74ddad7c01faaca7c26063537feb73ff2be03eb7fc83a42a655d2979261d',
    'bip32/bip-0032.mediawiki': 'e5e00a8289db2f681052cf24a745320afc225e66b25d1e489a7c884d2fc7f11f',
}
BECH32 = ('bc1', 'tb1', 'bcrt1')


def read(name):
    data = (UPSTREAM / name).read_bytes()
    assert hashlib.sha256(data).hexdigest() == PINS[name], name
    return data


def tables():
    codec = json.loads(read('bitcoin-core/base58_encode_decode.json'))
    assert all(len(row) == 2 for row in codec) and len(codec) == 21
    valid, skipped = [], 0
    for text, data, meta in json.loads(read('bitcoin-core/key_io_valid.json')):
        assert meta['chain'] in ('main', 'testnet4', 'signet', 'regtest')
        if text.lower().startswith(BECH32):
            skipped += 1
            continue
        valid.append((text, data, meta['chain'], meta['isPrivkey'], meta.get('isCompressed', False)))
    assert (len(valid), skipped) == (38, 32)
    invalid = [row[0] for row in json.loads(read('bitcoin-core/key_io_invalid.json'))]
    assert len(invalid) == 70 and all('"' not in s and '\\' not in s for s in invalid)
    pubs = re.findall(r'^\*\* ext pub: (xpub[1-9A-HJ-NP-Za-km-z]+)$', read('bip32/bip-0032.mediawiki').decode(), re.M)
    assert len(pubs) == 17
    return codec, valid, invalid, pubs


def render(codec, valid, invalid, pubs):
    out = ['// Generated by make_base58_vectors.py from Bitcoin Core\'s',
           '// base58_encode_decode.json, key_io_valid.json and key_io_invalid.json',
           '// and from BIP-32, pinned in coax/tests/vectors/upstream/ (see SOURCES.md',
           '// there). Published values, copied, not computed; hex is lowercased.',
           '// Test data only.',
           '// The WIF keys here are published test keys; they guard no coins.',
           'B58Pair :: struct {hex:string;text:string;}',
           'B58_CODEC :: [%d] B58Pair.[\n%s];' % (len(codec), ',\n'.join(
               '  B58Pair.{hex="%s",text="%s"}' % (h.lower(), t) for h, t in codec)),
           '// data is the scriptPubKey of an address or the 32-byte key of a WIF.',
           'B58Valid :: struct {text:string;data:string;chain:string;key:bool;compressed:bool;}',
           'B58_VALID :: [%d] B58Valid.[\n%s];' % (len(valid), ',\n'.join(
               '  B58Valid.{text="%s",data="%s",chain="%s",key=%s,compressed=%s}'
               % (t, d, c, 'true' if p else 'false', 'true' if k else 'false') for t, d, c, p, k in valid)),
           'B58_INVALID :: [%d] string.[\n%s];' % (len(invalid), ',\n'.join('  "%s"' % s for s in invalid)),
           'B58_XPUBS :: [%d] string.[\n%s];' % (len(pubs), ',\n'.join('  "%s"' % s for s in pubs))]
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    Path(__file__).with_name('base58_vectors.coax').write_text(render(*tables()))
