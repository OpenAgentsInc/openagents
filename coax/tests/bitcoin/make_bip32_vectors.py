#!/usr/bin/env python3
# Firm reason: 2 (independent oracle: copies published vectors outside Coax)
"""Writes coax/tests/bitcoin/bip32_vectors.coax for Bitcoin chapter 32 from
the pinned BIP-32 text and trezor/python-mnemonic's vectors.json, both in
coax/tests/vectors/upstream/:

  python3 -I coax/tests/bitcoin/make_bip32_vectors.py

- test vectors 1 to 4: each seed, and each chain's indexes, xpub and xprv;
- test vector 5: each invalid extended key and the reason BIP-32 gives;
- the xprv column of vectors.json: the master node of each English
  vector's seed (passphrase "TREZOR").

Each pinned file's SHA-256 must equal its pin below, so a changed file
refuses instead of silently changing the checks. Nothing here derives,
encodes or hashes keys: every value is copied, and each index is the
number the text writes, plus 2^31 when it is marked hardened."""
import hashlib
import json
from pathlib import Path
import re

UPSTREAM = Path(__file__).resolve().parents[1] / 'vectors/upstream'
PINS = {
    'bip32/bip-0032.mediawiki': 'e5e00a8289db2f681052cf24a745320afc225e66b25d1e489a7c884d2fc7f11f',
    'bip39/vectors.json': 'fa3b937b7cff9c9b8ecd3aa011faeb8d6dd67993174b72326e83f4de8fdb30f8',
}
HARDENED = 2 ** 31


def read(name):
    data = (UPSTREAM / name).read_bytes()
    assert hashlib.sha256(data).hexdigest() == PINS[name], name
    return data


def indexes(chain):
    """'m/0<sub>H</sub>/1' -> [2^31, 1]"""
    parts = chain.replace('<sub>H</sub>', 'H').split('/')
    assert parts[0] == 'm'
    out = []
    for part in parts[1:]:
        hardened = part.endswith('H')
        number = int(part[:-1] if hardened else part)
        assert 0 <= number < HARDENED
        out.append(number + (HARDENED if hardened else 0))
    return out


def tables():
    text = read('bip32/bip-0032.mediawiki').decode()
    parts = re.split(r'^===Test vector (\d)===$', text, flags=re.M)
    seeds, chains, invalid = [], [], []
    for number, body in zip(parts[1::2], parts[2::2]):
        body = body.split('==Acknowledgements==')[0]
        if number == '5':
            invalid = re.findall(r'^\* (\S+) \((.+)\)$', body, re.M)
            continue
        seeds.append(re.search(r'^Seed \(hex\): ([0-9a-f]+)$', body, re.M).group(1))
        found = re.findall(r'^\* Chain (\S+)\n\*\* ext pub: (\w+)\n\*\* ext prv: (\w+)$', body, re.M)
        assert found and len(found) == body.count('* Chain ')
        chains += [(int(number), chain.replace('<sub>H</sub>', 'H'), indexes(chain), pub, prv) for chain, pub, prv in found]
    assert len(seeds) == 4 and len(chains) == 17 and len(invalid) == 16
    english = json.loads(read('bip39/vectors.json'))['english']
    assert len(english) == 24
    return seeds, chains, invalid, [(s, x) for _e, _m, s, x in english]


def render(seeds, chains, invalid, trezor):
    out = ['// Generated by make_bip32_vectors.py from the BIP-32 text and',
           '// trezor/python-mnemonic\'s vectors.json, pinned in',
           '// coax/tests/vectors/upstream/ (see SOURCES.md there). Published values,',
           '// copied, not computed. Test data only: these keys are published and',
           '// guard no coins.',
           'B32Chain :: struct {vector:int;path:string;indexes:[5] int;depth:int;xpub:string;xprv:string;}',
           'BIP32_SEEDS :: [%d] string.[%s];' % (len(seeds), ', '.join('"%s"' % s for s in seeds)),
           '// Test vectors 1 to 4. path is the text\'s, with H for hardened.',
           'BIP32_CHAINS :: [%d] B32Chain.[\n%s];' % (len(chains), ',\n'.join(
               '  B32Chain.{vector=%d,path="%s",indexes=[5] int.[%s],depth=%d,xpub="%s",xprv="%s"}' % (
                   v, path, ', '.join(str(i) for i in (ix + [0] * 5)[:5]), len(ix), pub, prv)
               for v, path, ix, pub, prv in chains)),
           '// Test vector 5, with the reason the text gives.',
           'B32Bad :: struct {text:string;reason:string;}',
           'BIP32_INVALID :: [%d] B32Bad.[\n%s];' % (len(invalid), ',\n'.join(
               '  B32Bad.{text="%s",reason="%s"}' % (t, r) for t, r in invalid)),
           '// The xprv column of vectors.json: the master node of each seed.',
           'B32Trezor :: struct {seed:string;xprv:string;}',
           'BIP32_TREZOR :: [%d] B32Trezor.[\n%s];' % (len(trezor), ',\n'.join(
               '  B32Trezor.{seed="%s",xprv="%s"}' % (s, x) for s, x in trezor))]
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    Path(__file__).with_name('bip32_vectors.coax').write_text(render(*tables()))
