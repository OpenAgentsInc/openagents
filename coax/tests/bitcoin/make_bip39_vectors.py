#!/usr/bin/env python3
# Firm reason: 2 (independent oracle: copies published vectors outside Coax)
"""Writes coax/tests/bitcoin/bip39_vectors.coax for Bitcoin chapter 31 from
trezor/python-mnemonic's vectors.json, pinned in
coax/tests/vectors/upstream/bip39/:

  python3 -I coax/tests/bitcoin/make_bip39_vectors.py

- every English vector: entropy, phrase and seed (passphrase "TREZOR");
- the first vector of each other language, phrase and seed, with its UTF-8
  as it is in the file. These show that the seed hashes the phrase's bytes
  and not the list, and that a non-ASCII phrase refuses.

The file's SHA-256 must equal its pin below, so a changed file refuses
instead of silently changing the checks. Nothing here encodes, decodes or
hashes: every string is copied. The xprv column is BIP-32's (chapter 32)."""
import hashlib
import json
from pathlib import Path

UPSTREAM = Path(__file__).resolve().parents[1] / 'vectors/upstream'
PIN = ('bip39/vectors.json', 'fa3b937b7cff9c9b8ecd3aa011faeb8d6dd67993174b72326e83f4de8fdb30f8')


def literal(text):
    """A Coax string literal holding text's UTF-8 bytes as they are."""
    assert not any(c in text for c in '"\\\n\r\t\0')
    return '"' + text + '"'


def tables():
    data = (UPSTREAM / PIN[0]).read_bytes()
    assert hashlib.sha256(data).hexdigest() == PIN[1], PIN[0]
    vectors = json.loads(data)
    english = vectors['english']
    assert len(english) == 24 and all(len(row) == 4 for row in english)
    others = [(lang, rows[0][1], rows[0][2]) for lang, rows in vectors.items() if lang != 'english']
    assert len(others) == 11
    return english, others


def render(english, others):
    out = ['// Generated by make_bip39_vectors.py from trezor/python-mnemonic\'s',
           '// vectors.json, pinned in coax/tests/vectors/upstream/bip39/ (see',
           '// SOURCES.md there). Published values, copied, not computed. Every',
           '// seed uses the passphrase "TREZOR". Test data only: these phrases',
           '// are published and guard no coins.',
           'B39Vector :: struct {entropy:string;phrase:string;seed:string;}',
           'BIP39_VECTORS :: [%d] B39Vector.[\n%s];' % (len(english), ',\n'.join(
               '  B39Vector.{entropy="%s",phrase="%s",seed="%s"}' % (e, m, s) for e, m, s, _x in english)),
           '// The first vector of each other language in the file.',
           'B39Other :: struct {language:string;phrase:string;seed:string;}',
           'BIP39_OTHERS :: [%d] B39Other.[\n%s];' % (len(others), ',\n'.join(
               '  B39Other.{language="%s",phrase=%s,seed="%s"}' % (lang, literal(m), s) for lang, m, s in others))]
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    Path(__file__).with_name('bip39_vectors.coax').write_text(render(*tables()))
