#!/usr/bin/env python3
# Firm reason: 2 (independent oracle: copies published vectors outside Coax)
"""Writes coax/tests/bitcoin/ecdsa_recover_vectors.coax for Bitcoin chapter
22 from three pinned files under coax/tests/vectors/upstream/:

- tiny-secp256k1's tests/fixtures/ecdsa.json: the recoveryId of each of
  the 2,020 valid rows (their keys, hashes and signatures are already in
  ecdsa_sign_vectors.coax, in the same order) and the 8 invalid.recover rows;
- Bitcoin Core's src/test/util_tests.cpp: the message_sign case and the
  seven message_verify cases;
- Bitcoin Core's test/functional/rpc_signmessagewithprivkey.py: its WIF
  key, message, signature and P2PKH address.

  python3 -I coax/tests/bitcoin/make_ecdsa_recover_vectors.py

Each file's SHA-256 must equal its pin below, so a changed file refuses
instead of silently changing the checks. Nothing here signs, recovers or
verifies anything: every value is copied."""
import hashlib, json, re
from pathlib import Path

UPSTREAM = Path(__file__).resolve().parents[1] / 'vectors/upstream'
PINS = {
    'tiny-secp256k1/ecdsa.json': 'b830aa30d0ab3b6c51440caffac9206b24ae5450a387a2db73789f5ce795595d',
    'bitcoin-core/util_tests.cpp': 'ff05ad11d27d2444a7ced5a31c933fa2793ac5f8d4d3cc52b5f17fdefbc6cca7',
    'bitcoin-core/rpc_signmessagewithprivkey.py': '56e6f567ff363e884b27c03baee123deb9600ee2f62825317257a3e133fdd30b',
}


def read(name):
    data = (UPSTREAM / name).read_bytes()
    assert hashlib.sha256(data).hexdigest() == PINS[name], name
    return data.decode()


def tiny():
    doc = json.loads(read('tiny-secp256k1/ecdsa.json'))
    ids = [v['recoveryId'] for v in doc['valid']]
    assert len(ids) == 2020 and set(ids) == {0, 1}
    refuse = [(v['m'], v['signature'], v.get('recoveryId', 0), v['description']) for v in doc['invalid']['recover']]
    assert len(refuse) == 8
    return ids, refuse


def core():
    text = read('bitcoin-core/util_tests.cpp')
    sign = text[text.index('BOOST_AUTO_TEST_CASE(message_sign)'):text.index('BOOST_AUTO_TEST_CASE(message_verify)')]
    key = ''.join(re.findall(r'0x([0-9A-F]{2})', sign[sign.index('privkey_bytes'):sign.index('};')])).lower()
    message = re.search(r'const std::string message = "([^"]*)";', sign).group(1)
    signature = re.search(r'expected_signature =\s*"([^"]*)";', sign).group(1)
    assert len(key) == 64
    verify = text[text.index('BOOST_AUTO_TEST_CASE(message_verify)'):text.index('BOOST_AUTO_TEST_CASE(message_hash)')]
    cases = re.findall(r'MessageVerify\(\s*"([^"]*)",\s*"([^"]*)",\s*"([^"]*)"\),\s*MessageVerificationResult::(\w+)\);', verify)
    assert len(cases) == 7
    functional = read('bitcoin-core/rpc_signmessagewithprivkey.py')
    pick = lambda name: re.search(name + r" = '([^']*)'", functional).group(1)
    address = re.search(r"assert_equal\(addresses\[0\], '([^']*)'\)", functional).group(1)
    return (key, message, signature), cases, (pick('priv_key'), pick('message'), pick('expected_signature'), address)


def render(ids, refuse, signed, cases, functional):
    q = lambda s: '"%s"' % s.replace('\\', '\\\\').replace('"', '\\"')
    out = ["// Generated by make_ecdsa_recover_vectors.py from tiny-secp256k1's",
           "// tests/fixtures/ecdsa.json and Bitcoin Core's src/test/util_tests.cpp and",
           "// test/functional/rpc_signmessagewithprivkey.py, pinned in",
           "// coax/tests/vectors/upstream/ (see SOURCES.md there). Published",
           "// values, copied, not computed. Test keys only.",
           "// The recovery ID of each ES_CASES row (ecdsa_sign_vectors.coax), in order.",
           'ER_IDS :: [%d] u8.[%s];' % (len(ids), ','.join(map(str, ids))),
           '// Signatures whose recovery must refuse: hash, r || s, recovery ID.',
           'ErRefuse :: struct {m:string;sig:string;id:int;why:string;}',
           'ER_REFUSE :: [%d] ErRefuse.[\n%s];' % (len(refuse), ',\n'.join(
               '  ErRefuse.{m="%s",sig="%s",id=%d,why=%s}' % (m, s, i, q(w)) for m, s, i, w in refuse)),
           "// Core's message_sign: key, message, base64 signature.",
           'SM_CORE_SIGN :: [3] string.[%s];' % ','.join(q(v) for v in signed),
           "// Core's message_verify: address, signature, message, Core's result.",
           'SmCore :: struct {address:string;sig:string;message:string;result:string;}',
           'SM_CORE_VERIFY :: [%d] SmCore.[\n%s];' % (len(cases), ',\n'.join(
               '  SmCore.{address=%s,sig=%s,message=%s,result=%s}' % tuple(q(v) for v in c) for c in cases)),
           "// rpc_signmessagewithprivkey.py: WIF key, message, signature, P2PKH address.",
           'SM_CORE_FUNCTIONAL :: [4] string.[%s];' % ','.join(q(v) for v in functional)]
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    ids, refuse = tiny()
    signed, cases, functional = core()
    Path(__file__).with_name('ecdsa_recover_vectors.coax').write_text(render(ids, refuse, signed, cases, functional))
