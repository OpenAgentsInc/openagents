#!/usr/bin/env python3
# Firm reason: 2 (independent oracle: copies published vectors outside Coax)
"""Writes coax/tests/bitcoin/ecdsa_sign_vectors.coax for Bitcoin chapter 20
from tiny-secp256k1's tests/fixtures/ecdsa.json, pinned in
coax/tests/vectors/upstream/tiny-secp256k1/:

  python3 -I coax/tests/bitcoin/make_ecdsa_sign_vectors.py

The file's SHA-256 must equal its pin below, so a changed file refuses
instead of silently changing the checks. Nothing here signs or verifies
anything: every key, hash and signature is copied. The extraEntropy rows
(libsecp256k1's ndata) and the verify and recover rows are not copied."""
import hashlib, json
from pathlib import Path

SOURCE = Path(__file__).resolve().parents[1] / 'vectors/upstream/tiny-secp256k1/ecdsa.json'
PIN = 'b830aa30d0ab3b6c51440caffac9206b24ae5450a387a2db73789f5ce795595d'


def table():
    data = SOURCE.read_bytes()
    assert hashlib.sha256(data).hexdigest() == PIN, SOURCE
    doc = json.loads(data)
    valid = [(v['d'], v['m'], v['signature']) for v in doc['valid']]
    refuse = [(v['d'], v['m'], v['description']) for v in doc['invalid']['sign']]
    assert len(valid) == 2020 and len(refuse) == 4
    for d, m, s in valid:
        assert len(d) == 64 and len(m) == 64 and len(s) == 128 and (d + m + s) == (d + m + s).lower()
    return valid, refuse


def render(valid, refuse):
    out = ["// Generated by make_ecdsa_sign_vectors.py from tiny-secp256k1's",
           '// tests/fixtures/ecdsa.json, pinned in',
           '// coax/tests/vectors/upstream/tiny-secp256k1/ (see SOURCES.md there).',
           '// Published values, copied, not computed. Test keys only.',
           '// Each row is a secret key d, a 32-byte hash m and the compact',
           '// signature r || s that libsecp256k1 gives with RFC 6979 and low-S.',
           'EsCase :: struct {d:string;m:string;sig:string;}',
           'ES_CASES :: [%d] EsCase.[\n%s];' % (len(valid), ',\n'.join(
               '  EsCase.{d="%s",m="%s",sig="%s"}' % row for row in valid)),
           '// Keys the signer must refuse: 0, n, n + 1 and 2^256 - 1.',
           'EsRefuse :: struct {d:string;m:string;why:string;}',
           'ES_REFUSE :: [%d] EsRefuse.[\n%s];' % (len(refuse), ',\n'.join(
               '  EsRefuse.{d="%s",m="%s",why="%s"}' % row for row in refuse))]
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    Path(__file__).with_name('ecdsa_sign_vectors.coax').write_text(render(*table()))
