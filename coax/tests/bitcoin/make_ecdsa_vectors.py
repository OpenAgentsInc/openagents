#!/usr/bin/env python3
# Firm reason: 2 (independent oracle: copies published vectors outside Coax)
"""Writes coax/tests/bitcoin/ecdsa_vectors.coax for Bitcoin chapter 19 from
Wycheproof's ecdsa_secp256k1_sha256_bitcoin_test.json, pinned in
coax/tests/vectors/upstream/wycheproof/:

  python3 -I coax/tests/bitcoin/make_ecdsa_vectors.py

The file's SHA-256 must equal its pin below, so a changed file refuses
instead of silently changing the checks. Nothing here hashes or verifies
anything: every key, message, signature, flag and result is copied."""
import hashlib, json
from pathlib import Path

SOURCE = Path(__file__).resolve().parents[1] / 'vectors/upstream/wycheproof/ecdsa_secp256k1_sha256_bitcoin_test.json'
PIN = 'd3729ce83ff9740c45e74921009a4061eff6c09185b8dd1225ccd06ac57048a4'


def table():
    data = SOURCE.read_bytes()
    assert hashlib.sha256(data).hexdigest() == PIN, SOURCE
    doc = json.loads(data)
    assert doc['algorithm'] == 'ECDSA' and doc['schema'] == 'ecdsa_bitcoin_verify_schema.json'
    keys, cases = [], []
    for group in doc['testGroups']:
        assert group['type'] == 'EcdsaBitcoinVerify' and group['sha'] == 'SHA-256'
        assert group['publicKey']['curve'] == 'secp256k1'
        keys.append(group['publicKey']['uncompressed'])
        for t in group['tests']:
            assert t['result'] in ('valid', 'invalid') and '\\' not in t['comment']
            cases.append((t['tcId'], len(keys) - 1, t['msg'], t['sig'], t['result'] == 'valid',
                          ','.join(t['flags']), t['comment'].replace('"', '\\"')))
    assert len(cases) == doc['numberOfTests'] == 464 and len(keys) == 100
    return keys, cases


def render(keys, cases):
    out = ['// Generated by make_ecdsa_vectors.py from Wycheproof\'s',
           '// ecdsa_secp256k1_sha256_bitcoin_test.json, pinned in',
           '// coax/tests/vectors/upstream/wycheproof/ (see SOURCES.md there).',
           '// Published values, copied, not computed. Test data only.',
           '// Each key is SEC1 uncompressed; each message is hashed once with',
           '// SHA-256; each signature is DER; valid means the expected result.',
           'EV_KEYS :: [%d] string.[\n%s];' % (len(keys), ',\n'.join('  "%s"' % k for k in keys)),
           'EvCase :: struct {id:int;key:int;msg:string;sig:string;valid:bool;flags:string;comment:string;}',
           'EV_CASES :: [%d] EvCase.[\n%s];' % (len(cases), ',\n'.join(
               '  EvCase.{id=%d,key=%d,msg="%s",sig="%s",valid=%s,flags="%s",comment="%s"}'
               % (i, k, m, s, 'true' if v else 'false', f, c) for i, k, m, s, v, f, c in cases))]
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    Path(__file__).with_name('ecdsa_vectors.coax').write_text(render(*table()))
