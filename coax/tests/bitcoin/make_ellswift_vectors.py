#!/usr/bin/env python3
# Firm reason: 2 (independent oracle: transcribes BIP-324's published test vectors outside Coax)
"""Writes coax/tests/bitcoin/ellswift_vectors.coax for Bitcoin chapter 66:

  python3 -I coax/tests/bitcoin/make_ellswift_vectors.py

From BIP-324's test vectors, pinned in coax/tests/vectors/upstream/bip324/:

- ELLSWIFT_DECODE: every row of ellswift_decode_test_vectors.csv, a
  64-byte encoding and the x it decodes to.
- ELLSWIFT_INVERSE: every row of xswiftec_inv_test_vectors.csv, a u and an
  x with the t of each of the eight cases, or "" where the case has none.
- ELLSWIFT_XDH: the key-exchange columns of every row of
  packet_encoding_test_vectors.csv: our secret key and both encodings, who
  initiates, both decoded x, the shared x and the hashed shared secret.

Every pinned file's SHA-256 must equal its pin.
"""
import csv
import hashlib
from pathlib import Path

HERE = Path(__file__).resolve().parent
UP = HERE.parent / 'vectors/upstream/bip324'
OUT = HERE / 'ellswift_vectors.coax'
PINS = {
    'ellswift_decode_test_vectors.csv': 'a238a66b093bed3c571d5b57cb2bb1f69487788f0f872f7ea7501b5b98be20b0',
    'xswiftec_inv_test_vectors.csv': 'b5e8e0e9edfdee14c3ec4db3c6763543a9f17290a84a93de0ae2671c16f4432a',
    'packet_encoding_test_vectors.csv': '61704507945e2fa99e6c799fab888593eb7a2c3d2018f42ee4a3c3abe0684269',
}


def rows(name):
    data = (UP / name).read_bytes()
    assert hashlib.sha256(data).hexdigest() == PINS[name], f'{name} differs from its pin'
    return list(csv.DictReader(data.decode().splitlines()))


def main():
    decode = rows('ellswift_decode_test_vectors.csv')
    inverse = rows('xswiftec_inv_test_vectors.csv')
    packets = rows('packet_encoding_test_vectors.csv')
    text = [
        '// Generated by make_ellswift_vectors.py from BIP-324\'s test vectors,',
        '// pinned in coax/tests/vectors/upstream/bip324/ (see SOURCES.md there).',
        '// Test data only.',
        'EsDecodeRow :: struct { ellswift: string; x: string; comment: string; }',
        f'ELLSWIFT_DECODE :: [{len(decode)}] EsDecodeRow.[',
    ]
    text += [f'  EsDecodeRow.{{ellswift="{r["ellswift"]}", x="{r["x"]}", comment="{r["comment"]}"}},'
             for r in decode]
    text += ['];', 'EsInverseRow :: struct { u: string; x: string; t: [8] string; comment: string; }',
             f'ELLSWIFT_INVERSE :: [{len(inverse)}] EsInverseRow.[']
    for r in inverse:
        ts = ', '.join(f'"{r[f"case{i}_t"]}"' for i in range(8))
        text.append(f'  EsInverseRow.{{u="{r["u"]}", x="{r["x"]}", t=[8] string.[{ts}], comment="{r["comment"]}"}},')
    text += ['];', 'EsXdhRow :: struct { secret: string; ours: string; theirs: string; initiating: bool;',
             '  x_ours: string; x_theirs: string; x_shared: string; shared_secret: string; }',
             f'ELLSWIFT_XDH :: [{len(packets)}] EsXdhRow.[']
    for r in packets:
        init = 'true' if r['in_initiating'] == '1' else 'false'
        text.append(f'  EsXdhRow.{{secret="{r["in_priv_ours"]}", ours="{r["in_ellswift_ours"]}", '
                    f'theirs="{r["in_ellswift_theirs"]}", initiating={init}, x_ours="{r["mid_x_ours"]}", '
                    f'x_theirs="{r["mid_x_theirs"]}", x_shared="{r["mid_x_shared"]}", '
                    f'shared_secret="{r["mid_shared_secret"]}"}},')
    text += ['];', '']
    OUT.write_text('\n'.join(text))
    print(f'wrote {OUT.name}: {len(decode)} decodings, {len(inverse)} inverses, {len(packets)} exchanges')


if __name__ == '__main__':
    main()
