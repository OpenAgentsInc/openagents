#!/usr/bin/env python3
# Firm reason: 2 (independent oracle: copies BIP-445's published vector files, pinned by hash, into Coax data)
"""Writes frost_vectors.coax for Bitcoin chapter 102 from the FROST draft
BIP's vector files (BIP-445, siv2r/bip-frost-signing at ba299bad), pinned in
coax/tests/vectors/upstream/bip445/python/vectors/:

  python3 -I coax/tests/bitcoin/make_frost_vectors.py          # check the file
  python3 -I coax/tests/bitcoin/make_frost_vectors.py --write  # rewrite it

Each case is written with its inputs spelled out: the share, nonce, tweak
and signature indices of the JSON become the concatenated hex of the
values they name, ids become one byte each, x-only flags become a string
of 't' and 'f', and a null becomes a flag beside an empty string. An
error becomes frost.coax's code and the index it names (-1 for none).
Nothing is computed here: frost.py checks every case against the
reference implementation that ships with the BIP.
"""
import hashlib, json, re, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
VEC = HERE.parent / 'vectors'
UP = VEC / 'upstream' / 'bip445' / 'python' / 'vectors'
OUT = HERE / 'frost_vectors.coax'

# frost.coax's codes for the reference's errors.
CONTRIB = {'pubnonce': 1, 'aggnonce': 2, 'aggothernonce': 3, 'psig': 4}
VALUE = {
    'The threshold must be 1 <= t <= n.': 5,
    'The number of participants must be n <= 128.': 6,
    'The thresh_pk is not a valid point.': 7,
    'The pubshare at index % is not a valid point.': 8,
    'At least t pubshares must be present.': 9,
    'The provided key material is incorrect: the public shares do not lie on a single polynomial.': 10,
    'The provided key material is incorrect: the public shares do not match the threshold public key.': 11,
    'The threshold public key must not be the point at infinity.': 12,
    'The tweak value is out of range.': 13,
    'The tweaked threshold public key must not be the point at infinity.': 14,
    'The tweaks and is_xonly lists must have the same length.': 15,
    'The number of signers must satisfy t <= u <= n.': 16,
    'The pubshares and ids lists must have the same length.': 17,
    'The id at index % must satisfy 0 <= id <= n - 1.': 18,
    'The ids list contains duplicate elements.': 19,
    'The first half of secnonce is out of range.': 20,
    'The second half of secnonce is out of range.': 21,
    'The secshare is out of range.': 22,
    "The signer's id is missing from the ids list.": 23,
    "The signer's pubshare does not match its entry in the pubshares list.": 24,
    'The aggothernonce must be omitted when u = 1.': 25,
    'The aggothernonce must be present and a 66-byte array when u > 1.': 26,
    'The psigs and ids lists must have the same length.': 27,
}
FR_INVALID = 28


def load(name):
    b = (UP / f'{name}_vectors.json').read_bytes()
    m = json.loads((VEC / 'manifest.json').read_text())
    pin = next(e['sha256'] for e in m['files'] if e['path'] == f'upstream/bip445/python/vectors/{name}_vectors.json')
    assert hashlib.sha256(b).hexdigest() == pin, name
    return json.loads(b)


def h(x):
    return '' if x is None else x.lower()


def cat(values, indices):
    return '' if indices is None else ''.join(values[i].lower() for i in indices)


def ids(xs):
    assert all(0 <= x < 256 for x in xs)
    return ''.join(f'{x:02x}' for x in xs)


def flags(xs):
    return ''.join('t' if x else 'f' for x in xs)


def b(x):
    return 'true' if x else 'false'


def err(case):
    """frost.coax's code and the index it names, for a case's error."""
    if 'error' not in case:
        return 0, -1
    e = case['error']
    if e['type'] == 'InvalidContributionError':
        signer = e['signer_index']
        return CONTRIB[e['contrib']], -1 if signer is None else signer
    message = e['message']
    index = re.search(r' at index (\d+) ', message)
    if index:
        return VALUE[message.replace(index.group(1), '%', 1)], int(index.group(1))
    return VALUE[message], -1


def table(L, struct, name, fields, rows):
    L.append(f'{struct} :: struct {{ {fields} }}')
    L.append(f'{name} :: [{len(rows)}] {struct}.[')
    L += [f'  {struct}.{{{r}}},' for r in rows] + ['];']


def group_head(g, indices):
    present = indices is not None
    return (f'n={g["n"]}, t={g["t"]}, thresh_pk="{h(g["thresh_pk"])}", '
            f'pubshares="{cat(g["pubshares"], indices)}", has_pubshares={b(present)}')


def render():
    L = ['// Generated by make_frost_vectors.py from the FROST draft BIP\'s vector',
         '// files (BIP-445, coax/tests/vectors/upstream/bip445/, listed in',
         '// SOURCES.md). Indices are resolved: shares, nonces, tweaks and partial',
         '// signatures are the concatenated hex of the values the JSON names, ids',
         '// are one byte each, x-only flags are \'t\' and \'f\', and an error is',
         '// frost.coax\'s code with the index it names (-1 for none). Test data only.']

    g = load('nonce_gen')
    rows = []
    for c in g['valid_tests']:
        sid = -1 if c['signer_id'] is None else c['signer_id']
        rows.append(f'rand="{h(c["rand"])}", secshare="{h(c["secshare"])}", signer_id={sid}, pubshare="{h(c["pubshare"])}", '
                    f'xonly="{h(c["thresh_pk_xonly"])}", msg="{h(c["msg"])}", has_msg={b(c["msg"] is not None)}, '
                    f'extra="{h(c["extra_in"])}", secnonce="{h(c["expected"][0])}", pubnonce="{h(c["expected"][1])}"')
    table(L, 'FrNonceGenCase', 'FR_NONCE_GEN', 'rand: string; secshare: string; signer_id: int; pubshare: string; xonly: string; '
          'msg: string; has_msg: bool; extra: string; secnonce: string; pubnonce: string;', rows)

    a = load('nonce_agg')
    rows = []
    for c in a['valid_tests'] + a['error_tests']:
        code, signer = err(c)
        rows.append(f'nonces="{cat(a["pubnonces"], c["pubnonce_indices"])}", expected="{h(c.get("expected"))}", code={code}, signer={signer}')
    table(L, 'FrNonceAggCase', 'FR_NONCE_AGG', 'nonces: string; expected: string; code: int; signer: int;', rows)

    # Signing and verifying: sign_verify's cases, then tweak's.
    sv = load('sign_verify')
    tw = load('tweak')
    sign, verify = [], []
    for g in sv['test_groups'] + tw['test_groups']:
        tweaks = g.get('tweaks', [])
        for c in g['valid_tests'] + g.get('sign_error_tests', []) + g.get('error_tests', []):
            code, signer = err(c)
            tws = cat(tweaks, c.get('tweak_indices', []))
            xo = flags(c.get('is_xonly', []))
            sign.append(f'{group_head(g, c["pubshare_indices"])}, ids="{ids(c["ids"])}", signer_id={c["signer_id"]}, '
                        f'secshare="{h(g["secshares"][c["secshare_index"]])}", secnonce="{h(g["secnonces"][c["secnonce_index"]])}", '
                        f'aggnonce="{h(c["aggnonce"])}", tweaks="{tws}", xonly="{xo}", msg="{h(c["msg"])}", '
                        f'expected="{h(c.get("expected"))}", code={code}, signer={signer}')
            if code == 0 and c['pubshare_indices'] is not None:
                verify.append(f'{group_head(g, c["pubshare_indices"])}, ids="{ids(c["ids"])}", '
                              f'pubnonces="{cat(g["pubnonces"], c["pubnonce_indices"])}", tweaks="{tws}", xonly="{xo}", '
                              f'msg="{h(c["msg"])}", psig="{h(c["expected"])}", index={c["ids"].index(c["signer_id"])}, code=0, signer=-1')
        for c in g.get('verify_fail_tests', []) + g.get('verify_error_tests', []):
            code, signer = err(c) if 'error' in c else (FR_INVALID, -1)
            verify.append(f'{group_head(g, c["pubshare_indices"])}, ids="{ids(c["ids"])}", '
                          f'pubnonces="{cat(g["pubnonces"], c["pubnonce_indices"])}", tweaks="", xonly="", '
                          f'msg="{h(c["msg"])}", psig="{h(c["psig"])}", index={c["signer_index"]}, code={code}, signer={signer}')
    head = 'n: int; t: int; thresh_pk: string; pubshares: string; has_pubshares: bool; ids: string;'
    table(L, 'FrSignCase', 'FR_SIGN', head + ' signer_id: int; secshare: string; secnonce: string; aggnonce: string; '
          'tweaks: string; xonly: string; msg: string; expected: string; code: int; signer: int;', sign)
    table(L, 'FrVerifyCase', 'FR_VERIFY', head + ' pubnonces: string; tweaks: string; xonly: string; msg: string; '
          'psig: string; index: int; code: int; signer: int;', verify)

    d = load('det_sign')
    rows = []
    for g in d['test_groups']:
        for c in g['valid_tests'] + g['error_tests']:
            code, signer = err(c)
            pubnonce, psig = (h(c['expected'][0]), h(c['expected'][1])) if code == 0 else ('', '')
            rows.append(f'{group_head(g, c["pubshare_indices"])}, ids="{ids(c["ids"])}", signer_id={c["signer_id"]}, '
                        f'secshare="{h(g["secshares"][c["secshare_index"]])}", aggother="{h(c["aggothernonce"])}", '
                        f'has_aggother={b(c["aggothernonce"] is not None)}, aux="{h(c["aux_rand"])}", has_aux={b(c["aux_rand"] is not None)}, '
                        f'tweaks="{"".join(h(x) for x in c["tweaks"])}", xonly="{flags(c["is_xonly"])}", msg="{h(c["msg"])}", '
                        f'pubnonce="{pubnonce}", psig="{psig}", code={code}, signer={signer}')
    table(L, 'FrDetCase', 'FR_DET_SIGN', head + ' signer_id: int; secshare: string; aggother: string; has_aggother: bool; '
          'aux: string; has_aux: bool; tweaks: string; xonly: string; msg: string; pubnonce: string; psig: string; code: int; signer: int;', rows)

    a = load('sig_agg')
    rows = []
    for g in a['test_groups']:
        for c in g['valid_tests'] + g['error_tests']:
            code, signer = err(c)
            rows.append(f'{group_head(g, c["pubshare_indices"])}, ids="{ids(c["ids"])}", aggnonce="{h(c["aggnonce"])}", '
                        f'tweaks="{cat(g["tweaks"], c["tweak_indices"])}", xonly="{flags(c["is_xonly"])}", '
                        f'psigs="{"".join(h(x) for x in c["psigs"])}", msg="{h(c["msg"])}", expected="{h(c.get("expected"))}", '
                        f'code={code}, signer={signer}')
    table(L, 'FrAggCase', 'FR_SIG_AGG', head + ' aggnonce: string; tweaks: string; xonly: string; psigs: string; msg: string; '
          'expected: string; code: int; signer: int;', rows)

    ti = load('threshold_info')
    rows = []
    for g in ti['test_groups']:
        for c in g['valid_tests'] + g['error_tests']:
            code, signer = err(c)
            idx = c['pubshare_indices']
            shares = ''.join('00' * 33 if i is None else g['pubshares'][i].lower() for i in idx)
            assert all(i is None or len(g['pubshares'][i]) == 66 for i in idx)
            rows.append(f't={c["t"]}, thresh_pk="{h(c["thresh_pk"])}", pubshares="{shares}", present="{flags(i is not None for i in idx)}", '
                        f'code={code}, signer={signer}')
    table(L, 'FrInfoCase', 'FR_INFO', 't: int; thresh_pk: string; pubshares: string; present: string; code: int; signer: int;', rows)
    return '\n'.join(L) + '\n'


if __name__ == '__main__':
    text = render()
    if '--write' in sys.argv:
        OUT.write_text(text)
    assert OUT.read_text() == text, 'frost_vectors.coax differs; run with --write'
