#!/usr/bin/env python3
# Firm reason: 2 (independent oracle: copies published vectors outside Coax)
"""Writes coax/tests/bitcoin/fuzz_seeds.coax for Bitcoin chapter 119: a
few seeds for each parser the book's fuzzing example runs, taken from
fuzz.py's corpora, which read pinned files and check their SHA-256:

- transactions from Bitcoin Core's tx_valid.json,
- P2P frames and version payloads written with Core's pinned messages.py,
- PSBTs from BIP-174, BIP-370 and BIP-371 and Core's rpc_psbt.json,
- invoices from BOLT 11's invoice-test.json,
- Base58Check text from Core's key_io_valid.json.

  python3 -I coax/tests/bitcoin/make_fuzz_seeds.py
"""
from pathlib import Path
import sys

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import fuzz as F  # noqa: E402

# The example's targets, in the order it runs them, and how many seeds
# each takes, spread from the shortest to the longest.
EXAMPLE = [('tx', 6), ('p2p_frame', 4), ('p2p_version', 4), ('psbt', 6), ('invoice', 4), ('base58check', 6)]


def seeds():
    out = []
    for k, (target, n) in enumerate(EXAMPLE):
        corpus = sorted(F.TARGETS[target][0](), key=lambda b: (len(b), b))
        # only seeds the reference accepts: the corpora also hold the
        # published invalid cases
        corpus = [b for b in corpus if F.TARGETS[target][1](b) in (0, 101, 102, 103, 104)]
        # spread the picks over the corpus: shortest, longest and between
        picks = [corpus[round(i * (len(corpus) - 1) / (n - 1))] for i in range(n)]
        out += [(k, b) for b in picks]
    return out


def render():
    rows = seeds()
    lines = ['// Generated by make_fuzz_seeds.py from pinned vectors (see that file and',
             '// SOURCES.md). Test data only. target is the index into FZ_TARGETS; hex is',
             '// one seed input, as lowercase hex.',
             'FZ_TARGETS :: [%d] string.[%s];' % (len(F_EXAMPLE_NAMES()), ', '.join('"%s"' % t for t in F_EXAMPLE_NAMES())),
             'FzSeed :: struct { target: int; hex: string; }',
             'FZ_SEEDS :: [%d] FzSeed.[\n%s];' % (len(rows), ',\n'.join('  FzSeed.{target=%d, hex="%s"}' % (k, b.hex())
                                                                       for k, b in rows))]
    return '\n'.join(lines) + '\n'


def F_EXAMPLE_NAMES():
    return [t for t, _ in EXAMPLE]


if __name__ == '__main__':
    Path(__file__).with_name('fuzz_seeds.coax').write_text(render())
