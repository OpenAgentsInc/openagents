#!/usr/bin/env python3
# Firm reason: 2 (independent oracle: serializes the handshake's messages with Bitcoin Core's messages.py and pinned sources, outside Coax)
"""Writes coax/tests/bitcoin/handshake_vectors.coax for Bitcoin chapter 68:

  python3 -I coax/tests/bitcoin/make_handshake_vectors.py

HS_CORE: the payloads of the handshake's messages as Bitcoin Core writes
them. "their version" is a peer's version message from Core's
functional-test serializer, test_framework/messages.py (msg_version).
"our version" is PushNodeVersion (net_processing.cpp) transliterated:
messages.py writes only IPv4-mapped addresses, and Core writes the
unroutable CService{} as 16 zero bytes, so it is built here and read back
with messages.py. The empty messages and sendcmpct come from messages.py,
and the final alert's bytes from the pinned net_processing.cpp.
"""
import re
import sys
from io import BytesIO
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import core_messages  # noqa: E402
import p2p  # noqa: E402

OUT = HERE / 'handshake_vectors.coax'
M = core_messages.load()

# The node the chapter's tests open: an outbound connection at time 1000.
OURS = dict(version=70017, services=M.NODE_NETWORK | M.NODE_WITNESS | (1 << 11), time=1000,
            peer_services=M.NODE_NETWORK | M.NODE_WITNESS, nonce=0x0102030405060708,
            agent='/Coax:0.68/', height=900000, relay=1)


def our_version(o):
    """PushNodeVersion: version, services, time, then the peer's services and
    CNetAddr::V1 of an unroutable address (16 zero bytes, port 0), ours the
    same, the nonce, the user agent, the height and the relay flag."""
    r = o['version'].to_bytes(4, 'little', signed=True) + o['services'].to_bytes(8, 'little')
    r += o['time'].to_bytes(8, 'little', signed=True)
    r += o['peer_services'].to_bytes(8, 'little') + bytes(18)
    r += o['services'].to_bytes(8, 'little') + bytes(18)
    r += o['nonce'].to_bytes(8, 'little') + M.ser_string(o['agent'].encode())
    r += o['height'].to_bytes(4, 'little', signed=True) + bytes([o['relay']])
    v = M.msg_version()
    v.deserialize(BytesIO(r))
    assert (v.nVersion, v.nServices, v.nTime, v.nNonce, v.strSubVer, v.nStartingHeight, v.relay) == \
        (o['version'], o['services'], o['time'], o['nonce'], o['agent'], o['height'], o['relay'])
    return r


def their_version():
    v = M.msg_version()
    v.nVersion, v.nServices, v.nTime = 70017, M.NODE_NETWORK | M.NODE_WITNESS, 1700000000
    v.addrTo.port = v.addrFrom.port = 8333
    v.nNonce, v.strSubVer, v.nStartingHeight, v.relay = 0x1122334455667788, '/Satoshi:29.0.0/', 900000, 1
    return v.serialize()


def final_alert():
    text = p2p.pinned('net_processing.cpp')
    return bytes.fromhex(re.search(r'constexpr auto finalAlert\{"([0-9a-f]+)"_hex\};', text).group(1))


def vectors():
    return [
        ('our version', our_version(OURS)),
        ('their version', their_version()),
        ('verack', M.msg_verack().serialize()),
        ('wtxidrelay', M.msg_wtxidrelay().serialize()),
        ('sendaddrv2', M.msg_sendaddrv2().serialize()),
        ('sendcmpct', M.msg_sendcmpct(announce=False, version=2).serialize()),
        ('getaddr', M.msg_getaddr().serialize()),
        ('alert', final_alert()),
    ]


def main():
    rows = vectors()
    text = [
        '// Generated by make_handshake_vectors.py from Bitcoin Core\'s',
        '// test_framework/messages.py and net_processing.cpp, pinned in',
        '// coax/tests/vectors/upstream/bitcoin-core/ (see SOURCES.md there). Test data only.',
        '//',
        '// HS_CORE: the payloads of the handshake\'s messages as Core writes them.',
        'HsCore :: struct { name: string; hex: string; }',
        f'HS_CORE :: [{len(rows)}] HsCore.[',
    ]
    text += [f'  HsCore.{{name="{n}", hex="{b.hex()}"}},' for n, b in rows]
    text += ['];', '']
    OUT.write_text('\n'.join(text))
    print(f'wrote {OUT.name}: {len(rows)} payloads')


if __name__ == '__main__':
    main()
