#!/usr/bin/env python3
# Firm reason: 2 (independent oracle: copies published blocks and computes their IDs outside Coax)
"""Writes coax/tests/bitcoin/merkle_vectors.coax and merkle_block413567.coax
for Bitcoin chapter 46 from files pinned in coax/tests/vectors/upstream/:

  python3 -I coax/tests/bitcoin/make_merkle_vectors.py

- Mainnet block 100,000 (4 transactions) and block 514,999 (19, an odd
  count, 5 of them with witnesses): raw bytes from mempool.space's API,
  each pinned by its SHA-256, beside the JSON record that publishes its
  height, transaction count and Merkle root. Each block's header hashes
  to the block hash in its file name.
- Block 413,567 (1,557 transactions, an odd count): Bitcoin Core's
  src/bench/data/block413567.raw at the pinned revision. Its txids are
  written out in hash order, so a check can rebuild the root without
  reading a megabyte of transactions.

Every input's SHA-256 must equal its pin. The txids are computed here with
tx_reference.py and merkle_reference.py, which share no code with Coax,
and each block's root from them must equal the root in its own header (and
the published one). For block 514,999 the witness root reaches the
coinbase's BIP-141 commitment.
"""
import hashlib, json, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import merkle_reference as M  # noqa: E402
import tx_reference as R  # noqa: E402

ROOT = HERE.parent / 'vectors' / 'upstream'
B100000 = '000000000003ba27aa200b1cecaad478d2b00432346c3f1f3986da1afd33e506'
B514999 = '00000000000000000008fda0e5bb3105dab72605332085684c42dceb0ea61097'
B413567 = '0000000000000000025aff8be8a55df8f89c77296db6198f272d6577325d4069'
PINS = {
    f'mainnet/{B100000}.raw': 'b02256f05ce2fc0d152394b5cd2fa28fe4ab61100844c389581c4cffad88a2b1',
    f'mainnet/{B100000}.json': 'a40baaad74146e536439774ac3966f471c6745a942423db503789547cfe2b45e',
    f'mainnet/{B514999}.raw': '7c0d1862284dcd240a63b5bcb75e956c3645ed5d7453799abb721ce06e6b2902',
    f'mainnet/{B514999}.json': '81682b48567be9bafe33b712930567fea33f9a18cbabc56eb89b82666d144d64',
    'bitcoin-core/block413567.raw': '71964cee18c58675784846d498944b35daa41e36b6f65a7e8feb291def924cce',
}
src = {}
for name, pin in PINS.items():
    data = (ROOT / name).read_bytes()
    assert hashlib.sha256(data).hexdigest() == pin, name
    src[name] = data

# Block 413,567's root, as explorers publish it (mempool.space, 2026-11-02).
PUBLISHED_413567 = '64a50c649fc816baaa2effda230c39cacf1504e4e616a2863685b72aaa7dce05'


def block(raw, block_hash, published_root, count):
    assert M.sha256d(raw[:80])[::-1].hex() == block_hash, 'the header hashes to the block hash'
    txids, wtxids, txs = M.block_ids(raw)
    assert len(txids) == count
    root, mutated = M.compute_root(txids)
    assert root == raw[36:68] and root[::-1].hex() == published_root and not mutated
    assert M.check(txids, raw[36:68]) == M.OK
    return txids, wtxids, txs


blocks = {}
for h in (B100000, B514999):
    record = json.loads(src[f'mainnet/{h}.json'])
    assert record['id'] == h
    raw = src[f'mainnet/{h}.raw']
    assert len(raw) == record['size']
    blocks[h] = (raw, record, block(raw, h, record['merkle_root'], record['tx_count']))
raw413567 = src['bitcoin-core/block413567.raw']
txids413567, _, _ = block(raw413567, B413567, PUBLISHED_413567, 1557)

# Block 514,999's witness commitment: the last coinbase output whose script
# starts 6a24aa21a9ed holds SHA-256d(witness root || reserved value), and
# the reserved value is the coinbase's one witness item (BIP-141).
_, _, (_, wtxids514999, txs514999) = blocks[B514999]
coinbase = txs514999[0]
commitments = [o['script'][6:38] for o in coinbase['outs'] if o['script'][:6] == bytes.fromhex('6a24aa21a9ed') and len(o['script']) >= 38]
reserved = coinbase['ins'][0]['witness'][0]
assert len(reserved) == 32 and M.sha256d(M.witness_root(wtxids514999) + reserved) == commitments[-1]

# The 64-byte transaction of the chapter: one input with an empty
# scriptSig, one output of 0 satoshis whose script is OP_RETURN and a
# 2-byte push. It reads, its stripped size is 64, and its txid is the
# Merkle parent of its two 32-byte halves.
TX64 = ('01000000' + '01' + blocks[B100000][2][0][0].hex() + '00000000' + '00' + 'ffffffff'
        + '01' + '0000000000000000' + '04' + '6a020000' + '00000000')
tx64 = R.unserialize(bytes.fromhex(TX64), True)
assert len(R.serialize(tx64, False)) == 64
t64 = bytes.fromhex(TX64)
assert R.txid(tx64) == M.sha256d(t64[:32] + t64[32:])


def hexes(name, value, note):
    return f'// {note}\n{name} :: "{value}";\n'


out = ['// Generated by make_merkle_vectors.py from the files pinned in\n'
       '// coax/tests/vectors/upstream/ (see SOURCES.md there). Test data only.\n\n']
for label, h in (('100000', B100000), ('514999', B514999)):
    raw, record, (txids, wtxids, txs) = blocks[h]
    out.append(hexes(f'MK_BLOCK_{label}', raw.hex(),
                     f'Mainnet block {record["height"]:,}, {record["tx_count"]} transactions, '
                     f'{record["size"]} bytes (mempool.space).'))
    out.append(hexes(f'MK_HASH_{label}', h, 'Its block hash, as explorers show it.'))
    out.append(hexes(f'MK_ROOT_{label}', record['merkle_root'], 'Its published Merkle root, as explorers show it.'))
    out.append(hexes(f'MK_TXIDS_{label}', ''.join(t[::-1].hex() for t in txids),
                     'Its txids, as explorers show them (computed by tx_reference.py).'))
out.append(hexes('MK_WITNESS_ROOT_514999', M.witness_root(wtxids514999)[::-1].hex(),
                 "Block 514,999's witness root, as explorers would show it (computed)."))
out.append(hexes('MK_COMMITMENT_514999', commitments[-1].hex(),
                 'Its coinbase commitment, bytes 6 to 38 of the 6a24aa21a9ed output (hash order).'))
out.append(hexes('MK_RESERVED_514999', reserved.hex(), "Its coinbase's witness reserved value."))
out.append(hexes('MK_TX64', TX64, 'A transaction whose stripped size is 64 bytes, built here.'))
(HERE / 'merkle_vectors.coax').write_text(''.join(out))

big = ['// Generated by make_merkle_vectors.py from Bitcoin Core\'s\n'
       '// src/bench/data/block413567.raw, pinned in coax/tests/vectors/upstream/\n'
       '// bitcoin-core/ (see SOURCES.md there). Test data only.\n\n',
       hexes('MK_HEADER_413567', raw413567[:80].hex(), 'Block 413,567\'s 80-byte header.'),
       hexes('MK_HASH_413567', B413567, 'Its block hash, as explorers show it.'),
       hexes('MK_ROOT_413567', PUBLISHED_413567, 'Its published Merkle root, as explorers show it.'),
       'MK_COUNT_413567 :: 1557;\n',
       hexes('MK_LEAVES_413567', ''.join(t.hex() for t in txids413567),
             'Its 1,557 txids in hash order, the order the tree hashes them (computed by tx_reference.py).')]
(HERE / 'merkle_block413567.coax').write_text(''.join(big))
print('wrote merkle_vectors.coax and merkle_block413567.coax')
