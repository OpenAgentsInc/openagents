#!/usr/bin/env python3
# Firm reason: 2 (independent oracle: copies BIP-327's published vector files, pinned by hash, into Coax data)
"""Writes musig_vectors.coax for Bitcoin chapter 101 from BIP-327's vector
files, pinned in coax/tests/vectors/upstream/bip327/vectors/:

  python3 -I coax/tests/bitcoin/make_musig_vectors.py          # check the file
  python3 -I coax/tests/bitcoin/make_musig_vectors.py --write  # rewrite it

Each case is written with its inputs spelled out: the key, nonce, tweak
and partial-signature indices of the JSON become the concatenated hex of
the values they name, x-only flags become a string of 't' and 'f', and a
null becomes a flag beside an empty string. An error becomes musig.coax's
code and the signer it blames (-1 for none). Nothing is computed here:
musig.py checks every case against BIP-327's reference.py.
"""
import hashlib, json, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
VEC = HERE.parent / 'vectors'
UP = VEC / 'upstream' / 'bip327' / 'vectors'
OUT = HERE / 'musig_vectors.coax'

# musig.coax's codes for BIP-327's errors.
CONTRIB = {'pubkey': 1, 'pubnonce': 2, 'aggnonce': 3, 'aggothernonce': 4, 'psig': 5}
VALUE = {
    'The tweak must be less than n.': 6,
    'The result of tweaking cannot be infinity.': 7,
    'first secnonce value is out of range.': 8,
    'second secnonce value is out of range.': 9,
    'secret key value is out of range.': 10,
    'Public key does not match nonce_gen argument': 11,
    "The signer's pubkey must be included in the list of pubkeys.": 12,
}
MS_INVALID = 13


def load(name):
    b = (UP / f'{name}_vectors.json').read_bytes()
    m = json.loads((VEC / 'manifest.json').read_text())
    pin = next(e['sha256'] for e in m['files'] if e['path'] == f'upstream/bip327/vectors/{name}_vectors.json')
    assert hashlib.sha256(b).hexdigest() == pin, name
    return json.loads(b)


def h(x):
    return '' if x is None else x.lower()


def cat(values, indices):
    return ''.join(values[i].lower() for i in indices)


def flags(xs):
    return ''.join('t' if x else 'f' for x in xs)


def err(case):
    e = case['error']
    code = CONTRIB[e['contrib']] if e['type'] == 'invalid_contribution' else VALUE[e['message']]
    signer = e.get('signer')
    return code, -1 if signer is None else signer


def b(x):
    return 'true' if x else 'false'


def render():
    L = ['// Generated by make_musig_vectors.py from BIP-327\'s vector files',
         '// (coax/tests/vectors/upstream/bip327/vectors/, listed in SOURCES.md).',
         '// Indices are resolved: keys, nonces, tweaks and partial signatures are',
         '// the concatenated hex of the values the JSON names, x-only flags are',
         '// \'t\' and \'f\', and an error is musig.coax\'s code with the signer it',
         '// blames (-1 for none). Test data only.']

    s = load('key_sort')
    L.append(f'MS_SORT_KEYS :: "{cat(s["pubkeys"], range(len(s["pubkeys"])))}";')
    L.append(f'MS_SORT_SORTED :: "{cat(s["sorted_pubkeys"], range(len(s["sorted_pubkeys"])))}";')

    k = load('key_agg')
    rows = []
    for c in k['valid_test_cases']:
        rows.append(f'keys="{cat(k["pubkeys"], c["key_indices"])}", tweaks="", xonly="", expected="{h(c["expected"])}", code=0, signer=-1')
    for c in k['error_test_cases']:
        code, signer = err(c)
        rows.append(f'keys="{cat(k["pubkeys"], c["key_indices"])}", tweaks="{cat(k["tweaks"], c["tweak_indices"])}", '
                    f'xonly="{flags(c["is_xonly"])}", expected="", code={code}, signer={signer}')
    L.append('MsKeyAggCase :: struct { keys: string; tweaks: string; xonly: string; expected: string; code: int; signer: int; }')
    L.append(f'MS_KEY_AGG :: [{len(rows)}] MsKeyAggCase.[')
    L += [f'  MsKeyAggCase.{{{r}}},' for r in rows] + ['];']

    g = load('nonce_gen')
    rows = []
    for c in g['test_cases']:
        rows.append(f'rand="{h(c["rand_"])}", sk="{h(c["sk"])}", pk="{h(c["pk"])}", aggpk="{h(c["aggpk"])}", '
                    f'msg="{h(c["msg"])}", has_msg={b(c["msg"] is not None)}, extra="{h(c["extra_in"])}", '
                    f'secnonce="{h(c["expected_secnonce"])}", pubnonce="{h(c["expected_pubnonce"])}"')
    L.append('MsNonceGenCase :: struct { rand: string; sk: string; pk: string; aggpk: string; msg: string; has_msg: bool; extra: string; secnonce: string; pubnonce: string; }')
    L.append(f'MS_NONCE_GEN :: [{len(rows)}] MsNonceGenCase.[')
    L += [f'  MsNonceGenCase.{{{r}}},' for r in rows] + ['];']

    a = load('nonce_agg')
    rows = []
    for c in a['valid_test_cases']:
        rows.append(f'nonces="{cat(a["pnonces"], c["pnonce_indices"])}", expected="{h(c["expected"])}", code=0, signer=-1')
    for c in a['error_test_cases']:
        code, signer = err(c)
        rows.append(f'nonces="{cat(a["pnonces"], c["pnonce_indices"])}", expected="", code={code}, signer={signer}')
    L.append('MsNonceAggCase :: struct { nonces: string; expected: string; code: int; signer: int; }')
    L.append(f'MS_NONCE_AGG :: [{len(rows)}] MsNonceAggCase.[')
    L += [f'  MsNonceAggCase.{{{r}}},' for r in rows] + ['];']

    # Signing: sign_verify's valid and sign-error cases, then tweak's.
    sv = load('sign_verify')
    tw = load('tweak')
    sign, verify = [], []
    sk = h(sv['sk'])
    for c in sv['valid_test_cases']:
        common = (f'keys="{cat(sv["pubkeys"], c["key_indices"])}", nonces="{cat(sv["pnonces"], c["nonce_indices"])}", '
                  f'tweaks="", xonly="", msg="{h(sv["msgs"][c["msg_index"]])}", index={c["signer_index"]}')
        sign.append(f'sk="{sk}", secnonce="{h(sv["secnonces"][0])}", aggnonce="{h(sv["aggnonces"][c["aggnonce_index"]])}", '
                    f'{common}, expected="{h(c["expected"])}", code=0, signer=-1')
        verify.append(f'sig="{h(c["expected"])}", {common}, code=0, signer=-1')
    for c in sv['sign_error_test_cases']:
        code, signer = err(c)
        sign.append(f'sk="{sk}", secnonce="{h(sv["secnonces"][c["secnonce_index"]])}", aggnonce="{h(sv["aggnonces"][c["aggnonce_index"]])}", '
                    f'keys="{cat(sv["pubkeys"], c["key_indices"])}", nonces="", tweaks="", xonly="", '
                    f'msg="{h(sv["msgs"][c["msg_index"]])}", index={c.get("signer_index", -1)}, expected="", code={code}, signer={signer}')
    for c in sv['verify_fail_test_cases']:
        verify.append(f'sig="{h(c["sig"])}", keys="{cat(sv["pubkeys"], c["key_indices"])}", nonces="{cat(sv["pnonces"], c["nonce_indices"])}", '
                      f'tweaks="", xonly="", msg="{h(sv["msgs"][c["msg_index"]])}", index={c["signer_index"]}, code={MS_INVALID}, signer=-1')
    for c in sv['verify_error_test_cases']:
        code, signer = err(c)
        verify.append(f'sig="{h(c["sig"])}", keys="{cat(sv["pubkeys"], c["key_indices"])}", nonces="{cat(sv["pnonces"], c["nonce_indices"])}", '
                      f'tweaks="", xonly="", msg="{h(sv["msgs"][c["msg_index"]])}", index={c["signer_index"]}, code={code}, signer={signer}')
    for c in tw['valid_test_cases'] + tw['error_test_cases']:
        code, signer = err(c) if 'error' in c else (0, -1)
        expected = h(c.get('expected'))
        common = (f'keys="{cat(tw["pubkeys"], c["key_indices"])}", nonces="{cat(tw["pnonces"], c["nonce_indices"])}", '
                  f'tweaks="{cat(tw["tweaks"], c["tweak_indices"])}", xonly="{flags(c["is_xonly"])}", msg="{h(tw["msg"])}", index={c["signer_index"]}')
        sign.append(f'sk="{h(tw["sk"])}", secnonce="{h(tw["secnonce"])}", aggnonce="{h(tw["aggnonce"])}", {common}, '
                    f'expected="{expected}", code={code}, signer={signer}')
        if code == 0:
            verify.append(f'sig="{expected}", {common}, code=0, signer=-1')
    L.append('MsSignCase :: struct { sk: string; secnonce: string; aggnonce: string; keys: string; nonces: string; tweaks: string; xonly: string; msg: string; index: int; expected: string; code: int; signer: int; }')
    L.append(f'MS_SIGN :: [{len(sign)}] MsSignCase.[')
    L += [f'  MsSignCase.{{{r}}},' for r in sign] + ['];']
    L.append('MsVerifyCase :: struct { sig: string; keys: string; nonces: string; tweaks: string; xonly: string; msg: string; index: int; code: int; signer: int; }')
    L.append(f'MS_VERIFY :: [{len(verify)}] MsVerifyCase.[')
    L += [f'  MsVerifyCase.{{{r}}},' for r in verify] + ['];']

    d = load('det_sign')
    rows = []
    for c in d['valid_test_cases'] + d['error_test_cases']:
        code, signer = err(c) if 'error' in c else (0, -1)
        pubnonce, psig = (h(c['expected'][0]), h(c['expected'][1])) if code == 0 else ('', '')
        rows.append(f'sk="{h(d["sk"])}", rand="{h(c["rand"])}", has_rand={b(c["rand"] is not None)}, aggother="{h(c["aggothernonce"])}", '
                    f'keys="{cat(d["pubkeys"], c["key_indices"])}", tweaks="{"".join(h(t) for t in c["tweaks"])}", xonly="{flags(c["is_xonly"])}", '
                    f'msg="{h(d["msgs"][c["msg_index"]])}", index={c["signer_index"]}, pubnonce="{pubnonce}", psig="{psig}", code={code}, signer={signer}')
    L.append('MsDetCase :: struct { sk: string; rand: string; has_rand: bool; aggother: string; keys: string; tweaks: string; xonly: string; msg: string; index: int; pubnonce: string; psig: string; code: int; signer: int; }')
    L.append(f'MS_DET_SIGN :: [{len(rows)}] MsDetCase.[')
    L += [f'  MsDetCase.{{{r}}},' for r in rows] + ['];']

    a = load('sig_agg')
    rows = []
    for c in a['valid_test_cases'] + a['error_test_cases']:
        code, signer = err(c) if 'error' in c else (0, -1)
        aggnonce = h(c.get('aggnonce'))
        rows.append(f'aggnonce="{aggnonce}", nonces="{cat(a["pnonces"], c["nonce_indices"])}", keys="{cat(a["pubkeys"], c["key_indices"])}", '
                    f'tweaks="{cat(a["tweaks"], c["tweak_indices"])}", xonly="{flags(c["is_xonly"])}", psigs="{cat(a["psigs"], c["psig_indices"])}", '
                    f'msg="{h(a["msg"])}", expected="{h(c.get("expected"))}", code={code}, signer={signer}')
    L.append('MsSigAggCase :: struct { aggnonce: string; nonces: string; keys: string; tweaks: string; xonly: string; psigs: string; msg: string; expected: string; code: int; signer: int; }')
    L.append(f'MS_SIG_AGG :: [{len(rows)}] MsSigAggCase.[')
    L += [f'  MsSigAggCase.{{{r}}},' for r in rows] + ['];']
    return '\n'.join(L) + '\n'


if __name__ == '__main__':
    text = render()
    if '--write' in sys.argv:
        OUT.write_text(text)
    assert OUT.read_text() == text, 'musig_vectors.coax differs; run with --write'
