#!/usr/bin/env python3
# Firm reason: 2 (independent oracle: extracts published messages and serializes with Bitcoin Core's Python framework outside Coax)
"""Writes coax/tests/bitcoin/p2p_vectors.coax for Bitcoin chapter 65:

  python3 -I coax/tests/bitcoin/make_p2p_vectors.py

- P2P_SAMPLES: the annotated hexdumps of the Bitcoin developer reference
  (developer.bitcoin.org, reference/p2p_networking.rst, pinned in
  coax/tests/vectors/upstream/developer-bitcoin-org/): the verack message
  header and the getblocks, headers, inv, addr, addrv2, feefilter, ping and
  version payloads, joined from each dump's hex column. The addr and addrv2
  dumps show one of 1,000 addresses, so they are excerpts.
- P2P_ADDRV2: one addrv2 entry for each network messages.py knows, written
  by Bitcoin Core's own Python serializer (test_framework/messages.py,
  pinned) from the addresses of its test_addrv2_encode_decode.

Every pinned file's SHA-256 must equal its pin.
"""
import hashlib
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import core_messages  # noqa: E402

UP = HERE.parent / 'vectors/upstream'
OUT = HERE / 'p2p_vectors.coax'
RST = UP / 'developer-bitcoin-org/p2p_networking.rst'
RST_PIN = '6284673665cdf619238a828d1df15cffbe35f8ab1026583a280fb81a105ac379'
# The dumps, in the order they appear: the message the sentence before
# each one names, and the name the vectors use.
WANT = [('verack', 'verack header'), ('getblocks', 'getblocks'), ('headers', 'headers'),
        ('inv', 'inv'), ('addr', 'addr'), ('addrv2', 'addrv2'), ('feefilter', 'feefilter'),
        ('ping', 'ping'), ('version', 'version')]
# test_addrv2_encode_decode's addresses in messages.py, one per network.
ADDRV2 = [('1.65.195.98', 1), ('2001:41f0::62:6974:636f:696e', 2),
          ('2bqghnldu6mcug4pikzprwhtjjnsyederctvci6klcwzepnjd46ikjyd.onion', 4),
          ('255fhcp6ajvftnyo7bwz3an3t4a4brhopm3bamyh2iu5r3gnr2rq.b32.i2p', 5),
          ('fc32:17ea:e415:c3bf:9808:149d:b5a2:c9aa', 6)]


def samples():
    data = RST.read_bytes()
    assert hashlib.sha256(data).hexdigest() == RST_PIN, 'p2p_networking.rst differs from its pin'
    lines = data.decode().split('\n')
    found = []
    for i, line in enumerate(lines):
        if line.strip() != '::':
            continue
        before = ' '.join(lines[max(0, i - 8):i])
        names = re.findall(r'“(\w+)” message', before)
        hexes = []
        for row in lines[i + 1:]:
            if row.strip() and not row.startswith('   '):
                break
            words = row.split()
            if words and re.fullmatch(r'[0-9a-f]+', words[0]):
                hexes.append(words[0])
        if names and hexes:
            found.append((names[-1], ''.join(hexes)))
    out = []
    for message, name in WANT:
        match = [h for m, h in found if m == message]
        assert match, message
        out.append((name, match[0]))
    return out


def main():
    M = core_messages.load()
    rows = samples()
    entries = []
    for ip, net in ADDRV2:
        a = M.CAddress()
        a.time, a.nServices, a.net, a.ip, a.port = 1414012889, M.NODE_NETWORK | M.NODE_WITNESS, net, ip, 8333
        entries.append((ip, net, a.serialize_v2().hex()))
    text = [
        '// Generated by make_p2p_vectors.py from the Bitcoin developer reference\'s',
        '// annotated P2P hexdumps (developer.bitcoin.org reference/p2p_networking.rst)',
        '// and Bitcoin Core\'s test_framework/messages.py, both pinned in',
        '// coax/tests/vectors/upstream/ (see SOURCES.md there). Test data only.',
        '//',
        '// P2P_SAMPLES: the verack header and eight payloads, hex as published.',
        '// P2P_ADDRV2: an addrv2 entry per BIP-155 network that messages.py',
        '// writes, with time 1414012889, services NETWORK|WITNESS and port 8333.',
        'P2pSample :: struct { name: string; hex: string; }',
        f'P2P_SAMPLES :: [{len(rows)}] P2pSample.[',
    ]
    text += [f'  P2pSample.{{name="{n}", hex="{h}"}},' for n, h in rows]
    text += ['];', 'P2pAddrSample :: struct { text: string; net: int; hex: string; }',
             f'P2P_ADDRV2 :: [{len(entries)}] P2pAddrSample.[']
    text += [f'  P2pAddrSample.{{text="{t}", net={n}, hex="{h}"}},' for t, n, h in entries]
    text += ['];', '']
    OUT.write_text('\n'.join(text))
    print(f'wrote {OUT.name}: {len(rows)} samples, {len(entries)} addrv2 entries')


if __name__ == '__main__':
    main()
