#!/usr/bin/env python3
# Firm reason: 2 (independent oracle: copies a published file and its pin outside Coax)
"""Writes coax/tests/bitcoin/provenance_vectors.coax for Bitcoin chapter 116.

It copies one pinned file whole, BIP-340's test-vectors.csv
(coax/tests/vectors/upstream/bip340/), together with its manifest entry:
path, URL, revision, byte count and SHA-256. The example hashes the bytes
in Coax and compares them with the pin before it trusts a row.

  python3 -I coax/tests/bitcoin/make_provenance_vectors.py

The file's SHA-256 must equal its manifest entry, so a changed file refuses
instead of silently changing the example."""
import hashlib
import json
from pathlib import Path

VECTORS = Path(__file__).resolve().parents[1] / 'vectors'
PATH = 'upstream/bip340/test-vectors.csv'
CHUNK = 64


def entry():
    manifest = json.loads((VECTORS / 'manifest.json').read_text())
    return next(e for e in manifest['files'] if e['path'] == PATH)


def render():
    pin = entry()
    data = (VECTORS / PATH).read_bytes()
    if hashlib.sha256(data).hexdigest() != pin['sha256'] or len(data) != pin['bytes']:
        raise SystemExit('make_provenance_vectors.py: %s does not match its manifest entry' % PATH)
    chunks = [data[i:i + CHUNK].hex() for i in range(0, len(data), CHUNK)]
    out = ['// Generated by make_provenance_vectors.py from BIP-340\'s test-vectors.csv',
           '// (coax/tests/vectors/upstream/bip340/) and its entry in',
           '// coax/tests/vectors/manifest.json; see SOURCES.md. Test data only.',
           '// PV_HEX holds the file\'s bytes, %d per string, as lowercase hex.' % CHUNK,
           'PV_PATH :: "%s";' % pin['path'],
           'PV_URL :: "%s";' % pin['url'],
           'PV_REVISION :: "%s";' % pin['revision'],
           'PV_SHA256 :: "%s";' % pin['sha256'],
           'PV_BYTES :: %d;' % pin['bytes'],
           'PV_HEX :: [%d] string.[\n%s];' % (len(chunks), ',\n'.join('  "%s"' % c for c in chunks))]
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    Path(__file__).with_name('provenance_vectors.coax').write_text(render())
