#!/usr/bin/env python3
# Firm reason: 2 (independent oracle: copies the published PSBT cases and decides each with a Python transliteration of Bitcoin Core outside Coax)
"""Writes psbt_vectors.coax for Bitcoin chapter 94 from the pinned BIP-174,
BIP-370 and BIP-371 texts, Bitcoin Core's rpc_psbt.json and
tiny-secp256k1's ecdsa.json:

  python3 -I coax/tests/bitcoin/make_psbt_vectors.py          # check the file
  python3 -I coax/tests/bitcoin/make_psbt_vectors.py --write  # rewrite it

Each of the 155 distinct published PSBTs is decided by psbt_reference.py,
Core's reader in Python, and that verdict must be the published one: an
invalid case refuses, with Core's message where rpc_psbt.json gives one,
and every other case reads. The file holds each case's text and the code
Python found, the lock time BIP-370 publishes for its lock-time cases,
Core's signer, combiner, finalizer and extractor cases (each replayed in
Python first), BIP-174's worked example, and the five extraEntropy rows
of tiny-secp256k1, each signature recomputed by Python's RFC 6979.
"""
import hashlib, json, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import psbt_cases as PC  # noqa: E402
import psbt_reference as R  # noqa: E402
import der_reference as D  # noqa: E402

OUT = HERE / 'psbt_vectors.coax'
KINDS = {'invalid': 0, 'valid': 1, 'signer': 2, 'locktime': 3}
B58 = '123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz'


def wif(s):
    """A testnet WIF's key, its checksum checked."""
    n = 0
    for c in s: n = n * 58 + B58.index(c)
    b = n.to_bytes(38, 'big')
    assert b[0] == 0xef and b[33] == 1 and hashlib.sha256(hashlib.sha256(b[:-4]).digest()).digest()[:4] == b[-4:]
    return b[1:33]


def cases():
    out = []
    for kind, src, title, text in PC.all_cases():
        e = R.refusal_text(text)
        assert (e is not None) == (kind == 'invalid'), (src, title)
        if kind == 'invalid' and src.endswith('Core') and title: assert title in e.message(), (title, e.message())
        lt = 0
        if kind.startswith('locktime'):
            want = kind.split('=')[1]
            got = R.locktime(R.maps(R.unbase64(text)))
            assert got == (None if want == 'none' else int(want)), (title, got)
            lt = -1 if got is None else got
        code = e.code if e else 0
        where = e.where if e and e.where else (0, 0)
        out.append((KINDS[kind.split('=')[0]], src, text, code, where[0], where[1], lt))
    assert len(out) == 155
    return out


def signers(d):
    out = []
    for s in d['signer']:
        m = R.maps(R.unbase64(s['psbt']))
        keys = [wif(k) for k in s['privkeys']]
        for k in keys:
            for n in range(len(m['ins'])): R.sign(m, n, int.from_bytes(k, 'big'))
        assert R.write(m) == R.unbase64(s['result'])
        out.append((s['psbt'], b''.join(keys).hex(), s['result']))
    return out


def roles(d):
    for c in d['combiner']:
        a, b = (R.maps(R.unbase64(x)) for x in c['combine'])
        assert R.write(R.combine(a, b)) == R.write(R.combine(b, a)) == R.unbase64(c['result'])
    f = d['finalizer'][0]
    m = R.maps(R.unbase64(f['finalize'])); R.finalize(m)
    assert R.write(m) == R.unbase64(f['result'])
    x = d['extractor'][0]
    assert R.extract(R.maps(R.unbase64(x['extract']))).hex() == x['result']
    return [(c['combine'][0], c['combine'][1], c['result']) for c in d['combiner']], f, x


def entropy():
    data = json.loads(PC.pinned('tiny-secp256k1/ecdsa.json'))
    extras = [bytes(32), (1).to_bytes(32, 'big'), D.N.to_bytes(32, 'big'), b'\xff' * 32]
    out = []
    for row in data['extraEntropy']:
        d, m = int(row['d'], 16), bytes.fromhex(row['m'])
        sigs = []
        for e, name in zip(extras, ('0', '1', 'N', 'Max')):
            k = R.rfc6979(d, m, e)
            r = D.mul(k, D.G)[0] % D.N
            s = pow(k, -1, D.N) * (int.from_bytes(m, 'big') + r * d) % D.N
            s = min(s, D.N - s)
            assert (r.to_bytes(32, 'big') + s.to_bytes(32, 'big')).hex() == row['extraEntropy' + name]
            sigs.append(row['extraEntropy' + name])
        out.append((row['d'], row['m'], [e.hex() for e in extras], sigs))
    return out


def workflow(d):
    w = PC.bip174_workflow()
    assert R.unbase64(d['creator'][0]['result']).hex() == w['results'][0]
    keys = [(wif(k), p) for s in w['signers'] for k, p in s]
    for k, p in keys:
        assert any(p == q for _, q in w['paths'])
    return w, keys


def q(s):
    return '"' + s + '"'


def render():
    _, d = PC.core_cases()
    lines = ['// Generated by make_psbt_vectors.py from the pinned BIP-174, BIP-370 and',
             '// BIP-371 texts, Bitcoin Core\'s rpc_psbt.json and tiny-secp256k1\'s',
             '// ecdsa.json (coax/tests/vectors/upstream/, listed in SOURCES.md).',
             '// Published values, copied; each code is psbt_reference.py\'s verdict,',
             '// which agrees with the published one. Test keys only.',
             'PSBT_CASE_INVALID :: 0; PSBT_CASE_VALID :: 1; PSBT_CASE_SIGNER :: 2; PSBT_CASE_LOCKTIME :: 3;',
             '// A published PSBT (Base64): its kind, where it is published, the code',
             '// it reads with (and, for a key of the wrong size, the map and type),',
             '// and BIP-370\'s lock time for a lock-time case (-1: none).',
             'PsbtCase :: struct { kind: int; source: string; text: string; code: int; map: int; type: int; locktime: int; }']
    cs = cases()
    lines.append(f'PSBT_CASES :: [{len(cs)}] PsbtCase.[')
    for kind, src, text, code, mp, ty, lt in cs:
        lines.append(f'  PsbtCase.{{kind={kind}, source={q(src)}, text={q(text)}, code={code}, map={mp}, type={ty}, locktime={lt}}},')
    lines.append('];')
    lines.append('// Core\'s signer cases: a PSBT, the keys that sign it (32 bytes each) and the result.')
    lines.append('PsbtCoreSigner :: struct { psbt: string; keys: string; result: string; }')
    sg = signers(d)
    lines.append(f'PSBT_CORE_SIGNERS :: [{len(sg)}] PsbtCoreSigner.[')
    for a, b, c in sg: lines.append(f'  PsbtCoreSigner.{{psbt={q(a)}, keys={q(b)}, result={q(c)}}},')
    lines.append('];')
    cb, f, x = roles(d)
    lines.append('// Core\'s combiner cases (either order), finalizer case and extractor case.')
    lines.append('PsbtCoreCombiner :: struct { a: string; b: string; result: string; }')
    lines.append(f'PSBT_CORE_COMBINERS :: [{len(cb)}] PsbtCoreCombiner.[')
    for a, b, c in cb: lines.append(f'  PsbtCoreCombiner.{{a={q(a)}, b={q(b)}, result={q(c)}}},')
    lines.append('];')
    lines.append(f'PSBT_CORE_FINALIZE :: {q(f["finalize"])};')
    lines.append(f'PSBT_CORE_FINALIZED :: {q(f["result"])};')
    lines.append(f'PSBT_CORE_EXTRACT :: {q(x["extract"])};')
    lines.append(f'PSBT_CORE_EXTRACTED :: {q(x["result"])};')
    lines.append('// tiny-secp256k1\'s extraEntropy rows: a key, a hash, four extra data')
    lines.append('// (0, 1, n and 2^256 - 1) and the signature with each.')
    lines.append('PsbtEntropy :: struct { d: string; m: string; data: [4] string; sig: [4] string; }')
    en = entropy()
    lines.append(f'PSBT_EXTRA_ENTROPY :: [{len(en)}] PsbtEntropy.[')
    for dd, m, data, sigs in en:
        lines.append(f'  PsbtEntropy.{{d={q(dd)}, m={q(m)}, data=[4] string.[{", ".join(map(q, data))}], sig=[4] string.[{", ".join(map(q, sigs))}]}},')
    lines.append('];')
    w, keys = workflow(d)
    lines.append('// BIP-174\'s worked example: the master key, the creator\'s outputs')
    lines.append('// (script, satoshis) and inputs (txid, index), the updater\'s scripts,')
    lines.append('// previous transactions and key paths, each signer\'s keys (from their')
    lines.append('// WIFs, with their paths) and every published result, in order.')
    lines.append(f'PSBT_BIP174_TPRV :: {q(w["tprv"])};')
    lines.append('PsbtOutput :: struct { script: string; amount: int; }')
    lines.append('PsbtInput :: struct { txid: string; index: int; }')
    lines.append('PsbtPath :: struct { key: string; path: [3] int; }')
    lines.append('PSBT_BIP174_OUTPUTS :: [2] PsbtOutput.[' + ', '.join(
        f'PsbtOutput.{{script={q(s)}, amount={round(float(a) * 1e8)}}}' for s, a in w['outputs']) + '];')
    lines.append('PSBT_BIP174_INPUTS :: [2] PsbtInput.[' + ', '.join(
        f'PsbtInput.{{txid={q(t)}, index={i}}}' for t, i in w['inputs']) + '];')
    lines.append(f'PSBT_BIP174_REDEEM :: [{len(w["redeem"])}] string.[{", ".join(map(q, w["redeem"]))}];')
    lines.append(f'PSBT_BIP174_WITNESS :: [{len(w["witness"])}] string.[{", ".join(map(q, w["witness"]))}];')
    lines.append(f'PSBT_BIP174_PREV :: [{len(w["prev"])}] string.[{", ".join(map(q, w["prev"]))}];')
    path = lambda p: '[3] int.[' + ', '.join(x[:-1] for x in p.split('/')[1:]) + ']'
    lines.append(f'PSBT_BIP174_PATHS :: [{len(w["paths"])}] PsbtPath.[' + ', '.join(
        f'PsbtPath.{{key={q(k)}, path={path(p)}}}' for k, p in w['paths']) + '];')
    lines.append('PsbtKey :: struct { key: string; path: [3] int; }')
    lines.append(f'PSBT_BIP174_SIGNERS :: [{len(keys)}] PsbtKey.[' + ', '.join(
        f'PsbtKey.{{key={q(k.hex())}, path={path(p)}}}' for k, p in keys) + '];')
    lines.append(f'PSBT_BIP174_RESULTS :: [{len(w["results"])}] string.[')
    for h in w['results']: lines.append(f'  {q(h)},')
    lines.append('];')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    text = render()
    if '--write' in sys.argv:
        OUT.write_text(text)
    assert OUT.read_text() == text, 'psbt_vectors.coax differs; run with --write'
    print(f'psbt vectors: {text.count("PsbtCase.{")} cases agree with their published verdicts')
