#!/usr/bin/env python3
# Firm reason: 2 (independent oracle: copies published vectors outside Coax)
"""Writes coax/tests/bitcoin/sha256d_vectors.coax for Bitcoin chapter 5 from
files pinned in coax/tests/vectors/upstream/:

  python3 -I coax/tests/bitcoin/make_sha256d_vectors.py

- btcd's chaincfg/genesis_test.go: the serialized mainnet genesis block;
- Bitcoin Core's src/kernel/chainparams.cpp: its block hash and Merkle root;
- Bitcoin Core's src/test/data/tx_valid.json: mainnet transactions whose
  comment names their txid;
- BIP-341's wallet-test-vectors.json: leaf hashes, Merkle roots, tweaks and
  signature hashes;
- BIP-340's test-vectors.csv: row 0.

Every input's SHA-256 must equal its pin below, so a changed file refuses
instead of silently changing the checks. Nothing here hashes anything: every
value is copied."""
import csv, hashlib, json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / 'vectors' / 'upstream'
PINS = {
    'btcd/genesis_test.go': 'e188c4fb27cccec22a0853be80f5c9b308e88045baccbf81a2058b01c7155452',
    'bitcoin-core/chainparams.cpp': 'cfadf1478377c32625280520655b598674e6d487f08d7f7a80ac69252104b5e1',
    'bitcoin-core/tx_valid.json': '0abeb1a6e4b942e4e43ef8d49b7356c1f6204bcb14163f24153f4d0ec5418011',
    'bip341/wallet-test-vectors.json': '403e19fb81dd1f31e745699216308f61fb403774b2aafa87b631b8f7c042d37f',
    'bip340/test-vectors.csv': '34c9d1d9c3a88d524bc80778540dc43f8306ec249a7485293063c376db851c2d',
}
src = {}
for name, pin in PINS.items():
    data = (ROOT / name).read_bytes()
    assert hashlib.sha256(data).hexdigest() == pin, name
    src[name] = data.decode()

# The genesis block: the Go byte literal, comments removed.
go = re.search(r'var genesisBlockBytes = \[\]byte\{(.*?)\n\}', src['btcd/genesis_test.go'], re.S).group(1)
genesis = ''.join(re.findall(r'0x([0-9a-f]{2})', re.sub(r'/\*.*?\*/', '', go)))
assert len(genesis) == 285 * 2
main = src['bitcoin-core/chainparams.cpp']
main = main[main.index('class CMainParams'):main.index('class CTestNetParams')]
block_hash = re.search(r'hashGenesisBlock == uint256\{"([0-9a-f]{64})"\}', main).group(1)
merkle = re.search(r'hashMerkleRoot == uint256\{"([0-9a-f]{64})"\}', main).group(1)

# Mainnet transactions: a comment "The following is <txid>" (not "a tweaked
# form of", not "on testnet3") followed by the transaction's row.
txs = []
named = None
for row in json.loads(src['bitcoin-core/tx_valid.json']):
    if len(row) == 1:
        m = re.fullmatch(r'The following is ([0-9a-f]{64})', row[0])
        if m: named = m.group(1)
        continue
    if named:
        txs.append((named, row[1]))
        named = None
assert [t[0][:8] for t in txs] == ['23b397ed', 'c99c49da', 'f7fdd091']

# BIP-341 script trees, in the three shapes the file uses.
wallet = json.loads(src['bip341/wallet-test-vectors.json'])
def shape(t):
    if t is None: return 0, []
    if isinstance(t, dict): return 1, [t]
    if isinstance(t[0], dict) and isinstance(t[1], dict): return 2, t
    assert isinstance(t[0], dict) and isinstance(t[1], list) and all(isinstance(x, dict) for x in t[1])
    return 3, [t[0]] + t[1]
trees, leaves = [], []
for spk in wallet['scriptPubKey']:
    g, im = spk['given'], spk['intermediary']
    kind, ls = shape(g['scriptTree'])
    assert len(ls) == len(im.get('leafHashes', []))
    trees.append((g['internalPubkey'], kind, len(leaves), len(ls), im['merkleRoot'] or '', im['tweak']))
    for leaf, h in zip(ls, im.get('leafHashes', [])):
        leaves.append((leaf['leafVersion'], leaf['script'], h))
sigs = [(i['intermediary']['sigMsg'], i['intermediary']['sigHash']) for i in wallet['keyPathSpending'][0]['inputSpending']]

row0 = next(csv.DictReader(src['bip340/test-vectors.csv'].splitlines()))
assert row0['index'] == '0' and row0['verification result'] == 'TRUE'

out = ['// Generated by make_sha256d_vectors.py from the files pinned in',
       '// coax/tests/vectors/upstream/ (see SOURCES.md there). Published values,',
       '// copied, not computed. Test data only.', '',
       '// btcd chaincfg/genesis_test.go: the 285-byte mainnet genesis block.',
       'BH_GENESIS_BLOCK :: "%s";' % genesis,
       '// Bitcoin Core src/kernel/chainparams.cpp, CMainParams.',
       'BH_GENESIS_HASH :: "%s";' % block_hash,
       'BH_GENESIS_MERKLE :: "%s";' % merkle,
       '// Bitcoin Core src/test/data/tx_valid.json: "The following is <txid>".',
       'BhTx :: struct {txid:string;tx:string;}',
       'BH_TXS :: [%d] BhTx.[\n%s];' % (len(txs), ',\n'.join('  BhTx.{txid="%s",tx="%s"}' % t for t in txs)),
       '// BIP-341 wallet-test-vectors.json, scriptPubKey: shape 0 is no tree, 1 one',
       '// leaf, 2 two leaves [a, b], 3 three leaves [a, [b, c]]. A tree\'s leaves',
       '// are BH_LEAVES[first..<first+count].',
       'BhTree :: struct {internal:string;shape:int;first:int;count:int;merkle:string;tweak:string;}',
       'BH_TREES :: [%d] BhTree.[\n%s];' % (len(trees), ',\n'.join('  BhTree.{internal="%s",shape=%d,first=%d,count=%d,merkle="%s",tweak="%s"}' % t for t in trees)),
       'BhLeaf :: struct {version:int;script:string;hash:string;}',
       'BH_LEAVES :: [%d] BhLeaf.[\n%s];' % (len(leaves), ',\n'.join('  BhLeaf.{version=%d,script="%s",hash="%s"}' % l for l in leaves)),
       '// BIP-341 wallet-test-vectors.json, keyPathSpending: sigMsg and sigHash.',
       'BhSig :: struct {msg:string;hash:string;}',
       'BH_SIGS :: [%d] BhSig.[\n%s];' % (len(sigs), ',\n'.join('  BhSig.{msg="%s",hash="%s"}' % s for s in sigs)),
       '// BIP-340 test-vectors.csv, row 0.',
       'BH_BIP340_KEY :: "%s";' % row0['public key'].lower(),
       'BH_BIP340_MESSAGE :: "%s";' % row0['message'].lower(),
       'BH_BIP340_SIGNATURE :: "%s";' % row0['signature'].lower()]
Path(__file__).with_name('sha256d_vectors.coax').write_text('\n'.join(out) + '\n')
