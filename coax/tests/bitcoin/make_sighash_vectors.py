#!/usr/bin/env python3
# Firm reason: 2 (independent oracle: copies published vectors outside Coax)
"""Writes coax/tests/bitcoin/sighash_vectors.coax from the published BIP-143
examples and BIP-341 wallet test vectors.

  python3 -I coax/tests/bitcoin/make_sighash_vectors.py BIP143.mediawiki BIP341.json

The inputs are bitcoin/bips master's bip-0143.mediawiki and
bip-0341/wallet-test-vectors.json; their SHA-256 must equal the pins below,
so a changed upstream file refuses instead of silently changing the checks.
Nothing here computes a sighash or a signature: every value is copied."""
import hashlib,json,re,sys
from pathlib import Path
PIN143='62bc71351563e68baeb12643c68355d217953ae9eb6a6e68b2b0323275b6beec'
PIN341='403e19fb81dd1f31e745699216308f61fb403774b2aafa87b631b8f7c042d37f'
src143=Path(sys.argv[1]).read_bytes();src341=Path(sys.argv[2]).read_bytes()
assert hashlib.sha256(src143).hexdigest()==PIN143 and hashlib.sha256(src341).hexdigest()==PIN341
text=src143.decode()
def section(name):
    a=text.index('=== %s ==='%name);b=text.index('\n===',a+5) if '\n===' in text[a+5:] else len(text)
    return text[a:b]
def field(s,label):
    m=re.search(re.escape(label)+r'\s*:?\s*([0-9a-f]+)',s);return m.group(1)
out=['// Generated by make_sighash_vectors.py from bitcoin/bips: bip-0143.mediawiki',
     '// (sha256 %s) and bip-0341/wallet-test-vectors.json (sha256 %s).'%(PIN143,PIN341),
     '// Published values, copied, not computed. Test data only.','',
     'BtVec143 :: struct {tx:string;index:int;code:string;amount:int;hashtype:int;sighash:string;key:string;sig:string;}']
vec=[]
s=section('Native P2WPKH')
# The second input (index 1) is the P2WPKH one; its key is the section's second.
keys=re.findall(r'private key\s*:\s*([0-9a-f]+)',s)
vec.append((re.search(r'unsigned transaction:\s*([0-9a-f]+)',s).group(1),1,field(s,'scriptCode:'),600000000,1,field(s,'sigHash:'),keys[1],field(s,'signature:')))
s=section('P2SH-P2WPKH')
vec.append((re.search(r'unsigned transaction:\s*([0-9a-f]+)',s).group(1),0,field(s,'scriptCode:'),1000000000,1,field(s,'sigHash:'),field(s,'private key  :'),field(s,'signature:')))
s=section('P2SH-P2WSH')
tx=re.search(r'unsigned transaction:\s*([0-9a-f]+)',s).group(1);ws=field(s,'witnessScript:')
code='fd'+(len(ws)//2).to_bytes(2,'little').hex()+ws if len(ws)//2>=0xfd else '%02x'%(len(ws)//2)+ws
for ht,blk in zip([1,2,3,0x81,0x82,0x83],re.split(r'hash preimage for ',s)[1:]):
    assert ('nHashType:    %02x000000'%ht) in blk or ('nHashType:     %02x000000'%ht) in blk
    vec.append((tx,0,code,987654321,ht,field(blk,'sigHash:'),field(blk,'private key:'),field(blk,'signature:')))
for v in vec: assert int(v[7][-2:],16)==v[4]   # the DER signature ends in its hash type
out.append('BT_V143 :: [%d] BtVec143.['%len(vec))
out.append(',\n'.join('  BtVec143.{tx="%s",index=%d,code="%s",amount=%d,hashtype=%d,sighash="%s",key="%s",sig="%s"}'%(t,i,c,a,h,sh,k,sg[:-2]) for t,i,c,a,h,sh,k,sg in vec))
out.append('];')
d=json.loads(src341)['keyPathSpending'][0]
g=d['given']
out.append('BT_V341_TX :: "%s";'%g['rawUnsignedTx'])
out.append('BT_V341_SPK :: [%d] string.[%s];'%(len(g['utxosSpent']),','.join('"%s"'%u['scriptPubKey'] for u in g['utxosSpent'])))
out.append('BT_V341_AMOUNT :: [%d] int.[%s];'%(len(g['utxosSpent']),','.join(str(u['amountSats']) for u in g['utxosSpent'])))
out.append('BtVec341 :: struct {index:int;key:string;merkle:string;hashtype:int;internal:string;tweak:string;tweaked:string;sighash:string;witness:string;}')
rows=[]
for i in d['inputSpending']:
    gi,im=i['given'],i['intermediary']
    rows.append('  BtVec341.{index=%d,key="%s",merkle="%s",hashtype=%d,internal="%s",tweak="%s",tweaked="%s",sighash="%s",witness="%s"}'%(
        gi['txinIndex'],gi['internalPrivkey'],gi['merkleRoot'] or '',gi['hashType'],im['internalPubkey'],im['tweak'],im['tweakedPrivkey'],im['sigHash'],i['expected']['witness'][0]))
out.append('BT_V341 :: [%d] BtVec341.[\n%s\n];'%(len(rows),',\n'.join(rows)))
out.append('BT_V341_HASHES :: [5] string.["%s","%s","%s","%s","%s"];   // prevouts, amounts, scriptPubKeys, sequences, outputs'%tuple(d['intermediary'][k] for k in ['hashPrevouts','hashAmounts','hashScriptPubkeys','hashSequences','hashOutputs']))
Path(__file__).with_name('sighash_vectors.coax').write_text('\n'.join(out)+'\n')
