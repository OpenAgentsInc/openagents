#!/usr/bin/env python3
# Firm reason: 2 (independent oracle: copies the outputs a pinned mainnet block spends, as mempool.space publishes them, and checks them against the block outside Coax)
"""Writes sigops_vectors.coax for Bitcoin chapter 53 from files pinned in
coax/tests/vectors/upstream/mainnet/:

  python3 -I coax/tests/bitcoin/make_sigops_vectors.py          # check the file
  python3 -I coax/tests/bitcoin/make_sigops_vectors.py --write  # rewrite it

Mainnet block 514,999 (chapter 46 pinned its bytes) spends 20 outputs.
The .spent.json file beside it holds, for each of its 19 transactions,
mempool.space's record of the value and scriptPubKey of every output it
spends, the fee and the sigop cost mempool.space reports. Signature
operations under P2SH and segwit, and the fee, need those spent outputs;
they are not in the block.

The spent outputs come from a third party, so this script checks what it
can against the block itself: every P2SH output's hash is HASH160 of the
redeem script its input pushes last, every P2WPKH output's program is
HASH160 of the key its witness ends with, and every P2PKH output's hash
is HASH160 of the key its scriptSig ends with. The fees must add up to
the coinbase's claim above the 12.5 BTC subsidy.
"""
import hashlib, json, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import tx_reference as T  # noqa: E402
import merkle_reference as M  # noqa: E402
from script_reference import ripemd160  # noqa: E402

UP = HERE.parent / 'vectors' / 'upstream' / 'mainnet'
BLOCK = '00000000000000000008fda0e5bb3105dab72605332085684c42dceb0ea61097'
PINS = {
    f'{BLOCK}.raw': '7c0d1862284dcd240a63b5bcb75e956c3645ed5d7453799abb721ce06e6b2902',
    f'{BLOCK}.spent.json': 'f65a8fa8f6284871947a4a45838a93c20b7254816204f7c670c1db3034ae2e09',
}
OUT = HERE / 'sigops_vectors.coax'


def load(name):
    data = (UP / name).read_bytes()
    assert hashlib.sha256(data).hexdigest() == PINS[name], name
    return data


def hash160(b):
    return ripemd160(hashlib.sha256(b).digest())


def last_push(script):
    pc, data = 0, b''
    while pc < len(script):
        op = script[pc]; pc += 1
        if op == 0 or op > 0x4e:
            data = b''
            continue
        width = {0x4c: 1, 0x4d: 2, 0x4e: 4}.get(op, 0)
        n = op if width == 0 else int.from_bytes(script[pc:pc + width], 'little')
        pc += width
        data = script[pc:pc + n]; pc += n
    return data


def checked():
    raw = load(f'{BLOCK}.raw')
    txs = M.block_txs(raw)
    spent = json.loads(load(f'{BLOCK}.spent.json'))
    assert len(spent) == len(txs) == 19
    rows, fees = [], 0
    for k, (tx, rec) in enumerate(zip(txs, spent)):
        assert T.txid(tx)[::-1].hex() == rec['txid']
        if k == 0:
            assert rec['spent'] == [None]
            continue
        value_in = 0
        for i, s in zip(tx['ins'], rec['spent']):
            spk = bytes.fromhex(s['scriptpubkey'])
            if len(spk) == 23 and spk[0] == 0xa9:          # P2SH
                assert hash160(last_push(i['script'])) == spk[2:22]
            elif len(spk) == 22 and spk[:2] == b'\x00\x14':  # P2WPKH
                assert hash160(i['witness'][-1]) == spk[2:]
            elif len(spk) == 25 and spk[:3] == b'\x76\xa9\x14':  # P2PKH
                assert hash160(last_push(i['script'])) == spk[3:23]
            else:
                raise AssertionError(spk.hex())
            rows.append((k, s['value'], s['scriptpubkey']))
            value_in += s['value']
        value_out = sum(int.from_bytes(o['value'], 'little') for o in tx['outs'])
        assert value_in - value_out == rec['fee'], k
        fees += rec['fee']
    claimed = sum(int.from_bytes(o['value'], 'little') for o in txs[0]['outs'])
    assert claimed == 1250000000 + fees, (claimed, fees)
    return rows, [r['sigops'] for r in spent], [r['fee'] for r in spent]


def render():
    rows, sigops, fees = checked()
    lines = ['// Generated by make_sigops_vectors.py from the outputs mainnet block 514,999',
             '// spends, as mempool.space published them (coax/tests/vectors/upstream/',
             '// mainnet/, listed in SOURCES.md). One row per input that is not the',
             '// coinbase, in block order: the transaction it belongs to, the value and',
             '// the scriptPubKey of the output it spends. Then mempool.space\'s sigop cost',
             '// and fee of each transaction. Test data only.',
             'SigopSpentHex :: struct { tx: int; value: int; spk: string; }',
             f'SIGOPS_SPENT_514999 :: [{len(rows)}] SigopSpentHex.[']
    for k, value, spk in rows:
        lines.append(f'  SigopSpentHex.{{tx={k}, value={value}, spk="{spk}"}},')
    lines.append('];')
    lines.append(f'SIGOPS_MEMPOOL_514999 :: [{len(sigops)}] int.[{", ".join(map(str, sigops))}];')
    lines.append(f'SIGOPS_FEES_514999 :: [{len(fees)}] int.[{", ".join(map(str, fees))}];')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    text = render()
    if '--write' in sys.argv:
        OUT.write_text(text)
    assert OUT.read_text() == text, 'sigops_vectors.coax differs; run with --write'
    print(f'sigops vectors: {text.count("SigopSpentHex.{")} spent outputs agree with block 514,999')
