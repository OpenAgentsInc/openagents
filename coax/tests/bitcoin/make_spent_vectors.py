#!/usr/bin/env python3
# Firm reason: 2 (independent oracle: copies published values outside Coax)
"""Writes coax/tests/bitcoin/spent_vectors.coax for Bitcoin chapters 35
and 40 from the mempool.space JSON pinned in
coax/tests/vectors/upstream/mainnet/ (see SOURCES.md there):

  python3 -I coax/tests/bitcoin/make_spent_vectors.py

For each of chapter 34's three segwit mainnet transactions, in
TX_MAINNET order (3, 4, 5): the value and scriptPubKey of each coin it
spends, and the fee and sigop cost mempool.space publishes. Each JSON's
SHA-256 must equal its pin below, and the published fee must equal the
inputs minus the outputs the JSON lists.
"""
import hashlib, json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent / 'vectors' / 'upstream' / 'mainnet'
PINS = [
    ('f5864806e3565c34d1b41e716f72609d00b55ea5eac5b924c9719a842ef42206', '66d8bb646ababf838e207b78a0c6878c0d136709ea768b71d5ef78dc2a642f51'),
    ('33e794d097969002ee05d336686fc03c9e15a597c1b9827669460fac98799036', '49f1314013f8bffd9c13f8a45d54983a5f9b317c96d4b8dba1330e11a353a63b'),
    ('37777defed8717c581b4c0509329550e344bdc14ac38f71fc050096887e535c8', '8a9d44ab04ac3e4cf22472446690fcc5fad2b69ef9fb2d8711809338c51270b1'),
]

rows = []
for txid, pin in PINS:
    data = (ROOT / f'{txid}.json').read_bytes()
    assert hashlib.sha256(data).hexdigest() == pin, txid
    d = json.loads(data)
    assert d['txid'] == txid
    values = [i['prevout']['value'] for i in d['vin']]
    scripts = [i['prevout']['scriptpubkey'] for i in d['vin']]
    assert d['fee'] == sum(values) - sum(o['value'] for o in d['vout'])
    pad = 2 - len(values)
    rows.append((txid, len(values), values + [0] * pad, scripts + [''] * pad, d['fee'], d['sigops']))

out = ['// Generated by make_spent_vectors.py from the mempool.space JSON pinned in',
       '// coax/tests/vectors/upstream/mainnet/ (see SOURCES.md there). Test data only.',
       '',
       '// The coins each segwit mainnet transaction of TX_MAINNET[3..6] spends:',
       "// their values in satoshis and scriptPubKeys; and the transaction's fee",
       '// and sigop cost as mempool.space publishes them.',
       'TxSpent :: struct { txid: string; nin: int; values: [2] int; scripts: [2] string; fee: int; sigops: int; }',
       f'TX_SPENT :: [{len(rows)}] TxSpent.[']
for k, (txid, nin, values, scripts, fee, sigops) in enumerate(rows):
    end = '];' if k == len(rows) - 1 else ','
    out.append(f'  TxSpent.{{txid="{txid}", nin={nin}, values=[2] int.[{values[0]}, {values[1]}], '
               f'scripts=[2] string.["{scripts[0]}", "{scripts[1]}"], fee={fee}, sigops={sigops}}}{end}')
(HERE / 'spent_vectors.coax').write_text('\n'.join(out) + '\n')
print(f'spent_vectors.coax: {len(rows)} transactions')
