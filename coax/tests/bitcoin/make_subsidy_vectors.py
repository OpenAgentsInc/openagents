#!/usr/bin/env python3
# Firm reason: 2 (independent oracle: copies published mainnet headers and coinbases and proves each coinbase in its header outside Coax)
"""Writes subsidy_vectors.coax for Bitcoin chapter 54 from
coax/tests/vectors/upstream/mainnet/coinbase-proofs.json:

  python3 -I coax/tests/bitcoin/make_subsidy_vectors.py          # check the file
  python3 -I coax/tests/bitcoin/make_subsidy_vectors.py --write  # rewrite it

The JSON holds 14 mainnet blocks as mempool.space serves them: the four
blocks of the duplicate coinbases (91,722, 91,812, 91,842 and 91,880),
the blocks on both sides of BIP-34's activation (227,930 and 227,931) and
of each halving so far (209,999 to 840,000). For each: the height and
block hash, the 80-byte header, the coinbase, the Merkle branch from the
coinbase to the header's root, the transaction count, and the block's
fees and reward as mempool.space reports them.

This script checks each header against its hash, each coinbase against
its header's root by the branch (computed when the file was fetched
from the block's full txid list), the BIP-34 height in every coinbase
from 227,931, and that each coinbase claims mempool.space's reward. The
fees are mempool.space's: the chapter states them as published.
"""
import hashlib, json, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import tx_reference as T  # noqa: E402
import merkle_reference as M  # noqa: E402

UP = HERE.parent / 'vectors' / 'upstream' / 'mainnet'
PIN = '3a10ff94f45a2fbef360731be48c468ec7c2ecc3da760fb2861b97721aeb5efb'
OUT = HERE / 'subsidy_vectors.coax'


def rows():
    data = (UP / 'coinbase-proofs.json').read_bytes()
    assert hashlib.sha256(data).hexdigest() == PIN
    out = []
    for r in json.loads(data):
        header = bytes.fromhex(r['header'])
        assert len(header) == 80 and M.sha256d(header)[::-1].hex() == r['hash']
        cb = T.unserialize(bytes.fromhex(r['coinbase']), True)
        assert T.is_coinbase(cb)
        branch = [bytes.fromhex(h) for h in r['branch']]
        assert M.root_from_branch(T.txid(cb), branch, 0) == header[36:68]
        assert len(branch) == M.depth(r['tx_count'])
        claim = sum(int.from_bytes(o['value'], 'little') for o in cb['outs'])
        assert claim == r['reward'], r['height']
        if r['height'] >= 227931:
            s = cb['ins'][0]['script']
            assert s[0] == 3 and int.from_bytes(s[1:4], 'little') == r['height']
        out.append(r)
    by = {r['height']: r for r in out}
    for h in (210000, 227931, 420000, 630000, 840000):
        assert bytes.fromhex(by[h]['header'])[4:36][::-1].hex() == by[h - 1]['hash']
    return out


def render():
    lines = ['// Generated by make_subsidy_vectors.py from coinbase-proofs.json, mempool.space\'s',
             '// headers and coinbases of 14 mainnet blocks (coax/tests/vectors/upstream/',
             '// mainnet/, listed in SOURCES.md). Each block\'s height and hash, header,',
             '// coinbase, the Merkle branch from the coinbase to the header\'s root (hash',
             '// order, 32 bytes a step), the transaction count, and mempool.space\'s fees.',
             '// Test data only.',
             'CoinbaseProof :: struct { height: int; hash: string; header: string; coinbase: string; branch: string; count: int; fees: int; }',
             f'SUBSIDY_PROOFS :: [{len(rows())}] CoinbaseProof.[']
    for r in rows():
        lines.append(f'  CoinbaseProof.{{height={r["height"]}, hash="{r["hash"]}", header="{r["header"]}", coinbase="{r["coinbase"]}", '
                     f'branch="{"".join(r["branch"])}", count={r["tx_count"]}, fees={r["fees"]}}},')
    lines.append('];')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    text = render()
    if '--write' in sys.argv:
        OUT.write_text(text)
    assert OUT.read_text() == text, 'subsidy_vectors.coax differs; run with --write'
    print(f'subsidy vectors: {text.count("CoinbaseProof.{")} coinbases proved in their headers')
