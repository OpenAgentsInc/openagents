#!/usr/bin/env python3
# Firm reason: 2 (independent oracle: Bitcoin Core's own Python computes the values outside Coax)
"""Writes coax/tests/bitcoin/taproot_sighash_vectors.coax: BIP-341
signature messages with an annex or BIP-342's script-path extension, for
Bitcoin chapter 43.

  python3 -I coax/tests/bitcoin/make_taproot_sighash_vectors.py

BIP-341's wallet test vectors publish only key-path messages with no annex.
These cases are computed by Bitcoin Core's TaprootSignatureMsg
(test_framework/script.py, pinned), which taproot_reference.py runs as
written after checking that it gives BIP-341's seven published messages.
They are generated values: the transaction and spent outputs are
BIP-341's, the annexes, scripts and codesep positions are chosen here."""
from pathlib import Path
import sys

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import taproot_reference as T  # noqa: E402

T.check_core()
LEAF = bytes.fromhex(T.VECTORS["scriptPubKey"][1]["given"]["scriptTree"]["script"])
SHORT = bytes.fromhex("50")
ANNEX = bytes.fromhex("50") + bytes(range(1, 32))
LONG = bytes.fromhex("50") + bytes((7 * k) & 255 for k in range(299))   # 300 bytes: a 3-byte CompactSize
HASH_TYPES = (0, 1, 2, 3, 0x81, 0x82, 0x83)

cases = []
for ht in HASH_TYPES:
    cases.append((1, ht, SHORT, None, 0xffffffff))      # key path, an annex of the tag alone
    cases.append((1, ht, None, LEAF, 0xffffffff))       # script path, no OP_CODESEPARATOR run
    cases.append((1, ht, ANNEX, LEAF, 0xffffffff))      # script path with an annex
    cases.append((1, ht, None, LEAF, 7))                # an OP_CODESEPARATOR at position 7
cases.append((3, 0, LONG, None, 0xffffffff))
cases.append((8, 0x81, LONG, LEAF, 0))       # SINGLE at input 8 would refuse: 2 outputs

rows = []
for index, ht, annex, leaf, codesep in cases:
    m = T.sigmsg(index, ht, annex=annex, leaf_script=leaf, codesep=codesep)
    rows.append('  TrExt.{index=%d,hashtype=%d,annex="%s",script="%s",codesep=%d,msg="%s",sighash="%s"}' % (
        index, ht, (annex or b"").hex(), (leaf or b"").hex(), codesep, m.hex(), T.R.tagged_hash("TapSighash", m).hex()))
out = ["// Generated by make_taproot_sighash_vectors.py: BIP-341 signature messages",
       "// with an annex or BIP-342's script-path extension, for an input of",
       "// BIP-341's transaction (BT_V341_TX), computed by Bitcoin Core's",
       "// TaprootSignatureMsg (test/functional/test_framework/script.py at",
       "// ddea9196). Generated values, not published ones. Test data only.",
       "",
       "// annex is empty for none; script is empty for a key-path spend, else",
       "// the leaf script (version 0xc0) whose TapLeaf hash the message carries.",
       "TrExt :: struct {index:int;hashtype:int;annex:string;script:string;codesep:int;msg:string;sighash:string;}",
       "TR_EXT :: [%d] TrExt.[\n%s\n];" % (len(rows), ",\n".join(rows))]
HERE.joinpath("taproot_sighash_vectors.coax").write_text("\n".join(out) + "\n")
print(f"wrote {len(rows)} signature messages")
