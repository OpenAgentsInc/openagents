#!/usr/bin/env python3
# Firm reason: 2 (independent oracle: copies published vectors outside Coax)
"""Writes coax/tests/bitcoin/taproot_vectors.coax from BIP-341's wallet test
vectors (Bitcoin chapters 41-43).

  python3 -I coax/tests/bitcoin/make_taproot_vectors.py coax/tests/vectors/upstream/bip341/wallet-test-vectors.json

The input's SHA-256 must equal the pin below. Bitcoin Core's
src/test/data/bip341_wallet_vectors.json at ddea9196 is the same file, byte
for byte. Nothing here computes a hash, a key or a signature: every value is
copied. The one thing derived is each leaf's depth in its script tree, read
from the JSON nesting, which is how the Coax side describes a tree."""
import hashlib, json, sys
from pathlib import Path

PIN = "403e19fb81dd1f31e745699216308f61fb403774b2aafa87b631b8f7c042d37f"
src = Path(sys.argv[1]).read_bytes()
assert hashlib.sha256(src).hexdigest() == PIN
d = json.loads(src)

out = ["// Generated by make_taproot_vectors.py from bitcoin/bips:",
       "// bip-0341/wallet-test-vectors.json (sha256 %s)," % PIN,
       "// the same file as Bitcoin Core's bip341_wallet_vectors.json.",
       "// Published values, copied, not computed. Test data only.", "",
       "// A script tree's leaves left to right, each with its depth (the root's",
       "// children are depth 1), and the leaf hash and control block BIP-341",
       "// publishes for it.",
       "TrLeaf :: struct {depth:int;version:int;script:string;hash:string;control:string;}",
       "// A scriptPubKey vector: the internal key, leaves first..<first+count of",
       "// TR_LEAVES (none for a key with no script tree), and the results.",
       "TrSpk :: struct {internal:string;first:int;count:int;root:string;tweak:string;tweaked:string;spk:string;address:string;}"]
leaves, rows = [], []


def walk(tree, depth, found):
    if isinstance(tree, dict):
        found.append((depth, tree))
        return
    assert isinstance(tree, list) and len(tree) == 2
    for child in tree:
        walk(child, depth + 1, found)


for v in d["scriptPubKey"]:
    g, im, ex = v["given"], v["intermediary"], v["expected"]
    found = []
    if g["scriptTree"] is not None:
        walk(g["scriptTree"], 0, found)       # a lone leaf is the whole tree, depth 0
    first = len(leaves)
    for depth, leaf in found:
        k = leaf["id"]
        leaves.append('  TrLeaf.{depth=%d,version=%d,script="%s",hash="%s",control="%s"}' % (
            depth, leaf["leafVersion"], leaf["script"], im["leafHashes"][k], ex["scriptPathControlBlocks"][k]))
    rows.append('  TrSpk.{internal="%s",first=%d,count=%d,root="%s",tweak="%s",tweaked="%s",spk="%s",address="%s"}' % (
        g["internalPubkey"], first, len(found), im["merkleRoot"] or "", im["tweak"], im["tweakedPubkey"],
        ex["scriptPubKey"], ex["bip350Address"]))
out.append("TR_LEAVES :: [%d] TrLeaf.[\n%s\n];" % (len(leaves), ",\n".join(leaves)))
out.append("TR_SPK :: [%d] TrSpk.[\n%s\n];" % (len(rows), ",\n".join(rows)))
# The key-path spends' signature messages, in BT_V341's order (sighash_vectors.coax).
k = d["keyPathSpending"][0]
msgs = [i["intermediary"]["sigMsg"] for i in k["inputSpending"]]
out.append("TR_SIGMSG :: [%d] string.[\n%s\n];" % (len(msgs), ",\n".join('  "%s"' % m for m in msgs)))
out.append('TR_SIGNED_TX :: "%s";' % k["auxiliary"]["fullySignedTx"])
Path(__file__).with_name("taproot_vectors.coax").write_text("\n".join(out) + "\n")
