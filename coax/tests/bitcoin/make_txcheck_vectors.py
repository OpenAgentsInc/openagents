#!/usr/bin/env python3
# Firm reason: 2 (independent oracle: the vectors are Bitcoin Core's own tx_valid.json and tx_invalid.json, copied with their BADTX marks)
"""Writes txcheck_vectors.coax for Bitcoin chapter 52: every transaction of
Bitcoin Core's tx_valid.json and tx_invalid.json (pinned in
coax/tests/vectors/upstream/bitcoin-core/), whether Core marks it BADTX
(expected to fail CheckTransaction), and for those the comment above it.

  python3 -I coax/tests/bitcoin/make_txcheck_vectors.py          # check the file
  python3 -I coax/tests/bitcoin/make_txcheck_vectors.py --write  # rewrite it
"""
import hashlib, json, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
UP = HERE.parent / 'vectors' / 'upstream' / 'bitcoin-core'
OUT = HERE / 'txcheck_vectors.coax'
PINS = {
    'tx_valid.json': '0abeb1a6e4b942e4e43ef8d49b7356c1f6204bcb14163f24153f4d0ec5418011',
    'tx_invalid.json': '0c02ce44ff3a880458f9569a25589315a07f924fcaadac828613d4615776ca52',
}


def load(name):
    data = (UP / name).read_bytes()
    if PINS[name]:
        assert hashlib.sha256(data).hexdigest() == PINS[name], name
    return json.loads(data)


def entries():
    out = []
    for name, valid in (('tx_valid.json', True), ('tx_invalid.json', False)):
        # A note is the last comment line above a group, skipping lines
        # that start with "Note"; an entry right after another keeps its
        # group's note.
        note, in_comment = '', False
        for e in load(name):
            if len(e) == 1:
                if not in_comment:
                    note, in_comment = '', True
                if not e[0].startswith('Note'):
                    note = e[0]
                continue
            in_comment = False
            bad = e[2] == 'BADTX'
            out.append((e[1], valid, bad, note if bad else ''))
    return out


def render():
    rows = entries()
    lines = ['// Generated by make_txcheck_vectors.py from Bitcoin Core\'s tx_valid.json',
             '// and tx_invalid.json, pinned in coax/tests/vectors/upstream/bitcoin-core/',
             '// (see SOURCES.md there). Each transaction, whether it is from',
             '// tx_valid.json, whether Core marks it BADTX (CheckTransaction refuses',
             '// it), and for those the comment above it. Test data only.',
             'TxCheckCase :: struct { tx: string; valid: bool; badtx: bool; note: string; }',
             f'TXCHECK_CASES :: [{len(rows)}] TxCheckCase.[']
    for tx, valid, bad, note in rows:
        assert '"' not in note and '\\' not in note
        lines.append(f'  TxCheckCase.{{tx="{tx}", valid={"true" if valid else "false"}, badtx={"true" if bad else "false"}, note="{note}"}},')
    lines.append('];')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    text = render()
    if '--write' in sys.argv:
        OUT.write_text(text)
    assert OUT.read_text() == text, 'txcheck_vectors.coax differs; run with --write'
    print(f'txcheck vectors: {text.count("TxCheckCase.{")} cases agree')
