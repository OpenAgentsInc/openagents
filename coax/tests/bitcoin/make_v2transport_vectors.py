#!/usr/bin/env python3
# Firm reason: 2 (independent oracle: transcribes BIP-324's published test vectors outside Coax)
"""Writes coax/tests/bitcoin/v2transport_vectors.coax for Bitcoin chapter 67:

  python3 -I coax/tests/bitcoin/make_v2transport_vectors.py

V2_PACKETS: every row of BIP-324's packet_encoding_test_vectors.csv,
pinned in coax/tests/vectors/upstream/bip324/. A row gives our key and
both encodings, who initiates, the shared secret and every derived key,
then a packet: its index (that many empty packets come first), contents
repeated `multiply` times, AAD and ignore bit, and either the whole
ciphertext or its last 128 bytes.

The pinned file's SHA-256 must equal its pin.
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import make_ellswift_vectors as E  # noqa: E402

OUT = HERE / 'v2transport_vectors.coax'
FIELDS = [('idx', 'in_idx', int), ('priv', 'in_priv_ours', str), ('ours', 'in_ellswift_ours', str),
          ('theirs', 'in_ellswift_theirs', str), ('initiating', 'in_initiating', bool),
          ('contents', 'in_contents', str), ('multiply', 'in_multiply', int), ('aad', 'in_aad', str),
          ('ignore', 'in_ignore', bool), ('shared_secret', 'mid_shared_secret', str),
          ('initiator_l', 'mid_initiator_l', str), ('initiator_p', 'mid_initiator_p', str),
          ('responder_l', 'mid_responder_l', str), ('responder_p', 'mid_responder_p', str),
          ('send_terminator', 'mid_send_garbage_terminator', str),
          ('recv_terminator', 'mid_recv_garbage_terminator', str), ('session_id', 'out_session_id', str),
          ('ciphertext', 'out_ciphertext', str), ('endswith', 'out_ciphertext_endswith', str)]
TYPES = {str: 'string', int: 'int', bool: 'bool'}


def value(kind, text):
    if kind is int:
        return text
    if kind is bool:
        return 'true' if text == '1' else 'false'
    return f'"{text}"'


def main():
    rows = E.rows('packet_encoding_test_vectors.csv')
    text = [
        '// Generated by make_v2transport_vectors.py from BIP-324\'s',
        '// packet_encoding_test_vectors.csv, pinned in',
        '// coax/tests/vectors/upstream/bip324/ (see SOURCES.md there). Test data only.',
        'V2Row :: struct {',
    ]
    text += [f'  {name}: {TYPES[kind]};' for name, _, kind in FIELDS]
    text += ['}', f'V2_PACKETS :: [{len(rows)}] V2Row.[']
    for r in rows:
        text.append('  V2Row.{' + ', '.join(f'{n}={value(k, r[c])}' for n, c, k in FIELDS) + '},')
    text += ['];', '']
    OUT.write_text('\n'.join(text))
    print(f'wrote {OUT.name}: {len(rows)} packets')


if __name__ == '__main__':
    main()
