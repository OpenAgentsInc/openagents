#!/usr/bin/env python3
# Firm reason: 2 (independent oracle: transcribes BOLT 1's published test vectors outside Coax)
"""Writes coax/tests/lightning/bolt1_vectors.coax for Bitcoin chapter 104:

  python3 -I coax/tests/lightning/make_bolt1_vectors.py

From BOLT 1, pinned in coax/tests/vectors/upstream/bolts/01-messaging.md:

- LN_BIGSIZE: Appendix A's 18 decoding rows, each with its error (or none)
  and whether it is also one of the 8 encoding rows.
- LN_TLV: Appendix B's 57 streams, each with its namespace (0 for any, 1
  for n1, 2 for n2), whether it decodes, BOLT 1's reason, and for n1's
  successes the record and values BOLT 1 lists.
- LN_INIT_ROWS: Appendix C's 5 init messages and whether each is valid.

The pinned file's SHA-256 must equal its pin.
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import bolts  # noqa: E402

OUT = HERE / 'bolt1_vectors.coax'


def quote(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    big = bolts.bigsize()
    tlv = bolts.tlv()
    init = bolts.init_extension()
    text = [
        "// Generated by make_bolt1_vectors.py from BOLT 1's test vectors, pinned in",
        '// coax/tests/vectors/upstream/bolts/ (see SOURCES.md there). Test data only.',
        'LnBigSizeRow :: struct { name: string; value: u64; bytes: string; error: string; encode: bool; }',
        f'LN_BIGSIZE :: [{len(big)}] LnBigSizeRow.[',
    ]
    for r in big:
        text.append(f'  LnBigSizeRow.{{name={quote(r["name"])}, value={r["value"]}, bytes="{r["bytes"]}", '
                    f'error={quote(r.get("exp_error", ""))}, encode={"true" if r["encode"] else "false"}}},')
    text += ['];',
             'LnTlvRow :: struct { stream: string; space: int; ok: bool; reason: string; record: int;',
             '  amount: u64; scid: u64; node_id: string; amount_2: u64; cltv: u64; }',
             f'LN_TLV :: [{len(tlv)}] LnTlvRow.[']
    for stream, ns, ok, why, record, f in tlv:
        amount = f.get('amount_msat', f.get('amount_msat_1', '0'))
        scid = bolts.scid(f["scid"]) if "scid" in f else 0
        text.append(f'  LnTlvRow.{{stream="{stream}", space={ns}, ok={"true" if ok else "false"}, '
                    f'reason={quote(why.replace("`", ""))}, record={record}, amount={amount}, scid={scid}, '
                    f'node_id="{f.get("node_id", "")}", amount_2={f.get("amount_msat_2", "0")}, '
                    f'cltv={f.get("cltv_delta", "0")}}},')
    text += ['];', 'LnInitRow :: struct { message: string; ok: bool; why: string; }',
             f'LN_INIT_ROWS :: [{len(init)}] LnInitRow.[']
    for message, ok, why in init:
        text.append(f'  LnInitRow.{{message="{message}", ok={"true" if ok else "false"}, why={quote(why.replace("`", ""))}}},')
    text += ['];', '']
    OUT.write_text('\n'.join(text))
    print(f'wrote {OUT.name}: {len(big)} BigSize rows, {len(tlv)} TLV streams, {len(init)} init messages')


if __name__ == '__main__':
    main()
