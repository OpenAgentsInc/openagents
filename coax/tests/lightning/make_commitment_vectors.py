#!/usr/bin/env python3
# Firm reason: 2 (independent oracle: transcribes BOLT 3's published test vectors outside Coax)
"""Writes coax/tests/lightning/commitment_vectors.coax for Bitcoin chapter 108:

  python3 -I coax/tests/lightning/make_commitment_vectors.py

From BOLT 3, pinned in coax/tests/vectors/upstream/bolts/03-transactions.md:
Appendix B's funding transaction (LNC_FUNDING), Appendix C's channel and
its seven HTLCs (LNC_PARAMS, LNC_HTLCS), and every commitment test of
Appendix C (static_remotekey) and Appendix F (anchors) as LNC_VECTORS,
with their HTLC transactions in output order in LNC_HTLC_TXS.

Each vector names the HTLCs it commits as a bit mask of LNC_HTLCS. BOLT 3
says which in prose: the first test has none, the "same amount and
preimage" test has HTLCs 1, 5 and 6, and every other test has 0 to 4.
bolt3_tx.py, an independent Python builder, must rebuild every vector
byte for byte before the file is written.

The pinned file's SHA-256 must equal its pin.
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import bolts  # noqa: E402
import bolt3_tx as B  # noqa: E402

OUT = HERE / 'commitment_vectors.coax'
PARAMS = ['funding_txid', 'local_funding_privkey', 'remote_funding_privkey', 'local_payment_basepoint_secret',
          'remote_revocation_basepoint_secret', 'local_delayed_payment_basepoint_secret',
          'remote_payment_basepoint_secret', 'local_per_commitment_secret', 'local_payment_basepoint',
          'remote_payment_basepoint', 'local_funding_pubkey', 'remote_funding_pubkey', 'local_htlcpubkey',
          'remote_htlcpubkey', 'local_delayedpubkey', 'local_revocation_pubkey', 'local_per_commitment_point']
NUMBERS = ['funding_index', 'funding_sat', 'commitment_number', 'to_self_delay', 'dust_limit']


def which(name, uses_htlcs=True):
    if 'same amount' in name:
        return [1, 5, 6]
    return [0, 1, 2, 3, 4] if uses_htlcs and 'no HTLCs' not in name else []


def vectors():
    """(name, anchors, dust, to_local, to_remote, feerate, htlcs, tx, [htlc tx])."""
    p = bolts.commitment_params()
    rows = [(t['name'], False, p['dust_limit'], t['to_local_msat'], t['to_remote_msat'], t['feerate'],
             which(t['name']), t['tx'], [h for _, _, h in t['htlc_txs']]) for t in bolts.commitments()]
    rows += [(t['Name'], True, t['DustLimitSatoshis'], t['LocalBalance'], t['RemoteBalance'], t['FeePerKw'],
              which(t['Name'], t['UseTestHtlcs']), t['ExpectedCommitmentTxHex'],
              [d['ResolutionTxHex'] for d in t['HtlcDescs']]) for t in bolts.anchors()]
    return p, rows


def check(p, rows):
    """bolt3_tx.py rebuilds and signs every vector."""
    for name, anchors, dust, local, remote, feerate, used, tx, htlc_txs in rows:
        ch, secrets = B.vector_channel(p, anchors)
        ch.dust_limit = dust
        _, _, got, got_htlcs = B.build_vector(ch, secrets, local, remote, feerate, B.vector_htlcs(p, used))
        assert got.hex() == tx and [h.hex() for _, _, h in got_htlcs] == htlc_txs, name
    f = bolts.funding()
    tx, txid, script, _ = B.funding_tx(f)
    assert tx.hex() == f['tx'] and txid == f['txid'] and script.hex() == f['witness_script']


def main():
    p, rows = vectors()
    check(p, rows)
    f = bolts.funding()
    text = [
        "// Generated by make_commitment_vectors.py from BOLT 3's test vectors, pinned in",
        '// coax/tests/vectors/upstream/bolts/ (see SOURCES.md there). Test data only.',
        "// Appendix B's funding transaction.",
        'LncVecFunding :: struct { coinbase_privkey: string; input_txid: string; input_index: int; input_sat: int; '
        'funding_sat: int; feerate: int; local_funding_pubkey: string; remote_funding_pubkey: string; '
        'witness_script: string; tx: string; txid: string; }',
        'LNC_FUNDING :: LncVecFunding.{',
    ]
    for k in ('coinbase_privkey', 'input_txid'):
        text.append(f'  {k}="{f[k]}",')
    for k in ('input_index', 'input_sat', 'funding_sat', 'feerate'):
        text.append(f'  {k}={f[k]},')
    for k in ('local_funding_pubkey', 'remote_funding_pubkey', 'witness_script', 'tx', 'txid'):
        text.append(f'  {k}="{f[k]}",')
    text += ['};', "// Appendix C's channel: secrets without their trailing 01, keys, and numbers.",
             'LncVecParams :: struct {', '  ' + ' '.join(f'{k}: string;' for k in PARAMS),
             '  ' + ' '.join(f'{k}: int;' for k in NUMBERS), '}', 'LNC_PARAMS :: LncVecParams.{']
    text += [f'  {k}="{p[k]}",' for k in PARAMS] + [f'  {k}={p[k]},' for k in NUMBERS] + ['};']
    text += ["// Appendix C's HTLCs, offered meaning local->remote.",
             'LncVecHtlc :: struct { offered: bool; amount_msat: int; expiry: int; preimage: string; }',
             f'LNC_HTLCS :: [{len(p["htlcs"])}] LncVecHtlc.[']
    text += [f'  LncVecHtlc.{{offered={str(h["offered"]).lower()}, amount_msat={h["amount_msat"]}, '
             f'expiry={h["expiry"]}, preimage="{h["preimage"]}"}},' for h in p['htlcs']]
    text += ['];', '// Appendix C (anchors=false) and Appendix F (anchors=true). htlcs is a bit mask of',
             '// LNC_HTLCS; the HTLC transactions are LNC_HTLC_TXS[first..<first+count], in output order.',
             'LncVector :: struct { name: string; anchors: bool; dust_limit: int; to_local_msat: int; '
             'to_remote_msat: int; feerate: int; htlcs: int; tx: string; first: int; count: int; }',
             f'LNC_VECTORS :: [{len(rows)}] LncVector.[']
    txs = []
    for name, anchors, dust, local, remote, feerate, used, tx, htlc_txs in rows:
        mask = sum(1 << i for i in used)
        text.append(f'  LncVector.{{name="{name}", anchors={str(anchors).lower()}, dust_limit={dust}, '
                    f'to_local_msat={local}, to_remote_msat={remote}, feerate={feerate}, htlcs={mask}, '
                    f'tx="{tx}", first={len(txs)}, count={len(htlc_txs)}}},')
        txs += htlc_txs
    text += ['];', f'LNC_HTLC_TXS :: [{len(txs)}] string.[']
    text += [f'  "{h}",' for h in txs] + ['];', '']
    OUT.write_text('\n'.join(text))
    print(f'wrote {OUT.name}: {len(rows)} commitments, {len(txs)} HTLC transactions')


if __name__ == '__main__':
    main()
