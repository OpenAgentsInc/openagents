#!/usr/bin/env python3
# Firm reason: 2 (independent oracle: transcribes BOLT 7's published test vectors outside Coax)
"""Writes coax/tests/lightning/gossip_vectors.coax for Bitcoin chapter 112:

  python3 -I coax/tests/lightning/make_gossip_vectors.py

From BOLT 7, pinned in coax/tests/vectors/upstream/bolts/:

- ALIAS_ROWS (07-routing-gossip.md, "Test vectors"): six node_announcements
  signed with the key 0x11...11, each with an alias holding a character
  BOLT 1 forbids. Each signature verifies; each alias refuses.
- QUERY_ROWS (bolt07/extended-queries.json): query_channel_range,
  reply_channel_range and query_short_channel_ids messages with the
  fields the JSON states. The file was written when encoding 1 meant
  zlib; BOLT 7 at this revision says it "MUST NOT be used", so the five
  messages that use it refuse with BAD_ENCODING and the other five read.

BOLT 7 has no vectors for channel_announcement or channel_update; the
chapter's example makes them with its own keys.
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import bolt7 as G  # noqa: E402
import bolts  # noqa: E402

OUT = HERE / 'gossip_vectors.coax'
TYPES = {'QueryChannelRange': G.QUERY_RANGE, 'ReplyChannelRange': G.REPLY_RANGE,
         'QueryShortChannelIds': G.QUERY_SCIDS}
FLAGS = {'WANT_TIMESTAMPS | WANT_CHECKSUMS': 3}


def scid(t):
    return G.scid(*(int(x) for x in t.split('x')))


def arr(values, n):
    return f'[{n}] u64.[' + ', '.join(str(v) for v in list(values) + [0] * (n - len(values))) + ']'


def main():
    key, aliases = bolts.bolt7_aliases()
    queries = bolts.bolt7_queries()
    node = G.public(key)
    lines = [
        "// Generated by make_gossip_vectors.py from BOLT 7's test vectors, pinned in",
        '// coax/tests/vectors/upstream/bolts/ (see SOURCES.md there). Test data only.',
        f'ALIAS_NODE_ID :: "{node.hex()}";',
        'AliasRow :: struct { name: string; announcement: string; }',
        f'ALIAS_ROWS :: [{len(aliases)}] AliasRow.[',
    ]
    stamp = None
    for a in aliases:
        m = bytes.fromhex(a['announcement'])
        assert G.code(m) == 'BAD_ALIAS', a['name']
        r = G.Reader(m, 2 + 64 + 2)
        stamp = r.u32()
        assert r.take(33) == node
        lines.append(f'  AliasRow.{{name="{a["name"]}", announcement="{a["announcement"]}"}},')
    lines += ['];', f'ALIAS_TIMESTAMP :: {stamp};']
    chain = bytes.fromhex(queries[0]['msg']['chainHash'])
    lines.append('QUERY_CHAIN_BYTES :: [32] u8.[' + ', '.join(str(b) for b in chain) + '];')
    lines += ['// code: the GSP_ code the reader gives. extra: query options or sync_complete.',
              'QueryRow :: struct { hex: string; code: int; type: int; first: u64; number: u64; extra: u64;',
              '  scids: [3] u64; scid_n: int; stamps: [6] u64; stamps_n: int; sums: [6] u64; sums_n: int; flags_n: int; }',
              f'QUERY_ROWS :: [{len(queries)}] QueryRow.[']
    readable = 0
    for q in queries:
        m, msg = bytes.fromhex(q['hex']), q['msg']
        t = TYPES[msg['type']]
        zlib = 'COMPRESSED_ZLIB' in str(msg)
        want = 'BAD_ENCODING' if zlib else 'OK'
        assert G.code(m) == want, msg['type']
        assert bytes.fromhex(msg['chainHash']) == chain
        first = msg.get('firstBlockNum', 0)
        number = msg.get('numberOfBlocks', 0)
        extra = 0
        ids, stamps, sums, flags_n = [], [], [], 0
        if t == G.QUERY_RANGE:
            recs = msg['tlvStream']['records']
            extra = FLAGS[recs[0]] if recs else 0
        if 'shortChannelIds' in msg:
            ids = [scid(x) for x in msg['shortChannelIds']['array']]
        if t == G.REPLY_RANGE:
            extra = msg['complete']
            if 'timestamps' in msg:
                stamps = [v for x in msg['timestamps']['timestamps'] for v in (x['timestamp1'], x['timestamp2'])]
            if 'checksums' in msg:
                sums = [v for x in msg['checksums']['checksums'] for v in (x['checksum1'], x['checksum2'])]
        if t == G.QUERY_SCIDS and msg['tlvStream']['records']:
            flags_n = len(msg['tlvStream']['records'][0]['array'])
        if want == 'OK':
            readable += 1
            r = G.read(m)
            assert r['chain'] == chain
            if t != G.QUERY_RANGE:
                assert r['scids'] == ids
            else:
                assert (r['first'], r['number'], r['options']) == (first, number, extra)
            if t == G.REPLY_RANGE:
                assert (r['first'], r['number'], r['complete']) == (first, number, extra)
                assert [v for p in (r['timestamps'] or []) for v in p] == stamps
                assert [v for p in (r['checksums'] or []) for v in p] == sums
            if t == G.QUERY_SCIDS:
                assert len(r['flags'] or []) == flags_n
        lines.append(f'  QueryRow.{{hex="{q["hex"]}", code={G.CODES.index(want)}, type={t}, first={first}, '
                     f'number={number}, extra={extra}, scids={arr(ids, 3)}, scid_n={len(ids)}, '
                     f'stamps={arr(stamps, 6)}, stamps_n={len(stamps)}, sums={arr(sums, 6)}, '
                     f'sums_n={len(sums)}, flags_n={flags_n}}},  // {msg["type"]}')
    lines += ['];', '']
    assert readable == 5
    OUT.write_text('\n'.join(lines))
    print(f'wrote {OUT.name}: {len(aliases)} node announcements, {len(queries)} query messages')


if __name__ == '__main__':
    main()
