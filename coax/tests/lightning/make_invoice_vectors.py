#!/usr/bin/env python3
# Firm reason: 2 (independent oracle: transcribes BOLT 11's published test vectors outside Coax)
"""Writes coax/tests/lightning/invoice_vectors.coax for Bitcoin chapter 114:

  python3 -I coax/tests/lightning/make_invoice_vectors.py

From BOLT 11, pinned in coax/tests/vectors/upstream/bolts/:

- INVOICE_ROWS (bolt11/invoice-test.json): every example invoice, valid
  and invalid, with what the Examples section of 11-payment-encoding.md
  states for it: the timestamp, and the signature, recovery flag, signed
  data and its SHA-256 where its "Signature breakdown" gives them.
- INVOICE_KEY and INVOICE_SECRET: the private key that signs the examples
  and the payment secret they carry.

Every pinned file's SHA-256 must equal its pin.
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import bolts  # noqa: E402

OUT = HERE / 'invoice_vectors.coax'


def main():
    rows = bolts.bolt11_json()
    key, secret, stated = bolts.bolt11_examples()
    assert len(rows) == 31 and sum(r['valid'] for r in rows) == 16
    assert all(r['invoice'] in stated for r in rows if r['valid'])
    text = [
        "// Generated by make_invoice_vectors.py from BOLT 11's test vectors, pinned in",
        '// coax/tests/vectors/upstream/bolts/ (see SOURCES.md there). Test data only.',
        '// timestamp 0, recovery -1 and empty strings mark what BOLT 11 does not state.',
        'InvoiceRow :: struct { text: string; valid: bool; timestamp: u64; recovery: int; '
        'signature: string; data: string; digest: string; }',
        f'INVOICE_KEY :: "{key}";',
        f'INVOICE_SECRET :: "{secret}";',
        f'INVOICE_ROWS :: [{len(rows)}] InvoiceRow.[',
    ]
    for r in rows:
        s = stated.get(r['invoice'], {'timestamp': 0, 'recovery': -1, 'signature': '', 'data': '', 'digest': ''})
        text.append(f'  InvoiceRow.{{text="{r["invoice"]}", valid={"true" if r["valid"] else "false"}, '
                    f'timestamp={s["timestamp"]}, recovery={s["recovery"]}, signature="{s["signature"]}", '
                    f'data="{s["data"]}", digest="{s["digest"]}"}},')
    text += ['];', '']
    OUT.write_text('\n'.join(text))
    print(f'wrote {OUT.name}: {len(rows)} invoices')


if __name__ == '__main__':
    main()
