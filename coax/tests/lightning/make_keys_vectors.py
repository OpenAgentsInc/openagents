#!/usr/bin/env python3
# Firm reason: 2 (independent oracle: transcribes BOLT 3's published test vectors outside Coax)
"""Writes coax/tests/lightning/keys_vectors.coax for Bitcoin chapter 106:

  python3 -I coax/tests/lightning/make_keys_vectors.py

From BOLT 3's Appendix E, pinned in
coax/tests/vectors/upstream/bolts/03-transactions.md: the base secret and
per-commitment secret, the points BOLT 3 gives for them, and the four
derived keys (localpubkey, localprivkey, revocationpubkey and
revocationprivkey), as LNK_VECTOR.

The pinned file's SHA-256 must equal its pin.
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import bolts  # noqa: E402

OUT = HERE / 'keys_vectors.coax'
FIELDS = ['base_secret', 'per_commitment_secret', 'base_point', 'per_commitment_point',
          'localpubkey', 'localprivkey', 'revocationpubkey', 'revocationprivkey']


def main():
    k = bolts.keys()
    assert sorted(k) == sorted(FIELDS), sorted(k)
    text = [
        "// Generated by make_keys_vectors.py from BOLT 3's test vectors, pinned in",
        '// coax/tests/vectors/upstream/bolts/ (see SOURCES.md there). Test data only.',
        'LnkVector :: struct {',
        '  ' + ' '.join(f'{f}: string;' for f in FIELDS),
        '}',
        'LNK_VECTOR :: LnkVector.{',
    ]
    text += [f'  {f}="{k[f]}",' for f in FIELDS]
    text += ['};', '']
    OUT.write_text('\n'.join(text))
    print(f'wrote {OUT.name}: {len(FIELDS)} values')


if __name__ == '__main__':
    main()
