#!/usr/bin/env python3
# Firm reason: 2 (independent oracle: transcribes BOLT 8's published test vectors outside Coax)
"""Writes coax/tests/lightning/noise_vectors.coax for Bitcoin chapter 105:

  python3 -I coax/tests/lightning/make_noise_vectors.py

From BOLT 8's Appendix A, pinned in
coax/tests/vectors/upstream/bolts/08-transport.md:

- NOISE_HANDSHAKES: the 5 initiator and 9 responder tests. Each gives the
  side's static and ephemeral secret keys (and the initiator's view of the
  responder's static key), the three acts as sent or received, and either
  the session keys or the error BOLT 8 expects.
- NOISE_MESSAGES: the message test's chaining key and session keys, and
  the six encrypted "hello" messages BOLT 8 shows, by index.

The pinned file's SHA-256 must equal its pin.
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import bolts  # noqa: E402

OUT = HERE / 'noise_vectors.coax'
FIELDS = ['name', 'initiator', 'rs_pub', 'ls_priv', 'e_priv', 'act1', 'act2', 'act3', 'keys', 'error']


def value(v):
    return ('true' if v else 'false') if isinstance(v, bool) else f'"{v}"'


def main():
    tests = bolts.handshakes()
    keys, outputs = bolts.messages()
    text = [
        "// Generated by make_noise_vectors.py from BOLT 8's test vectors, pinned in",
        '// coax/tests/vectors/upstream/bolts/ (see SOURCES.md there). Test data only.',
        'NoiseRow :: struct {',
        '  name: string; initiator: bool; rs_pub: string; ls_priv: string; e_priv: string;',
        '  act1: string; act2: string; act3: string; keys: string; error: string;',
        '}',
        f'NOISE_HANDSHAKES :: [{len(tests)}] NoiseRow.[',
    ]
    for t in tests:
        text.append('  NoiseRow.{' + ', '.join(f'{f}={value(t[f])}' for f in FIELDS) + '},')
    text += ['];',
             'NoiseOutput :: struct { index: int; hex: string; }',
             f'NoiseMessages :: struct {{ ck: string; sk: string; rk: string; outputs: [{len(outputs)}] NoiseOutput; }}',
             f'NOISE_MESSAGES :: NoiseMessages.{{ck="{keys["ck"]}", sk="{keys["sk"]}", rk="{keys["rk"]}", '
             f'outputs=[{len(outputs)}] NoiseOutput.[']
    text += [f'  NoiseOutput.{{index={i}, hex="{h}"}},' for i, h in outputs]
    text += ['  ]};', '']
    OUT.write_text('\n'.join(text))
    print(f'wrote {OUT.name}: {len(tests)} handshakes, {len(outputs)} messages')


if __name__ == '__main__':
    main()
