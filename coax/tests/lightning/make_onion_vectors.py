#!/usr/bin/env python3
# Firm reason: 2 (independent oracle: transcribes BOLT 4's published test vectors outside Coax)
"""Writes coax/tests/lightning/onion_vectors.coax for Bitcoin chapter 111:

  python3 -I coax/tests/lightning/make_onion_vectors.py

From BOLT 4, pinned in coax/tests/vectors/upstream/bolts/:

- ONION_TEST (bolt04/onion-test.json): five hops' keys and payloads, the
  session key and associated data, the onion, and each hop's secret key.
- ONION_ERROR (bolt04/onion-error-test.json and the "Returning Errors"
  trace of 04-onion-routing.md): each hop's shared secret and ammag key,
  the short failure and its packet, and the long failure's packet as each
  node sends it back.
- ONION_BLINDING (bolt04/route-blinding-test.json): a blinded path made
  of two joined paths, and each hop's view when it unblinds.
- ONION_BLINDED_PAYMENT (bolt04/blinded-payment-onion-test.json): a
  payment onion whose last four hops are a blinded path, and the onion as
  each hop receives it.
- ONION_MESSAGE (bolt04/blinded-onion-message-onion-test.json): an onion
  message along a blinded path, and the onion_message each hop receives.

Every pinned file's SHA-256 must equal its pin.
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import bolts  # noqa: E402

OUT = HERE / 'onion_vectors.coax'


def struct(name, fields):
    return f'{name} :: struct {{ ' + ' '.join(f'{f}: {t};' for f, t in fields) + ' }'


def literal(name, values):
    return f'{name}.{{' + ', '.join(f'{k}={v}' for k, v in values) + '}'


def s(v):
    return f'"{v}"'


def rows(name, items):
    return f'[{len(items)}] {name}.[\n' + ''.join(f'    {i},\n' for i in items) + '  ]'


def main():
    out = [
        "// Generated by make_onion_vectors.py from BOLT 4's test vectors, pinned in",
        '// coax/tests/vectors/upstream/bolts/ (see SOURCES.md there). Test data only.',
    ]

    # ---- the packet
    d = bolts.bolt4_json('onion-test.json')
    g = d['generate']
    assert len(g['hops']) == len(d['decode']) == 5
    out.append(struct('OnionHopRow', [('pubkey', 'string'), ('payload', 'string'), ('secret', 'string')]))
    out.append(struct('OnionPacketTest', [('session', 'string'), ('ad', 'string'), ('hops', '[5] OnionHopRow'),
                                          ('onion', 'string')]))
    hops = [literal('OnionHopRow', [('pubkey', s(h['pubkey'])), ('payload', s(h['payload'])), ('secret', s(k))])
            for h, k in zip(g['hops'], d['decode'])]
    out.append('ONION_TEST :: ' + literal('OnionPacketTest', [
        ('session', s(g['session_key'])), ('ad', s(g['associated_data'])), ('hops', rows('OnionHopRow', hops)),
        ('onion', s(d['onion']))]) + ';')

    # ---- errors
    e = bolts.bolt4_json('onion-error-test.json')
    trace = bolts.error_trace()
    by_node = {n: (ss, ammag, packet) for n, ss, ammag, packet in trace['hops']}
    assert sorted(by_node) == [0, 1, 2, 3, 4]
    out.append(struct('OnionErrorHop', [('pubkey', 'string'), ('shared_secret', 'string'), ('ammag', 'string'),
                                        ('packet', 'string')]))
    out.append(struct('OnionErrorTest', [('session', 'string'), ('failure', 'string'), ('payload', 'string'),
                                         ('um', 'string'), ('errorpacket', 'string'), ('long_payload', 'string'),
                                         ('long_raw', 'string'), ('hops', '[5] OnionErrorHop')]))
    ehops = []
    for i, h in enumerate(e['generate']['hops']):
        ss, ammag, packet = by_node[i]
        assert ss == h['hop_shared_secret'] and ammag == h['ammag_key'], i
        ehops.append(literal('OnionErrorHop', [('pubkey', s(h['pubkey'])), ('shared_secret', s(ss)),
                                               ('ammag', s(ammag)), ('packet', s(packet))]))
    last = e['generate']['hops'][4]
    assert last['um_key'] == trace['um_key']
    out.append('ONION_ERROR :: ' + literal('OnionErrorTest', [
        ('session', s(e['generate']['session_key'])), ('failure', s(e['generate']['failure_message'])),
        ('payload', s(last['payload'])), ('um', s(last['um_key'])), ('errorpacket', s(e['errorpacket'])),
        ('long_payload', s(trace['payload'])), ('long_raw', s(trace['raw'])), ('hops', rows('OnionErrorHop', ehops))]) + ';')

    # ---- route blinding
    b = bolts.bolt4_json('route-blinding-test.json')
    gen, route, unblind = b['generate']['hops'], b['route']['hops'], b['unblind']['hops']
    assert len(gen) == len(route) == len(unblind) == 4
    out.append(struct('OnionBlindRow', [('alias', 'string'), ('session', 'string'), ('node_id', 'string'),
                                        ('data', 'string'), ('path_key', 'string'), ('shared_secret', 'string'),
                                        ('blinded_node_id', 'string'), ('encrypted', 'string'), ('node_secret', 'string'),
                                        ('blinded_secret', 'string'), ('next_path_key', 'string')]))
    brows = []
    for x, r, u in zip(gen, route, unblind):
        assert r['encrypted_data'] == x['encrypted_data'] and u['decrypted_data'] == x['encoded_tlvs']
        assert u['path_key'] == x['path_key']
        brows.append(literal('OnionBlindRow', [
            ('alias', s(x['alias'])), ('session', s(x.get('session_key', ''))), ('node_id', s(x['node_id'])),
            ('data', s(x['encoded_tlvs'])), ('path_key', s(x['path_key'])), ('shared_secret', s(x['shared_secret'])),
            ('blinded_node_id', s(x['blinded_node_id'])), ('encrypted', s(x['encrypted_data'])),
            ('node_secret', s(u['node_privkey'])), ('blinded_secret', s(u['blinded_privkey'])),
            ('next_path_key', s(u.get('next_path_key_override', u['next_path_key'])))]))
    out.append('ONION_BLINDING :: ' + rows('OnionBlindRow', brows) + ';')

    # ---- a payment onion into a blinded path
    p = bolts.bolt4_json('blinded-payment-onion-test.json')
    pg, full, dec = p['generate'], p['generate']['full_route']['hops'], p['decrypt']['hops']
    assert len(full) == len(dec) == 5 and dec[0]['onion'] == pg['onion']
    out.append(struct('OnionPaymentHop', [('alias', 'string'), ('pubkey', 'string'), ('payload', 'string'),
                                          ('onion', 'string'), ('node_secret', 'string'), ('next_path_key', 'string')]))
    out.append(struct('OnionPaymentTest', [('session', 'string'), ('ad', 'string'), ('hops', '[5] OnionPaymentHop')]))
    phops = [literal('OnionPaymentHop', [
        ('alias', s(f['alias'])), ('pubkey', s(f['pubkey'])), ('payload', s(f['payload'])), ('onion', s(x['onion'])),
        ('node_secret', s(x['node_privkey'])), ('next_path_key', s(x.get('next_path_key', '')))]) for f, x in zip(full, dec)]
    out.append('ONION_BLINDED_PAYMENT :: ' + literal('OnionPaymentTest', [
        ('session', s(pg['session_key'])), ('ad', s(pg['associated_data'])), ('hops', rows('OnionPaymentHop', phops))]) + ';')

    # ---- an onion message along a blinded path
    m = bolts.bolt4_json('blinded-onion-message-onion-test.json')
    mg, mroute, mdec = m['generate']['hops'], m['route']['hops'], m['decrypt']['hops']
    assert len(mg) == len(mroute) == len(mdec) == 4
    out.append(struct('OnionMessageHop', [('alias', 'string'), ('path_secret', 'string'), ('node_secret', 'string'),
                                          ('data', 'string'), ('path_key', 'string'), ('shared_secret', 'string'),
                                          ('blinded_node_id', 'string'), ('encrypted', 'string'), ('message', 'string'),
                                          ('next_node_id', 'string')]))
    out.append(struct('OnionMessageTest', [('session', 'string'), ('hello', 'string'), ('packet', 'string'),
                                           ('hops', '[4] OnionMessageHop')]))
    mhops = []
    for i, (x, r, y) in enumerate(zip(mg, mroute, mdec)):
        assert r['encrypted_recipient_data'] == x['encrypted_recipient_data'] and r['blinded_node_id'] == x['blinded_node_id']
        # Alice starts the path and Bob starts Dave's path, which Alice joins.
        mhops.append(literal('OnionMessageHop', [
            ('alias', s(x['alias'])), ('path_secret', s(x['path_key_secret'] if i < 2 else '')),
            ('node_secret', s(y['privkey'])), ('data', s(x['encrypted_data_tlv'])), ('path_key', s(x['E'])),
            ('shared_secret', s(x['ss'])), ('blinded_node_id', s(x['blinded_node_id'])),
            ('encrypted', s(x['encrypted_recipient_data'])), ('message', s(y['onion_message'])),
            ('next_node_id', s(y.get('next_node_id', '')))]))
    out.append('ONION_MESSAGE :: ' + literal('OnionMessageTest', [
        ('session', s(m['generate']['session_key'])), ('hello', s(m['onionmessage']['unknown_tag_1'])),
        ('packet', s(m['onionmessage']['onion_message_packet'])), ('hops', rows('OnionMessageHop', mhops))]) + ';')

    OUT.write_text('\n'.join(out) + '\n')
    print(f'wrote {OUT.name}: 5 packet hops, 5 error hops, 4 blinded hops, 5 payment hops, 4 message hops')


if __name__ == '__main__':
    main()
