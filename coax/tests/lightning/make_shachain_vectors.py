#!/usr/bin/env python3
# Firm reason: 2 (independent oracle: transcribes BOLT 3's published test vectors outside Coax)
"""Writes coax/tests/lightning/shachain_vectors.coax for Bitcoin chapter 107:

  python3 -I coax/tests/lightning/make_shachain_vectors.py

From BOLT 3's Appendix D, pinned in
coax/tests/vectors/upstream/bolts/03-transactions.md:

- SHACHAIN_GENERATION: the 5 generation tests, each a seed, an index and
  the secret BOLT 3 says it gives.
- SHACHAIN_STORAGE: the 9 storage tests, as one row per insert: the test
  it belongs to, the index, the secret, and whether BOLT 3 says the insert
  succeeds. SHACHAIN_STORAGE_NAMES names the tests.

The pinned file's SHA-256 must equal its pin.
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import bolts  # noqa: E402

OUT = HERE / 'shachain_vectors.coax'


def main():
    gen, store = bolts.generation(), bolts.storage()
    rows = [(t, i, s, ok) for t, (_, steps) in enumerate(store) for i, s, ok in steps]
    text = [
        "// Generated by make_shachain_vectors.py from BOLT 3's test vectors, pinned in",
        '// coax/tests/vectors/upstream/bolts/ (see SOURCES.md there). Test data only.',
        'ShachainGeneration :: struct { name: string; seed: string; index: u64; output: string; }',
        f'SHACHAIN_GENERATION :: [{len(gen)}] ShachainGeneration.[',
    ]
    text += [f'  ShachainGeneration.{{name="{n}", seed="{s}", index={i}, output="{o}"}},' for n, s, i, o in gen]
    text += ['];', 'ShachainInsert :: struct { test: int; index: u64; secret: string; ok: bool; }',
             f'SHACHAIN_STORAGE :: [{len(rows)}] ShachainInsert.[']
    text += [f'  ShachainInsert.{{test={t}, index={i}, secret="{s}", ok={"true" if ok else "false"}}},'
             for t, i, s, ok in rows]
    text += ['];', f'SHACHAIN_STORAGE_NAMES :: [{len(store)}] string.[']
    text += [f'  "{n}",' for n, _ in store]
    text += ['];', '']
    OUT.write_text('\n'.join(text))
    print(f'wrote {OUT.name}: {len(gen)} generation tests, {len(store)} storage tests, {len(rows)} inserts')


if __name__ == '__main__':
    main()
