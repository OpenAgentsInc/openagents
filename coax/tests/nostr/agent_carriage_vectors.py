#!/usr/bin/env python3
"""NIP-AGENT private carriage vectors for chapter 79.

Written from NIP-01, BIP-340, NIP-44 v2, the shared artifact envelope and
NIP-AGENT with only hashlib, hmac and integers (signing and encryption come
from nip59_reference.py, which shares no code with Coax). Tooling only,
never shipped. TEST keys only: the sender is the secp256k1 scalar 1, the
recipient (the host) 3, another host 2.

  python3 coax/tests/nostr/agent_carriage_vectors.py > coax/tests/nostr/agent_carriage_vectors.coax

The artifact digest is SHA-256 over the payload's RFC 8785 JCS bytes; for
these payloads (ASCII strings, small integers, no floats) JCS is
json.dumps(sort_keys=True, separators=(",", ":")). The inline payload keeps
its own key order, as the envelope allows.
"""
import hashlib
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from nip59_reference import conversation_key, dumps, event_id, nip44_encrypt, sign, xonly  # noqa: E402

T0 = 1790000000
SENDER, OTHER, RECIPIENT = (1).to_bytes(32, "big"), (2).to_bytes(32, "big"), (3).to_bytes(32, "big")
AGENT_ID = hashlib.sha256(b"agent:triage").hexdigest()
MAILBOX = hashlib.sha256(b"mailbox:triage:host").hexdigest()
INSTRUCTIONS = "Label each new issue: bug, feature or question."


def payload(revision, extra=None):
    p = {"schema": "openagents.agent.definition.v1",
         "definition": {"id": AGENT_ID, "revision": revision,
                        "spec": {"name": "Triage", "description": "Sorts new issues",
                                 "instructions": INSTRUCTIONS, "runtime": "codex",
                                 "model": None, "access": "read_only"},
                        "deleted": False}}
    if extra:
        p.update(extra)
    return dumps(p)


def jcs_digest(text):
    canon = json.dumps(json.loads(text), sort_keys=True, separators=(",", ":"), ensure_ascii=False)
    return "sha256:" + hashlib.sha256(canon.encode()).hexdigest(), len(canon.encode())


def envelope(text, digest=None):
    d, size = jcs_digest(text)
    return dumps({"v": "openagents.artifact-envelope.v1", "requires": [],
                  "artifact": {"digest": digest or d, "size": size, "media_type": "application/json",
                               "schema": "openagents.agent.definition.v1"},
                  "inline": json.loads(text), "issued_at": T0, "retain_until": T0 + 86400})


def sealed(body, to_secret, p_secret, kind=3188, aux=0x41, nonce=0x24):
    to_pub = xonly(to_secret)
    ck = conversation_key(SENDER, to_pub)
    content = nip44_encrypt(ck, bytes([nonce]) * 32, body.encode())
    tags = [["p", xonly(p_secret).hex()], ["h", MAILBOX], ["t", "oa:artifact:v1"]]
    pub = xonly(SENDER).hex()
    eid = event_id(pub, T0, kind, tags, content)
    sig = sign(SENDER, eid, bytes([aux]) * 32)
    return eid.hex(), dumps({"id": eid.hex(), "pubkey": pub, "created_at": T0, "kind": kind,
                             "tags": tags, "content": content, "sig": sig.hex()})


def coax(name, s):
    print("%s :: \"%s\";" % (name, s.replace("\\", "\\\\").replace("\"", "\\\"")))


p3, p4 = payload(3), payload(4)
digest3, _ = jcs_digest(p3)
digest4, _ = jcs_digest(p4)
ok_id, ok = sealed(envelope(p3), RECIPIENT, RECIPIENT)
r4_id, r4 = sealed(envelope(p4), RECIPIENT, RECIPIENT, aux=0x42, nonce=0x25)

print("// Generated by coax/tests/nostr/agent_carriage_vectors.py: NIP-AGENT 3188")
print("// private artifacts sealed by an independent NIP-44 v2 and BIP-340.")
print("// TEST keys: sender scalar 1, recipient 3, another host 2.")
coax("ACV_SENDER_SECRET", SENDER.hex())
coax("ACV_SENDER_X", xonly(SENDER).hex())
coax("ACV_RECIPIENT_SECRET", RECIPIENT.hex())
coax("ACV_RECIPIENT_X", xonly(RECIPIENT).hex())
coax("ACV_OTHER_X", xonly(OTHER).hex())
coax("ACV_AGENT_ID", AGENT_ID)
coax("ACV_MAILBOX", MAILBOX)
coax("ACV_PAYLOAD", p3)
coax("ACV_DIGEST", digest3)
coax("ACV_DIGEST_R4", digest4)
coax("ACV_SEALED_ID", ok_id)
coax("ACV_SEALED", ok)
coax("ACV_SEALED_R4_ID", r4_id)
coax("ACV_SEALED_R4", r4)
coax("ACV_FOR_OTHER", sealed(envelope(p3), OTHER, OTHER, aux=0x43)[1])
coax("ACV_KIND1", sealed(envelope(p3), RECIPIENT, RECIPIENT, kind=1, aux=0x44)[1])
coax("ACV_BAD_DIGEST", sealed(envelope(p3, digest=digest4), RECIPIENT, RECIPIENT, aux=0x45)[1])
coax("ACV_GRANTS", sealed(envelope(payload(3, {"grants": []})), RECIPIENT, RECIPIENT, aux=0x46)[1])
coax("ACV_WRONG_KEY", sealed(envelope(p3), OTHER, RECIPIENT, aux=0x47)[1])
