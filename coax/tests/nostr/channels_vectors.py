#!/usr/bin/env python3
"""Channel events for chapter 89 (NIP-CL, NIP-CW, NIP-DV).

Written from NIP-01, NIP-10, Block's NIP-CL, NIP-CW and NIP-DV with only
hashlib and integers (signing comes from nip59_reference.py, which shares no
code with Coax). Tooling only, never shipped. TEST keys only: Alice is the
secp256k1 scalar 1, Bob 2 and the relay 3.

  python3 coax/tests/nostr/channels_vectors.py > coax/tests/nostr/channels_vectors.coax

Besides the signed events it prints the pages a channel window must return,
computed here independently: the top-level rows (no reply-marked e tag, or a
depth-1 reply with ["broadcast", "1"]) sorted by (-created_at, id), cut
into pages of two, each page ending with has_more and its next cursor.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from nip59_reference import dumps, k, signed, xonly  # noqa: E402
import json  # noqa: E402

T0 = 1790000000
ALICE, BOB, RELAY = k(1), k(2), k(3)
CH = "general"


def msg(secret, aux, at, content, extra=()):
    return json.loads(signed(secret, bytes([aux]) * 32, at, 9, [["h", CH]] + list(extra), content))


m1 = msg(ALICE, 0x41, T0, "Hello, channel.")
m2 = msg(BOB, 0x42, T0 + 60, "Lunch at noon?")
m3 = msg(ALICE, 0x43, T0 + 60, "Deploy done.")
m4 = msg(BOB, 0x44, T0 + 60, "Standup moved to 10.")
r1 = msg(BOB, 0x45, T0 + 90, "Nice work.",
         [["e", m3["id"], "", "root"], ["e", m3["id"], "", "reply"]])
r2 = msg(ALICE, 0x46, T0 + 120, "Thanks. Release notes are in the wiki.",
         [["e", m3["id"], "", "root"], ["e", m3["id"], "", "reply"], ["broadcast", "1"]])
events = [m1, m2, m3, m4, r1, r2]


def is_reply(e):
    return any(t[0] == "e" and len(t) >= 4 and t[3] == "reply" for t in e["tags"])


def top(e):
    return not is_reply(e) or ["broadcast", "1"] in e["tags"]


rows = sorted((e for e in events if top(e)), key=lambda e: (-e["created_at"], e["id"]))
pages = [rows[i:i + 2] for i in range(0, len(rows), 2)]

# The relay's 39000 for the channel and Alice's DM visibility snapshot.
alice = xonly(ALICE).hex()
meta = signed(RELAY, bytes([0x47]) * 32, T0 + 1, 39000,
              [["d", CH], ["t", "stream"], ["t", "team"], ["P", alice], ["created_at", str(T0)]], "")
snap = signed(RELAY, bytes([0x48]) * 32, T0 + 200, 30622,
              [["d", alice], ["p", alice], ["h", "dm-ab"]], "")


# Commands: Alice creates the channel with the label team (at T0, the
# relay's clock); two creates that refuse on their labels; Alice creates a
# system channel; Alice sets the workspace icon, and an icon that refuses.
cmds = {
    "CREATE": signed(ALICE, bytes([0x51]) * 32, T0, 9007, [["h", CH], ["t", "team"]], ""),
    "CREATE_SPACE": signed(BOB, bytes([0x52]) * 32, T0, 9007, [["h", "chat"], ["t", "Team Chat"]], ""),
    "CREATE_DM_LABEL": signed(BOB, bytes([0x53]) * 32, T0, 9007, [["h", "chat"], ["t", "dm"]], ""),
    "CREATE_SYSTEM": signed(ALICE, bytes([0x54]) * 32, T0 + 5, 9007,
                            [["h", "agent-cfg"], ["channel_type", "system"], ["t", "agent-config"]], ""),
    "ICON": signed(ALICE, bytes([0x55]) * 32, T0 + 300, 9033, [["icon", "https://example.com/team.png"]], ""),
    "ICON_SCRIPT": signed(ALICE, bytes([0x56]) * 32, T0 + 301, 9033, [["icon", "javascript:alert(1)"]], ""),
}


def coax(name, s):
    print("%s :: \"%s\";" % (name, s.replace("\\", "\\\\").replace("\"", "\\\"").replace("\n", "\\n")))


print("// Generated by coax/tests/nostr/channels_vectors.py: channel events signed")
print("// by an independent BIP-340, and the window pages computed in Python.")
print("// TEST keys: Alice is scalar 1, Bob 2, the relay 3.")
coax("CHV_ALICE", alice)
coax("CHV_BOB", xonly(BOB).hex())
coax("CHV_RELAY", xonly(RELAY).hex())
for name, e in zip(["M1", "M2", "M3", "M4", "R1", "R2"], events):
    coax("CHV_" + name, dumps(e))
    coax("CHV_%s_ID" % name, e["id"])
for i, page in enumerate(pages):
    coax("CHV_PAGE%d" % (i + 1), ",".join(e["id"][:8] for e in page))
    more = i + 1 < len(pages)
    coax("CHV_PAGE%d_NEXT" % (i + 1), "%d:%s" % (page[-1]["created_at"], page[-1]["id"]) if more else "null")
coax("CHV_META", meta)
coax("CHV_META_ID", json.loads(meta)["id"])
coax("CHV_SNAPSHOT", snap)
coax("CHV_SNAPSHOT_ID", json.loads(snap)["id"])
for name, e in cmds.items():
    coax("CHV_" + name, e)
