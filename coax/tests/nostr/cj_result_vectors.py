#!/usr/bin/env python3
"""NIP-CJ execution request and result events for chapter 80.

Written from NIP-01, NIP-44 v2, BIP-340 and NIP-CJ with only hashlib and
integers (signing and encryption come from nip59_reference.py, which shares
no code with Coax). Tooling only, never shipped. Test keys only: the buyer
is the secp256k1 scalar 1, the worker 3 and an impostor 7.

  python3 coax/tests/nostr/cj_result_vectors.py > coax/tests/nostr/cj_result_vectors.coax

It prints the Coax constants coax/lib/nostr/cj/result.coax and
nostr/examples/labor-market.coax read: one 25920 execute request from the
buyer to worker 3, and six answers to it: worker 3's 26920 result and 27020
acceptance, the same result signed by key 7, a 26900 conversation result,
a result whose e tag names another event and one whose p tag names key 7.
Each with its NIP-01 id; every content is NIP-44 v2 to its recipient.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from nip59_reference import conversation_key, dumps, event_id, nip44_encrypt, sign, xonly  # noqa: E402

T0 = 1790000000
BUYER, WORKER, IMPOSTOR = (1).to_bytes(32, "big"), (3).to_bytes(32, "big"), (7).to_bytes(32, "big")
B, W, X = xonly(BUYER).hex(), xonly(WORKER).hex(), xonly(IMPOSTOR).hex()
REQUEST_ID = "1" * 64
RUN_ID = "2" * 64


def event(secret, aux, at, kind, tags, body, to):
    pub = xonly(secret).hex()
    content = nip44_encrypt(conversation_key(secret, bytes.fromhex(to)), bytes([aux]) * 32, dumps(body).encode())
    eid = event_id(pub, at, kind, tags, content)
    sig = sign(secret, eid, bytes([aux]) * 32)
    return eid.hex(), dumps({"id": eid.hex(), "pubkey": pub, "created_at": at, "kind": kind,
                             "tags": tags, "content": content, "sig": sig.hex()})


def result_body(kind):
    return {"v": "openagents.execution.v1", "requires": ["openagents.labor-binding.v1"],
            "type": kind, "request": REQUEST_ID, "attempt": 1, "run": RUN_ID}


req = event(BUYER, 0x41, T0 + 400, 25920, [["p", W]],
            {"v": "openagents.execution.v1", "requires": ["openagents.labor-binding.v1"],
             "type": "execute", "request": REQUEST_ID, "attempt": 1, "run": RUN_ID,
             "deadline": T0 + 3600, "retain_until": T0 + 30 * 86400}, W)
ok = event(WORKER, 0x42, T0 + 900, 26920, [["p", B], ["e", req[0]]], result_body("result"), B)
acc = event(WORKER, 0x43, T0 + 401, 27020, [["p", B], ["e", req[0]]], result_body("accepted"), B)
imp = event(IMPOSTOR, 0x44, T0 + 900, 26920, [["p", B], ["e", req[0]]], result_body("result"), B)
fam = event(WORKER, 0x45, T0 + 900, 26900, [["p", B], ["e", req[0]]], {"v": 1, "requires": [], "type": "result", "text": "done"}, B)
wre = event(WORKER, 0x46, T0 + 900, 26920, [["p", B], ["e", "3" * 64]], result_body("result"), B)
wrp = event(WORKER, 0x47, T0 + 900, 26920, [["p", X], ["e", req[0]]], result_body("result"), X)


def coax(name, s):
    print("%s :: \"%s\";" % (name, s.replace("\\", "\\\\").replace("\"", "\\\"")))


print("// Generated by coax/tests/nostr/cj_result_vectors.py: NIP-CJ events signed")
print("// and encrypted by an independent BIP-340 and NIP-44 (TEST keys 1, 3, 7).")
for name, (eid, text) in [("REQUEST", req), ("RESULT", ok), ("ACCEPTED", acc), ("IMPOSTOR", imp),
                          ("FAMILY", fam), ("WRONG_E", wre), ("WRONG_P", wrp)]:
    coax("CJV_" + name, text)
    coax("CJV_" + name + "_ID", eid)
