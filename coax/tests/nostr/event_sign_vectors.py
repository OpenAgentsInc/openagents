#!/usr/bin/env python3
"""Writes event_sign_vectors.coax: one NIP-01 event signed independently in
pure Python (BIP-340 vector 1's key and aux), with escapes in tags and content."""
if not __debug__: raise SystemExit('tests require Python assertions')
import csv,json,hashlib,sys
from pathlib import Path
R=Path(__file__).resolve().parents[2].parent;sys.path.insert(0,str(R/'tools/coax-nostr/fuzz'))
from oracle import N,point_mul,tagged,schnorr_verify
row=list(csv.DictReader(open(R/'coax/tests/vectors/upstream/bip340/test-vectors.csv')))[1]
d0=int(row['secret key'],16);aux=bytes.fromhex(row['aux_rand'])
def sign(m):
 P=point_mul(d0);d=N-d0 if P[1]&1 else d0;pub=P[0].to_bytes(32,'big')
 t=bytes(x^y for x,y in zip(d.to_bytes(32,'big'),tagged('BIP0340/aux',aux)))
 k0=int.from_bytes(tagged('BIP0340/nonce',t+pub+m),'big')%N;Rp=point_mul(k0);k=N-k0 if Rp[1]&1 else k0
 r=Rp[0].to_bytes(32,'big');e=int.from_bytes(tagged('BIP0340/challenge',r+pub+m),'big')%N
 sig=r+((k+e*d)%N).to_bytes(32,'big');assert schnorr_verify(m,pub,sig);return pub,sig
created=1730000000;kind=1
tags=[['e','5c83da77af1dec6d7289834998ad7aafbd9e2191396d75ec3cc27f5a77226f36','wss://nostr.example.com'],
 ['p','f7234bd4c1394dda46d09f35bd384dd30cc552ad5541990f98844fb06676e9ca'],[],['t','a"b\\c','é']]
# The caller's tags text uses escapes the writer must normalize: A and \/.
tags_text='[["e","5c83da77af1dec6d7289834998ad7aafbd9e2191396d75ec3cc27f5a77226f36","wss:\\/\\/nostr.example.com"],["p","f7234bd4c1394dda46d09f35bd384dd30cc552ad5541990f98844fb06676e9ca"],[],["t","a\\"b\\\\c","\\u00e9"]]'
assert json.loads(tags_text)==tags
content='line one\nline two\t"quoted" \\ back\r\x08\x0c é 😀'
dump=lambda v:json.dumps(v,separators=(',',':'),ensure_ascii=False)
pub=point_mul(d0)[0].to_bytes(32,'big')
pre=dump([0,pub.hex(),created,kind,tags,content]).encode()
eid=hashlib.sha256(pre).digest();_,sig=sign(eid)
event=('{"id":%s,"pubkey":%s,"created_at":%d,"kind":%d,"tags":%s,"content":%s,"sig":%s}'%(
 dump(eid.hex()),dump(pub.hex()),created,kind,dump(tags),dump(content),dump(sig.hex()))).encode()
def arr(data):return '[%d]u8.[%s]'%(len(data),','.join('0x%02x'%c for c in data))
lines=['// Generated by event_sign_vectors.py: one event signed in pure Python.',
 'ES_KEY :: %s;'%arr(bytes.fromhex(row['secret key'])),'ES_AUX :: %s;'%arr(aux),
 'ES_CREATED :: %d;'%created,'ES_KIND :: %d;'%kind,
 'ES_TAGS :: %s;'%arr(tags_text.encode()),'ES_CONTENT :: %s;'%arr(content.encode()),
 'ES_PUB :: %s;'%arr(pub),'ES_ID :: %s;'%arr(eid),'ES_SIG :: %s;'%arr(sig),
 'ES_PREIMAGE :: %s;'%arr(pre),'ES_EVENT :: %s;'%arr(event)]
Path(__file__).with_suffix('.coax').write_text('\n'.join(lines)+'\n')
print(len(pre),len(event))
