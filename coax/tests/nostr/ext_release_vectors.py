#!/usr/bin/env python3
"""NIP-EXT release, revocation and checkpoint events for chapter 77.

Written from NIP-01, BIP-340 and NIP-EXT with only hashlib and integers
(the signing comes from nip59_reference.py, which shares no code with
Coax). Tooling only, never shipped. Test keys only: the root is the
secp256k1 scalar 1, the impostor the scalar 2.

  python3 coax/tests/nostr/ext_release_vectors.py > coax/tests/nostr/ext_release_vectors.coax

It prints the Coax constants nostr/examples/extensions-policy.coax reads:
two package manifests, four 3184 releases (1.0.0, 1.0.1, an equivocating
1.0.0 and one signed by another key), the 3185 revocation of 1.0.0 and the
30185 checkpoint that lists it, each event with its NIP-01 id.
"""
import hashlib
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from nip59_reference import dumps, event_id, sign, xonly  # noqa: E402

T0 = 1790000000
ROOT, OTHER = (1).to_bytes(32, "big"), (2).to_bytes(32, "big")
PK = xonly(ROOT).hex()
PACKAGE = PK + ":hello"


def manifest(version, kinds):
    return dumps({"v": "openagents.package.v1", "requires": [], "package": PACKAGE,
                  "version": version, "license": "MIT",
                  "provenance": {"source": None, "receipts": [], "unknowns": ["build"]},
                  "components": [{"slug": "c%d" % i, "kind": k} for i, k in enumerate(kinds)],
                  "files": [], "dependencies": []})


def ref(text):
    b = text.encode()
    return {"digest": "sha256:" + hashlib.sha256(b).hexdigest(), "size": len(b),
            "media_type": "application/json", "schema": "openagents.package.v1"}


def event(secret, aux, at, kind, tags, content):
    pub = xonly(secret).hex()
    eid = event_id(pub, at, kind, tags, content)
    sig = sign(secret, eid, bytes([aux]) * 32)
    return eid.hex(), dumps({"id": eid.hex(), "pubkey": pub, "created_at": at, "kind": kind,
                             "tags": tags, "content": content, "sig": sig.hex()})


def release(secret, aux, at, version, m):
    body = dumps({"v": 1, "requires": [], "type": "release", "package": PACKAGE,
                  "version": version, "manifest": ref(m)})
    return event(secret, aux, at, 3184, [["t", "oa:ext:release:v1"]], body)


def coax(name, s):
    print("%s :: \"%s\";" % (name, s.replace("\\", "\\\\").replace("\"", "\\\"")))


m1 = manifest("1.0.0", ["skill", "guidance"])
m2 = manifest("1.0.1", ["skill", "guidance"])
r1 = release(ROOT, 0x31, T0, "1.0.0", m1)
r2 = release(ROOT, 0x32, T0 + 100, "1.0.1", m2)
eq = release(ROOT, 0x33, T0 + 50, "1.0.0", m2)
fk = release(OTHER, 0x34, T0 + 60, "1.0.0", m1)
rv = event(ROOT, 0x35, T0 + 1000, 3185, [["e", r1[0]], ["t", "oa:ext:revocation:v1"]],
           dumps({"v": 1, "requires": [], "type": "revocation", "package": PACKAGE,
                  "release": {"id": r1[0], "pubkey": PK, "kind": 3184},
                  "reason": "1.0.0 writes the API key to its log", "effective_at": T0 + 1000}))
cp = event(ROOT, 0x36, T0 + 1000, 30185, [["d", "hello"], ["t", "oa:ext:checkpoint:v1"]],
           dumps({"v": 1, "requires": [], "type": "checkpoint", "package": PACKAGE, "revision": 1,
                  "as_of": T0 + 1000, "valid_until": T0 + 1000 + 86400,
                  "revocations": [{"id": rv[0], "pubkey": PK, "kind": 3185}]}))

print("// Generated by coax/tests/nostr/ext_release_vectors.py: NIP-EXT events")
print("// signed by an independent BIP-340 (TEST keys: root scalar 1, other 2).")
coax("EXT_MANIFEST_1", m1)
coax("EXT_MANIFEST_2", m2)
for name, (eid, text) in [("RELEASE_1", r1), ("RELEASE_2", r2), ("EQUIVOCATION", eq),
                          ("FOREIGN", fk), ("REVOCATION", rv), ("CHECKPOINT", cp)]:
    coax("EXT_%s_ID" % name, eid)
    coax("EXT_%s" % name, text)
coax("EXT_MANIFEST_1_DIGEST", hashlib.sha256(m1.encode()).hexdigest())
coax("EXT_MANIFEST_2_DIGEST", hashlib.sha256(m2.encode()).hexdigest())
