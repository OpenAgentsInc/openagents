#!/usr/bin/env python3
"""NIP-KB events and NIP-WS document digests for chapter 84.

Written from NIP-01, BIP-340, NIP-KB and NIP-WS with only hashlib and
integers (signing comes from nip59_reference.py, which shares no code with
Coax). Tooling only, never shipped. TEST keys only: the author is the
secp256k1 scalar 1, another author 2.

  python3 coax/tests/nostr/kb_vectors.py > coax/tests/nostr/kb_vectors.coax

The x tag is the lowercase hex SHA-256 of the exact document bytes. The
workspace texts are the entry file as it moves through one conditional
edit, one stale edit and a merge by hand; the merged text is version 2.
"""
import hashlib
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from nip59_reference import dumps, k, signed, xonly  # noqa: E402

T0 = 1790000000
AUTHOR, OTHER = k(1), k(2)
EID = "statistics.mmd-estimators"


def doc(version, details, check=False, front_version=None):
    v = front_version if front_version is not None else version
    text = ("---\nid: %s\nversion: %d\nkind: method\n"
            "title: Biased and unbiased MMD estimators\nstatus: admitted\n---\n"
            "## Details\n%s\n" % (EID, v, details))
    if check:
        text += "## How to check\nTwo samples from one distribution give an unbiased value near 0.\n"
    return text


WRONG = "The unbiased estimator divides the within-sample sums by m^2."
RIGHT = "The unbiased estimator divides the within-sample sums by m(m-1)."
DOC1 = doc(1, WRONG)
TEXT_A = doc(1, RIGHT)               # Alice's edit: the denominator
TEXT_B = doc(1, WRONG, check=True)   # Bob's edit: a check section
DOC2 = doc(2, RIGHT, check=True)     # merged by hand, published as version 2
DOC2_OTHER = doc(2, RIGHT + " Bias is O(1/m).")


def sha(text):
    return hashlib.sha256(text.encode()).hexdigest()


def entry(version, document, secret=AUTHOR, at=T0, d=EID, x=None, body_extra=None, aux=0x11):
    body = {"v": 1, "requires": [], "type": "entry", "id": EID, "version": version,
            "kind": "method", "document": document}
    if body_extra:
        body.update(body_extra)
    tags = [["d", d], ["x", x or sha(document)], ["t", "oa:kb:entry:v1"],
            ["t", "oa:kb:kind:method"], ["t", "statistics"]]
    return signed(secret, bytes([aux]) * 32, at, 3190, tags, dumps(body))


def ref(text):
    import json
    return json.loads(text)


def pointer(kind, typ, target, secret=AUTHOR, at=T0, aux=0x21, reason=None):
    e = ref(target)
    body = {"v": 1, "requires": [], "type": typ, "id": EID,
            "version": ref(e["content"])["version"],
            "entry": {"id": e["id"], "pubkey": e["pubkey"], "kind": 3190}}
    if reason is not None:
        body["reason"] = reason
    tags = [["d", EID], ["e", e["id"]], ["t", "oa:kb:%s:v1" % typ]]
    return signed(secret, bytes([aux]) * 32, at, kind, tags, dumps(body))


def coax(name, s):
    print("%s :: \"%s\";" % (name, s.replace("\\", "\\\\").replace("\"", "\\\"").replace("\n", "\\n")))


e1 = entry(1, DOC1, aux=0x11)
e2 = entry(2, DOC2, at=T0 + 100, aux=0x12)
h2 = pointer(30190, "head", e2, at=T0 + 110, aux=0x13)
w2 = pointer(3191, "withdrawal", e2, at=T0 + 200, aux=0x14,
             reason="The check section's claim needs a citation.")
eq = entry(2, DOC2_OTHER, at=T0 + 120, aux=0x15)
e3 = entry(3, doc(3, RIGHT, check=True), at=T0 + 300, aux=0x16)
bad_sig = ref(e1)
bad_sig["sig"] = bad_sig["sig"][:-2] + ("00" if bad_sig["sig"][-2:] != "00" else "01")

print("// Generated by coax/tests/nostr/kb_vectors.py: NIP-KB events signed by an")
print("// independent BIP-340, and the NIP-WS worked example's texts and digests.")
print("// TEST keys: the author is scalar 1, another author 2.")
coax("KBV_AUTHOR", xonly(AUTHOR).hex())
coax("KBV_OTHER", xonly(OTHER).hex())
coax("KBV_DOC1", DOC1)
coax("KBV_DOC1_SHA", sha(DOC1))
coax("KBV_TEXT_A", TEXT_A)
coax("KBV_TEXT_A_SHA", sha(TEXT_A))
coax("KBV_TEXT_B", TEXT_B)
coax("KBV_TEXT_B_SHA", sha(TEXT_B))
coax("KBV_DOC2", DOC2)
coax("KBV_DOC2_SHA", sha(DOC2))
coax("KBV_E1", e1)
coax("KBV_E1_ID", ref(e1)["id"])
coax("KBV_E2", e2)
coax("KBV_E2_ID", ref(e2)["id"])
coax("KBV_HEAD2", h2)
coax("KBV_HEAD2_ID", ref(h2)["id"])
coax("KBV_WITHDRAW2", w2)
coax("KBV_WITHDRAW2_ID", ref(w2)["id"])
coax("KBV_E3", e3)
coax("KBV_E3_ID", ref(e3)["id"])
coax("KBV_EQUIVOCATION", eq)
coax("KBV_EQUIVOCATION_ID", ref(eq)["id"])
# The conformance fixtures NIP-KB lists, each re-signed so only its own fault shows.
coax("KBV_TAMPERED_DOCUMENT", entry(2, DOC2.replace("m(m-1)", "m^2"), at=T0 + 100, x=sha(DOC2), aux=0x31))
coax("KBV_TAMPERED_SIGNATURE", dumps(bad_sig))
coax("KBV_TAG_DISAGREES", entry(1, DOC1, d="statistics.other", aux=0x32))
coax("KBV_FRONT_DISAGREES", entry(3, doc(3, RIGHT, front_version=2), aux=0x33))
coax("KBV_HEAD_BY_OTHER", pointer(30190, "head", e2, secret=OTHER, aux=0x34))
coax("KBV_WITHDRAWAL_BY_OTHER", pointer(3191, "withdrawal", e1, secret=OTHER, aux=0x35, reason="Wrong."))
coax("KBV_KIND1", signed(AUTHOR, bytes([0x37]) * 32, T0, 1, [], "not a KB record"))
coax("KBV_EMPTY", signed(AUTHOR, bytes([0x38]) * 32, T0, 3190, [["d", EID]], ""))
coax("KBV_VECTOR_FIELD", entry(1, DOC1, body_extra={"embedding": [0.5, 0.25]}, aux=0x36))
