// Generates coax/tests/nostr/nip44_vectors.coax from the pinned NIP-44 corpus.
// Tooling only; never shipped. Inputs:
//   coax/tests/vectors/upstream/nip44/nip44.vectors.json (sha256 269ed0f6...)
// Independent oracles (already installed for the project board tool, not
// downloaded by this script): @noble/curves 1.8.1 supplies the raw shared x
// that the vectors' get_conversation_key rows imply, and nostr-effect 0.0.13
// (@noble/ciphers, @noble/hashes, @scure/base) encrypts throwaway-key
// interoperability rows. No production key is used.
//
//   ln -s <board>/coax/web/project/node_modules coax/web/project/node_modules
//   bun coax/tests/nostr/nip44_fixtures.ts > coax/tests/nostr/nip44_vectors.coax
import { readFileSync } from "node:fs"
import { createHash } from "node:crypto"
import { secp256k1 } from "../../web/project/node_modules/@noble/curves/secp256k1.js"
import * as nip44 from "../../web/project/node_modules/nostr-effect/src/wrappers/nip44.ts"

const path = new URL("../vectors/upstream/nip44/nip44.vectors.json", import.meta.url)
const raw = readFileSync(path)
const digest = createHash("sha256").update(raw).digest("hex")
if (digest !== "269ed0f69e4c192512cc779e78c555090cebc7c785b609e338a62afc3ce25040") throw new Error("vector file digest")
const v = JSON.parse(raw.toString("utf8")).v2

const hex = (s: string) => Uint8Array.from(Buffer.from(s, "hex"))
const utf8 = (s: string) => new TextEncoder().encode(s)
const lit = (b: Uint8Array) => `[${b.length}]u8.[${Array.from(b).join(",")}]`
const sharedX = (sec: string, pubX: string) => secp256k1.getSharedSecret(hex(sec), hex("02" + pubX)).subarray(1, 33)
const pubOf = (sec: string) => Buffer.from(secp256k1.getPublicKey(hex(sec), true).subarray(1)).toString("hex")

const out: string[] = []
const emit = (s: string) => out.push(s)

// Both directions with dirty work: conversation key from shared x, encrypt
// equals the reference payload under both profiles, decrypt returns plaintext.
const roundtrip = (n: number, chars: number) => {
  const prefix = n >= 65536 ? 6 : 2
  const padded = prefix + calcPadded(n)
  const raw = 65 + padded
  const ew = 2 * raw - 65
  emit(`  key:[33]u8;key[32]=165;`)
  emit(`  #assert nip44_conversation_key_checked(shared[..],key[..],false)==NIP44_OK;`)
  emit(`  for j:0..<32 {#assert key[j]==ck[j];} #assert key[32]==165;`)
  emit(`  #assert nip44_payload_size(NIP44_COMPAT,${n})==${chars} && nip44_encrypt_work_size(NIP44_COMPAT,${n})==${ew};`)
  emit(`  for profile:[2]u32.[NIP44_COMPAT,NIP44_EXTENDED] {`)
  emit(`    work:[${ew}]u8;for i:0..<${ew} {work[i]=165;} out:[${chars + 1}]u8;out[${chars}]=165;`)
  emit(`    r:=nip44_encrypt_checked(profile,ck[..],nonce[..],plain[..],work[..],out[..],false);`)
  emit(`    #assert r.error==NIP44_OK && r.written==${chars} && out[${chars}]==165;`)
  emit(`    for j:0..<${chars} {#assert out[j]==payload[j];}`)
  emit(`    dwork:[${2 * Math.floor(chars / 4) * 3 - 65}]u8;for i:0..<dwork.count {dwork[i]=165;} back:[${n + 1}]u8;back[${n}]=165;`)
  emit(`    d:=nip44_decrypt_checked(profile,ck[..],cast(string)payload[..],dwork[..],back[..],false);`)
  emit(`    #assert d.error==NIP44_OK && d.written==${n} && back[${n}]==165;`)
  emit(`    for j:0..<${n} {#assert back[j]==plain[j];}`)
  emit(`  }`)
}
const calcPadded = (n: number) => {
  if (n <= 32) return 32
  const next = 2 ** (Math.floor(Math.log2(n - 1)) + 1)
  const chunk = next <= 256 ? 32 : next / 8
  return chunk * (Math.floor((n - 1) / chunk) + 1)
}
emit("// GENERATED by nip44_fixtures.ts from tests/vectors/upstream/nip44/nip44.vectors.json")
emit("// (paulmillr/nip44 671a1f04, sha256 269ed0f6...). Do not edit by hand.")
emit("// shared_x columns come from @noble/curves 1.8.1; interop rows from nostr-effect 0.0.13.")
emit("")

// calc_padded_len
emit(`#test "NIP-44 calc_padded_len: all ${v.valid.calc_padded_len.length} upstream rows" {`)
emit(`  rows:=[${v.valid.calc_padded_len.length}][2]int.[${v.valid.calc_padded_len.map((r: number[]) => `[2]int.[${r[0]},${r[1]}]`).join(",")}];`)
emit(`  for r:rows {#assert nip44_calc_padded_len(r[0])==r[1];}`)
emit("}")

// get_message_keys
const mk = v.valid.get_message_keys
emit(`#test "NIP-44 get_message_keys: all ${mk.keys.length} upstream rows" {`)
emit(`  ck:=${lit(hex(mk.conversation_key))};`)
emit(`  nonces:=[${mk.keys.length}][32]u8.[${mk.keys.map((k: any) => lit(hex(k.nonce))).join(",")}];`)
emit(`  expected:=[${mk.keys.length}][76]u8.[${mk.keys.map((k: any) => lit(new Uint8Array([...hex(k.chacha_key), ...hex(k.chacha_nonce), ...hex(k.hmac_key)]))).join(",")}];`)
emit(`  for i:0..<${mk.keys.length} {`)
emit(`    keys:[77]u8;keys[76]=165;`)
emit(`    #assert nip44_message_keys_checked(ck[..],nonces[i][..],keys[..],false)==NIP44_OK;`)
emit(`    for j:0..<76 {#assert keys[j]==expected[i][j];} #assert keys[76]==165;`)
emit(`  }`)
emit("}")

// get_conversation_key via caller-supplied raw shared x
const ckRows = v.valid.get_conversation_key
emit(`#test "NIP-44 get_conversation_key: all ${ckRows.length} upstream rows from oracle shared x" {`)
emit(`  shared:=[${ckRows.length}][32]u8.[${ckRows.map((r: any) => lit(sharedX(r.sec1, r.pub2))).join(",")}];`)
emit(`  expected:=[${ckRows.length}][32]u8.[${ckRows.map((r: any) => lit(hex(r.conversation_key))).join(",")}];`)
emit(`  for i:0..<${ckRows.length} {`)
emit(`    key:[33]u8;key[32]=165;`)
emit(`    #assert nip44_conversation_key_checked(shared[i][..],key[..],false)==NIP44_OK;`)
emit(`    for j:0..<32 {#assert key[j]==expected[i][j];} #assert key[32]==165;`)
emit(`  }`)
emit("}")

// encrypt_decrypt: both directions
v.valid.encrypt_decrypt.forEach((r: any, i: number) => {
  const pub2 = pubOf(r.sec2), pub1 = pubOf(r.sec1)
  const x12 = sharedX(r.sec1, pub2), x21 = sharedX(r.sec2, pub1)
  if (Buffer.compare(Buffer.from(x12), Buffer.from(x21)) !== 0) throw new Error("ecdh symmetry")
  const p = utf8(r.plaintext), payload = utf8(r.payload)
  emit(`#test "NIP-44 encrypt_decrypt upstream row ${i}" {`)
  emit(`  shared:=${lit(x12)};ck:=${lit(hex(r.conversation_key))};nonce:=${lit(hex(r.nonce))};`)
  emit(`  plain:=${lit(p)};payload:=${lit(payload)};`)
  roundtrip(p.length, payload.length)
  emit("}")
})

// invalid decrypt
const code = (note: string) => {
  if (note === "unknown encryption version" || note.startsWith("unknown encryption version")) return "NIP44_VERSION"
  if (note === "invalid base64") return "NIP44_BASE64"
  if (note === "invalid MAC") return "NIP44_MAC"
  if (note === "invalid padding") return "NIP44_PADDING"
  if (note.startsWith("invalid payload length")) return "NIP44_PAYLOAD"
  throw new Error("unmapped note " + note)
}
v.invalid.decrypt.forEach((r: any, i: number) => {
  const payload = utf8(r.payload)
  emit(`#test "NIP-44 invalid decrypt upstream row ${i}: ${r.note}" {`)
  emit(`  ck:=${lit(hex(r.conversation_key))};payload:=${lit(new Uint8Array([...payload, 0]))};`)
  const w = 2 * Math.max(99, Math.floor(payload.length / 4) * 3)
  emit(`  work:[${w}]u8;for i:0..<${w} {work[i]=165;} out:=[4]u8.[165,165,165,165];`)
  emit(`  for profile:[2]u32.[NIP44_COMPAT,NIP44_EXTENDED] {`)
  emit(`    r:=nip44_decrypt_checked(profile,ck[..],cast(string)payload[0..<${payload.length}],work[..],out[..],false);`)
  emit(`    #assert r.error==${code(r.note)} && r.written==0;`)
  emit(`    for b:out {#assert b==165;}`)
  emit(`  }`)
  emit("}")
})

// invalid encrypt lengths: compat profile refuses all; the pinned extended NIP
// admits 65536 and 100000 and refuses 0 (length) and 10000000 (capacity).
emit(`#test "NIP-44 invalid encrypt_msg_lengths under both named profiles" {`)
emit(`  lengths:=[${v.invalid.encrypt_msg_lengths.length}]int.[${v.invalid.encrypt_msg_lengths.join(",")}];`)
emit(`  for n:lengths {`)
emit(`    compat:=nip44_encrypt_request(NIP44_COMPAT,32,32,n,1<<22,1<<22,false);`)
emit(`    extended:=nip44_encrypt_request(NIP44_EXTENDED,32,32,n,1<<22,1<<22,false);`)
emit(`    if n==0 {#assert compat==NIP44_LENGTH && extended==NIP44_LENGTH;}`)
emit(`    else if n<=NIP44_EXTENDED_MAX {#assert compat==NIP44_CAPACITY && extended==NIP44_OK;}`)
emit(`    else {#assert compat==NIP44_CAPACITY && extended==NIP44_CAPACITY;}`)
emit(`  }`)
emit("}")

// interoperability with nostr-effect, throwaway keys, deterministic nonces
const lengths = [1, 2, 31, 32, 33, 64, 65, 255, 256, 257, 300]
lengths.forEach((n, i) => {
  const secA = createHash("sha256").update("nip44-interop-a-" + i).digest("hex")
  const secB = createHash("sha256").update("nip44-interop-b-" + i).digest("hex")
  const nonce = createHash("sha256").update("nip44-interop-nonce-" + i).digest()
  let text = ""
  for (let k = 0; text.length < n; k++) text += String.fromCharCode(33 + ((k * 7 + i) % 94))
  text = text.slice(0, n)
  const ckA = nip44.getConversationKey(hex(secA), pubOf(secB))
  const ckB = nip44.getConversationKey(hex(secB), pubOf(secA))
  if (Buffer.compare(Buffer.from(ckA), Buffer.from(ckB)) !== 0) throw new Error("interop ck symmetry")
  const payload = nip44.encrypt(text, ckA, nonce)
  if (nip44.decrypt(payload, ckB) !== text) throw new Error("interop self")
  emit(`#test "NIP-44 interop with nostr-effect: throwaway keys, ${n}-byte plaintext" {`)
  emit(`  shared:=${lit(sharedX(secA, pubOf(secB)))};ck:=${lit(ckA)};nonce:=${lit(new Uint8Array(nonce))};`)
  emit(`  plain:=${lit(utf8(text))};payload:=${lit(utf8(payload))};`)
  const p = utf8(text)
  roundtrip(p.length, utf8(payload).length)
  emit("}")
})

console.log(out.join("\n"))
