# Generates coax/tests/nostr/nip44_key_vectors.coax from the pinned NIP-44
# corpus. Tooling only; never shipped, never needed at run time. Standard
# library only: the public keys of the encrypt_decrypt rows' sec2/sec1 come
# from a small affine secp256k1 multiply here, and the invalid rows' expected
# refusal (peer before secret, as ecdh_stage checks them) from Euler's
# criterion. The vectors' own conversation keys then check those keys.
#
#   python3 -I coax/tests/nostr/nip44_key_fixtures.py > coax/tests/nostr/nip44_key_vectors.coax
import hashlib
import json
import pathlib

P = 2**256 - 2**32 - 977
N = 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEBAAEDCE6AF48A03BBFD25E8CD0364141
G = (0x79BE667EF9DCBBAC55A06295CE870B07029BFCDB2DCE28D959F2815B16F81798,
     0x483ADA7726A3C4655DA4FBFC0E1108A8FD17B448A68554199C47D08FFB10D4B8)


def add(a, b):
    if a is None:
        return b
    if b is None:
        return a
    if a[0] == b[0] and (a[1] + b[1]) % P == 0:
        return None
    if a == b:
        m = 3 * a[0] * a[0] * pow(2 * a[1], P - 2, P) % P
    else:
        m = (b[1] - a[1]) * pow(b[0] - a[0], P - 2, P) % P
    x = (m * m - a[0] - b[0]) % P
    return (x, (m * (a[0] - x) - a[1]) % P)


def mul(k, point):
    r = None
    while k:
        if k & 1:
            r = add(r, point)
        point = add(point, point)
        k >>= 1
    return r


def pub_of(sec):
    return mul(int(sec, 16), G)[0].to_bytes(32, "big").hex()


def peer_valid(x_hex):
    x = int(x_hex, 16)
    if x >= P:
        return False
    rhs = (x * x * x + 7) % P
    return pow(rhs, (P - 1) // 2, P) in (0, 1)


def secret_valid(sec):
    return 0 < int(sec, 16) < N


def calc_padded(n):
    if n <= 32:
        return 32
    nxt = 1 << (n - 1).bit_length()
    chunk = 32 if nxt <= 256 else nxt // 8
    return chunk * ((n - 1) // chunk + 1)


def lit(b):
    return "[%d]u8.[%s]" % (len(b), ",".join(str(x) for x in b))


def hexlit(h):
    return lit(bytes.fromhex(h))


def rows_lit(hexes):
    return "[%d][32]u8.[%s]" % (len(hexes), ",".join(hexlit(h) for h in hexes))


root = pathlib.Path(__file__).resolve().parent
raw = (root / "../vectors/upstream/nip44/nip44.vectors.json").read_bytes()
if hashlib.sha256(raw).hexdigest() != "269ed0f69e4c192512cc779e78c555090cebc7c785b609e338a62afc3ce25040":
    raise SystemExit("vector file digest")
v = json.loads(raw)["v2"]
out = []
emit = out.append

emit("// GENERATED by nip44_key_fixtures.py from tests/vectors/upstream/nip44/nip44.vectors.json")
emit("// (paulmillr/nip44 671a1f04, sha256 269ed0f6...). Do not edit by hand.")
emit("// Every conversation key here comes from the two keys through our own ECDH.")
emit('#load "../../lib/nostr/nip44-key.coax";')
emit("")
emit("// The whole caller scratch reads zero; ECDH work is wiped on every accepted path.")
emit("nip44_key_test_clear :: (w:EcdhScratch)->bool {")
emit("  bits:u64;")
emit("  for i:0..<8 {bits|=cast(u64)w.scalar.limbs[i];}")
emit("  for i:0..<10 {bits|=w.shared.x.limb[i]|w.shared.y.limb[i]|w.shared.z.limb[i]|w.affine.x.limb[i]|w.affine.y.limb[i];}")
emit("  bits|=w.affine.infinity;")
emit("  for i:0..<32 {bits|=cast(u64)w.staged[i];}")
emit("  return bits==0;")
emit("}")
emit("nip44_key_test_dirty :: ()->[1]EcdhScratch {")
emit("  w:[1]EcdhScratch;")
emit("  for i:0..<8 {w[0].scalar.limbs[i]=165;}")
emit("  for i:0..<10 {w[0].shared.x.limb[i]=165;w[0].shared.y.limb[i]=165;w[0].shared.z.limb[i]=165;w[0].affine.x.limb[i]=165;w[0].affine.y.limb[i]=165;}")
emit("  w[0].affine.infinity=165;")
emit("  for i:0..<32 {w[0].staged[i]=165;}")
emit("  return w;")
emit("}")

# valid get_conversation_key, split so each check stays in a modest budget
ck = v["valid"]["get_conversation_key"]
CHUNK = 5
for start in range(0, len(ck), CHUNK):
    part = ck[start:start + CHUNK]
    emit('#test "NIP-44 get_conversation_key from two keys: upstream rows %d..%d of %d" {' % (start, start + len(part) - 1, len(ck)))
    emit("  secs:=%s;" % rows_lit([r["sec1"] for r in part]))
    emit("  pubs:=%s;" % rows_lit([r["pub2"] for r in part]))
    emit("  expected:=%s;" % rows_lit([r["conversation_key"] for r in part]))
    emit("  for i:0..<%d {" % len(part))
    emit("    work:=nip44_key_test_dirty();key:[33]u8;key[32]=165;")
    emit("    #assert nip44_conversation_key_from_keys_checked(secs[i][..],pubs[i][..],work[..],key[..],false)==NIP44_OK;")
    emit("    for j:0..<32 {#assert key[j]==expected[i][j];} #assert key[32]==165;")
    emit("    #assert nip44_key_test_clear(work[0]);")
    emit("  }")
    emit("}")

# invalid get_conversation_key: each refuses with its code, out untouched, work wiped
for i, r in enumerate(v["invalid"]["get_conversation_key"]):
    if not peer_valid(r["pub2"]):
        code = "NIP44_PEER"
    elif not secret_valid(r["sec1"]):
        code = "NIP44_SECRET"
    else:
        raise SystemExit("invalid row %d is valid here" % i)
    emit('#test "NIP-44 invalid get_conversation_key upstream row %d: %s" {' % (i, r["note"]))
    emit("  sec:=%s;pub:=%s;" % (hexlit(r["sec1"]), hexlit(r["pub2"])))
    emit("  work:=nip44_key_test_dirty();out:[33]u8;for j:0..<33 {out[j]=165;}")
    emit("  #assert nip44_conversation_key_from_keys_checked(sec[..],pub[..],work[..],out[..],false)==%s;" % code)
    emit("  for b:out {#assert b==165;}")
    emit("  #assert nip44_key_test_clear(work[0]);")
    emit("}")

# encrypt_decrypt end to end from the two keys, both directions, and symmetry
for i, r in enumerate(v["valid"]["encrypt_decrypt"]):
    pub1, pub2 = pub_of(r["sec1"]), pub_of(r["sec2"])
    plain = r["plaintext"].encode("utf-8")
    payload = r["payload"].encode("utf-8")
    n, chars = len(plain), len(payload)
    ew = 2 * (65 + 2 + calc_padded(n)) - 65
    emit('#test "NIP-44 encrypt_decrypt upstream row %d from sec1/pub2 and sec2/pub1" {' % i)
    emit("  sec1:=%s;pub1:=%s;" % (hexlit(r["sec1"]), hexlit(pub1)))
    emit("  sec2:=%s;pub2:=%s;" % (hexlit(r["sec2"]), hexlit(pub2)))
    emit("  ck:=%s;nonce:=%s;" % (hexlit(r["conversation_key"]), hexlit(r["nonce"])))
    emit("  plain:=%s;payload:=%s;" % (lit(plain), lit(payload)))
    emit("  work:=nip44_key_test_dirty();ab:[32]u8;ba:[32]u8;")
    emit("  #assert nip44_conversation_key_from_keys_checked(sec1[..],pub2[..],work[..],ab[..],false)==NIP44_OK;")
    emit("  #assert nip44_key_test_clear(work[0]);work=nip44_key_test_dirty();")
    emit("  #assert nip44_conversation_key_from_keys_checked(sec2[..],pub1[..],work[..],ba[..],false)==NIP44_OK;")
    emit("  #assert nip44_key_test_clear(work[0]);")
    emit("  for j:0..<32 {#assert ab[j]==ba[j] && ab[j]==ck[j];}")
    emit("  #assert nip44_encrypt_work_size(NIP44_COMPAT,%d)==%d && nip44_payload_size(NIP44_COMPAT,%d)==%d;" % (n, ew, n, chars))
    emit("  ework:[%d]u8;sealed:[%d]u8;" % (ew, chars))
    emit("  e:=nip44_encrypt_checked(NIP44_COMPAT,ab[..],nonce[..],plain[..],ework[..],sealed[..],false);")
    emit("  #assert e.error==NIP44_OK && e.written==%d;" % chars)
    emit("  for j:0..<%d {#assert sealed[j]==payload[j];}" % chars)
    emit("  dwork:[%d]u8;back:[%d]u8;back[%d]=165;" % (2 * (chars // 4 * 3) - 65, n + 1, n))
    emit("  d:=nip44_decrypt_checked(NIP44_COMPAT,ba[..],cast(string)payload[..],dwork[..],back[..],false);")
    emit("  #assert d.error==NIP44_OK && d.written==%d && back[%d]==165;" % (n, n))
    emit("  for j:0..<%d {#assert back[j]==plain[j];}" % n)
    emit("}")

print("\n".join(out))
