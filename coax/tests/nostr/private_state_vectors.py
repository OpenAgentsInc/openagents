def frame(sender, recipient_x, agent_x, kind, body, at, n, extra=None):
    content = nip44_encrypt(conversation_key(sender, recipient_x), nonce(0x100 + n), body.encode())
    tags = [["p", recipient_x.hex()], ["agent", agent_x.hex()], ["frame", kind]] + (extra or [])
    return event(sender, at, 24200, tags, content, aux=bytes([n]) * 32)


