def nonce(n):
    return n.to_bytes(32, "big")


def d_tag(ck, slug):
    return hmac.new(ck, b"agent-memory/v1/d-tag\x00" + slug.encode(), hashlib.sha256).hexdigest()


def event(secret, at, kind, tags, content, aux=ZERO_AUX):
    pub = xonly(secret).hex()
    eid = event_id(pub, at, kind, tags, content)
    sig = sign(secret, eid, aux)
    return eid.hex(), sig.hex(), dumps({"id": eid.hex(), "pubkey": pub, "created_at": at, "kind": kind,
                                        "tags": tags, "content": content, "sig": sig.hex()})


def engram(body, at, n, signer=AGENT, owner_x=OX, d_slug=None):
    ck = conversation_key(signer, owner_x)
    content = nip44_encrypt(ck, nonce(n), body.encode())
    slug = d_slug or __import__("json").loads(body)["slug"]
    tags = [["d", d_tag(ck, slug)], ["p", owner_x.hex()]]
    return content, event(signer, at, 30174, tags, content)


