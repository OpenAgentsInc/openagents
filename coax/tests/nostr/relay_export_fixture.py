#!/usr/bin/env python3
"""Writes coax/lib/nostr/fixtures/relay_export.coax: chapter 103's six-line
relay export, built from the recorded production capture coax_relay.jsonl
(2026-10-28; no network). Five events are copied byte for byte. The sixth is
a forgery: status a6adbc17... with its `e` tag pointed at issue 791f0799...
and its id recomputed (NIP-01 serialization, SHA-256), its signature copied
unchanged, so the id check passes and BIP-340 fails. Tooling only.

  python3 coax/tests/nostr/relay_export_fixture.py
"""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
CAPTURE = ROOT / "coax/lib/nostr/fixtures/coax_relay.jsonl"
OUT = ROOT / "coax/lib/nostr/fixtures/relay_export.coax"
# In ingest order: repo, project, two issues, the forged status, a status.
ORDER = ["813d9fb02bd7", "375b0d296e3a", "791f07997d9b", "0c13c6ed2696", "a6adbc176098", "2a4b0130b776"]
FORGED = "a6adbc176098"
TARGET = "791f07997d9b98b2a86b2f3157fcd71db650fca9cfa838f634998d3bbc9d92ee"


def objects():
    found = {}
    for line in CAPTURE.read_text().splitlines():
        if not line.startswith('["EVENT",'):
            continue
        sub_end = line.index('",', 10)
        text = line[sub_end + 2:-1]
        found[json.loads(text)["id"][:12]] = text
    return found


def nip01_id(e):
    body = json.dumps([0, e["pubkey"], e["created_at"], e["kind"], e["tags"], e["content"]],
                      separators=(",", ":"), ensure_ascii=False)
    return hashlib.sha256(body.encode()).hexdigest()


def forge(text):
    e = json.loads(text)
    old = e["id"]
    e["tags"][0][1] = TARGET
    e["id"] = nip01_id(e)
    out = text.replace(old, e["id"]).replace('"e","d2231dfceab3e2e404cb4c4bcf29a0d11ae02857a5ba4fbb1ee0331384b2e14d"', f'"e","{TARGET}"')
    assert json.loads(out) == e and nip01_id(json.loads(out)) == e["id"]
    return out


def main():
    found = objects()
    lines = []
    for key in ORDER:
        text = found[key]
        assert nip01_id(json.loads(text)) == json.loads(text)["id"]
        lines.append(forge(text) if key == FORGED else text)
    export = "".join(line + "\n" for line in lines)
    esc = export.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    ids = [json.loads(line)["id"] for line in lines]
    OUT.write_text(
        "// Generated by coax/tests/nostr/relay_export_fixture.py from coax_relay.jsonl (the\n"
        "// 2026-10-28 capture of wss://relay.openagents.com): chapter 103's six-line export.\n"
        "// Line 5 is forged (its e tag retargeted, its id recomputed, its sig copied). Do not edit.\n"
        f"RX_EXPORT_LINES :: {len(lines)};\n"
        f"RX_EXPORT :: \"{esc}\";\n"
        "// The six ids, in line order.\n"
        "RX_IDS :: [6] string.[\n" + ",\n".join(f'  "{i}"' for i in ids) + "];\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(lines)} lines, {len(export)} bytes, forged id {ids[4]}")
    # relay_equal.coax's digest: SHA-256 over (created_at as 8 bytes big-endian || id), sorted.
    def digest(events):
        items = sorted((e["created_at"], bytes.fromhex(e["id"])) for e in events)
        return hashlib.sha256(b"".join(c.to_bytes(8, "big") + i for c, i in items)).hexdigest()
    valid = [json.loads(line) for k, line in enumerate(lines) if k != 4]
    print("digest of the five valid events:", digest(valid))
    print("digest without line 4:", digest([e for e in valid if e["id"] != ids[3]]))

if __name__ == "__main__":
    main()
