#!/usr/bin/env python3
"""Writes relay_server_fixtures.coax: events for relay_server.coax's checks.

Each event has a correct NIP-01 id (sha256 of the canonical serialization,
from hashlib, independent of Coax) and an all-f signature, whose s is not
below the group order, so verification refuses it without a full Schnorr
verify. The pubkey is the x coordinate of the secp256k1 generator: no one's
key. Tooling only.

  python3 coax/tests/nostr/relay_server_fixtures.py
"""
import hashlib
import json
from pathlib import Path

PK = "79be667ef9dcbbac55a06295ce870b07029bfcdb2dce28d959f2815b16f81798"


def event(kind, created, tags, content):
    ser = json.dumps([0, PK, created, kind, tags, content], separators=(',', ':'), ensure_ascii=False)
    eid = hashlib.sha256(ser.encode()).hexdigest()
    return json.dumps({"id": eid, "pubkey": PK, "created_at": created, "kind": kind, "tags": tags,
                       "content": content, "sig": "f" * 128}, separators=(',', ':'), ensure_ascii=False)


EVENTS = [
    ("RST_PLAIN", event(1, 1000, [], "hi")),
    ("RST_AUTH", event(22242, 1000, [["relay", "ws://x"], ["challenge", "c"]], "")),
    ("RST_FUTURE", event(1, 1901, [], "")),
    ("RST_EDGE", event(1, 1900, [], "")),
    ("RST_EXPIRED", event(1, 900, [["expiration", "1000"]], "")),
    ("RST_LIVE", event(1, 900, [["expiration", "1001"]], "")),
    ("RST_ADDR", event(30617, 1000, [["t", "x"], ["d", "re\"po"], ["d", "second"]], "")),
    ("RST_ADDR_NOD", event(30000, 1000, [["t", "x"]], "")),
    ("RST_ADDR_LONG", event(30000, 1000, [["d", "x" * 257]], "")),
    ("RST_TAGS", event(1, 1000, [["t", "x"]] * 257, "")),
    ("RST_TAGS256", event(1, 1000, [["t", "x"]] * 256, "")),
]


def main():
    out = Path(__file__).with_name('relay_server_fixtures.coax')
    lines = ["// Generated by relay_server_fixtures.py: correct ids, an invalid all-f",
             "// signature, the generator's x as pubkey (no one's key). Do not edit."]
    for name, text in EVENTS:
        lines.append("%s :: %s;" % (name, json.dumps(text, ensure_ascii=False)))
    out.write_text("\n".join(lines) + "\n")


if __name__ == '__main__':
    main()
