#!/usr/bin/env python3
"""Writes schnorr_sign_vectors.coax: BIP-340 signing vectors 0-3 from the
pinned upstream CSV with each stage's independent pure-Python intermediates."""
if not __debug__: raise SystemExit('tests require Python assertions')
import csv,sys
from pathlib import Path
R=Path(__file__).resolve().parents[2].parent;sys.path.insert(0,str(R/'tools/coax-nostr/fuzz'))
from oracle import N,point_mul,tagged,schnorr_verify
rows=list(csv.DictReader(open(R/'coax/tests/vectors/upstream/bip340/test-vectors.csv')))
def b(x):return bytes.fromhex(x)
def arr(data):return '[%d]u8.[%s]'%(len(data),','.join('0x%02x'%c for c in data))
out=['// Generated by schnorr_sign_vectors.py from the pinned BIP-340 test-vectors.csv',
 '// (vectors 0-3, the signing rows) with independent pure-Python intermediates.',
 'SignVector :: struct {key:[32]u8;pub:[32]u8;aux:[32]u8;message:[32]u8;sig:[64]u8;r:[32]u8;normalized:[32]u8;key_odd:u64;hash:[32]u8;nonce_odd:u64;}',
 'SIGN_VECTORS :: [4]SignVector.[']
items=[]
for row in rows[:4]:
 assert row['secret key'] and row['verification result']=='TRUE'
 d0=int(row['secret key'],16);P=point_mul(d0);pub=P[0].to_bytes(32,'big');assert pub==b(row['public key'])
 d=N-d0 if P[1]&1 else d0;key=d.to_bytes(32,'big');aux=b(row['aux_rand']);m=b(row['message']);assert len(m)==32
 t=bytes(x^y for x,y in zip(key,tagged('BIP0340/aux',aux)));h=tagged('BIP0340/nonce',t+pub+m)
 k0=int.from_bytes(h,'big')%N;assert k0;Rp=point_mul(k0);k=N-k0 if Rp[1]&1 else k0;r=Rp[0].to_bytes(32,'big')
 e=int.from_bytes(tagged('BIP0340/challenge',r+pub+m),'big')%N;sig=r+((k+e*d)%N).to_bytes(32,'big')
 assert sig==b(row['signature']) and schnorr_verify(m,pub,sig)
 items.append(' SignVector.{key=%s,pub=%s,aux=%s,message=%s,sig=%s,r=%s,normalized=%s,key_odd=%d,hash=%s,nonce_odd=%d}'%(
  arr(b(row['secret key'])),arr(pub),arr(aux),arr(m),arr(sig),arr(r),arr(key),P[1]&1,arr(h),Rp[1]&1))
out.append(',\n'.join(items));out.append('];')
Path(__file__).with_suffix('.coax').write_text('\n'.join(out)+'\n')
