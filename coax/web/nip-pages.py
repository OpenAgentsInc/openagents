#!/usr/bin/env python3
"""Generate the NIP pages and Coax catalog from the reviewed implementation inventory."""
import argparse
import html
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
APP = ROOT/'apps/openagents-web'


def quote(value):
    return json.dumps(value, ensure_ascii=True)


def link(path):
    return 'https://github.com/OpenAgentsInc/openagents/'+('tree' if (ROOT/path).is_dir() else 'blob')+'/main/'+path


def generate():
    catalog = json.loads((APP/'nip/catalog.json').read_text()); rows = catalog['pages']
    files = {}
    arrays = {'NG_NUMBERS':('int',[r['number'] for r in rows]),
              'NG_TITLES':('string',[r['title'] for r in rows]),
              'NG_SUMMARY':('string',[r['summary'] for r in rows]),
              'NG_COVERAGE':('string',[r['coverage'] for r in rows]),
              'NG_GAPS':('string',[r['gap'] for r in rows]),
              'NG_SCOPE':('string',[r['demo_scope'] for r in rows]),
              'NG_SOURCE':('string',[' | '.join(r['sources']) for r in rows]),
              'NG_LINKS':('string',[link(r['sources'][0]) for r in rows]),
              'NG_STATUS':('int',[{'coax':0,'partial':1,'relay':2}[r['status']] for r in rows]),
              'NG_DISCOVERY':('bool',[r['demo']=='relay' for r in rows])}
    code = ['// Generated by coax/web/nip-pages.py; edit nip/catalog.json.', f'NG_COUNT :: {len(rows)};']
    for name,(kind,values) in arrays.items():
        code.append(f'{name} :: [{len(rows)}]{kind}.['+','.join(quote(v) for v in values)+'];')
    for name,kind,key in [('NG_CASES','string','cases'),('NG_EXPECTED','int','expected')]:
        code.append(f'{name} :: [{len(rows)}][3]{kind}.['+','.join('[3]'+kind+'.['+','.join(quote(v) for v in r[key])+']' for r in rows)+'];')
    files[APP/'nip/catalog.coax']='\n'.join(code)+'\n'
    style = '''html,body{margin:0;height:100%;background:#000;color:#ededed}body{overflow:hidden;font:14px/1.5 system-ui,sans-serif}canvas{position:fixed;inset:0;width:100%;height:100%;touch-action:none}canvas[data-cursor=pointer]{cursor:pointer}main{position:relative;max-width:760px;margin:0 auto;padding:24px 16px}html:not(.gpu) body{overflow:auto}a{color:#ff8c1f}.gpu main{position:absolute;width:1px;height:1px;overflow:hidden;clip-path:inset(50%);white-space:nowrap;padding:0}'''

    def page(title, description, content, app, number, path):
        return f'''<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>{html.escape(title)} · OpenAgents</title>
<meta name="description" content="{html.escape(description, quote=True)}">
<meta name="theme-color" content="#000000">
<link rel="icon" type="image/svg+xml" href="/favicon.svg">
<link rel="alternate" type="text/markdown" href="{path}/index.md">
<script>if ("gpu" in navigator) document.documentElement.classList.add("gpu")</script>
<style>{style}</style>
</head>
<body>
<canvas id="coaxial" aria-hidden="true"></canvas>
<main>
{content}
</main>
<script type="module" src="/coaxial/host.js" data-app="{app}" data-page="{number}"></script>
</body>
</html>
'''

    listing='\n'.join(f'- [NIP-{r["number"]:02}: {r["title"]}](/nip/{r["number"]:02}) — '+{'coax':'Coax library','partial':'Partial Coax support','relay':'Production relay declaration'}[r['status']] for r in rows)
    intro='The NIPs OpenAgents currently implements or partially supports, with executable public examples, source links and explicit limits. A production relay declaration is shown separately from a shared Coax implementation.'
    files[APP/'nip/index.md']='# Nostr in OpenAgents\n\n'+intro+'\n\n'+listing+'\n\nThe relay declarations are a frozen public NIP-11 observation from 2026-10-30, not a promise of complete conformance. The pages use public fixtures and never request real keys.\n'
    items='\n'.join(f'<li><a href="/nip/{r["number"]:02}">NIP-{r["number"]:02}: {html.escape(r["title"])}</a></li>' for r in rows)
    files[APP/'nip/index.html']=page('Nostr in OpenAgents',intro,'<h1>Nostr in OpenAgents</h1>\n<p>'+intro+'</p>\n<ul>'+items+'</ul>', 'nip-guide',0,'/nip')
    for i,r in enumerate(rows):
        number=r['number']; path=f'/nip/{number:02}'; directory=APP/f'nip/{number:02}'
        sources='\n'.join(f'- [{p}]({link(p)})' for p in r['sources'])
        evidence='\n'.join(f'- [{p}]({link(p)})' for p in r['evidence'])
        examples='\n'.join('- **'+name+'**: '+desc for name,desc in zip(r['cases'],
                    ['The original public fixture.','A changed fixture that exercises the stated boundary.','A size, shape, time or capability boundary.']))
        if r['demo']=='relay':
            examples='- **DECLARED:** find this NIP in the frozen production relay information.\n- **REMOVED:** read a document whose list omits it.\n- **MALFORMED:** refuse a capability list with the wrong JSON type.'
        note=''
        if number==1:
            examples='- **REAL (1):** the captured event verifies.\n- **ID (2):** an altered id refuses at the hash comparison.\n- **TEXT (3):** changed content refuses at the hash comparison.\n- **SIG (4):** a changed signature refuses at BIP-340.\n- **KIND (5):** kind 99999 refuses while parsing.\n- **PARTS (6):** inspect what is implemented and where it runs.'
            note='''\n## The event verification demo\n\nThe original /nip/01 pipeline remains: REAL verifies a captured kind 30617 event; ID and TEXT refuse at the id check; SIG refuses at BIP-340; KIND refuses during parsing. Select with keys 1 to 5 or the buttons. PARTS (6) lists the implementation. Signing, typed tags, metadata and message codecs are now on main. The Coax signer uses a fixed-work self-check, but production keys still await review. The project pages read live relay traffic but do not yet locally verify every kept event.\n'''
        text=f'''# NIP-{number:02}: {r['title']}

[All implemented NIPs](/nip) · [Pinned specification]({link(f'nips/official/{number:02}.md')})

{r['summary']}

## Implementation

{r['coverage']}

## Try the example

{r['demo_scope']}

{examples}

The page draws its observations in Coax on WebGPU. Its examples are fixed public fixtures; no key is entered, no event is published, and a successful example grants no authority.
{note}
## What remains

{r['gap']}

## Source

{sources}
'''
        if evidence:text+='\n## Verification records\n\n'+evidence+'\n'
        implementation='apps/openagents-web/nip01-verify.coax' if number==1 else 'apps/openagents-web/nip-guide-observe.coax'
        text+='\nThe page examples are in ['+implementation.split('/')[-1]+']('+link(implementation)+'). Relay-only examples inspect NIP-11 metadata, not relay behavior. The catalog distinguishes native library, partial support and relay declarations.\n'
        files[directory/'index.md']=text
        content=f'<h1>NIP-{number:02}: {html.escape(r["title"])}</h1>\n<p>{html.escape(r["summary"])}</p>\n<h2>Implementation</h2>\n<p>{html.escape(r["coverage"])}</p>\n<h2>Example</h2>\n<p>{html.escape(r["demo_scope"])}</p>\n<h2>What remains</h2>\n<p>{html.escape(r["gap"])}</p>\n<p><a href="/nip">All implemented NIPs</a> · <a href="{path}/index.md">Full write-up and source links</a></p>'
        files[directory/'index.html']=page(f'NIP-{number:02}: '+r['title'],r['summary'],content,'nip01' if number==1 else 'nip-guide',i+1,path)
    return files


def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    wrong=[]
    for path,text in generate().items():
        if args.check:
            if not path.exists() or path.read_text()!=text:wrong.append(str(path.relative_to(ROOT)))
        else:path.parent.mkdir(parents=True,exist_ok=True);path.write_text(text)
    if wrong:raise SystemExit('NIP pages need regeneration: '+', '.join(wrong))


if __name__=='__main__':main()
