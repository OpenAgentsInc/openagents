#!/usr/bin/env python3
"""NIP pages use the splash HUD and the existing system-sans glyph ABI."""
from pathlib import Path
import sys

source = Path(sys.argv[1]).read_text()
uniform = '@group(0) @binding(0) var<uniform> u: U;'
bar = '  if (mode > 3.5) {'
assert source.count(uniform) == 1 and source.count(bar) == 1
source = source.replace(uniform, uniform + '''
// font.coax's sans glyphs and ui.coax's HUD bars share mode 4. Glyphs have
// shape.y = 0; a HUD bar has its positive half-height in that field.
@group(0) @binding(1) var sans_atlas: texture_2d<f32>;
@group(0) @binding(2) var sans_sampler: sampler;
''')
source = source.replace(bar, '''  if (mode > 3.5 && v.shape.y == 0.0) {
    let lod = clamp(log2(64.0 / max(v.shape.x, 1.0)), 0.0, 4.0);
    let a = pow(textureSampleLevel(sans_atlas, sans_sampler, v.place, lod).a, 0.85);
    return vec4f(v.tint.rgb * a * min(v.shape.z * 1.15, 1.0) * u.fade, 1.0);
  }
''' + bar)
text = '// Generated by coax/web/nip-shader.py from splash.wgsl.\n' + source
# Only when its bytes change: coax serve's watcher reloads every tab's shaders on a write.
if not Path(sys.argv[2]).exists() or Path(sys.argv[2]).read_text() != text: Path(sys.argv[2]).write_text(text)
