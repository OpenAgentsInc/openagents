// Every public project this site has a page for, baked into the one
// project.wasm: for each apps/openagents-web/projects/<slug>/project.json with
// a pubkey and a page (index.html), its commit history (projects/commits.sh
// into <slug>/commits.coax) and one Baked entry in
//
//   apps/openagents-web/projects/baked.coax   BAKED_N and baked(k), loaded by project.coax
//
// The tables themselves come from snapshot.ts (<slug>/work.coax). Coax is
// entry 0: a page that names no project is Coax's. Adding a project is data:
// its project.json and index.html, then the next build.
//
//   bun baked.ts            (the build runs it after the snapshots)
//   bun baked.ts --list     (print the slugs, for build.sh's snapshot loop)
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import { spawnSync } from "node:child_process"

const SITE = join(import.meta.dir, "../../../apps/openagents-web/projects")

/** The constant prefix a slug's generated names use: COAX, VERSE, PLANETARY_VILLA. */
export const prefix = (slug: string) => slug.toUpperCase().replace(/-/g, "_")

export function projects(): { slug: string; owner: string }[] {
  const out: { slug: string; owner: string }[] = []
  for (const slug of readdirSync(SITE).sort()) {
    const file = join(SITE, slug, "project.json")
    if (!existsSync(file) || !existsSync(join(SITE, slug, "index.html"))) continue
    const p = JSON.parse(readFileSync(file, "utf8"))
    if (!/^[0-9a-f]{64}$/.test(p.pubkey ?? "") || p.slug !== slug || !/^[a-z0-9][a-z0-9-]{0,63}$/.test(slug)) continue
    out.push({ slug, owner: String(p.owner || p.repo?.name || "OpenAgents") })
  }
  return out.sort((a, b) => (a.slug === "coax" ? -1 : b.slug === "coax" ? 1 : a.slug < b.slug ? -1 : 1))
}

if (import.meta.main) {
  const list = projects()
  if (process.argv.includes("--list")) { console.log(list.map((p) => p.slug).join("\n")); process.exit(0) }
  const lit = (s: string) => JSON.stringify(s.replace(/[^\x20-\x7e]/g, "").replace(/[|]/g, " "))
  const loads: string[] = [], cases: string[] = []
  list.forEach(({ slug, owner }, k) => {
    const P = prefix(slug)
    const commits = spawnSync("bash", [join(SITE, "commits.sh"), slug, P], { encoding: "utf8" })
    if (commits.status !== 0) throw new Error(`commits.sh ${slug}: ${commits.stderr}`)
    writeFileSync(join(SITE, slug, "commits.coax"), commits.stdout)
    if (!existsSync(join(SITE, slug, "work.coax"))) throw new Error(`${slug}/work.coax is missing: run snapshot.ts --project ${slug}`)
    loads.push(`#load "${slug}/commits.coax";`, `#load "${slug}/work.coax";`)
    const W = `${P}_WORK_`
    const fields = ["slug", "pubkey", "relay", "naddr", "name", "description", "license", "path", "repo", "items", "log", "plans",
      "plan_info", "details", "steps", "links"].map((f) => `${f} = ${W}${f.toUpperCase()}`)
    const entry = `Baked.{${fields.join(", ")}, owner = ${lit(owner)},\n      history = ${P}_HISTORY, commits = ${P}_COMMITS, authors = ${P}_AUTHORS, lines = ${P}_LINES}`
    cases.push(k === list.length - 1 ? `  return ${entry};` : `  if k == ${k} { return ${entry}; }`)
  })
  writeFileSync(join(SITE, "baked.coax"), `// Generated by coax/web/project/baked.ts: do not edit. Every project with a
// page, Coax first: ${list.map((p) => p.slug).join(", ")}.
${loads.join("\n")}
BAKED_N :: ${list.length};
baked :: (k: int) -> Baked {
${cases.join("\n")}
}
`)
  console.log(`baked ${list.length} projects: ${list.map((p) => p.slug).join(", ")}`)
}
