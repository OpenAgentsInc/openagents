// Captures what relay.openagents.com sends the project page: the page's own
// four single-filter REQs (apps/openagents-web/project-live.coax, live_req),
// every frame until each one's EOSE, verbatim. Writes the frames a line each
// (coax/lib/nostr/fixtures/coax_relay.jsonl) and as a Coax constant
// (coax_relay.coax) for the tests of json.coax and the page's fold.
//
//   bun capture.ts [--project coax]
import { readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"

const ROOT = join(import.meta.dir, "../../..")
const args = process.argv.slice(2)
const i = args.indexOf("--project")
const slug = i >= 0 ? args[i + 1] : "coax"
const config = JSON.parse(readFileSync(join(ROOT, "apps/openagents-web/project", slug, "project.json"), "utf8"))
const pk: string = config.pubkey
const reqs = [
  ["order", { kinds: [30623], authors: [pk], "#d": [slug] }],
  ["issues", { kinds: [1621], authors: [pk], "#a": [`30621:${pk}:${slug}`] }],
  ["comments", { kinds: [1111], authors: [pk] }],
  ["status", { kinds: [1630, 1631, 1632, 1633], authors: [pk] }],
] as const
const frames: string[] = []
await new Promise<void>((resolve, reject) => {
  const ws = new WebSocket(config.relay)
  const timer = setTimeout(() => reject(new Error("timed out")), 20000)
  let ended = 0
  ws.onopen = () => { for (const [id, f] of reqs) ws.send(JSON.stringify(["REQ", id, f])) }
  ws.onmessage = (m) => {
    const s = String(m.data)
    if (s.includes("\n")) throw new Error("a frame with a raw newline")
    frames.push(s)
    if (JSON.parse(s)[0] === "EOSE" && ++ended === reqs.length) { clearTimeout(timer); ws.close(); resolve() }
  }
  ws.onerror = () => reject(new Error(`${config.relay}: unreachable`))
})
const dir = join(ROOT, "coax/lib/nostr/fixtures")
writeFileSync(join(dir, `${slug}_relay.jsonl`), frames.join("\n") + "\n")
const lit = (s: string) => s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\r/g, "\\r").replace(/\t/g, "\\t")
const name = slug.toUpperCase()
writeFileSync(join(dir, `${slug}_relay.coax`), `// Generated by coax/web/project/capture.ts: what ${config.relay} sent for the ${config.name}
// project's four subscriptions, ${new Date().toISOString().slice(0, 16)}Z, a frame a line. Do not edit.
${name}_RELAY_FRAMES :: ${frames.length};
${name}_RELAY :: "${frames.map(lit).join("\\n")}\\n";
`)
console.log(`capture: ${frames.length} frames, ${frames.reduce((n, f) => n + f.length, 0)} bytes`)
