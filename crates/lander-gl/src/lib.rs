//! The `/lander4` first frame (crate README): the Grid's white floor,
//! "OpenAgents", and a Download button, drawn with raw WebGL2 from a wasm
//! module small enough to inline in the page.
//!
//! The page lays itself out in HTML: a real `<h1>` and a real `<a>`. This
//! module reads their boxes and paints over them, so the link, the focus,
//! the keyboard and the reader all stay the browser's, and the canvas only
//! decides how they look. It draws once, synchronously, while the page's
//! script runs, then marks `lander-first-frame`; without WebGL2 it leaves
//! the page's CSS look in place.

#![cfg_attr(target_arch = "wasm32", no_std)]

