//! Writes `src/glyphs.rs`: "OpenAgents" and "Download" shaped (kerning
//! included) and outlined from Geist SemiBold, the brand face the site
//! ships in `crates/openagents-web/static/fonts/geist/`. The page then
//! needs no font file: the painter fills these outlines at the exact
//! device size it draws them.
//!
//! `LANDER_GL_WRITE=1 cargo test -p lander-gl --test glyphs` regenerates
//! the file; without it the test fails when the file is stale.

use std::fmt::Write as _;

const FONT: &[u8] = include_bytes!("../../openagents-web/static/fonts/geist/Geist-SemiBold.ttf");

/// The words and their tracking, in thousandths of an em. Display type is
/// set a little tighter, as the desktop app's headings are.
const RUNS: [(&str, &str, i32); 2] = [("TITLE", "OpenAgents", -10), ("LABEL", "Download", 0)];

struct Outline {
    path: Vec<i32>,
    dx: f32,
}

impl Outline {
    fn point(&mut self, x: f32, y: f32) {
        self.path.push((x + self.dx).round() as i32);
        self.path.push(y.round() as i32);
    }
}

impl ttf_parser::OutlineBuilder for Outline {
    fn move_to(&mut self, x: f32, y: f32) {
        self.path.push(0);
        self.point(x, y);
    }
    fn line_to(&mut self, x: f32, y: f32) {
        self.path.push(1);
        self.point(x, y);
    }
    fn quad_to(&mut self, x1: f32, y1: f32, x: f32, y: f32) {
        self.path.push(2);
        self.point(x1, y1);
        self.point(x, y);
    }
    fn curve_to(&mut self, x1: f32, y1: f32, x2: f32, y2: f32, x: f32, y: f32) {
        self.path.push(3);
        self.point(x1, y1);
        self.point(x2, y2);
        self.point(x, y);
    }
    fn close(&mut self) {
        self.path.push(4);
    }
}

fn generate() -> String {
    let face = ttf_parser::Face::parse(FONT, 0).expect("Geist SemiBold");
    let upm = face.units_per_em();
    let cap = face.capital_height().expect("a cap height");
    let font = swash::FontRef::from_index(FONT, 0).expect("Geist SemiBold");
    let mut context = swash::shape::ShapeContext::new();
    let mut out = String::new();
    writeln!(
        out,
        "//! @generated by `tests/glyphs.rs` from Geist SemiBold (OFL); do not edit.\n\
         //! Regenerate: `LANDER_GL_WRITE=1 cargo test -p lander-gl --test glyphs`.\n\n\
         use crate::text::Run;\n\n\
         /// Font units per em.\npub const UNITS_PER_EM: f32 = {upm}.0;\n\
         /// The capital height, in font units.\npub const CAP_HEIGHT: f32 = {cap}.0;"
    )
    .unwrap();
    for (name, text, tracking) in RUNS {
        let mut shaper = context.builder(font).size(upm as f32).build();
        shaper.add_str(text);
        let mut glyphs = Vec::new();
        shaper.shape_with(|cluster| {
            for glyph in cluster.glyphs {
                glyphs.push((glyph.id, glyph.x, glyph.advance));
            }
        });
        let track = (tracking * upm as i32) as f32 / 1000.0;
        let mut outline = Outline {
            path: Vec::new(),
            dx: 0.0,
        };
        let mut pen = 0.0f32;
        let (mut x0, mut y0, mut x1, mut y1) = (i32::MAX, i32::MAX, i32::MIN, i32::MIN);
        for (index, (id, x, advance)) in glyphs.iter().enumerate() {
            outline.dx = pen + x;
            if let Some(rect) = face.outline_glyph(ttf_parser::GlyphId(*id), &mut outline) {
                let dx = outline.dx.round() as i32;
                x0 = x0.min(rect.x_min as i32 + dx);
                x1 = x1.max(rect.x_max as i32 + dx);
                y0 = y0.min(rect.y_min as i32);
                y1 = y1.max(rect.y_max as i32);
            }
            pen += advance;
            if index + 1 < glyphs.len() {
                pen += track;
            }
        }
        let path = outline
            .path
            .iter()
            .map(|v| i16::try_from(*v).expect("fits i16").to_string())
            .collect::<Vec<_>>();
        let mut lines = String::new();
        for chunk in path.chunks(16) {
            writeln!(lines, "        {},", chunk.join(", ")).unwrap();
        }
        writeln!(
            out,
            "\n/// {text:?}, set in one run.\npub const {name}: Run = Run {{\n    \
             advance: {pen:.1},\n    bounds: [{x0}.0, {y0}.0, {x1}.0, {y1}.0],\n    \
             path: &[\n{lines}    ],\n}};"
        )
        .unwrap();
    }
    out
}

#[test]
fn glyphs_are_current() {
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("src/glyphs.rs");
    let fresh = generate();
    if std::env::var_os("LANDER_GL_WRITE").is_some() {
        std::fs::write(&path, &fresh).unwrap();
        return;
    }
    let held = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(
        held == fresh,
        "src/glyphs.rs is stale: run LANDER_GL_WRITE=1 cargo test -p lander-gl --test glyphs"
    );
}
