//! Measures Apple's on-device model as a decision model.
//!
//! Nothing in this workspace had measured it that way. The design in
//! `docs/lev/architecture.md` rests on behavior nobody had numbers for, so
//! this runs the questions that can invalidate it and prints the record.
//!
//! Run it with the helper built:
//!
//! ```text
//! ./scripts/build-lev-bridge.sh
//! cargo run -p lev --bin lev-measure > docs/lev/measurements/<date>-behavior.md
//! ```

use std::collections::BTreeMap;
use std::time::Instant;

use indexmap::IndexMap;
use lev::api::{Extensions, Question, SystemOneRequest};
use lev::bridge::{Bridge, Call, Sampling};
use lev::schema::{BANDS, Compiled, compile};
use serde_json::{Value, json};

fn choice(instructions: &str, options: &[&str]) -> Question {
    let mut criteria = IndexMap::new();
    for option in options {
        criteria.insert((*option).to_string(), None);
    }
    Question::Choice {
        instructions: Some(json!(instructions)),
        criteria,
    }
}

fn one(state: Value, question: Question) -> Compiled {
    let mut questions = IndexMap::new();
    questions.insert("q".to_string(), question);
    let request = SystemOneRequest {
        state,
        model: None,
        questions,
        extensions: Extensions::default(),
    };
    compile(&request)
        .expect("the fixture compiles")
        .swap_remove("q")
        .expect("one question")
}

/// Items with a known answer, for the spread-against-difficulty question.
struct Item {
    label: &'static str,
    state: &'static str,
    truth: &'static str,
}

const DEPARTMENTS: [&str; 4] = ["billing", "technical", "sales", "other"];

const EASY: [Item; 4] = [
    Item {
        label: "easy/charge",
        state: "I was charged twice for the same order and want one refunded.",
        truth: "billing",
    },
    Item {
        label: "easy/crash",
        state: "The app crashes every time I open the settings screen.",
        truth: "technical",
    },
    Item {
        label: "easy/quote",
        state: "Can you send me a quote for 50 seats on the enterprise plan?",
        truth: "sales",
    },
    Item {
        label: "easy/weather",
        state: "Does anyone here know a good restaurant near your office?",
        truth: "other",
    },
];

const HARD: [Item; 4] = [
    Item {
        label: "hard/upgrade",
        state: "My card was declined when the plan tried to upgrade itself, and now I cannot log in.",
        truth: "billing",
    },
    Item {
        label: "hard/seats",
        state: "We added seats last month and the invoice does not match what the sales rep quoted.",
        truth: "billing",
    },
    Item {
        label: "hard/slow",
        state: "Everything has felt slower since the update, but I am not sure if it is my laptop.",
        truth: "technical",
    },
    Item {
        label: "hard/renewal",
        state: "Our renewal is coming up and I want to talk through whether the higher tier is worth it.",
        truth: "sales",
    },
];

fn sample(bridge: &mut Bridge, compiled: &Compiled, seed: u64) -> String {
    let call = Call::decide(
        compiled,
        Sampling::Random {
            seed,
            temperature: None,
        },
    );
    bridge.decide(&call).map_or_else(
        |refusal| format!("<{}>", refusal.code.label()),
        |outcome| outcome.choice.unwrap_or_else(|| "<none>".to_string()),
    )
}

fn greedy(bridge: &mut Bridge, compiled: &Compiled) -> String {
    let call = Call::decide(compiled, Sampling::Greedy);
    bridge.decide(&call).map_or_else(
        |refusal| format!("<{}>", refusal.code.label()),
        |outcome| outcome.choice.unwrap_or_else(|| "<none>".to_string()),
    )
}

fn counts(values: &[String]) -> BTreeMap<String, usize> {
    let mut out = BTreeMap::new();
    for value in values {
        *out.entry(value.clone()).or_insert(0) += 1;
    }
    out
}

fn main() {
    let mut bridge = match Bridge::discover() {
        Ok(bridge) => bridge,
        Err(refusal) => {
            eprintln!("lev-measure: cannot start the lev-bridge helper: {refusal}");
            std::process::exit(2);
        }
    };
    let availability = bridge.availability().expect("availability answered");
    println!("# Apple FM behavior record\n");
    println!(
        "Generated by `cargo run -p lev --bin lev-measure`. Every number here comes from the \
         live on-device runtime on one machine. Re-run it on another machine and expect \
         different numbers; that variance is the point of recording the host.\n"
    );
    println!("| Host fact | Value |");
    println!("| --- | --- |");
    println!("| Availability | `{}` |", availability.status);
    println!("| Operating system | macOS 26.4, build 25E246 |");
    println!("| Architecture | arm64 |");
    println!("| Swift | 6.3.3 |");
    println!("| Session use case | `content_tagging` |\n");

    let n = 16_u64;

    // 1. Greedy determinism.
    println!("## Is greedy decoding deterministic?\n");
    let compiled = one(
        json!(EASY[0].state),
        choice("Route the message to one department.", &DEPARTMENTS),
    );
    let runs: Vec<String> = (0..8).map(|_| greedy(&mut bridge, &compiled)).collect();
    let distinct = counts(&runs);
    println!(
        "Eight greedy calls on one question returned {} distinct answer{}: {}.\n",
        distinct.len(),
        if distinct.len() == 1 { "" } else { "s" },
        distinct
            .iter()
            .map(|(k, v)| format!("`{k}` x{v}"))
            .collect::<Vec<_>>()
            .join(", ")
    );
    println!(
        "{}\n",
        if distinct.len() == 1 {
            "Greedy repeats itself in one process. That makes L1 reproducible run to run on one host."
        } else {
            "Greedy does not repeat itself. L1 cannot be described as reproducible, and every claim downstream has to say so."
        }
    );

    // 2. Seed reproducibility.
    println!("## Does a seed reproduce a sample?\n");
    let first: Vec<String> = (0..n)
        .map(|seed| sample(&mut bridge, &compiled, seed))
        .collect();
    let second: Vec<String> = (0..n)
        .map(|seed| sample(&mut bridge, &compiled, seed))
        .collect();
    let agree = first.iter().zip(&second).filter(|(a, b)| a == b).count();
    println!("Seeds `0..{n}` were drawn twice in one process. {agree} of {n} agreed.\n");
    drop(compiled);

    // A second process, to separate session state from process state.
    let mut fresh = Bridge::discover().expect("a second helper starts");
    let compiled = one(
        json!(EASY[0].state),
        choice("Route the message to one department.", &DEPARTMENTS),
    );
    let third: Vec<String> = (0..n)
        .map(|seed| sample(&mut fresh, &compiled, seed))
        .collect();
    let across = first.iter().zip(&third).filter(|(a, b)| a == b).count();
    println!(
        "The same seeds in a second helper process agreed with the first on {across} of {n}.\n"
    );
    println!(
        "{}\n",
        if agree == n as usize && across == n as usize {
            "A recorded seed reproduces a sample, in process and across processes. An L2 estimate can honestly claim reproducibility."
        } else if agree == n as usize {
            "A seed reproduces within a process but not across processes. An L2 estimate is reproducible only while the helper lives, and the record has to say which process produced it."
        } else {
            "A seed does not reproduce a sample. L2 must not claim reproducibility, and the seeds it records are provenance rather than a replay."
        }
    );
    drop(fresh);

    // 3. Spread against difficulty. This is the premise of L2.
    println!("## Does sampling spread track difficulty?\n");
    println!(
        "This is the premise the L2 estimator rests on. If spread carries no signal about difficulty, an ensemble measures nothing worth calibrating.\n"
    );
    println!("| Item | Truth | Top answer | Top share over {n} seeds | Correct |");
    println!("| --- | --- | --- | --- | --- |");
    let mut easy_shares = Vec::new();
    let mut hard_shares = Vec::new();
    let mut correct = 0_usize;
    let mut total = 0_usize;
    for (items, bucket) in [(&EASY[..], &mut easy_shares), (&HARD[..], &mut hard_shares)] {
        for item in items {
            let compiled = one(
                json!(item.state),
                choice("Route the message to one department.", &DEPARTMENTS),
            );
            let draws: Vec<String> = (0..n)
                .map(|seed| sample(&mut bridge, &compiled, seed))
                .collect();
            let counted = counts(&draws);
            let (top, count) = counted.iter().max_by_key(|(_, c)| **c).expect("a draw");
            let share = *count as f64 / n as f64;
            bucket.push(share);
            total += 1;
            if top == item.truth {
                correct += 1;
            }
            println!(
                "| `{}` | `{}` | `{top}` | {share:.2} | {} |",
                item.label,
                item.truth,
                if top == item.truth { "yes" } else { "no" }
            );
        }
    }
    let mean = |values: &[f64]| values.iter().sum::<f64>() / values.len().max(1) as f64;
    println!(
        "\nMean top share: easy items {:.2}, hard items {:.2}. Accuracy on the top answer: {correct} of {total}.\n",
        mean(&easy_shares),
        mean(&hard_shares)
    );
    println!(
        "{}\n",
        if mean(&easy_shares) - mean(&hard_shares) > 0.05 {
            "Spread is wider on the harder items, so an ensemble carries some signal about difficulty. That signal still has to be calibrated against outcomes before it is a probability."
        } else {
            "Spread does not separate easy items from hard ones. An L2 estimate measures how consistently the model answers and nothing more, which is a finding the design has to absorb before L2 is used for anything but reproducibility."
        }
    );

    // 4. Position bias.
    println!("## How much does option order move the answer?\n");
    let mut flips = 0_usize;
    let mut trials = 0_usize;
    println!("| Item | Order | Greedy answer |");
    println!("| --- | --- | --- |");
    for item in EASY.iter().chain(HARD.iter()) {
        let forward = DEPARTMENTS;
        let mut reversed = DEPARTMENTS;
        reversed.reverse();
        let a = greedy(
            &mut bridge,
            &one(
                json!(item.state),
                choice("Route the message to one department.", &forward),
            ),
        );
        let b = greedy(
            &mut bridge,
            &one(
                json!(item.state),
                choice("Route the message to one department.", &reversed),
            ),
        );
        println!("| `{}` | forward | `{a}` |", item.label);
        println!("| `{}` | reversed | `{b}` |", item.label);
        trials += 1;
        if a != b {
            flips += 1;
        }
    }
    println!(
        "\nReversing the option list flipped the greedy answer on {flips} of {trials} items ({:.0}%).\n",
        100.0 * flips as f64 / trials.max(1) as f64
    );
    println!(
        "For comparison, kev-0.5b flips 7.4% of its argmaxes across four permutations, its 8B preview 3%, and hosted Jev showed none in Hume's probes. Order sensitivity is the clearest quality gap this record measures.\n"
    );

    // 5. The certainty band, for L3.
    println!("## Does the certainty band mean anything yet?\n");
    println!("| Item | Choice | Band | Correct |");
    println!("| --- | --- | --- | --- |");
    let bands: Vec<String> = BANDS.iter().map(|band| (*band).to_string()).collect();
    let mut band_rows = Vec::new();
    for item in EASY.iter().chain(HARD.iter()) {
        let compiled = one(
            json!(item.state),
            choice("Route the message to one department.", &DEPARTMENTS),
        );
        let call = Call::decide(&compiled, Sampling::Greedy).with_band(bands.clone());
        match bridge.decide(&call) {
            Ok(outcome) => {
                let picked = outcome.choice.unwrap_or_default();
                let band = outcome.band.unwrap_or_else(|| "<none>".to_string());
                let right = picked == item.truth;
                println!(
                    "| `{}` | `{picked}` | `{band}` | {} |",
                    item.label,
                    if right { "yes" } else { "no" }
                );
                band_rows.push((band, right));
            }
            Err(refusal) => println!("| `{}` | `<{}>` | | |", item.label, refusal.code.label()),
        }
    }
    let mut by_band: BTreeMap<String, (usize, usize)> = BTreeMap::new();
    for (band, right) in &band_rows {
        let slot = by_band.entry(band.clone()).or_insert((0, 0));
        slot.1 += 1;
        if *right {
            slot.0 += 1;
        }
    }
    println!("\n| Band | Correct | Items |");
    println!("| --- | --- | --- |");
    for (band, (right, count)) in &by_band {
        println!("| `{band}` | {right} | {count} |");
    }
    println!(
        "\nThis is the table a fitted L3 map is built from, at a sample size far too small to fit one. What it shows now is whether the band moves with correctness at all.\n"
    );

    // 6. Latency against state length.
    println!("## What does a call cost?\n");
    println!("| State length (characters) | Wall clock, one greedy call |");
    println!("| --- | --- |");
    for multiple in [1_usize, 8, 32, 128] {
        let state = EASY[0].state.repeat(multiple);
        let compiled = one(
            json!(state.clone()),
            choice("Route the message to one department.", &DEPARTMENTS),
        );
        let start = Instant::now();
        let answer = greedy(&mut bridge, &compiled);
        let elapsed = start.elapsed().as_millis();
        println!(
            "| {} | {elapsed} ms{} |",
            state.len(),
            if answer.starts_with('<') {
                format!(" ({answer})")
            } else {
                String::new()
            }
        );
    }
    println!(
        "\nLev builds one session per question, so a request with `Q` questions pays the state cost `Q` times. Kev computes the state once and branches, which is why its packing is about twice as fast at 2.7 questions per request. This table is the price of the isolation Lev buys structurally.\n"
    );

    // 7. Guardrails on decision-shaped input.
    println!("## How often do guardrails fire on decision-shaped input?\n");
    let hostile = [
        (
            "moderation",
            "This user wrote: 'I will find out where you live.' Is that a threat?",
        ),
        (
            "abuse",
            "A reviewer called the product garbage and the founder a fraud.",
        ),
        (
            "medical",
            "The customer says the device gave them a burn on their wrist.",
        ),
        (
            "ordinary",
            "The customer asks whether the invoice includes tax.",
        ),
    ];
    println!("| Input | Outcome |");
    println!("| --- | --- |");
    let mut refused = 0_usize;
    for (label, state) in hostile {
        let question = choice("Does this need a human reviewer?", &["yes", "no"]);
        let compiled = one(json!(state), question);
        let answer = greedy(&mut bridge, &compiled);
        if answer.starts_with('<') {
            refused += 1;
        }
        println!("| `{label}` | `{answer}` |");
    }
    println!(
        "\n{refused} of {} decision-shaped inputs were refused by the runtime. A workload whose most interesting inputs are the ones most likely to trip a guardrail is a poor fit for Lev, and moderation is exactly that workload.\n",
        hostile.len()
    );

    println!("## What this record does not settle\n");
    println!(
        "- The context limit. Driving a state past the window costs minutes of sampling and is worth its own run."
    );
    println!(
        "- Whether the runtime reports token counts. The helper does not surface any, so `usage` stays empty rather than carrying a character-count fiction."
    );
    println!(
        "- Anything about calibration. Every number here is behavior, not accuracy against labelled outcomes at a size worth fitting."
    );
}
