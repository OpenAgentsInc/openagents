//! Measures how much an L2 estimate moves when only the seed block moves.
//!
//! The behavior record shows a seed reproducing its sample exactly, which is
//! what makes an estimate replayable and also what removes every trace of
//! trial-to-trial variance from a fixed seed set. Rerunning block 0 is not a
//! second trial. Drawing block 1 is, because it shares no seed with block 0
//! and nothing else about the question changed.
//!
//! The spread across blocks is this suite's own resampling variance: the
//! difference a comparison has to beat before it is reporting anything but
//! which seeds it happened to draw.
//!
//! Run it with the helper built:
//!
//! ```text
//! ./scripts/build-lev-bridge.sh
//! cargo run -p lev --bin lev-seed-sweep -- --bases 8 --items 24 \
//!     > docs/lev/measurements/<date>-seed-variance.md
//! ```

use lev::api::{Extensions, SystemOneRequest};
use lev::bridge::Pool;
use lev::estimator::l2_pool_with;
use lev::schema::compile;
use lev::suite::{Item, Suite};

const SUITE: &str = include_str!("../../suites/support-v2.json");

/// One item answered from one seed block.
struct Draw {
    top: f64,
    correct: bool,
    choice: String,
}

fn spread(values: &[f64]) -> (f64, f64, f64, f64) {
    let n = values.len() as f64;
    let mean = values.iter().sum::<f64>() / n;
    // The sample standard deviation: these blocks are a sample of the blocks
    // that could have been drawn, not the whole population of them.
    let variance = if values.len() < 2 {
        0.0
    } else {
        values
            .iter()
            .map(|value| (value - mean).powi(2))
            .sum::<f64>()
            / (n - 1.0)
    };
    let low = values.iter().copied().fold(f64::INFINITY, f64::min);
    let high = values.iter().copied().fold(f64::NEG_INFINITY, f64::max);
    (mean, variance.sqrt(), low, high)
}

fn draw(
    pool: &Pool,
    item: &Item,
    samples: u64,
    seed_base: u64,
    adapter: Option<&str>,
) -> Option<Draw> {
    let request = SystemOneRequest {
        state: item.state.clone(),
        model: None,
        questions: [("q".to_string(), item.question.clone())]
            .into_iter()
            .collect(),
        extensions: Extensions::default(),
    };
    let compiled = compile(&request).ok()?;
    let raw = l2_pool_with(pool, &compiled["q"], samples, seed_base, adapter).ok()?;
    Some(Draw {
        top: raw.top(),
        correct: raw.choice == item.truth,
        choice: raw.choice,
    })
}

fn main() {
    let mut bases = 8_u64;
    let mut samples = 8_u64;
    let mut items = 24_usize;
    let mut helpers = 4_usize;
    let mut headline: Option<String> = None;
    let mut adapter: Option<String> = None;
    let mut args = std::env::args().skip(1);
    while let Some(flag) = args.next() {
        match flag.as_str() {
            "--bases" => bases = args.next().and_then(|v| v.parse().ok()).unwrap_or(bases),
            "--samples" => samples = args.next().and_then(|v| v.parse().ok()).unwrap_or(samples),
            "--items" => items = args.next().and_then(|v| v.parse().ok()).unwrap_or(items),
            "--helpers" => helpers = args.next().and_then(|v| v.parse().ok()).unwrap_or(helpers),
            "--item" => headline = args.next(),
            "--adapter" => adapter = args.next(),
            other => {
                eprintln!("lev-seed-sweep: unknown flag `{other}`");
                std::process::exit(2);
            }
        }
    }

    let suite = Suite::load(SUITE).expect("the shipped suite loads");
    // The evaluation split, thinned evenly so the sample spans every family
    // rather than the first items of one.
    let evaluation: Vec<&Item> = suite.split("evaluation").collect();
    let stride = (evaluation.len() / items.max(1)).max(1);
    let chosen: Vec<&Item> = evaluation
        .iter()
        .copied()
        .step_by(stride)
        .take(items)
        .collect();
    let headline_item = match &headline {
        Some(id) => chosen
            .iter()
            .chain(evaluation.iter())
            .find(|item| &item.id == id)
            .copied()
            .unwrap_or_else(|| panic!("no item {id} in the suite")),
        None => chosen[0],
    };

    let pool = match Pool::discover(helpers) {
        Ok(pool) => pool,
        Err(refusal) => {
            eprintln!("lev-seed-sweep: cannot start the lev-bridge helper: {refusal}");
            std::process::exit(2);
        }
    };
    let availability = pool.availability().expect("availability answered");

    println!("# The spread an L2 estimate carries across seed blocks\n");
    println!(
        "Generated by `cargo run -p lev --bin lev-seed-sweep`. Every number comes from the live \
         on-device runtime on one machine.\n"
    );
    println!("| Run fact | Value |");
    println!("| --- | --- |");
    println!("| Availability | `{}` |", availability.status);
    println!("| Suite | `{}`, {} items |", suite.name, suite.items.len());
    println!("| Samples per estimate | {samples} |");
    println!(
        "| Seed blocks | {bases}, drawing seeds 0 to {} |",
        bases * samples - 1
    );
    println!(
        "| Items swept | {} from the evaluation split |",
        chosen.len()
    );
    println!("| Pool width | {} |", pool.width());
    println!("| Adapter | {} |\n", adapter.as_deref().unwrap_or("none"));

    // 1. One item, every block.
    println!("## One item across every block\n");
    println!("`{}`, truth `{}`.\n", headline_item.id, headline_item.truth);
    println!("| Seed block | Seeds | Answer | Top share |");
    println!("| --- | --- | --- | --- |");
    let mut headline_tops = Vec::new();
    for base in 0..bases {
        let first = base * samples;
        match draw(&pool, headline_item, samples, base, adapter.as_deref()) {
            Some(drawn) => {
                println!(
                    "| {base} | {first}–{} | `{}` | {:.3} |",
                    first + samples - 1,
                    drawn.choice,
                    drawn.top
                );
                headline_tops.push(drawn.top);
            }
            None => println!(
                "| {base} | {first}–{} | `<refused>` | |",
                first + samples - 1
            ),
        }
    }
    let (mean, sd, low, high) = spread(&headline_tops);
    println!(
        "\nMean {mean:.3}, standard deviation {sd:.3}, range {low:.3} to {high:.3}, \
         spread {:.3}.\n",
        high - low
    );

    // 2. Every item, every block.
    println!("## The suite across every block\n");
    println!("| Seed block | Mean top share | Accuracy | Items scored |");
    println!("| --- | --- | --- | --- |");
    let mut per_item: Vec<Vec<f64>> = vec![Vec::new(); chosen.len()];
    let mut per_item_choices: Vec<Vec<String>> = vec![Vec::new(); chosen.len()];
    let mut block_means = Vec::new();
    let mut block_accuracies = Vec::new();
    for base in 0..bases {
        let mut tops = Vec::new();
        let mut correct = 0_usize;
        let mut scored = 0_usize;
        for (index, item) in chosen.iter().enumerate() {
            let Some(drawn) = draw(&pool, item, samples, base, adapter.as_deref()) else {
                continue;
            };
            tops.push(drawn.top);
            per_item[index].push(drawn.top);
            per_item_choices[index].push(drawn.choice);
            correct += usize::from(drawn.correct);
            scored += 1;
        }
        let mean = tops.iter().sum::<f64>() / tops.len() as f64;
        let accuracy = correct as f64 / scored as f64;
        println!("| {base} | {mean:.3} | {accuracy:.3} | {scored} |");
        block_means.push(mean);
        block_accuracies.push(accuracy);
    }
    let (mean, sd, low, high) = spread(&block_means);
    println!(
        "\nMean top share over blocks: {mean:.3}, standard deviation {sd:.4}, range {low:.3} to \
         {high:.3}, spread {:.3}.",
        high - low
    );
    let (mean, sd, low, high) = spread(&block_accuracies);
    println!(
        "\nAccuracy over blocks: {mean:.3}, standard deviation {sd:.4}, range {low:.3} to \
         {high:.3}, spread {:.3}.\n",
        high - low
    );

    // 3. What moved, item by item.
    println!("## Which items moved\n");
    println!("| Item | Blocks | Answers | Top share range |");
    println!("| --- | --- | --- | --- |");
    let mut flipped = 0_usize;
    let mut ranges = Vec::new();
    for (index, item) in chosen.iter().enumerate() {
        let tops = &per_item[index];
        if tops.is_empty() {
            continue;
        }
        let (_, _, low, high) = spread(tops);
        ranges.push(high - low);
        let mut answers: Vec<&str> = Vec::new();
        for choice in &per_item_choices[index] {
            if !answers.contains(&choice.as_str()) {
                answers.push(choice);
            }
        }
        if answers.len() > 1 {
            flipped += 1;
        }
        println!(
            "| `{}` | {} | {} | {:.3} |",
            item.id,
            tops.len(),
            answers
                .iter()
                .map(|a| format!("`{a}`"))
                .collect::<Vec<_>>()
                .join(", "),
            high - low
        );
    }
    let (mean_range, _, _, widest) = spread(&ranges);
    println!(
        "\n{flipped} of {} items changed their answer across blocks. Mean within-item top-share \
         range {mean_range:.3}, widest {widest:.3}.",
        chosen.len()
    );
}
