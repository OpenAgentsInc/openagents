use std::path::{Path, PathBuf};
fn files(root: &Path) -> Vec<PathBuf> {
    let mut out = Vec::new();
    for entry in std::fs::read_dir(root).unwrap() {
        let p = entry.unwrap().path();
        if p.is_dir() {
            out.extend(files(&p));
        } else if p.extension().is_some_and(|e| e == "proto") {
            out.push(p);
        }
    }
    out.sort();
    out
}
#[test]
fn generated_protocols_match_pinned_sources() {
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    use sha2::{Digest, Sha256};
    let sources: Vec<serde_json::Value> =
        serde_json::from_slice(&std::fs::read(root.join("proto/sources.json")).unwrap()).unwrap();
    for source in sources {
        assert_eq!(
            hex::encode(Sha256::digest(
                std::fs::read(root.join(source["file"].as_str().unwrap())).unwrap()
            )),
            source["sha256"].as_str().unwrap(),
            "vendored upstream source changed"
        );
    }
    let temp = tempfile::tempdir().unwrap();
    let output = temp.path();
    let lnd = root.join("proto/lnd/v0.21.1-beta");
    let tap = root.join("proto/taproot-assets/v0.8.0/taprpc");
    let lp = root.join("proto/loop/v0.34.0-beta");
    let lit = root.join("proto/lightning-terminal/v0.17.0-alpha/litrpc");
    tonic_build::configure()
        .build_server(true)
        .generate_default_stubs(true)
        .out_dir(output)
        .compile_protos(&files(&lnd.join("lnrpc")), &[lnd.join("lnrpc")])
        .unwrap();
    let extras = tempfile::tempdir().unwrap();
    let mut builder = tonic_build::configure()
        .build_server(true)
        .generate_default_stubs(true)
        .out_dir(extras.path());
    for pkg in ["lnrpc", "routerrpc", "signrpc", "walletrpc"] {
        builder = builder.extern_path(format!(".{pkg}"), format!("crate::proto::{pkg}"));
    }
    builder
        .compile_protos(&files(&tap), &[tap.clone(), lnd.join("lnrpc")])
        .unwrap();
    tonic_build::configure()
        .build_server(true)
        .generate_default_stubs(true)
        .out_dir(extras.path())
        .extern_path(".lnrpc", "crate::proto::lnrpc")
        .compile_protos(&files(&lp), &[lp.clone(), lnd.clone()])
        .unwrap();
    tonic_build::configure()
        .build_server(true)
        .generate_default_stubs(true)
        .out_dir(output)
        .compile_protos(&files(&lit), &[lit])
        .unwrap();
    for entry in std::fs::read_dir(extras.path()).unwrap() {
        let p = entry.unwrap().path();
        if !output.join(p.file_name().unwrap()).exists() {
            std::fs::copy(&p, output.join(p.file_name().unwrap())).unwrap();
        }
    }
    let mut generated: Vec<_> = std::fs::read_dir(output)
        .unwrap()
        .map(|e| e.unwrap().path())
        .collect();
    generated.sort();
    let mut modules = String::from("// @generated by scripts/lnd-sdk-proto.sh.\n");
    for file in &generated {
        // Upstream equations are text, not executable Rust examples.
        let source = std::fs::read_to_string(file).unwrap();
        std::fs::write(
            file,
            source.replace(
                "/// ```\n/// V = F_c / (10^F_s)",
                "/// ```text\n/// V = F_c / (10^F_s)",
            ),
        )
        .unwrap();
        let name = file.file_stem().unwrap().to_str().unwrap();
        modules.push_str(&format!("pub mod {name} {{ include!(\"{name}.rs\"); }}\n"));
    }
    std::fs::write(output.join("mod.rs"), modules).unwrap();
    let checked = root.join("src/generated");
    if std::env::var_os("LND_SDK_REGENERATE").is_some() {
        std::fs::create_dir_all(&checked).unwrap();
        for entry in std::fs::read_dir(output).unwrap() {
            let p = entry.unwrap().path();
            std::fs::copy(&p, checked.join(p.file_name().unwrap())).unwrap();
        }
    } else {
        for entry in std::fs::read_dir(output).unwrap() {
            let p = entry.unwrap().path();
            assert_eq!(
                std::fs::read(&p).unwrap(),
                std::fs::read(checked.join(p.file_name().unwrap())).unwrap(),
                "regenerate with scripts/lnd-sdk-proto.sh"
            );
        }
    }
}
