//! Bundles the stylesheet and script that `openagents_ui::stylesheet()` and
//! `openagents_ui::script()` return. The bundling is `src/bundle.rs`, which
//! the library also exposes for deploys that ship the bundle as content.

use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

#[allow(dead_code)]
#[path = "src/css_lower.rs"]
mod css_lower;

#[allow(dead_code)]
#[path = "src/bundle.rs"]
mod bundle;

fn main() {
    let root = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("manifest dir"));
    let out = PathBuf::from(std::env::var("OUT_DIR").expect("out dir"));
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=src/css_lower.rs");
    println!("cargo:rerun-if-changed=src/bundle.rs");
    println!("cargo:rerun-if-changed=static/components");

    let bundle = bundle::bundle(&root);
    for path in &bundle.inputs {
        println!("cargo:rerun-if-changed={}", path.display());
    }
    for label in &bundle.missing {
        // Only while bootstrapping: the token files are generated by a test.
        println!(
            "cargo:warning=openagents-ui: {label} is missing; regenerate with OPENAGENTS_UI_BLESS=1"
        );
    }
    fs::write(out.join("openagents-ui.css"), &bundle.css).expect("write bundled css");
    fs::write(out.join("openagents-ui.js"), &bundle.js).expect("write bundled js");

    let mut meta = String::new();
    let _ = writeln!(
        meta,
        "pub(crate) const STYLESHEET_VERSION: &str = \"{}\";",
        bundle::version(bundle.css.as_bytes())
    );
    let _ = writeln!(
        meta,
        "pub(crate) const SCRIPT_VERSION: &str = \"{}\";",
        bundle::version(bundle.js.as_bytes())
    );
    let _ = writeln!(meta, "pub(crate) const COMPONENT_STYLESHEETS: &[&str] = &[");
    for name in &bundle.components {
        let _ = writeln!(meta, "    {name:?},");
    }
    let _ = writeln!(meta, "];");
    fs::write(out.join("bundle_meta.rs"), meta).expect("write bundle meta");
}
