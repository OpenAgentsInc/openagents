//! Bundles the stylesheet and script that `openagents_ui::stylesheet()` and
//! `openagents_ui::script()` return.
//!
//! Stylesheet order: the three generated token files, `static/base.css`, then
//! every `static/components/*.css` in file-name order, each wrapped in
//! `@layer components` (as Apps SDK UI wraps its CSS modules). Script: the
//! theme toggle, then every `static/components/*.js` in file-name order.
//!
//! New component files are picked up automatically; nobody edits a list.
//! Apps SDK UI's `alpha()` and `spacing()` build functions are lowered to
//! plain CSS in every file.

use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

#[allow(dead_code)]
#[path = "src/css_lower.rs"]
mod css_lower;

const TOKEN_FILES: [&str; 3] = [
    "static/tokens-primitive.css",
    "static/tokens-semantic.css",
    "static/tokens-components.css",
];

fn main() {
    let root = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("manifest dir"));
    let out = PathBuf::from(std::env::var("OUT_DIR").expect("out dir"));
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=src/css_lower.rs");
    println!("cargo:rerun-if-changed=static/components");

    let mut css = String::from("@layer theme, base, components;\n");
    for file in TOKEN_FILES.iter().chain(["static/base.css"].iter()) {
        let path = root.join(file);
        append(&mut css, &path, file, false);
    }
    let components = files_with_extension(&root.join("static/components"), "css");
    for path in &components {
        let label = format!(
            "static/components/{}",
            path.file_name().unwrap().to_string_lossy()
        );
        append(&mut css, path, &label, true);
    }
    fs::write(out.join("openagents-ui.css"), &css).expect("write bundled css");

    let mut js = String::new();
    let toggle = root.join("static/theme-toggle.js");
    append_js(&mut js, &toggle, "static/theme-toggle.js");
    for path in files_with_extension(&root.join("static/components"), "js") {
        let label = format!(
            "static/components/{}",
            path.file_name().unwrap().to_string_lossy()
        );
        append_js(&mut js, &path, &label);
    }
    fs::write(out.join("openagents-ui.js"), &js).expect("write bundled js");

    let mut meta = String::new();
    let _ = writeln!(
        meta,
        "pub(crate) const STYLESHEET_VERSION: &str = \"{:016x}\";",
        fnv1a(css.as_bytes())
    );
    let _ = writeln!(
        meta,
        "pub(crate) const SCRIPT_VERSION: &str = \"{:016x}\";",
        fnv1a(js.as_bytes())
    );
    let _ = writeln!(meta, "pub(crate) const COMPONENT_STYLESHEETS: &[&str] = &[");
    for path in &components {
        let _ = writeln!(
            meta,
            "    {:?},",
            path.file_name().unwrap().to_string_lossy()
        );
    }
    let _ = writeln!(meta, "];");
    fs::write(out.join("bundle_meta.rs"), meta).expect("write bundle meta");
}

fn files_with_extension(dir: &Path, extension: &str) -> Vec<PathBuf> {
    let mut files: Vec<PathBuf> = match fs::read_dir(dir) {
        Ok(entries) => entries
            .filter_map(Result::ok)
            .map(|entry| entry.path())
            .filter(|path| path.is_file() && path.extension().is_some_and(|e| e == extension))
            .collect(),
        Err(_) => Vec::new(),
    };
    files.sort();
    files
}

fn append(css: &mut String, path: &Path, label: &str, layered: bool) {
    println!("cargo:rerun-if-changed={}", path.display());
    let Ok(text) = fs::read_to_string(path) else {
        // Only while bootstrapping: the token files are generated by a test.
        println!(
            "cargo:warning=openagents-ui: {label} is missing; regenerate with OPENAGENTS_UI_BLESS=1"
        );
        return;
    };
    let text = lower_outside_comments(&text);
    let _ = writeln!(css, "\n/* {label} */");
    if layered {
        let _ = writeln!(css, "@layer components {{\n{}\n}}", text.trim_end());
    } else {
        let _ = writeln!(css, "{}", text.trim_end());
    }
}

/// Lower `alpha()`/`spacing()` in rules, leaving `/* comments */` as written.
fn lower_outside_comments(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut rest = text;
    while let Some(start) = rest.find("/*") {
        out.push_str(&css_lower::css_value(&rest[..start]));
        match rest[start..].find("*/") {
            Some(end) => {
                out.push_str(&rest[start..start + end + 2]);
                rest = &rest[start + end + 2..];
            }
            None => {
                out.push_str(&rest[start..]);
                rest = "";
            }
        }
    }
    out.push_str(&css_lower::css_value(rest));
    out
}

fn append_js(js: &mut String, path: &Path, label: &str) {
    println!("cargo:rerun-if-changed={}", path.display());
    let text = fs::read_to_string(path).unwrap_or_else(|e| panic!("read {label}: {e}"));
    let _ = writeln!(js, "/* {label} */\n{}\n;", text.trim_end());
}

fn fnv1a(bytes: &[u8]) -> u64 {
    let mut hash: u64 = 0xcbf2_9ce4_8422_2325;
    for byte in bytes {
        hash ^= u64::from(*byte);
        hash = hash.wrapping_mul(0x0100_0000_01b3);
    }
    hash
}
