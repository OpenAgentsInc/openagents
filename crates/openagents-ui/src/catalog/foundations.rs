pub(super) fn icons(_pane: Pane) -> Markup {
    let sizes = [
        (IconSize::Xs, "xs"),
        (IconSize::Sm, "sm"),
        (IconSize::Md, "md"),
        (IconSize::Lg, "lg"),
        (IconSize::Xl, "xl"),
        (IconSize::Xxl, "2xl"),
    ];
    html! {
        (specimen("SizedIcon", "Sizes", row(html! {
            @for (size, name) in sizes {
                span class="oa-catalog-labelled" { (Icon::Sparkles.size(size)) (caption(name)) }
            }
        })))
        (specimen("Icon", &format!("All {} icons", Icon::ALL.len()), stack(html! {
            ul class="oa-catalog-icons" role="list" {
                @for icon in Icon::ALL {
                    li class="oa-catalog-icons__item" title=(icon.name()) {
                        (PreEscaped(format!(
                            r##"<svg class="oa-icon" data-size="lg" aria-hidden="true" focusable="false" width="1em" height="1em"><use href="#{}"></use></svg>"##,
                            sprite_id(icon)
                        )))
                        span class="oa-catalog-icons__name" { (icon.name()) }
                    }
                }
            }
        })))
    }
}

fn sprite_id(icon: Icon) -> String {
    format!("catalog-icon-{}", icon.name())
}

/// Every icon once, as `<symbol>`s the icon grids in both panes `<use>`:
/// drawing 755 inline SVGs twice would double the page. Hidden without
/// `display: none`, which would break the brand icons' clip paths.
pub(super) fn icon_sprite() -> Markup {
    let mut out =
        String::from(r#"<svg class="oa-catalog-sprite" aria-hidden="true" focusable="false">"#);
    for icon in Icon::ALL {
        let svg = icon.render().into_string();
        // `<svg class="oa-icon" aria-hidden="true" focusable="false"
        // width="1em" height="1em" ATTRS>BODY</svg>`
        let open_end = svg.find('>').expect("svg open tag");
        let attrs = svg[..open_end]
            .split_once(r#"height="1em""#)
            .map_or("", |(_, rest)| rest);
        let body = &svg[open_end + 1..svg.len() - "</svg>".len()];
        out.push_str(&format!(
            r#"<symbol id="{}"{attrs}>{body}</symbol>"#,
            sprite_id(icon)
        ));
    }
    out.push_str("</svg>");
    PreEscaped(out)
}
