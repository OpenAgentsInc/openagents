/// The generated `static/components/catalog-tokens.css`.
#[must_use]
pub fn tokens_css() -> String {
    let mut out = String::from(
        "/* Generated by openagents-ui from src/catalog/foundations.rs (OPENAGENTS_UI_BLESS=1 cargo test -p openagents-ui). Do not edit.\n   One rule per catalog swatch: the site CSP forbids inline styles. */\n",
    );
    for (_, tokens) in COLOR_GROUPS {
        for token in *tokens {
            out.push_str(&format!(
                "\n.oa-catalog-swatch__chip[data-token=\"{token}\"] {{\n  background: var(--{token});\n}}\n"
            ));
        }
    }
    for name in TYPE_SCALE {
        out.push_str(&format!(
            "\n.oa-catalog-type__sample[data-token=\"{name}\"] {{\n  font-size: var(--font-{name}-size);\n  line-height: var(--font-{name}-line-height);\n  font-weight: var(--font-{name}-weight);\n  letter-spacing: var(--font-{name}-tracking);\n}}\n"
        ));
    }
    for token in RADII {
        out.push_str(&format!(
            "\n.oa-catalog-shape[data-token=\"{token}\"] {{\n  border-radius: var(--{token});\n}}\n"
        ));
    }
    for token in SHADOWS {
        out.push_str(&format!(
            "\n.oa-catalog-shape[data-token=\"{token}\"] {{\n  box-shadow: var(--{token});\n}}\n"
        ));
    }
    out
}

fn hex(color: Rgba) -> String {
    let channel = |v: f64| (v.clamp(0.0, 1.0) * 255.0).round() as u8;
    let rgb = format!(
        "#{:02x}{:02x}{:02x}",
        channel(color.r),
        channel(color.g),
        channel(color.b)
    );
    if color.a < 0.999 {
        format!("{rgb} / {}%", (color.a * 100.0).round())
    } else {
        rgb
    }
}

pub(super) fn colors(pane: Pane) -> Markup {
    let resolver = Resolver::new();
    html! {
        @for (title, tokens) in COLOR_GROUPS {
            div class="oa-catalog-swatches" {
                p class="oa-catalog-specimen__title" { (title) }
                ul class="oa-catalog-swatches__list" role="list" {
                    @for token in *tokens {
                        @let value = resolver.color(&format!("--{token}"), pane.scheme()).map(hex);
                        li class="oa-catalog-swatch" {
                            span class="oa-catalog-swatch__chip" data-token=(token) {}
                            code class="oa-catalog-swatch__name" { "--" (token) }
                            @if let Some(value) = value {
                                span class="oa-catalog-swatch__value" { (value) }
                            }
                        }
                    }
                }
            }
        }
    }
}

