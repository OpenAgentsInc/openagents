async fn page() -> Response {
    let mut response = axum::response::Html(document()).into_response();
    response.headers_mut().insert(
        header::CONTENT_SECURITY_POLICY,
        HeaderValue::from_static(LANDER3_POLICY),
    );
    response
}

async fn scene_file() -> Response {
    (
        [
            (header::CONTENT_TYPE, "application/json"),
            (header::CACHE_CONTROL, CACHE),
        ],
        SCENE,
    )
        .into_response()
}

async fn texture(UrlPath(file): UrlPath<String>) -> Response {
    match TEXTURES.iter().find(|(name, _)| *name == file) {
        Some((_, bytes)) => (
            [
                (header::CONTENT_TYPE, "image/png"),
                (header::CACHE_CONTROL, CACHE),
            ],
            *bytes,
        )
            .into_response(),
        None => crate::not_found().await,
    }
}

async fn three(UrlPath(file): UrlPath<String>) -> Response {
    match THREE.iter().find(|(name, _)| *name == file) {
        Some((_, text)) => javascript(text),
        None => crate::not_found().await,
    }
}

async fn script() -> Response {
    javascript(SCRIPT)
}

async fn styles() -> Response {
    (
        [
            (header::CONTENT_TYPE, "text/css; charset=utf-8"),
            (header::CACHE_CONTROL, CACHE),
        ],
        STYLES,
    )
        .into_response()
}

fn javascript(text: &'static str) -> Response {
    (
        [
            (header::CONTENT_TYPE, "text/javascript; charset=utf-8"),
            (header::CACHE_CONTROL, CACHE),
        ],
        text,
    )
        .into_response()
}

#[cfg(test)]
mod tests {
    use base64::Engine as _;
    use serde_json::Value;
    use sha2::{Digest, Sha256};

    use super::*;

    fn pack() -> Value {
        serde_json::from_str(include_str!("../../../../assets/verse/grid/pack.json")).unwrap()
    }

    #[test]
    fn the_scene_comes_from_the_pinned_pack() {
        let pack = pack();
        let scene: Value = serde_json::from_str(SCENE).unwrap();
        assert_eq!(scene["source_revision"], pack["source_revision"]);
        let statics = scene["statics"].as_array().unwrap();
        let placements = pack["placements"].as_array().unwrap();
        assert_eq!(statics.len(), placements.len());
        for (placed, source) in statics.iter().zip(placements) {
            assert_eq!(placed["model"], source["model"]);
        }
        let gates = scene["gates"].as_array().unwrap();
        for placed in statics.iter().chain(gates) {
            let name = placed["model"].as_str().unwrap();
            assert!(scene["models"].get(name).is_some(), "{name}");
            assert!(pack["models"].get(name).is_some(), "{name}");
            assert_eq!(placed["matrix"].as_array().unwrap().len(), 16);
        }
        for arch in ["grid/arch-everglade", "grid/arch-lagrange-2"] {
            assert!(gates.iter().any(|gate| gate["model"] == arch));
        }
        assert_eq!(scene["textures"].as_array().unwrap().len(), TEXTURES.len());
        for (texture, (name, _)) in scene["textures"].as_array().unwrap().iter().zip(TEXTURES) {
            assert_eq!(texture, &format!("/lander3/texture/{name}"));
        }

        let robots = &scene["robots"];
        let rate = robots["rate"].as_f64().unwrap() as f32;
        assert_eq!(robots["patrols"].as_array().unwrap().len(), 5);
        for patrol in robots["patrols"].as_array().unwrap() {
            let frames = (patrol["round"].as_f64().unwrap() as f32 * rate).ceil() as usize;
            assert_eq!(decoded(&patrol["samples"]).len(), frames * 5 * 4);
        }
        for name in [
            robots["near"].as_str().unwrap(),
            robots["far"].as_str().unwrap(),
        ] {
            let model = &scene["models"][name];
            let bones = model["bones"].as_u64().unwrap() as usize;
            assert_eq!(
                bones,
                pack["models"][name]["skin"]["names"]
                    .as_array()
                    .unwrap()
                    .len()
            );
            let clips = robots["poses"][name].as_array().unwrap();
            assert_eq!(clips.len(), robots["clips"].as_array().unwrap().len());
            for clip in clips {
                let frames = (clip["duration"].as_f64().unwrap() as f32 * rate).ceil() as usize;
                assert_eq!(decoded(&clip["frames"]).len(), frames * bones * 16 * 4);
            }
        }
    }

    fn decoded(value: &Value) -> Vec<u8> {
        base64::engine::general_purpose::STANDARD
            .decode(value.as_str().unwrap())
            .unwrap()
    }

    #[test]
    fn the_textures_are_the_packs_own() {
        let pack = pack();
        let textures = pack["textures"].as_array().unwrap();
        assert_eq!(TEXTURES.len(), textures.len());
        for texture in textures {
            let (_, bytes) = TEXTURES
                .iter()
                .find(|(name, _)| *name == texture["file"].as_str().unwrap())
                .unwrap();
            assert_eq!(format!("{:x}", Sha256::digest(bytes)), texture["sha256"]);
        }
    }

    #[test]
    fn the_policy_allows_only_this_site() {
        assert!(LANDER3_POLICY.starts_with("default-src 'none'"));
        assert!(LANDER3_POLICY.contains("script-src 'self';"));
        assert!(!LANDER3_POLICY.contains("unsafe"));
        assert!(!LANDER3_POLICY.contains("http"));
    }

    #[test]
    fn three_imports_only_its_vendored_core() {
        let (_, module) = THREE[0];
        assert!(module.contains("from\"./three.core.min.js\""));
        assert!(!module.contains("http://") && !module.contains("https://cdn"));
    }
}
