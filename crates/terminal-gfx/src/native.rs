fn modifiers(mods: ModifiersState) -> terminal_core::input::ModifiersState {
    use terminal_core::input::ModifiersState as Core;
    let mut out = Core::empty();
    for (enabled, flag) in [
        (mods.shift_key(), Core::SHIFT),
        (mods.control_key(), Core::CONTROL),
        (mods.alt_key(), Core::ALT),
        (mods.super_key(), Core::SUPER),
    ] {
        if enabled {
            out = out | flag;
        }
    }
    out
}

