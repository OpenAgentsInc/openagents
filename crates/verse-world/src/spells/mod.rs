//! The physics layer SRD spells act through.
//!
//! [`SpellWorld`] holds a `physics::World` of dynamic props beside the
//! chamber's kinematic characters, stepped on the chamber's 120 Hz clock and
//! saved with every checkpoint. It also holds the seeded [`dice::Dice`],
//! active [`fields::SpellField`] areas, spell-owned bodies and joints,
//! concentration, and a momentum [`physics::Ledger`] with one named term per
//! source of external momentum.
//!
//! To add a spell, write `spells/<name>.rs` with its cast function and its
//! playground scenario, then add one line to [`CATALOG`] (its action-bar
//! slot) and one line to `crate::playground::scenarios`.
