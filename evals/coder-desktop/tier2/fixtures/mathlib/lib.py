def add(a, b):
    return a + b


def sub(a, b):
    return a - b


def mul(a, b):
    return a * b


def div(a, b):
    return a / b


def mod(a, b):
    return a % b


def power(a, b):
    return a ** b


def floordiv(a, b):
    return a // b


def maxof(a, b):
    return max(a, b)


def minof(a, b):
    return min(a, b)


def avg(a, b):
    return (a + b) / 2


def hyp(a, b):
    return (a * a + b * b) ** 0.5


def diff(a, b):
    return abs(a - b)
