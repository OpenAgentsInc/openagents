#!/usr/bin/env python3
# Firm reason: 5 (offline fixture generator for Tier 1 Coder Desktop evals)
"""Generate evals/openagents-desktop/tier1/fixtures_data.coax from tier1/fixtures/*.jsonl."""
import argparse
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent
FIXTURES_DIR = ROOT / "fixtures"
OUT_PATH = ROOT / "fixtures_data.coax"

EXPECTED_FIXTURES = [
    ("FIX_01_SIMPLE_QA", "01_simple_qa.jsonl"),
    ("FIX_02_MULTI_STEP_EDIT", "02_multi_step_edit.jsonl"),
    ("FIX_03_SUBAGENT_PARALLEL", "03_subagent_parallel.jsonl"),
    ("FIX_04_SUBAGENT_PAUSE_100", "04_subagent_pause_100.jsonl"),
    ("FIX_05_GOAL_AUTONOMOUS", "05_goal_autonomous.jsonl"),
    ("FIX_06_BUDGET_EXCEEDED", "06_budget_exceeded.jsonl"),
    ("FIX_07_STOP_AND_CRASH", "07_stop_and_crash.jsonl"),
    ("FIX_08_BACKGROUND_CHAT_SWITCH", "08_background_chat_switch.jsonl"),
    ("FIX_09_MALFORMED_WIRE", "09_malformed_wire.jsonl"),
    ("FIX_10_LARGE_SAVE_LOAD", "10_large_save_load.jsonl"),
]


def coax_escape(text: str) -> str:
    out = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        else:
            out.append(ch)
    return "".join(out)


def build_coax() -> str:
    lines = [
        "// Generated by evals/openagents-desktop/tier1/gen_fixtures.py from tier1/fixtures/*.jsonl.",
        "// Do not edit by hand; update the JSONL fixtures and re-run gen_fixtures.py.",
        "",
    ]
    for const_name, filename in EXPECTED_FIXTURES:
        path = FIXTURES_DIR / filename
        if not path.is_file():
            raise SystemExit(f"missing fixture: {path}")
        content = path.read_text(encoding="utf-8")
        lines.append(f'{const_name} :: "{coax_escape(content)}";')
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if fixtures_data.coax is out of date.")
    args = parser.parse_args()
    generated = build_coax()
    if args.check:
        if not OUT_PATH.is_file() or OUT_PATH.read_text(encoding="utf-8") != generated:
            print("fixtures_data.coax is out of date; run python3 evals/openagents-desktop/tier1/gen_fixtures.py", file=sys.stderr)
            return 1
        return 0
    OUT_PATH.write_text(generated, encoding="utf-8")
    print(f"wrote {OUT_PATH} ({len(generated)} bytes, {len(EXPECTED_FIXTURES)} fixtures)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
