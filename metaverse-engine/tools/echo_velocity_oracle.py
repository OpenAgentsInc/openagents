    args = [f(((k * 37) % 1025 - 512) / 128), f(((k * 73) % 1025 - 512) / 128), f(dx), f(dz), f([0, .25, .5, 1][(k // 8) % 4]), f([0, .5, 1.47, 4.27][(k // 32) % 4]), f([0, 5][(k // 128) % 2]), f([0, 4][(k // 256) % 2]), f([0, 10][(k // 512) % 2]), f(2), f(1 / 64)]
    rows.append(reference(*args))
