# Firm reason: 2 (independent float32 oracle for the Coax port of Unreal's scalar velocity path).
import math
import struct
from pathlib import Path

def f(x):
    return struct.unpack('<f', struct.pack('<f', x))[0]

def add(a, b): return f(a + b)
def sub(a, b): return f(a - b)
def mul(a, b): return f(a * b)
def div(a, b): return f(a / b)
def sq(x, z): return add(mul(x, x), mul(z, z))
def bits(x): return struct.unpack('<I', struct.pack('<f', x))[0]

def reference(x, z, dx, dz, amount, speed, accel, friction, brake, factor, dt):
    vx, vz = x, z
    old_size = f(math.sqrt(sq(x, z)))
    maximum = mul(speed, amount)
    ax, az = mul(mul(dx, accel), amount), mul(mul(dz, accel), amount)
    zero = ax == 0 and az == 0
    over = mul(old_size, old_size) > mul(mul(maximum, maximum), f(1.01))
    if zero or over:
        if old_size > 0:
            vx = add(vx, mul(sub(sub(0, mul(mul(friction, factor), vx)), div(mul(brake, x), old_size)), dt))
            vz = add(vz, mul(sub(sub(0, mul(mul(friction, factor), vz)), div(mul(brake, z), old_size)), dt))
            if add(mul(vx, x), mul(vz, z)) <= 0 or sq(vx, vz) <= f(1e-8) or (brake > 0 and sq(vx, vz) <= f(.01)):
                vx = vz = f(0)
            if over and sq(vx, vz) < mul(maximum, maximum) and add(mul(ax, x), mul(az, z)) > 0:
                vx, vz = mul(div(x, old_size), maximum), mul(div(z, old_size), maximum)
    else:
        share = min(mul(friction, dt), f(1))
        vx = sub(vx, mul(sub(vx, mul(dx, old_size)), share))
        vz = sub(vz, mul(sub(vz, mul(dz, old_size)), share))
    if not zero:
        now = f(math.sqrt(sq(vx, vz)))
        limit = now if mul(now, now) > mul(mul(maximum, maximum), f(1.01)) else maximum
        vx, vz = add(vx, mul(ax, dt)), add(vz, mul(az, dt))
        size = f(math.sqrt(sq(vx, vz)))
        if size > limit and size > 0:
            vx, vz = mul(div(vx, size), limit), mul(div(vz, size), limit)
    return bits(vx), bits(vz)

