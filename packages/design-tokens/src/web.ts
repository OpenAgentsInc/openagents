import { colorTokens, defaultTheme, khalaTheme } from "./index.ts";
import type { Theme } from "./index.ts";

const kebab = (value: string): string =>
  value.replace(/[A-Z]/g, (match) => `-${match.toLowerCase()}`);

const declarations = (theme: Theme): ReadonlyArray<string> => [
  ...colorTokens.map((token) => `  --oa-color-${kebab(token)}: ${theme.color[token]};`),
  ...Object.entries(theme.spacing).map(
    ([token, value]) => `  --oa-space-${token.replace(".", "_")}: ${value}px;`,
  ),
  ...Object.entries(theme.radius).map(([token, value]) => `  --oa-radius-${token}: ${value}px;`),
  `  --oa-motion-fast: ${theme.motion.durationFastMs}ms;`,
  `  --oa-motion-enter: ${theme.motion.durationEnterMs}ms;`,
  `  --oa-motion-exit: ${theme.motion.durationExitMs}ms;`,
  `  --oa-motion-loop: ${theme.motion.durationLoopMs}ms;`,
  `  --oa-ease-basic: ${theme.motion.easeBasic};`,
  `  --oa-ease-enter: ${theme.motion.easeEnter};`,
  `  --oa-ease-exit: ${theme.motion.easeExit};`,
  `  --oa-ease-move: ${theme.motion.easeMove};`,
];

const themeBlock = (selectors: string, theme: Theme, scheme: "dark" | "light") =>
  `${selectors} {\n  color-scheme: ${scheme};\n${declarations(theme).join("\n")}\n}`;

const tailwindProjection = [
  ...colorTokens.map((token) => `  --color-oa-${kebab(token)}: var(--oa-color-${kebab(token)});`),
  `  --duration-oa-fast: var(--oa-motion-fast);`,
  `  --duration-oa-enter: var(--oa-motion-enter);`,
  `  --duration-oa-exit: var(--oa-motion-exit);`,
].join("\n");

export const renderWebDesignTokens = (): string => `/*
 * Generated by packages/design-tokens/scripts/generate-web-css.ts.
 * Edit src/index.ts or src/web.ts, then regenerate. Do not hand-edit.
 */

${themeBlock(':root, [data-oa-theme="dark"]', khalaTheme, "dark")}

${themeBlock('[data-oa-theme="light"]', defaultTheme, "light")}

@media (prefers-reduced-motion: reduce) {
  :root,
  [data-oa-theme="dark"],
  [data-oa-theme="light"] {
    --oa-motion-fast: 0ms;
    --oa-motion-enter: 0ms;
    --oa-motion-exit: 0ms;
    --oa-motion-loop: 0ms;
  }
}

@theme inline {
${tailwindProjection}
}
`;
