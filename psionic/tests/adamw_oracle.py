#!/usr/bin/env python3
# Firm reason: 2 (independent oracle: recomputes our answer outside Coax, so it must not share our implementation)
"""Independent AdamW: per-group dictionaries, Python floats and struct-packed binary32.

Formula (decoupled decay before the moment update, bias-corrected step):
  p <- p * (1 - lr*wd)
  m <- b1*m + (1-b1)*g ; v <- b2*v + (1-b2)*g*g
  p <- p - (lr/(1-b1^t)) * m / (sqrt(v)/sqrt(1-b2^t) + eps)
--write regenerates psionic/fixtures/adamw/{reference.json,reference.coax};
the default verifies the committed files reproduce; --header prints C goldens.
"""
import argparse, json, math, struct
from pathlib import Path

D = Path(__file__).resolve().parents[1] / 'fixtures/adamw'

def f32(x):
    return struct.unpack('<f', struct.pack('<f', x))[0]

CASES = [
    # name, n, groups (first, count, lr, b1, b2, eps, wd), steps, compute
    ('matrix', 12, [(0, 8, 0.01, 0.9, 0.999, 1e-8, 0.1), (8, 4, 0.05, 0.8, 0.95, 1e-6, 0.0)], 5, 'binary64'),
    ('narrow', 3, [(0, 3, 0.125, 0.5, 0.75, 0.001, 0.25)], 3, 'binary32'),
    ('scalar', 1, [(0, 1, 0.3, 0.0, 0.5, 0.01, 0.5)], 4, 'binary64'),
]

def start(name, n):
    return [((i * 7 + len(name)) % 11 - 5) / 4 for i in range(n)]

def gradient(name, n, step, compute):
    out = []
    for i in range(n):
        g = math.sin(0.37 * i + 1.3 * step + len(name)) * (1 + 0.5 * step)
        out.append(f32(g) if compute == 'binary32' else g)
    return out

def run(case):
    name, n, groups, steps, compute = case
    params = {i: x for i, x in enumerate(start(name, n))}
    first = {i: 0.0 for i in range(n)}
    second = {i: 0.0 for i in range(n)}
    trace = []
    for t in range(1, steps + 1):
        grads = gradient(name, n, t - 1, compute)
        for (lo, count, lr, b1, b2, eps, wd) in groups:
            c1 = 1 - b1 ** t
            c2 = 1 - b2 ** t
            for i in range(lo, lo + count):
                decayed = params[i] * (1 - lr * wd)
                first[i] = b1 * first[i] + (1 - b1) * grads[i]
                second[i] = b2 * second[i] + (1 - b2) * grads[i] * grads[i]
                params[i] = decayed - (lr / c1) * (first[i] / (math.sqrt(second[i]) / math.sqrt(c2) + eps))
        row = dict(grads=grads, params=[params[i] for i in range(n)], m=[first[i] for i in range(n)], v=[second[i] for i in range(n)])
        if compute == 'binary32':
            row['compute'] = [f32(params[i]) for i in range(n)]
        trace.append(row)
    return dict(name=name, n=n, steps=steps, compute=compute, start=start(name, n),
                groups=[dict(first=g[0], count=g[1], lr=g[2], beta1=g[3], beta2=g[4], eps=g[5], decay=g[6]) for g in groups], trace=trace)

def coax(ref):
    lines = ['// Generated by psionic/tests/adamw_oracle.py --write. Independent AdamW values; do not edit.\n']
    for c in ref['cases']:
        p = 'AW_' + c['name'].upper()
        def arr(label, values):
            lines.append(f"{p}_{label} :: [{len(values)}]f64.[{','.join(repr(float(x)) for x in values)}];\n")
        arr('START', c['start'])
        for label in ['grads', 'params', 'm', 'v'] + (['compute'] if c['compute'] == 'binary32' else []):
            arr(label.upper(), [x for row in c['trace'] for x in row[label]])
    return ''.join(lines)

def build():
    return dict(schema=1, profile='cpu-adamw-v1', master='binary64', formula='decay-then-moments, bias-corrected, eps outside sqrt', cases=[run(c) for c in CASES])

def main():
    a = argparse.ArgumentParser()
    a.add_argument('--write', action='store_true')
    a.add_argument('--header', action='store_true')
    args = a.parse_args()
    ref = build()
    text = json.dumps(ref, indent=1) + '\n'
    if args.write:
        D.mkdir(parents=True, exist_ok=True)
        (D / 'reference.json').write_text(text)
        (D / 'reference.coax').write_text(coax(ref))
        print('Captured', ', '.join(f"{c['name']} ({c['n']} parameters, {c['steps']} steps)" for c in ref['cases']))
        return
    assert (D / 'reference.json').read_text() == text, 'reference.json does not reproduce'
    assert (D / 'reference.coax').read_text() == coax(ref), 'reference.coax does not reproduce'
    if args.header:
        for c in ref['cases']:
            p = 'aw_' + c['name']
            def arr(label, values):
                print(f"static const double {p}_{label}[]={{{','.join(repr(float(x)) for x in values)}}};")
            arr('start', c['start'])
            for label in ['grads', 'params', 'm', 'v'] + (['compute'] if c['compute'] == 'binary32' else []):
                arr(label, [x for row in c['trace'] for x in row[label]])
    else:
        print('AdamW reference reproduces:', ', '.join(f"{c['name']} {c['n']}x{c['steps']}" for c in ref['cases']))

if __name__ == '__main__':
    main()
