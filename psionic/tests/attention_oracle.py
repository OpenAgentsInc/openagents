ROOT = Path(__file__).resolve().parents[2]
def f(x): return struct.unpack('<f', struct.pack('<f', x))[0]
def bits(x): return struct.unpack('<I', struct.pack('<f', x))[0]
def cases():
    for d,h,kv,hd,ff,cap in [(4,2,1,2,3,3),(4,1,1,4,5,3),(6,3,3,2,4,3)]:
        k=kv*hd; n=2*d+2*d*d+2*k*d+3*ff*d
        w=[f(((i*17+3)%29-14)/32) for i in range(n)]
        for i in range(d): w[i]=f(0.75+i/8)
        no=d+d*d+2*k*d+d*d
        for i in range(d): w[no+i]=f(1.0-i/16)
        rope=[]
        for p in range(cap):
            for pair in range(hd//2):
                angle=p/(10000**(2*pair/hd));rope.extend([f(math.cos(angle)),f(math.sin(angle))])
        x=[f(((i*11+5)%19-9)/8) for i in range(cap*d)]
        eps=f(0.125)
        qoff=d;koff=qoff+d*d;voff=koff+k*d;ooff=voff+k*d;n2off=ooff+d*d;goff=n2off+d;uoff=goff+ff*d;doff=uoff+ff*d
        def linear(off, rows, cols, a):
            return [f(sum(float(w[off+r*cols+c])*a[c] for c in range(cols))) for r in range(rows)]
        def norm(a,off):
            divisor=math.sqrt(sum(float(v)*v for v in a)/d+eps)
            return [f(v/divisor*w[off+i]) for i,v in enumerate(a)]
        def rotate(v,heads,pos):
            v=list(v)
            for head in range(heads):
                for pair in range(hd//2):
                    j=head*hd+2*pair; r=pos*hd+2*pair
                    a,b=v[j:j+2];c,s=rope[r:r+2]
                    v[j]=f(a*c-b*s);v[j+1]=f(a*s+b*c)
            return v
        qs=[];ks=[];vs=[]
        for p in range(cap):
            a=norm(x[p*d:(p+1)*d],0)
            qs.append(rotate(linear(qoff,d,d,a),h,p))
            ks.append(rotate(linear(koff,k,d,a),kv,p))
            vs.append(linear(voff,k,d,a))
        output=[];cache=[]
        for pos in range(cap):
            context=[]
            for head in range(h):
                group=head//(h//kv)
                scores=[f(sum(qs[pos][head*hd+j]*ks[t][group*hd+j] for j in range(hd))/math.sqrt(hd)) for t in range(pos+1)]
                maximum=max(scores); probs=[math.exp(v-maximum) for v in scores];total=sum(probs)
                context.extend(f(sum(probs[t]/total*vs[t][group*hd+j] for t in range(pos+1))) for j in range(hd))
            project=linear(ooff,d,d,context)
            residual=[f(x[pos*d+i]+project[i]) for i in range(d)]
            a=norm(residual,n2off);gate=linear(goff,ff,d,a);up=linear(uoff,ff,d,a)
            prod=[f(g/(1+math.exp(-g))*u) for g,u in zip(gate,up)]
            down=linear(doff,d,ff,prod)
            output.extend(f(residual[i]+down[i]) for i in range(d))
            cache.extend(ks[pos]+vs[pos])
        yield dict(d=d,h=h,kv=kv,hd=hd,ff=ff,cap=cap,eps=eps,w=w,rope=rope,x=x,out=output,cache=cache)

def coax_array(name,values):
    return f"{name}:=[{len(values)}]f32.["+','.join(f"f32_from_bits(0x{bits(x):08x})" for x in values)+'];'
def coax_text():
    lines=['// Generated by psionic/tests/attention_oracle.py; independent full-sequence reference.']
    for number,c in enumerate(cases()):
        d,h,kv,hd,ff,cap=(c[k] for k in ('d','h','kv','hd','ff','cap'))
        lines.append(f'#test "independent causal forward fixture {number}" {{')
        lines.append(f'    s:=PaShape.{{width={d},heads={h},kv_heads={kv},head_width={hd},hidden={ff},capacity={cap},epsilon=0.125f32}};')
        for name in ('w','rope','x','out','cache'):lines.append('    '+coax_array('expected' if name=='out' else 'keys' if name=='cache' else name,c[name]))
        lines.append(f'    out:[{cap*d}]f32; state:[{cap*kv*hd*2}]f32;')
        lines.append(f'    r:=pa_forward(s,w[..],rope[..],x[..],{cap},out[..],false);#assert r.status==PaStatus.ok && r.written=={cap*d};')
        lines.append(f'    for i:0..<{cap*d} {{#assert abs(out[i]-expected[i])<0.000002f32;}}')
        lines.append(f'    for p:0..<{cap} {{q:=pa_step(s,w[..],rope[..],x[p*{d}..<(p+1)*{d}],p,state[..],out[p*{d}..<(p+1)*{d}],false);#assert q.status==PaStatus.ok;}}')
        lines.append(f'    for i:0..<{cap*d} {{#assert abs(out[i]-expected[i])<0.000002f32;}}')
        lines.append(f'    for i:0..<{cap*kv*hd*2} {{#assert abs(state[i]-keys[i])<0.000002f32;}}')
        lines.append('}')
    return '\n'.join(lines)+'\n'
