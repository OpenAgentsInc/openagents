#!/usr/bin/env python3
"""Owned protocol oracle; no upstream code and no model execution."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def fixture():
    units, events = [], []

    def plain(text):
        units.extend(text.encode())

    def special(n):
        units.append(256 + n)

    def emit(kind, call, text):
        events.extend((kind, call, b) for b in text.encode())

    def tag(text):
        a, b = text.split('@')
        plain(a)
        special(7)
        plain(b)

    reason = 'why </think> 😀\n'
    plain(reason)
    emit(0, 0, reason)
    special(6)
    final = '  answer <think>\n'
    plain(final)
    emit(1, 0, final)
    tag('<@ calls>')
    for call, (name, args) in enumerate([
        ('search_1', [('query', 'a"\\\n\t\x00😀', True), ('count', 12, False)]),
        ('empty', []),
    ], 1):
        plain('\n')
        tag(f'<@ invoke name="{name}">')
        events.append((2, call, 0))
        emit(3, call, name)
        emit(4, call, '{')
        for i, (key, value, string) in enumerate(args):
            plain('\n')
            tag(f'<@ parameter name="{key}" string="{str(string).lower()}">')
            encoded = json.dumps(value, ensure_ascii=False, separators=(',', ':'))
            plain(value if string else encoded)
            tag('</@ parameter>')
            # The profile uses canonical \u00xx escapes for all control bytes.
            if string:
                encoded = '"' + ''.join(
                    f'\\u{ord(c):04x}' if ord(c) < 32 else
                    '\\' + c if c in '\\"' else c for c in value) + '"'
            emit(4, call, (',' if i else '') + json.dumps(key) + ':' + encoded)
        plain('\n')
        tag('</@ invoke>')
        emit(4, call, '}')
        events.append((5, call, 0))
    plain('\n')
    tag('</@ calls>')
    special(1)
    return units, events


def main():
    units, events = fixture()
    fields = [('UNITS', units), ('KINDS', [x[0] for x in events]),
              ('CALLS', [x[1] for x in events]), ('BYTES', [x[2] for x in events])]
    coax = '// Generated by tests/deepseek_front_fixture.py; owned protocol oracle.\n'
    header = '/* Owned independent protocol vectors. */\n'
    for name, values in fields:
        body = ','.join(map(str, values))
        coax += f'DFF_{name} :: [{len(values)}]int.[{body}];\n'
        header += f'static const int64_t DFF_{name}[] = {{{body}}};\n'
    target = ROOT / 'psionic/fixtures/deepseek'
    for name, data in [('front-goldens.coax', coax), ('front-goldens.h', header)]:
        p = target / name
        if '--write' in __import__('sys').argv:
            p.write_text(data)
        else:
            assert p.read_text() == data, f'stale {p}'
    print(f'front oracle: {len(units)} typed units, {len(events)} exact events')


if __name__ == '__main__':
    main()
