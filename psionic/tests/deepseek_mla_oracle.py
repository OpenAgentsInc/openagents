"""Owned full-prefix MLA oracle: independent expansion and absorbed products."""
import argparse
import json
import math
from pathlib import Path
import struct

ROOT=Path(__file__).resolve().parents[2]


def f32(x):return struct.unpack('<f',struct.pack('<f',x))[0]


def bf(x):
    u=struct.unpack('<I',struct.pack('<f',x))[0]
    return struct.unpack('<f',struct.pack('<I',((u+0x7fff+((u>>16)&1))>>16)<<16))[0]


def dot(a,b):return f32(math.fsum(float(x)*float(y) for x,y in zip(a,b)))


def fixture():
    heads,nope,rope,value,latent=2,2,2,2,3
    weights=[[bf((((i*7+j*3)%17)-8)/16) for j in range(latent)] for i in range(heads*(nope+value))]
    queries=[[f32((((t*11+i*3)%19)-9)/8) for i in range(heads*(nope+rope))] for t in range(4)]
    zs=[[f32((((t*5+j*7)%13)-6)/8) for j in range(latent)] for t in range(4)]
    pes=[[f32((t+1)*(j*2-1)/16) for j in range(rope)] for t in range(4)]
    scale=0.375
    outputs={};rows={};scores={}
    for mode in ['compressed','expanded']:
        outputs[mode]=[];rows[mode]=[];scores[mode]=[]
        for t,q in enumerate(queries):
            expanded=[[dot(w,z) for w in weights] for z in zs[:t+1]]
            rows[mode].append((zs[t] if mode=='compressed' else expanded[t])+pes[t])
            result=[];step_scores=[]
            for h in range(heads):
                w=weights[h*(nope+value):(h+1)*(nope+value)]
                plain=q[h*(nope+rope):h*(nope+rope)+nope]
                rotary=q[h*(nope+rope)+nope:(h+1)*(nope+rope)]
                absorbed=[dot(plain,[w[r][j] for r in range(nope)]) for j in range(latent)]
                logits=[]
                for pos in range(t+1):
                    left=absorbed if mode=='compressed' else plain
                    right=zs[pos] if mode=='compressed' else expanded[pos][h*(nope+value):h*(nope+value)+nope]
                    logits.append(math.fsum([*(float(a)*float(b) for a,b in zip(left,right)),*(float(a)*float(b) for a,b in zip(rotary,pes[pos]))])*scale)
                exp=[math.exp(x-max(logits)) for x in logits];den=math.fsum(exp);step_scores.extend(exp)
                if mode=='compressed':
                    ctx=[f32(math.fsum(exp[pos]*zs[pos][j] for pos in range(t+1))/den) for j in range(latent)]
                    result.extend(dot(w[nope+j],ctx) for j in range(value))
                else:
                    result.extend(f32(math.fsum(exp[pos]*expanded[pos][h*(nope+value)+nope+j] for pos in range(t+1))/den) for j in range(value))
            outputs[mode].append(result);scores[mode].append(step_scores)
    raw=b''.join(struct.pack('<H',struct.unpack('<I',struct.pack('<f',x))[0]>>16) for row in weights for x in row)
    return dict(shape=dict(heads=heads,nope=nope,rope=rope,value=value,latent=latent,capacity=5),scale=scale,
                weights=list(raw),queries=queries,latents=zs,key_rope=pes,outputs=outputs,rows=rows,scores=scores)


def artifacts():
    f=fixture();coax='// Owned full-prefix MLA references; generated by deepseek_mla_oracle.py.\n';header='/* Independent owned full-prefix latent-attention vectors. */\n'
    arrays={'WEIGHTS':(f['weights'],'u8','uint8_t')}
    for k,v in [('QUERIES',f['queries']),('LATENTS',f['latents']),('PE',f['key_rope'])]:arrays[k]=([x for row in v for x in row],'f32','float')
    for mode in ['compressed','expanded']:
        for t in range(4):
            for kind in ['outputs','rows','scores']:arrays[f'{mode.upper()}_{kind.upper()}{t}']=(f[kind][mode][t],'f64' if kind=='scores' else 'f32','double' if kind=='scores' else 'float')
    for name,(data,typ,ctype) in arrays.items():
        body=','.join(str(x)+('f32' if typ=='f32' else '') for x in data)
        coax+=f'MLG_{name} :: [{len(data)}]{typ}.[{body}];\n'
        header+=f'static const {ctype} mlg_{name.lower()}[] = {{{",".join(map(str,data))}}};\n'
    for mode in ['compressed','expanded']:
        width=len(f['rows'][mode][0]);test=f'''#test "MLA {mode} matches independent full-prefix expansion and continuation" {{
    s:=MlShape.{{heads=2,nope=2,rope=2,value=2,latent=3,capacity=5}};w:=MLG_WEIGHTS;q:=MLG_QUERIES;z:=MLG_LATENTS;pe:=MLG_PE;
    history:[{5*width}]f32;out:[5]f32;row:[{width+1}]f32;work:[64]f32;scores:[10]f64;out[4]=-7;row[{width}]=-9;
'''
        for t in range(4):
            test+=f'''    r{t}:=ml_attention(s,MlMode.{mode},w[..],q[{t*8}..<{(t+1)*8}],z[{t*3}..<{(t+1)*3}],pe[{t*2}..<{(t+1)*2}],history[0..<{t*width}],{t},0.375,out[..],row[..],work[..],scores[..],false);
    #assert r{t}.status==DsStatus.ok && r{t}.written==4 && r{t}.row_written=={width};
    for j:0..<4 {{#assert abs(out[j]-MLG_{mode.upper()}_OUTPUTS{t}[j])<0.0000002f32;}}
    for j:0..<{width} {{#assert row[j]==MLG_{mode.upper()}_ROWS{t}[j];history[{t*width}+j]=row[j];}}
    for j:0..<{2*(t+1)} {{#assert abs(scores[j]-MLG_{mode.upper()}_SCORES{t}[j])<1e-13;}}
'''
        test+=f'    #assert out[4]==-7 && row[{width}]==-9;\n}}\n';coax+=test
    return {'mla-goldens.coax':coax,'mla-goldens.h':header,'mla-goldens.json':json.dumps({'schema':1,'oracle':'owned full-prefix math.fsum, explicit F32 boundaries and BF16 coefficients','fixture':f},indent=2)+'\n'}


def main():
    p=argparse.ArgumentParser();p.add_argument('--write',action='store_true');a=p.parse_args()
    for name,data in artifacts().items():
        path=ROOT/'psionic/fixtures/deepseek'/name
        if a.write:path.write_text(data)
        else:assert path.read_text()==data,f'stale {path}'
    f=fixture();error=max(abs(a-b) for x,y in zip(f['outputs']['compressed'],f['outputs']['expanded']) for a,b in zip(x,y))
    print(f'MLA oracle: both forms, 2 heads, 3-wide latent, 4 tokens; maximum difference {error:.9g}')


if __name__=='__main__':main()
