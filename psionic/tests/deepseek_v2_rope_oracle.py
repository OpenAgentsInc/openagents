#!/usr/bin/env python3
"""Independent fixed original V2-Lite YaRN and adjacent-pair permutation DATA."""
import argparse
import json
import math
from pathlib import Path
import struct
ROOT=Path(__file__).resolve().parents[2]


def f32(x):return struct.unpack('<f',struct.pack('<f',x))[0]


def coefficients(dim,pos):
    low=max(math.floor(dim*math.log(4096/(32*2*math.pi))/(2*math.log(10000))),0)
    high=min(math.ceil(dim*math.log(4096/(2*math.pi))/(2*math.log(10000))),dim-1)
    assert high>low
    frequencies=[]
    for j in range(dim//2):
        ramp=min(max((j-low)/(high-low),0),1)
        extra=1/(10000**(2*j/dim));frequencies.append(extra*(1-ramp)+extra/40*ramp)
    return [f32(math.cos(pos*x)) for x in frequencies]+[f32(math.sin(pos*x)) for x in frequencies]


def artifacts():
    cases=[dict(dim=d,position=p,coefficients=coefficients(d,p)) for d,p in [(2,0),(8,1),(64,4096),(64,163839),(128,163839)]]
    dim,heads,nope,pos=8,2,3,731
    q=[f32(((i*7)%31-15)/8) for i in range(heads*(nope+dim))];k=[f32(((i*3)%11-5)/8) for i in range(dim)];c=coefficients(dim,pos)
    def rotate(x):
        pairs=list(zip(x[::2],x[1::2]));return [f32(a*c[j]-b*c[dim//2+j]) for j,(a,b) in enumerate(pairs)]+[f32(b*c[j]+a*c[dim//2+j]) for j,(a,b) in enumerate(pairs)]
    expected=[]
    for h in range(heads):expected.extend(q[h*(nope+dim):h*(nope+dim)+nope]+rotate(q[h*(nope+dim)+nope:(h+1)*(nope+dim)]))
    rotation=dict(heads=heads,nope=nope,rope=dim,position=pos,query=q,key=k,expected_query=expected,expected_key=rotate(k))
    coax='// Owned original-parameter YaRN oracle; generated by deepseek_v2_rope_oracle.py.\n';header='/* Independent original-parameter YaRN vectors. */\n'
    for i,case in enumerate(cases):
        d,p,v=case['dim'],case['position'],case['coefficients'];name=f'DVR_COEFF{i}'
        coax+=f'{name} :: [{d}]f32.['+','.join(str(x)+'f32' for x in v)+'];\n'
        header+=f'static const float dvr_coeff{i}[] = {{'+','.join(map(str,v))+'};\n'
        coax+=f'''#test "V2 YaRN original width {d} position {p}" {{
    out:[{d+1}]f32;stage:[{d}]f32;out[{d}]=-7;r:=dv_yarn({d},{p},out[..],stage[..],false);
    #assert r.status==DsStatus.ok && r.written=={d} && out[{d}]==-7;
    for i:0..<{d} {{#assert abs(out[i]-{name}[i])<=0.0000002f32;}}
}}
'''
    for key,values in [('QUERY',q),('KEY',k),('EXPECTED_QUERY',expected),('EXPECTED_KEY',rotation['expected_key'])]:
        coax+=f'DVR_{key} :: [{len(values)}]f32.['+','.join(str(x)+'f32' for x in values)+'];\n'
        header+=f'static const float dvr_{key.lower()}[] = {{'+','.join(map(str,values))+'};\n'
    coax+='''#test "V2 rotary permutes adjacent pairs before split-half rotation" {
    q:=DVR_QUERY;k:=DVR_KEY;out:[22]f32;key:[8]f32;work:[30]f32;r:=dv_rotary(2,3,8,q[..],k[..],731,out[..],key[..],work[..],false);
    #assert r.status==DsStatus.ok && r.query_written==22 && r.key_written==8;
    for i:0..<22 {#assert abs(out[i]-DVR_EXPECTED_QUERY[i])<0.0000005f32;}
    for i:0..<8 {#assert abs(key[i]-DVR_EXPECTED_KEY[i])<0.0000005f32;}
}
'''
    scale=(1+0.1*0.707*math.log(40))**2/math.sqrt(192)
    coax+=f'#test "V2 attention scale includes both YaRN mscale factors" {{#assert abs(dv_attention_scale(128,64)-{scale!r})<1e-15;}}\n'
    return {'v2-rope-goldens.coax':coax,'v2-rope-goldens.h':header,'v2-rope-goldens.json':json.dumps({'schema':1,'cases':cases,'rotation':rotation,'attention_scale':scale},indent=2)+'\n'}


def main():
    p=argparse.ArgumentParser();p.add_argument('--write',action='store_true');a=p.parse_args()
    for name,data in artifacts().items():
        path=ROOT/'psionic/fixtures/deepseek'/name
        if a.write:path.write_text(data)
        else:assert path.read_text()==data,f'stale {path}'
    print('V2 rotary oracle: original YaRN at first/long/final positions and adjacent-pair permutation')


if __name__=='__main__':main()
