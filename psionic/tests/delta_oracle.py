#!/usr/bin/env python3
"""Independent scalar, sequential oracle for the bounded causal DeltaNet cell."""
import math
import struct
import sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
def f(x):return struct.unpack('<f',struct.pack('<f',x))[0]
def bits(x):return struct.unpack('<I',struct.pack('<f',x))[0]
def reference():
    kh,vh,kd,vd=2,4,2,2;c=2*kh*kd+vh*vd;n=vh*kd*vd
    w=[f((((i*7+1)%17)-8)/16) for i in range(c*4)]
    a=[f((i-2)/3) for i in range(vh)];b=[f((2-i)/4) for i in range(vh)]
    loga=[f((i-2)/8) for i in range(vh)];dt=[f((i-1)/6) for i in range(vh)]
    gamma=[f(1+i/4) for i in range(vd)];history=[f(((i*3)%11-5)/8) for i in range(c*3)]
    state=[f(((i*5)%13-6)/20) for i in range(n)]
    initial_history=history[:];initial_state=state[:];samples=[]
    for step in range(3):
        x=[f(((i*11+step*5)%23-11)/10) for i in range(c)]
        z=[f(((i*7+step)%13-6)/5) for i in range(vh*vd)]
        packed=x+w+a+b+loga+dt+z+gamma
        conv=[]
        for ch in range(c):
            taps=history[ch*3:ch*3+3]+[x[ch]]
            y=sum(float(taps[t])*w[ch*4+t] for t in range(4))
            conv.append(f(y/(1+math.exp(-y))))
            history[ch*3:ch*3+3]=taps[1:]
        output=[];new_state=state[:]
        for head in range(vh):
            key_head=head//(vh//kh);q=conv[key_head*kd:(key_head+1)*kd]
            key=conv[kh*kd+key_head*kd:kh*kd+(key_head+1)*kd]
            val=conv[2*kh*kd+head*vd:2*kh*kd+(head+1)*vd]
            qden=math.sqrt(sum(x*x for x in q)+1e-6)*math.sqrt(kd)
            kden=math.sqrt(sum(x*x for x in key)+1e-6)
            decay=math.exp(-math.exp(loga[head])*math.log1p(math.exp(a[head]+dt[head])))
            beta=1/(1+math.exp(-b[head]));raw=[]
            for col in range(vd):
                memory=sum(state[(head*kd+row)*vd+col]*decay*key[row]/kden for row in range(kd))
                diff=(val[col]-memory)*beta
                for row in range(kd):
                    idx=(head*kd+row)*vd+col
                    new_state[idx]=f(state[idx]*decay+key[row]/kden*diff)
                raw.append(f(sum(q[row]/qden*new_state[(head*kd+row)*vd+col] for row in range(kd))))
            den=math.sqrt(sum(v*v for v in raw)/vd+0.125)
            output.extend(f(raw[i]/den*gamma[i]*(z[head*vd+i]/(1+math.exp(-z[head*vd+i])))) for i in range(vd))
        state=new_state;samples.append((packed,output,state[:],history[:]))
    return (kh,vh,kd,vd,c,n,initial_history,initial_state,samples)
def array(name,values):return f'{name}:=[{len(values)}]f32.['+','.join(f'f32_from_bits(0x{bits(x):08x})' for x in values)+'];'
