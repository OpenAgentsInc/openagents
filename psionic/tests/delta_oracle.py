    lines=['// Generated by psionic/tests/delta_oracle.py.','#test "independent Qwen-style convolution and delta sequence" {',f'    s:=PdShape.{{key_heads={kh},value_heads={vh},key_dim={kd},value_dim={vd},epsilon=0.125f32}};', '    '+array('history',hist),'    '+array('state',state),f'    out:[{v}]f32;work:[{work}]f32;']
