def header():
    kh,vh,kd,vd,c,n,hist,state,samples=reference();lines=[]
    def emit(name,values):
        lines.append(f'static const float {name}[] = {{'+','.join(float(x).hex()+'f' for x in values)+'};')
    emit('initial_history',hist);emit('initial_state',state)
    for i,(inp,out,st,hi) in enumerate(samples):
        for name,values in [('input',inp),('expected',out),('expected_state',st),('expected_history',hi)]:emit(name+str(i),values)
