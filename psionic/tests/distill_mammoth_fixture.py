"""Chapter 141: turn the recorded CUDA corpus runs into a Coax fixture.

Reads psionic/fixtures/distill-mammoth/corpus.tsv and the two recorded
harness logs (elephant-cuda.log, mammoth-cuda.log), and writes
psionic/fixtures/distill-mammoth/records.coax: every request's family, gold
label, both models' yes probability, slot mass and device time, the model
identities, and an independent oracle for the held-out comparison of the two
recorded models (agreement, mean KL, accuracy, Brier score and top-label
calibration error over 15 bins), computed here in Python from the logs.
Tooling only; nothing here runs at run time.
Usage: python3 -I psionic/tests/distill_mammoth_fixture.py [--check]"""
import json
import math
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
DIR = ROOT / "psionic/fixtures/distill-mammoth"
HELD_FIRST = 16  # families 16 to 23 are held out (frozen with the corpus)


def corpus():
    rows = []
    for line in (DIR / "corpus.tsv").read_text().splitlines():
        if not line or line.startswith("#"):
            continue
        item, family, gold, message, question = line.split("\t")
        rows.append((int(item), int(family), int(gold)))
    return rows


def log(name):
    out = {}
    for line in (DIR / name).read_text().splitlines():
        m = re.match(r"distill item=(\d+) tokens=(\d+) ms=([\d.]+) p_yes=([\d.]+) p_no=([\d.]+) slot_mass=([\d.]+)$", line)
        if m:
            out[int(m.group(1))] = (int(m.group(2)), float(m.group(3)), float(m.group(4)), float(m.group(6)))
    return out


def pin(name):
    return json.loads((ROOT / f"psionic/fixtures/models/pins/{name}.json").read_text())["inventory_sha256"]


def ece(ps, golds):
    conf = [0.0] * 15
    hits = [0.0] * 15
    for p, g in zip(ps, golds):
        best = 0 if p >= 1 - p else 1
        c = p if best == 0 else 1 - p
        b = 0
        while c > (b + 1) / 15:
            b += 1
        conf[b] += c
        hits[b] += 1 if (best == 0) == (g == 1) else 0
    return sum(abs(c - h) / len(ps) for c, h in zip(conf, hits))


def oracle(rows, e, m):
    held = [r for r in rows if r[1] >= HELD_FIRST]
    out = {}
    for name, rec in (("ELEPHANT", e), ("MAMMOTH", m)):
        ps = [rec[r[0]][2] for r in held]
        golds = [r[2] for r in held]
        out[name + "_RIGHT"] = sum(1 for p, g in zip(ps, golds) if (p >= 1 - p) == (g == 1))
        out[name + "_BRIER"] = sum(2 * (p - g) ** 2 for p, g in zip(ps, golds)) / len(ps)
        out[name + "_ECE"] = ece(ps, golds)
    pe = [e[r[0]][2] for r in held]
    pm = [m[r[0]][2] for r in held]
    out["AGREE"] = sum(1 for a, b in zip(pe, pm) if (a >= 1 - a) == (b >= 1 - b))
    out["KL"] = sum(t * math.log(t / s) + (1 - t) * math.log((1 - t) / (1 - s)) for t, s in zip(pm, pe)) / len(pm)
    return out


def render():
    rows = corpus()
    e, m = log("elephant-cuda.log"), log("mammoth-cuda.log")
    if sorted(e) != [r[0] for r in rows] or sorted(m) != [r[0] for r in rows]:
        sys.exit("a log does not hold every corpus item")
    n = len(rows)
    lines = ["// Generated by psionic/tests/distill_mammoth_fixture.py from corpus.tsv,",
             "// elephant-cuda.log and mammoth-cuda.log. Do not edit.",
             f"DM_N :: {n};"]

    def arr(name, typ, vals, fmt):
        lines.append(f"{name} :: [{n}]{typ}.[" + ",".join(fmt(v) for v in vals) + "];")

    arr("DM_FAMILY", "int", [r[1] for r in rows], str)
    arr("DM_GOLD", "int", [r[2] for r in rows], str)
    for tag, rec in (("ELEPHANT", e), ("MAMMOTH", m)):
        arr(f"DM_{tag}_P", "f64", [rec[r[0]][2] for r in rows], lambda v: f"{v:.9f}")
        arr(f"DM_{tag}_MASS", "f64", [rec[r[0]][3] for r in rows], lambda v: f"{v:.9f}")
        arr(f"DM_{tag}_MS", "f64", [rec[r[0]][1] for r in rows], lambda v: f"{v:.1f}")
    for tag, name in (("ELEPHANT", "elephant-1"), ("MAMMOTH", "mammoth-1")):
        h = pin(name)
        lines.append(f"DM_{tag}_ID :: [32]u8.[" + ",".join(f"0x{h[i:i + 2]}" for i in range(0, 64, 2)) + "];")
    for k, v in oracle(rows, e, m).items():
        lines.append(f"DM_ORACLE_{k} :: {v!r};" if isinstance(v, int) else f"DM_ORACLE_{k} :: {v:.17g};")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    text = render()
    path = DIR / "records.coax"
    if sys.argv[1:] == ["--check"]:
        sys.exit(0 if path.read_text() == text else "records.coax is stale")
    path.write_text(text)
