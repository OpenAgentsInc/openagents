"""Chapter 223's teacher stand-in and its oracle, written from the chapter's
description without reading psionic/lib/distill.coax.

--teacher prints psionic/fixtures/distill/teacher.coax: the stand-in
teacher's probabilities for 512 requests at temperature 1, its FNV-1a
identity, and one outcome label per request drawn from those probabilities.

Without --teacher it prints psionic/fixtures/distill/oracle.coax: the pooled
features of every request (through chapter 222's own Python oracle), the
split, the head trained by the chapter's distillation under chapter 118's
trainer rules (AdamW, shuffled batches, evaluation and early stopping), the
fitted temperature and the test counts.

Usage:
  python3 -I psionic/tests/distill_oracle.py --teacher > psionic/fixtures/distill/teacher.coax
  python3 -I psionic/tests/distill_oracle.py > psionic/fixtures/distill/oracle.coax"""
import math
import os
import struct
import sys

M = (1 << 64) - 1


def splitmix(seed, counter):
    z = (seed + 0x9E3779B97F4A7C15 * (counter + 1)) & M
    z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & M
    z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & M
    return z ^ (z >> 31)


FAMILIES, PER, TOKENS, TEMPLATE = 64, 8, 16, 8
N = FAMILIES * PER


def request(r):
    f, j = divmod(r, PER)
    return [splitmix(2233, f * TEMPLATE + i) % 15 for i in range(TEMPLATE)] + \
        [splitmix(2234, r * (TOKENS - TEMPLATE) + i) % 64 for i in range(TOKENS - TEMPLATE)]


def softmax(z):
    top = max(z)
    e = [math.exp(v - top) for v in z]
    s = sum(e)
    return [v / s for v in e]


def fnv(values):
    h = 0xCBF29CE484222325
    for v in values:
        h = ((h ^ struct.unpack("<Q", struct.pack("<d", v))[0]) * 0x100000001B3) & M
    return h


# The stand-in teacher: logit c is the sum over the request's tokens of a
# fixed value in [-1, 1) for (c, token ID); its labels are drawn from its own
# probabilities, so it is calibrated by construction.
TABLE = [[(splitmix(2236, c * 64 + i) >> 11) / 2.0**52 - 1 for i in range(64)] for c in range(3)]
TEACHER = [softmax([sum(TABLE[c][t] for t in request(r)) for c in range(3)]) for r in range(N)]


def label(r):
    u = (splitmix(2235, r) >> 11) / 2.0**53
    p = TEACHER[r]
    return 0 if u < p[0] else 1 if u < p[0] + p[1] else 2


LABELS = [label(r) for r in range(N)]

if sys.argv[1:] == ["--teacher"]:
    print("// Generated by psionic/tests/distill_oracle.py --teacher; do not edit.")
    print("// The recorded teacher stand-in: probabilities at temperature 1 for 512 requests, three options each.")
    print(f"DS_TEACHER_ID :: cast(u64)0x{fnv([p for row in TEACHER for p in row]):016x};")
    print("DS_TEACHER_P :: [1536]f64.[" + ",".join(repr(p) for row in TEACHER for p in row) + "];")
    print("DS_LABELS :: [512]int.[" + ",".join(str(y) for y in LABELS) + "];")
    sys.exit(0)

# Chapter 222's Python oracle supplies the encoder; only its definitions run.
src = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "fast_encoder_oracle.py")).read()
fe = {}
exec(src.split("\nlogits = []")[0], fe)


def pool(ids):
    # The 222 oracle's forward pass, stopped at the pooled vector: read it
    # through the heads by making the first head rows unit vectors.
    saved = fe["W"][:]
    out = []
    for first in (0, 9):
        for o in range(9):
            for c in range(16):
                fe["W"][fe["HEAD_AT"] + o * 16 + c] = 1.0 if c == first + o else 0.0
        out += fe["forward"](ids)
    fe["W"][:] = saved
    return out[:16]


FEAT = [pool(request(r)) for r in range(N)]

# The split: families in pairs share a task, so a pair is one group; family
# f's time is f. Groups ending at 39 or earlier train, at 51 or earlier are
# development, the rest test. Templates are checked for near duplicates.


def bigrams(f):
    t = request(f * PER)[:TEMPLATE]
    prev, s = 15, set()
    for x in t:
        s.add((prev, x))
        prev = x
    return s


for a in range(FAMILIES):
    for b in range(a + 1, FAMILIES):
        x, y = bigrams(a), bigrams(b)
        assert 2 * len(x & y) < len(x | y), (a, b)
SPLIT = [0 if f <= 39 else 1 if f <= 51 else 2 for f in range(FAMILIES)]
TRAIN = [r for r in range(N) if SPLIT[r // PER] == 0]
DEV = [r for r in range(N) if SPLIT[r // PER] == 1]
TEST = [r for r in range(N) if SPLIT[r // PER] == 2]

T, HEAD_T = 2.0, 0.5


def logits(w, r):
    return [sum(w[c * 16 + k] * FEAT[r][k] for k in range(16)) for c in range(3)]


def log_softmax(z):
    top = max(z)
    s = math.log(sum(math.exp(v - top) for v in z))
    return [v - top - s for v in z]


def loss_grad(w, rows):
    # T^2 KL(p_T || q_T), p_T the teacher at temperature T, q_T the student
    # with logits s/(HEAD_T*T); gradient (T/HEAD_T)(q_T - p_T) times the features.
    g = [0.0] * 48
    total = 0.0
    for r in rows:
        lp = softmax([math.log(p) / T for p in TEACHER[r]])
        lq = log_softmax([s / (HEAD_T * T) for s in logits(w, r)])
        total += T * T * sum(lp[c] * (math.log(lp[c]) - lq[c]) for c in range(3))
        for c in range(3):
            d = (T / HEAD_T) * (math.exp(lq[c]) - lp[c])
            for k in range(16):
                g[c * 16 + k] += d * FEAT[r][k]
    return total / len(rows), [x / len(rows) for x in g]


def shuffle(order, seed, counter):
    for i in range(len(order) - 1, 0, -1):
        j = splitmix(seed, counter) % (i + 1)
        counter += 1
        order[i], order[j] = order[j], order[i]
    return counter


# Chapter 118's trainer, rows mode: AdamW rate 0.05, betas 0.9 and 0.999,
# eps 1e-8, no decay or clipping; batches of 32 in an order reshuffled each
# epoch (seed 223); 40 epochs; the development loss each epoch, from step 0,
# and a stop after 3 evaluations without improvement.
RATE, B1, B2, EPS, BATCH, EPOCHS, SEED, PATIENCE = 0.05, 0.9, 0.999, 1e-8, 32, 40, 223, 3
n = len(TRAIN)
every = -(-n // BATCH)
order = list(range(n))
shuffle(order, SEED, 0)
w, m, v = [0.0] * 48, [0.0] * 48, [0.0] * 48
step, epoch, at, evals, best, stale, stopped = 0, 0, 0, 0, 0.0, 0, False
while True:
    if step % every == 0:
        dl = loss_grad(w, DEV)[0]
        if evals == 0 or dl < best:
            best, stale = dl, 0
        else:
            stale += 1
        evals += 1
        if stale >= PATIENCE:
            stopped = True
            break
    if step >= EPOCHS * every:
        break
    rows = [TRAIN[order[i]] for i in range(at, min(at + BATCH, n))]
    _, g = loss_grad(w, rows)
    t = step + 1
    for i in range(48):
        m[i] = B1 * m[i] + (1 - B1) * g[i]
        v[i] = B2 * v[i] + (1 - B2) * g[i] * g[i]
        w[i] = w[i] - (RATE / (1 - B1 ** t)) * (m[i] / (math.sqrt(v[i]) / math.sqrt(1 - B2 ** t) + EPS))
    step += 1
    at += BATCH
    if at >= n:
        at, epoch = 0, epoch + 1
        shuffle(order, SEED, epoch * (n - 1))


def nll(tau, rows):
    return sum(-log_softmax([s / (HEAD_T * tau) for s in logits(w, r)])[LABELS[r]] for r in rows) / len(rows)


taus = [k / 8 for k in range(2, 33)]
scores = [nll(tau, DEV) for tau in taus]
tau = taus[scores.index(min(scores))]


def first_max(p):
    return max(range(len(p)), key=lambda c: (p[c], -c))


teacher_dev = sum(first_max(TEACHER[r]) == LABELS[r] for r in DEV)
cut = teacher_dev / len(DEV) - 0.1


def quality(dists):
    # Top-label calibration error over 15 equal bins (b/15, (b+1)/15], and the
    # multi-class Brier score, against the outcome labels.
    conf, hits = [0.0] * 15, [0] * 15
    brier = 0.0
    for r, p in zip(TEST, dists):
        b = first_max(p)
        brier += sum((v - (1.0 if c == LABELS[r] else 0.0)) ** 2 for c, v in enumerate(p))
        k = next(k for k in range(15) if p[b] <= (k + 1) / 15)
        conf[k] += p[b]
        hits[k] += b == LABELS[r]
    return sum(abs(conf[k] - hits[k]) for k in range(15)) / len(TEST), brier / len(TEST)


agree = answered = answered_agree = answered_right = teacher_right_answered = teacher_right = student_right = 0
student = []
for r in TEST:
    q = softmax([s / (HEAD_T * tau) for s in logits(w, r)])
    student.append(q)
    s, e = first_max(q), first_max(TEACHER[r])
    agree += s == e
    teacher_right += e == LABELS[r]
    student_right += s == LABELS[r]
    if q[s] >= cut:
        answered += 1
        answered_agree += s == e
        answered_right += s == LABELS[r]
        teacher_right_answered += e == LABELS[r]

print("// Generated by psionic/tests/distill_oracle.py; do not edit.")
print("DS_ORACLE_FEATS :: [8192]f64.[" + ",".join(repr(x) for row in FEAT for x in row) + "];")
print(f"DS_ORACLE_SPLIT :: [3]int.[{len(TRAIN)},{len(DEV)},{len(TEST)}];")
print("DS_ORACLE_W :: [48]f64.[" + ",".join(repr(x) for x in w) + "];")
print(f"DS_ORACLE_RUN :: [3]int.[{step},{evals},{int(stopped)}];")
print(f"DS_ORACLE_BEST :: {best!r};")
print(f"DS_ORACLE_TAU :: {tau!r};")
print(f"DS_ORACLE_TEST :: [8]int.[{teacher_dev},{agree},{answered},{answered_agree},{answered_right},{teacher_right_answered},{teacher_right},{student_right}];")
print("DS_ORACLE_QUALITY :: [4]f64.[" + ",".join(repr(x) for x in quality(student) + quality([TEACHER[r] for r in TEST])) + "];")
