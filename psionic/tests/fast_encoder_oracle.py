"""Chapter 222's oracle: the fe-tiny-v1 encoder written again in plain Python
binary64, from the chapter's description, without reading the Coax source.
Prints psionic/fixtures/fast-encoder/oracle.coax: two weights, the model's
FNV-1a identity and the reference logits for 1, 5 and 70 token IDs.
Usage: python3 -I psionic/tests/fast_encoder_oracle.py > psionic/fixtures/fast-encoder/oracle.coax"""
import math
import struct

M = (1 << 64) - 1


def splitmix(seed, counter):
    z = (seed + 0x9E3779B97F4A7C15 * (counter + 1)) & M
    z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & M
    z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & M
    return z ^ (z >> 31)


D, HD, LAYERS, FF, WINDOW, VOCAB = 16, 8, 3, 32, 64, 64
LAYER_W = 3 * D * D + D * D + 2 * FF * D + D * FF  # 2560
HEAD_AT = VOCAB * D + LAYERS * LAYER_W               # 8704


def scale(i):
    if i < VOCAB * D or i >= HEAD_AT:
        return 1.0   # embedding rows and heads
    k = (i - VOCAB * D) % LAYER_W
    if k < 768:
        return 0.5   # q, k, v
    if k < 1024:
        return 0.25  # output
    if k < 2048:
        return 0.5   # up
    return 0.25      # down


W = [scale(i) * ((splitmix(222, i) >> 11) / 2.0**52 - 1.0) for i in range(HEAD_AT + 9 * D)]


def fnv(ws):
    h = 0xCBF29CE484222325
    for v in ws:
        h = ((h ^ struct.unpack("<Q", struct.pack("<d", v))[0]) * 0x100000001B3) & M
    return h


def norm(x):
    mean = sum(x) / D
    var = sum((v - mean) ** 2 for v in x) / D
    return [(v - mean) / math.sqrt(var + 1e-5) for v in x]


def matvec(at, rows, width, x):
    return [sum(W[at + r * width + c] * x[c] for c in range(width)) for r in range(rows)]


def gelu(z):
    return 0.5 * z * (1 + math.tanh(math.sqrt(2 / math.pi) * (z + 0.044715 * z ** 3)))


def forward(ids):
    t = len(ids)
    x = [W[i * D:(i + 1) * D] for i in ids]
    for layer in range(LAYERS):
        at = VOCAB * D + layer * LAYER_W
        qkv = [matvec(at, 3 * D, D, norm(row)) for row in x]
        att = []
        for i in range(t):
            keys = range(t) if layer % 3 == 0 else [j for j in range(t) if abs(i - j) <= WINDOW]
            out = []
            for h in range(2):
                q = qkv[i][h * HD:(h + 1) * HD]
                s = {j: sum(a * b for a, b in zip(q, qkv[j][D + h * HD:D + (h + 1) * HD])) / math.sqrt(HD) for j in keys}
                top = max(s.values())
                e = {j: math.exp(v - top) for j, v in s.items()}
                total = sum(e.values())
                out += [sum(e[j] * qkv[j][2 * D + h * HD + c] for j in keys) / total for c in range(HD)]
            att.append(out)
        x = [[a + b for a, b in zip(row, matvec(at + 768, D, D, o))] for row, o in zip(x, att)]
        new = []
        for row in x:
            u = matvec(at + 1024, 2 * FF, D, norm(row))
            g = [gelu(u[c]) * u[FF + c] for c in range(FF)]
            new.append([a + b for a, b in zip(row, matvec(at + 2048, D, FF, g))])
        x = new
    pool = [0.0] * D
    for row in x:
        pool = [p + v for p, v in zip(pool, norm(row))]
    return matvec(HEAD_AT, 9, D, [p / t for p in pool])


logits = []
for case, n in enumerate([1, 5, 70]):
    logits += forward([splitmix(2220 + case, i) % 64 for i in range(n)])
print("// Generated by psionic/tests/fast_encoder_oracle.py; do not edit.")
print(f"FE_ORACLE_W0 :: {W[0]!r};")
print(f"FE_ORACLE_W8847 :: {W[-1]!r};")
print(f"FE_ORACLE_ID :: cast(u64)0x{fnv(W):016x};")
print("FE_ORACLE_LOGITS :: [27]f64.[" + ",".join(repr(v) for v in logits) + "];")
