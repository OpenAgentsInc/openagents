#!/usr/bin/env python3
# Firm reason: 2 (independent oracle: recomputes our answer outside Coax, so it must not share our implementation)
"""Independent FP8 E4M3 fixtures from exact rational arithmetic.

Each code is evaluated from the OCP 8-bit floating-point definition with
Python's Fraction type, then packed as binary64. Rounding vectors use the
same exact rationals and choose the nearest code, ties to the even code.
This owned tool does not import or execute any upstream repository or Coax.
"""
from fractions import Fraction
from pathlib import Path
import struct
import sys

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / "psionic/fixtures/fp8-vectors.coax"
NAN = 0x7ff8000000000000


def value(code):
    sign = -1 if code & 0x80 else 1
    exponent = (code >> 3) & 15
    mantissa = code & 7
    if exponent == 15 and mantissa == 7:
        return None
    if exponent == 0:
        magnitude = Fraction(mantissa, 8) * Fraction(1, 2 ** 6)
    else:
        magnitude = (1 + Fraction(mantissa, 8)) * Fraction(2) ** (exponent - 7)
    return sign * magnitude


def bits(x):
    return struct.unpack("<Q", struct.pack("<d", float(x)))[0]


def unit_bits():
    out = []
    for code in range(256):
        v = value(code)
        if v is None:
            out.append(NAN)
        elif v == 0 and code & 0x80:
            out.append(0x8000000000000000)
        else:
            assert Fraction(float(v)) == v
            out.append(bits(v))
    return out


def nearest(x):
    """Nearest non-negative code for 0 <= x <= 448, ties to even code."""
    best = None
    for code in range(127):
        d = abs(value(code) - x)
        if best is None or d < best[0] or (d == best[0] and code % 2 == 0):
            best = (d, code)
    return best[1]


def rounding_inputs():
    xs = set()
    for code in range(126):
        a, b = value(code), value(code + 1)
        mid = (a + b) / 2
        xs.update([a, mid])
        step = (b - a) / 64
        xs.update([mid - step, mid + step])
    xs.add(value(126))
    xs = sorted(xs)
    for x in xs:
        assert Fraction(float(x)) == x
    return xs


def round_vectors():
    xs = rounding_inputs()
    return [bits(x) for x in xs], [nearest(x) for x in xs]


def checks(units):
    assert units[0x00] == 0 and units[0x80] == 0x8000000000000000
    assert struct.unpack("<d", struct.pack("<Q", units[0x7e]))[0] == 448.0
    assert struct.unpack("<d", struct.pack("<Q", units[0x01]))[0] == 2.0 ** -9
    assert struct.unpack("<d", struct.pack("<Q", units[0x38]))[0] == 1.0
    assert units[0x7f] == NAN and units[0xff] == NAN
    assert sum(1 for u in units if u == NAN) == 2


def fixture(units, inputs, codes):
    lines = ["// Generated by psionic/tests/fp8_oracle.py; independent exact rationals.",
             "// NaN codes 0x7f and 0xff carry the quiet-NaN marker 0x7ff8000000000000.",
             "FP8_E4M3_UNIT_BITS :: [256]u64.["]
    for start in range(0, 256, 8):
        lines.append("    " + ",".join(f"0x{x:016x}" for x in units[start:start + 8]) + ",")
    lines.append("];")
    lines.append(f"FP8_ROUND_INPUT :: [{len(inputs)}]u64.[")
    for start in range(0, len(inputs), 8):
        lines.append("    " + ",".join(f"0x{x:016x}" for x in inputs[start:start + 8]) + ",")
    lines.append("];")
    lines.append(f"FP8_ROUND_CODE :: [{len(codes)}]u8.[")
    for start in range(0, len(codes), 16):
        lines.append("    " + ",".join(str(c) for c in codes[start:start + 16]) + ",")
    lines.append("];")
    return "\n".join(lines + [""])


def main():
    units = unit_bits()
    checks(units)
    inputs, codes = round_vectors()
    expected = fixture(units, inputs, codes)
    if sys.argv[1:] == ["--write"]:
        TARGET.write_text(expected)
        return
    assert not sys.argv[1:], "usage: fp8_oracle.py [--write]"
    assert TARGET.read_text() == expected, "FP8 fixture drifted"
    print(f"FP8 oracle: 256 E4M3 codes and {len(inputs)} rounding inputs match the fixture")


if __name__ == "__main__":
    main()
