#!/usr/bin/env python3
"""Owned scalar references: full-prefix attention (no ring), direct-power YaRN,
and Decimal(100) activation. Never imports upstream or Coax-generated output.
"""
from decimal import Decimal, localcontext
from pathlib import Path
import math
import struct
import sys

ROOT = Path(__file__).resolve().parents[2]

def f32(x):
    return struct.unpack('<f', struct.pack('<f', x))[0]

def bits(x):
    return struct.unpack('<I', struct.pack('<f', x))[0]

def yarn(p):
    low = 32*math.log(4096/(32*2*math.pi))/math.log(150000)
    high = 32*math.log(4096/(2*math.pi))/math.log(150000)
    c = 1+0.1*math.log(32)
    result = []
    for i in range(32):
        ramp = min(1, max(0, (i-low)/(high-low)))
        inverse = (1-ramp)/150000**(2*i/64) + ramp/(32*150000**(2*i/64))
        angle = p*inverse
        result.extend([f32(math.cos(angle)*c), f32(math.sin(angle)*c)])
    return result

def rotate(x, p):
    c = yarn(p)
    result = []
    for offset in range(0, len(x), 64):
        a, b = x[offset:offset+32], x[offset+32:offset+64]
        result += [f32(a[i]*c[2*i]-b[i]*c[2*i+1]) for i in range(32)]
        result += [f32(b[i]*c[2*i]+a[i]*c[2*i+1]) for i in range(32)]
    return result

def activations():
    data = [(0, 0), (1, -1), (-8, 2), (8, 0), (7, 8), (-1, -8),
            (-1000, 7), (1000, -1000), (-7, 7), (7, -7),
            (0.125, 0.25), (-0.25, 0.5), (3.4028234663852886e38, 0),
            (-3.4028234663852886e38, 0), (7, 7), (-7, -7)]
    with localcontext() as ctx:
        ctx.prec = 100
        for raw, linear in data:
            raw, linear = f32(raw), f32(linear)
            gate = Decimal.from_float(min(raw, 7))
            lane = Decimal.from_float(max(-7, min(7, linear)))
            # Decimal's finite exponent range is deliberately avoided at -f32max.
            result = Decimal(0) if gate < -1000 else gate/(1+(-Decimal('1.702')*gate).exp())*(lane+1)
            yield raw, linear, f32(float(result)), int(raw > 7)+int(linear > 7 or linear < -7)

def attention_cases():
    seed = 314159
    def vector(n):
        nonlocal seed
        result = []
        for _ in range(n):
            seed = (1664525*seed+1013904223) & 0xffffffff
            result.append(((seed >> 16) % 33-16)/16)
        return result
    for heads, kv, window, capacity, n in [(1,1,0,4,4), (2,1,2,2,5), (4,2,3,3,5), (2,2,0,3,3)]:
        qs, ks, vs = [], [], []
        sinks = [-2, 0.5, 3, -0.25][:heads]
        expected = []
        for p in range(n):
            q, k, v = vector(heads*64), vector(kv*64), vector(kv*64)
            qs += q;ks += k;vs += v
            rq = rotate(q, p)
            # Dense full-prefix reference: materialize every historical key,
            # then select causal/window visibility. No circular indexing.
            keys = [rotate(ks[t*kv*64:(t+1)*kv*64], t) for t in range(p+1)]
            values = [vs[t*kv*64:(t+1)*kv*64] for t in range(p+1)]
            visible = list(range(max(0,p-window+1) if window else 0, p+1))
            for h in range(heads):
                kh = h//(heads//kv)
                scores = [math.fsum(rq[h*64+d]*keys[t][kh*64+d] for d in range(64))/8 for t in visible]
                maximum = max(scores+[sinks[h]])
                weights = [math.exp(x-maximum) for x in scores]
                total = math.fsum(weights+[math.exp(sinks[h]-maximum)])
                expected += [f32(math.fsum(w*values[t][kh*64+d] for w,t in zip(weights,visible))/total) for d in range(64)]
        yield heads,kv,window,capacity,n,qs,ks,vs,sinks,expected

def coax_array(name, xs):
    return f'    {name}:=[{len(xs)}]f32.['+','.join(f'f32_from_bits(0x{bits(x):08x})' for x in xs)+'];'

def math_fixture():
    lines=['// Generated by tests/gptoss_oracle.py: direct-power YaRN and Decimal activation.']
    for p in [0,1,4095,4096,65535,131071]:
        lines += [f'#test "independent YaRN at position {p}" {{',coax_array('expected',yarn(p)),
                  '    out:[64]f32;', f'    r:=go_yarn({p},1,out[..]);#assert r.status==GoStatus.ok && r.written==64;',
                  '    for i:0..<64 {#assert abs(out[i]-expected[i])<0.000002f32;}', '}']
    x=[(i%13-6)/8 for i in range(128)]
    lines += ['#test "independent split-half rotary across two heads" {',coax_array('x',x),coax_array('c',yarn(4096)),
              coax_array('expected',rotate(x,4096)), '    out:[128]f32;work:[128]f32;',
              '    r:=go_rotate(2,x[..],c[..],out[..],work[..],false);#assert r.status==GoStatus.ok;',
              '    for i:0..<128 {#assert abs(out[i]-expected[i])<0.000002f32;}', '}']
    data=list(activations())
    lines += ['#test "independent Decimal activation and clamp diagnostics" {',coax_array('x',[x for a,b,_,_ in data for x in (a,b)]),
              coax_array('expected',[c for _,_,c,_ in data]), f'    out:[{len(data)}]f32;',
              f'    r:=go_swiglu(x[..],out[..],false);#assert r.status==GoStatus.ok && r.written=={len(data)} && r.clamped=={sum(d for *_,d in data)};',
              '    for i:0..<out.count {#assert abs(out[i]-expected[i])<0.000002f32*(1+abs(expected[i]));}', '}']
    return '\n'.join(lines)+'\n'

def attention_fixture(data):
    lines=['// Generated by tests/gptoss_oracle.py: independent dense full-prefix attention.']
    for idx,(h,k,w,c,n,q,key,v,s,expected) in enumerate(data):
        lines += [f'#test "independent full-prefix versus cached sink attention {idx}" {{',
                  coax_array('q',q),coax_array('k',key),coax_array('v',v),coax_array('sinks',s),coax_array('expected',expected),
                  f'    cache:[{c*2*k*64}]f32;out:[{h*64}]f32;work:[{(3*h+k)*64}]f32;',
                  f'    shape:=GaShape.{{heads={h},kv_heads={k},window={w},capacity={c}}};',f'    for p:0..<{n} {{',
                  f'        r:=ga_step(shape,p,q[p*{h*64}..<(p+1)*{h*64}],k[p*{k*64}..<(p+1)*{k*64}],v[p*{k*64}..<(p+1)*{k*64}],sinks[..],cache[..],out[..],work[..],false);',
                  f'        #assert r.status==GoStatus.ok && r.written=={h*64} && r.next==p+1;',
                  f'        for i:0..<{h*64} {{#assert abs(out[i]-expected[p*{h*64}+i])<0.00002f32*(1+abs(expected[p*{h*64}+i]));}}', '    }', '}']
    return '\n'.join(lines)+'\n'

def header(data):
    print('static const struct {int position; float coefficients[64];} yarn_cases[] = {')
    for p in [0,1,4095,4096,65535,131071]:
        print('{'+str(p)+',{'+','.join(float(x).hex()+'f' for x in yarn(p))+'}},')
    print('};\nstatic const struct {float gate,linear,expected; int clamped;} activation_cases[] = {')
    for a,b,c,d in activations():
        print('{'+','.join(float(x).hex()+'f' for x in (a,b,c))+','+str(d)+'},')
    print('};\nstatic const struct {int h,k,w,c,n;float q[1280],key[640],v[640],sinks[4],expected[1280];} attention_cases[] = {')
    for h,k,w,c,n,*arrays in data:
        print('{'+','.join(map(str,(h,k,w,c,n)))+','+','.join('{'+','.join(float(x).hex()+'f' for x in a)+'}' for a in arrays)+'},')
    print('};')

def main():
    data=list(attention_cases())
    for name,content in [('gptoss-math-vectors.coax',math_fixture()),('gptoss-attention-vectors.coax',attention_fixture(data))]:
        target=ROOT/'psionic/fixtures'/name
        if sys.argv[1:]==['--write']:
            target.write_text(content)
        else:
            assert target.read_text()==content, f'{name}: independent fixture drift'
    if sys.argv[1:]==['--header']:
        header(data)
    elif sys.argv[1:]!=['--write']:
        assert not sys.argv[1:], 'usage: gptoss_oracle.py [--write | --header]'
        print('gpt-oss oracle: 6 rotary positions, 16 Decimal activation pairs, 4 dense-prefix attention sequences')

if __name__=='__main__':
    main()
