"""Writes psionic/fixtures/granite/unicode.coax: the code point classes of
GPT-2's split expression, from this Python's unicodedata. Class 1 is
\\p{L} (Lu Ll Lt Lm Lo), 2 is \\p{N} (Nd Nl No), 4 is \\s (White_Space)."""
import sys,unicodedata
SPACE={*range(9,14),0x20,0x85,0xa0,0x1680,*range(0x2000,0x200b),0x2028,0x2029,0x202f,0x205f,0x3000}
def cls(cp):
    if cp in SPACE:return 4
    c=unicodedata.category(chr(cp))
    return 1 if c[0]=='L' else 2 if c[0]=='N' else 0
runs=[];start=0;cur=cls(0)
for cp in range(1,0x110000):
    c=cls(cp)
    if c!=cur:
        if cur:runs.append((start,cp-1,cur))
        start=cp;cur=c
if cur:runs.append((start,0x10ffff,cur))
flat=[x for r in runs for x in r]
print(f'// Generated by psionic/tests/granite_unicode.py from Python {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}.')
print('// Runs of first, last, class: 1 letter (L*), 2 number (N*), 4 White_Space.')
print(f'GR_UC_RUNS :: {len(runs)};')
print(f'GR_UC :: [{len(flat)}]int.['+','.join(map(str,flat))+'];')
