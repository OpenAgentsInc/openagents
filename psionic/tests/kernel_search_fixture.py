"""Turn chapter 247's evaluator ledger into Coax data for the book example.

Reads psionic/kernels/norm/ledger/*.log (raw evaluator output, kept as
recorded) and writes psionic/fixtures/kernel-search-l4.coax: one row per
evaluation and one per knob, with each knob's case results and its timing
trials on the L4. No decision is made here; the example decides in Coax.
    python3 -I psionic/tests/kernel_search_fixture.py [--check]
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
LEDGER = ROOT / "psionic/kernels/norm/ledger"
OUT = ROOT / "psionic/fixtures/kernel-search-l4.coax"
BLOCKS = [32, 64, 128, 256, 512, 1024]
TRIALS = 11
CASES = 10


def parse(path):
    run = {"name": path.stem, "knobs": {}, "order": [], "note": "", "admitted": False, "seconds": 0, "confirm": False,
           "gpu": "", "commit": "", "evaluator": ""}
    for line in path.read_text().splitlines():
        p = line.split()
        if not p:
            continue
        if p[0] == "source":
            run["file"], run["sha"] = p[1], p[3]
        elif p[0] == "prefix":
            run["prefix"] = p[1]
        elif p[0] == "confirmation":
            run["confirm"] = True
        elif p[0] == "gpu":
            run["gpu"] = " ".join(p[1:])
        elif p[0] in ("commit", "evaluator"):
            run[p[0]] = p[1]
        elif p[0] == "when":
            run["when"] = " ".join(p[1:])
        elif p[0] == "seconds":
            run["seconds"] = int(p[1])
        elif p[0] == "admission":
            run["admitted"] = p[1] == "ok:"
            if not run["admitted"]:
                run["note"] = line
        elif p[0] in ("build", "device") and p[1] in ("refused:", "run") and not run["note"]:
            run["note"] = line
        elif p[0] == "error":
            # The host's failure, from the driver's message on.
            run["note"] = line[line.find("CUDA error"):] if "CUDA error" in line else line
        elif p[0] in ("cpu", "device") and len(p) == 4:
            k = knob(run, int(p[1]))
            k[p[0]][int(p[2])] = p[3]
        elif p[0] == "time":
            k = knob(run, int(p[1]))
            k["trials"][BLOCKS.index(int(p[2]))] = [float(v) for v in p[3:]]
        elif p[0] == "pass":
            k = knob(run, int(p[1]))
            k["pass"] = (int(p[2]), float(p[3]), float(p[4]))
    return run


def knob(run, value):
    if value not in run["knobs"]:
        run["knobs"][value] = {"cpu": [""] * CASES, "device": [""] * CASES, "trials": [None] * len(BLOCKS), "pass": None}
        run["order"].append(value)
    return run["knobs"][value]


def quote(s):
    return '"' + s.replace("\\", "\\\\").replace('"', "'") + '"'


def render(runs):
    knobs = [(i, v, r["knobs"][v]) for i, r in enumerate(runs) for v in r["order"]]
    out = ["// Generated by psionic/tests/kernel_search_fixture.py from psionic/kernels/norm/ledger.",
           "// Chapter 247's evaluations on the L4, as recorded. Do not edit.",
           f"KR_COUNT :: {len(runs)};",
           f"KK_COUNT :: {len(knobs)};"]

    def arr(name, typ, values):
        out.append(f"{name} :: [{len(values)}]{typ}.[{','.join(values)}];")

    arr("KR_PREFIX", "string", [quote(r.get("prefix", "")) for r in runs])
    arr("KR_FILE", "string", [quote(r.get("file", "")) for r in runs])
    arr("KR_SHA", "string", [quote(r.get("sha", "")) for r in runs])
    arr("KR_WHEN", "string", [quote(r.get("when", "")) for r in runs])
    arr("KR_NOTE", "string", [quote(r["note"]) for r in runs])
    arr("KR_GPU", "string", [quote(r["gpu"]) for r in runs])
    arr("KR_COMMIT", "string", [quote(r["commit"]) for r in runs])
    arr("KR_CONFIRM", "bool", ["true" if r["confirm"] else "false" for r in runs])
    arr("KR_ADMITTED", "bool", ["true" if r["admitted"] else "false" for r in runs])
    arr("KR_SECONDS", "int", [str(r["seconds"]) for r in runs])
    arr("KK_RUN", "int", [str(i) for i, v, k in knobs])
    arr("KK_KNOB", "int", [str(v) for i, v, k in knobs])
    # Per knob and case: 0 not run, 1 ok, 2 wrong, 3 unwritten, 4 order, 5 plan, 6 trap, 7 differs.
    codes = {"": 0, "ok": 1, "wrong": 2, "unwritten": 3, "order": 4, "plan": 5, "trap": 6, "cpu-differs": 7, "repeat-differs": 7}
    arr("KK_CPU", "int", [str(codes[k["cpu"][c].split(":")[0]]) for i, v, k in knobs for c in range(CASES)])
    arr("KK_DEVICE", "int", [str(codes[k["device"][c].split(":")[0]]) for i, v, k in knobs for c in range(CASES)])
    arr("KK_TRIALS", "f64", [repr(t[j]) if t else "0" for i, v, k in knobs for t in k["trials"] for j in range(TRIALS)])
    arr("KK_PASS", "f64", [repr(x) for i, v, k in knobs
                           for x in ((float(k["pass"][0]), k["pass"][1], k["pass"][2]) if k["pass"] else (0.0, 0.0, 0.0))])
    return "\n".join(out) + "\n"


def main():
    runs = [parse(p) for p in sorted(LEDGER.glob("*.log"))]
    text = render(runs)
    if "--check" in sys.argv:
        assert OUT.read_text() == text, "psionic/fixtures/kernel-search-l4.coax is not the ledger's rendering"
        print(f"kernel-search fixture: {len(runs)} evaluations rendered from the ledger, equal to the file")
        return
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(runs)} evaluations")


if __name__ == "__main__":
    main()
