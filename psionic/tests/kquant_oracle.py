#!/usr/bin/env python3
# Firm reason: 2 (independent oracle: recomputes our answer outside Coax, so it must not share our implementation)
"""Independent K-quant, IQ4, IQ3 and IQ2 decode vectors for chapter 51.

Each block is decoded from ggml's published block structs (ggml-common.h at
llama.cpp 0893ec98f5eafad36a43a72cd1c3723d72b0d03a, MIT, "Copyright (c)
2023-2026 The ggml authors"), walking the bytes in the order the structs and
ggml's reference loops lay them out: super-blocks of 256, sub-block scales
and mins packed in 4, 6 or 8 bits. Every value is computed as an exact
integer multiple of 2^-24 and rounded to binary32 with integer arithmetic,
nearest with ties to even, so no float type takes part. The bytes come from
a fixed counter stream; half-precision scales cover subnormals, both signs
and the largest finite half. This owned tool imports and runs no upstream
code, and no Coax.

The IQ3 and IQ2 lattice formats index codebook grids. `--grids HEADER`
reads those tables as data from ggml/src/ggml-common.h (llama.cpp
9b05354ec6fb58b4e665e9a39ebc40285c015638, MIT) without building or running
anything, and checks (or with `--write`, writes) psionic/fixtures/iq-grids.coax.
Without it, the grids are read back from that fixture, and each table's
SHA-256 (over its entries as little-endian bytes) must equal the digest
pinned below, the one recorded when the tables were extracted. The lattice
decoders below then follow ggml's dequantize_row_iq* loops (ggml-quants.c at
the same commit): sub-blocks of 32, four groups of 8, the sign byte, and the
grid's bytes in memory order on a little-endian host. Their values are exact
integers in 2^-27 units.
"""
from pathlib import Path
import hashlib
import re
import struct
import sys

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / "psionic/fixtures/kquant-vectors.coax"
GRIDS = ROOT / "psionic/fixtures/iq-grids.coax"
GGML_COMMIT = "9b05354ec6fb58b4e665e9a39ebc40285c015638"

# (ggml name, C type, entries, Coax name, SHA-256 of the little-endian bytes)
TABLES = (
    ("kmask_iq2xs", "uint8_t", 8, "KQ_KMASK",
     "5ac9831b2e30eb285ef34f8501620f878432d5c04331ad1ae47f977a83ba41a5"),
    ("ksigns_iq2xs", "uint8_t", 128, "KQ_KSIGNS",
     "a76742a603f8beca5212ecce0f1f02f11a4887fd2f7c8b15aca0ea3eb3380c31"),
    ("iq2xxs_grid", "uint64_t", 256, "KQ_IQ2XXS_GRID",
     "05826b5d3e472a3a78f196be62ac78acf81df0f909626e12ab9fa2a5d490dd54"),
    ("iq2xs_grid", "uint64_t", 512, "KQ_IQ2XS_GRID",
     "06e47aaca60b4dc1d9b5a3f34540437058a6b142b4d7a59d5ded769b4d1bf1de"),
    ("iq2s_grid", "uint64_t", 1024, "KQ_IQ2S_GRID",
     "e1aa1473412b0552c2174c30ef22ab4073f6a181b85a17056e8249bd2932fd88"),
    ("iq3xxs_grid", "uint32_t", 256, "KQ_IQ3XXS_GRID",
     "46e35f5a997efdee6c99ce57854c8a0d4f0ff8ca57e5e8a60c0793ea580acf5d"),
    ("iq3s_grid", "uint32_t", 512, "KQ_IQ3S_GRID",
     "bd1af4945a1717c65610b0284e4628b9a1ba3b306fae3a06f6e5f597356e349f"),
)
WIDTH = {"uint8_t": 1, "uint32_t": 4, "uint64_t": 8}
COAX_TYPE = {"uint8_t": "u8", "uint32_t": "u32", "uint64_t": "u64"}


def table_bytes(ctype, values):
    return b"".join(v.to_bytes(WIDTH[ctype], "little") for v in values)


def extract(header):
    """The tables from ggml-common.h, read as text."""
    text = Path(header).read_text()
    out = {}
    for name, ctype, count, _, _ in TABLES:
        m = re.search(r"GGML_TABLE_BEGIN\(" + ctype + ", " + name + r", (\d+)\)(.*?)GGML_TABLE_END\(\)", text, re.S)
        assert m and int(m.group(1)) == count, name
        values = [int(v, 0) for v in re.findall(r"0x[0-9a-fA-F]+|\d+", m.group(2))]
        assert len(values) == count and all(0 <= v < 256 ** WIDTH[ctype] for v in values), name
        out[name] = values
    return out


def grid_fixture(tables):
    lines = ["// Generated by psionic/tests/kquant_oracle.py --grids from ggml/src/ggml-common.h",
             f"// at llama.cpp {GGML_COMMIT}. MIT License, Copyright (c)",
             "// 2023-2026 The ggml authors; see psionic/NOTICE. Each table's _SHA256 is the",
             "// SHA-256 of its entries as little-endian bytes. Do not edit."]
    for name, ctype, count, coax, _ in TABLES:
        values, width = tables[name], WIDTH[ctype]
        per = 16 if width == 1 else 8 if width == 4 else 4
        lines.append(f"// {name}[{count}]")
        lines.append(f"{coax} :: [{count}]{COAX_TYPE[ctype]}.[")
        for start in range(0, count, per):
            row = values[start:start + per]
            lines.append("    " + ",".join(str(v) if width == 1 else f"0x{v:0{2 * width}x}" for v in row) + ",")
        lines.append("];")
        digest = hashlib.sha256(table_bytes(ctype, values)).digest()
        lines.append(f"{coax}_SHA256 :: [32]u8.[" + ",".join(str(c) for c in digest) + "];")
    return "\n".join(lines + [""])


def read_grids():
    """The tables back from the fixture, each checked against its pinned digest."""
    text = GRIDS.read_text()
    out = {}
    for name, ctype, count, coax, pinned in TABLES:
        m = re.search(r"^" + coax + r" :: \[(\d+)\]\w+\.\[(.*?)\];", text, re.S | re.M)
        assert m and int(m.group(1)) == count, coax
        values = [int(v, 0) for v in re.findall(r"0x[0-9a-f]+|\d+", m.group(2))]
        assert len(values) == count, coax
        assert hashlib.sha256(table_bytes(ctype, values)).hexdigest() == pinned, f"{name} digest changed"
        out[name] = values
    assert text == grid_fixture(out), "grid fixture drifted"
    return out


def grid_checks(t):
    """What the tables must be, derived without them."""
    assert t["kmask_iq2xs"] == [1 << j for j in range(8)]
    # Seven sign bits; the eighth makes the count of minus signs even.
    assert t["ksigns_iq2xs"] == [i | (bin(i).count("1") & 1) << 7 for i in range(128)]
    levels = {"iq2xxs_grid": (8, {8, 25, 43}), "iq2xs_grid": (8, {8, 25, 43}), "iq2s_grid": (8, {8, 25, 43}),
              "iq3xxs_grid": (4, {4, 12, 20, 28, 36, 44, 52, 62}), "iq3s_grid": (4, set(range(1, 16, 2)))}
    for name, (width, allowed) in levels.items():
        values = t[name]
        assert values == sorted(set(values)), name
        assert all((v >> 8 * j) & 255 in allowed for v in values for j in range(width)), name

# The IQ4 non-uniform values, kvalues_iq4nl in ggml-common.h (MIT, see above).
IQ4 = (-127, -104, -83, -65, -49, -35, -22, -10, 1, 13, 25, 38, 53, 69, 89, 113)

# name: (GGUF type, values per block, bytes per block, offsets of half scales)
FORMATS = {
    "Q2_K": (10, 256, 16 + 64 + 2 + 2, (80, 82)),
    "Q3_K": (11, 256, 32 + 64 + 12 + 2, (108,)),
    "Q4_K": (12, 256, 2 + 2 + 12 + 128, (0, 2)),
    "Q5_K": (13, 256, 2 + 2 + 12 + 32 + 128, (0, 2)),
    "Q6_K": (14, 256, 128 + 64 + 16 + 2, (208,)),
    "IQ4_NL": (20, 32, 2 + 16, (0,)),
    "IQ4_XS": (23, 256, 2 + 2 + 4 + 128, (0,)),
}
BLOCKS = {"IQ4_NL": 8}


def half_units(bits):
    """The half as an integer number of 2^-24 units."""
    sign = -1 if bits & 0x8000 else 1
    exponent, fraction = (bits >> 10) & 31, bits & 1023
    assert exponent != 31, "no infinities or NaNs in vectors"
    if exponent == 0:
        return sign * fraction
    return sign * (1024 + fraction) * 2 ** (exponent - 1)


def f32_bits(units, frac=24):
    """units * 2^-frac rounded to binary32 (nearest, ties to even), as bits."""
    if units == 0:
        return 0
    sign = 0x80000000 if units < 0 else 0
    a = abs(units)
    shift = max(a.bit_length() - 24, 0)
    kept, rest = a >> shift, a & ((1 << shift) - 1)
    if shift and (rest > 1 << (shift - 1) or (rest == 1 << (shift - 1) and kept & 1)):
        kept += 1
    if kept == 1 << 24:
        kept, shift = kept >> 1, shift + 1
    exponent = kept.bit_length() - 1 + shift - frac  # value = kept * 2^(shift-frac)
    assert -126 <= exponent < 128
    mantissa = (kept << (23 - (kept.bit_length() - 1))) & 0x7fffff
    return sign | (exponent + 127) << 23 | mantissa


def half_at(b, at):
    return half_units(b[at] | b[at + 1] << 8)


def q2_k(b):
    scales, qs, d, dmin = b[0:16], b[16:80], half_at(b, 80), half_at(b, 82)
    out, s = [], 0
    for n in range(2):
        q = qs[32 * n:32 * n + 32]
        for shift in (0, 2, 4, 6):
            for half in (0, 16):
                sc = scales[s]
                s += 1
                for l in range(16):
                    out.append(d * (sc & 15) * ((q[half + l] >> shift) & 3) - dmin * (sc >> 4))
    return out


def q3_k(b):
    hmask, qs, packed, d = b[0:32], b[32:96], b[96:108], half_at(b, 108)
    # Sixteen 6-bit scales: low nibbles of bytes 0-7 then their high
    # nibbles; the top two bits of each from bytes 8-11, two bits at a time.
    scales = []
    for j in range(16):
        low = packed[j] & 15 if j < 8 else packed[j - 8] >> 4
        scales.append((low | ((packed[8 + j % 4] >> (2 * (j // 4))) & 3) << 4) - 32)
    out, s, m = [], 0, 1
    for n in range(2):
        q = qs[32 * n:32 * n + 32]
        for shift in (0, 2, 4, 6):
            for half in (0, 16):
                for l in range(16):
                    low = (q[half + l] >> shift) & 3
                    out.append(d * scales[s] * (low - (0 if hmask[half + l] & m else 4)))
                s += 1
            m <<= 1
    return out


def scale_min_k4(j, q):
    if j < 4:
        return q[j] & 63, q[j + 4] & 63
    return (q[j + 4] & 15) | (q[j - 4] >> 6) << 4, (q[j + 4] >> 4) | (q[j] >> 6) << 4


def q45_k(b, five):
    d, dmin, packed = half_at(b, 0), half_at(b, 2), b[4:16]
    qh = b[16:48] if five else bytes(32)
    qs = b[48:176] if five else b[16:144]
    out = []
    for g in range(4):
        for part in (0, 1):
            sc, mn = scale_min_k4(2 * g + part, packed)
            for l in range(32):
                q = (qs[32 * g + l] >> (4 * part)) & 15
                if (qh[l] >> (2 * g + part)) & 1:
                    q += 16
                out.append(d * sc * q - dmin * mn)
    return out


def q6_k(b):
    ql, qh, d = b[0:128], b[128:192], half_at(b, 208)
    sc = [v - 256 if v > 127 else v for v in b[192:208]]
    out = [0] * 256
    for n in range(2):
        for l in range(32):
            i = l // 16
            lo, hi = ql[64 * n + l], ql[64 * n + 32 + l]
            h = qh[32 * n + l]
            quads = ((lo & 15) | (h & 3) << 4, (hi & 15) | (h >> 2 & 3) << 4,
                     (lo >> 4) | (h >> 4 & 3) << 4, (hi >> 4) | (h >> 6 & 3) << 4)
            for part, q in enumerate(quads):
                out[128 * n + 32 * part + l] = d * sc[8 * n + i + 2 * part] * (q - 32)
    return out


def iq4_nl(b):
    d, qs = half_at(b, 0), b[2:18]
    return [d * IQ4[v & 15] for v in qs] + [d * IQ4[v >> 4] for v in qs]


def iq4_xs(b):
    d, high, low, qs = half_at(b, 0), b[2] | b[3] << 8, b[4:8], b[8:136]
    out = []
    for ib in range(8):
        ls = (low[ib // 2] >> (4 * (ib % 2)) & 15) | ((high >> (2 * ib)) & 3) << 4
        part = qs[16 * ib:16 * ib + 16]
        out += [d * (ls - 32) * IQ4[v & 15] for v in part] + [d * (ls - 32) * IQ4[v >> 4] for v in part]
    return out


def grid_bytes(entry, width):
    """A grid entry's bytes in memory order on a little-endian host."""
    return [(entry >> 8 * j) & 255 for j in range(width)]


def u32_at(b, at):
    return b[at] | b[at + 1] << 8 | b[at + 2] << 16 | b[at + 3] << 24


# The lattice formats: values in 2^-27 units. ggml's db is d * (0.5 + s) *
# 0.25 (IQ2), d * (0.5 + s) * 0.5 (IQ3_XXS) or d * (1 + 2 s) (IQ3_S): with d
# in 2^-24 units, that is d * (2 s + 1) times 1, 2 or 8 units of 2^-27.
def iq2_xxs(b, t):
    d, out = half_at(b, 0), []
    for ib32 in range(8):
        aux = b[2 + 8 * ib32:2 + 8 * ib32 + 8]
        high = u32_at(aux, 4)
        db = d * (2 * (high >> 28) + 1)
        for l in range(4):
            grid = grid_bytes(t["iq2xxs_grid"][aux[l]], 8)
            signs = t["ksigns_iq2xs"][(high >> 7 * l) & 127]
            for j in range(8):
                out.append(db * grid[j] * (-1 if signs & t["kmask_iq2xs"][j] else 1))
    return out


def iq2_xs(b, t):
    d, scales, out = half_at(b, 0), b[66:74], []
    for ib32 in range(8):
        dbs = (d * (2 * (scales[ib32] & 15) + 1), d * (2 * (scales[ib32] >> 4) + 1))
        for l in range(4):
            q = b[2 + 2 * (4 * ib32 + l)] | b[3 + 2 * (4 * ib32 + l)] << 8
            grid = grid_bytes(t["iq2xs_grid"][q & 511], 8)
            signs = t["ksigns_iq2xs"][q >> 9]
            for j in range(8):
                out.append(dbs[l // 2] * grid[j] * (-1 if signs & t["kmask_iq2xs"][j] else 1))
    return out


def iq2_s(b, t):
    d, qs, qh, scales, out = half_at(b, 0), b[2:66], b[66:74], b[74:82], []
    signs = qs[32:]
    for ib32 in range(8):
        dbs = (d * (2 * (scales[ib32] & 15) + 1), d * (2 * (scales[ib32] >> 4) + 1))
        for l in range(4):
            grid = grid_bytes(t["iq2s_grid"][qs[4 * ib32 + l] | ((qh[ib32] << (8 - 2 * l)) & 0x300)], 8)
            for j in range(8):
                out.append(dbs[l // 2] * grid[j] * (-1 if signs[4 * ib32 + l] & t["kmask_iq2xs"][j] else 1))
    return out


def iq3_xxs(b, t):
    d, qs, out = half_at(b, 0), b[2:66], []
    for ib32 in range(8):
        aux = u32_at(b, 66 + 4 * ib32)
        db = d * (2 * (aux >> 28) + 1) * 2
        for l in range(4):
            signs = t["ksigns_iq2xs"][(aux >> 7 * l) & 127]
            one = grid_bytes(t["iq3xxs_grid"][qs[8 * ib32 + 2 * l]], 4)
            two = grid_bytes(t["iq3xxs_grid"][qs[8 * ib32 + 2 * l + 1]], 4)
            group = [0] * 8
            for j in range(4):
                group[j] = db * one[j] * (-1 if signs & t["kmask_iq2xs"][j] else 1)
                group[j + 4] = db * two[j] * (-1 if signs & t["kmask_iq2xs"][j + 4] else 1)
            out += group
    return out


def iq3_s(b, t):
    d, qs, qh, signs, scales, out = half_at(b, 0), b[2:66], b[66:74], b[74:106], b[106:110], []
    for pair in range(4):
        for half in range(2):
            ib32 = 2 * pair + half
            db = d * (2 * ((scales[pair] >> 4 * half) & 15) + 1) * 8
            for l in range(4):
                one = grid_bytes(t["iq3s_grid"][qs[8 * ib32 + 2 * l] | ((qh[ib32] << (8 - 2 * l)) & 256)], 4)
                two = grid_bytes(t["iq3s_grid"][qs[8 * ib32 + 2 * l + 1] | ((qh[ib32] << (7 - 2 * l)) & 256)], 4)
                sign = signs[4 * ib32 + l]
                group = [0] * 8
                for j in range(4):
                    group[j] = db * one[j] * (-1 if sign & t["kmask_iq2xs"][j] else 1)
                    group[j + 4] = db * two[j] * (-1 if sign & t["kmask_iq2xs"][j + 4] else 1)
                out += group
    return out


LATTICE = {"IQ2_XXS": (16, 2 + 64, iq2_xxs), "IQ2_XS": (17, 2 + 64 + 8, iq2_xs), "IQ2_S": (22, 2 + 64 + 8 + 8, iq2_s),
           "IQ3_XXS": (18, 2 + 64 + 32, iq3_xxs), "IQ3_S": (21, 2 + 64 + 8 + 32 + 4, iq3_s)}
for _name, (_kind, _size, _) in LATTICE.items():
    FORMATS[_name] = (_kind, 256, _size, (0,))

DECODE = {"Q2_K": q2_k, "Q3_K": q3_k, "Q4_K": lambda b: q45_k(b, False),
          "Q5_K": lambda b: q45_k(b, True), "Q6_K": q6_k, "IQ4_NL": iq4_nl, "IQ4_XS": iq4_xs}

# Scales: subnormal, small, ordinary, negative, the largest finite half.
HALVES = (0x0001, 0x03ff, 0x1234, 0x2c00, 0x3555, 0x3c00, 0xb800, 0x4a3f, 0x7bff, 0xfbff, 0x0400, 0x2e66)


def block_bytes(name, index):
    _, _, size, halves = FORMATS[name]
    state = 977 * (index + 1) + sum(map(ord, name))
    out = bytearray()
    for _ in range(size):
        state = (state * 1103515245 + 12345) % 2147483648
        out.append((state >> 16) & 255)
    for k, at in enumerate(halves):
        h = HALVES[(3 * index + 5 * k + len(name)) % len(HALVES)]
        out[at], out[at + 1] = h & 255, h >> 8
    return bytes(out)


def vectors(tables):
    result = {}
    for name in FORMATS:
        kind, values, size, _ = FORMATS[name]
        data, bits = b"", []
        for index in range(BLOCKS.get(name, 2)):
            b = block_bytes(name, index)
            lattice = name in LATTICE
            decoded = LATTICE[name][2](b, tables) if lattice else DECODE[name](b)
            assert len(decoded) == values and len(b) == size
            data += b
            bits += [f32_bits(v, 27 if lattice else 24) for v in decoded]
        result[name] = (kind, data, bits)
    return result


def checks():
    assert f32_bits(1 << 24) == 0x3f800000 and f32_bits(-(1 << 23)) == 0xbf000000
    assert f32_bits(1) == 0x33800000 and f32_bits((1 << 24) + 1) == 0x3f800000
    assert f32_bits((1 << 25) + 3) == 0x40000001 and f32_bits((1 << 25) + 2) == 0x40000000 and f32_bits((1 << 25) + 6) == 0x40000002
    assert f32_bits((1 << 26) - 1) == 0x40800000
    for bits in range(0x7c00):
        if bits & 1023 == 0 or bits < 1024:
            units = half_units(bits)
            assert struct.unpack("<f", struct.pack("<I", f32_bits(units)))[0] == units / 2 ** 24 or units == 0
    # One hand block per family, the same blocks the chapter decodes by hand.
    b = bytearray(84)
    b[0], b[16], b[80], b[81], b[82], b[83] = 0x21, 0b11100100, 0x00, 0x38, 0x00, 0x3c
    v = q2_k(bytes(b))
    assert [x / 2 ** 24 for x in v[:4]] == [-2.0, -2.0, -2.0, -2.0] and v[16] == 0
    assert struct.calcsize("<" + "B" * 84) == FORMATS["Q2_K"][2]


def fixture(result):
    lines = ["// Generated by psionic/tests/kquant_oracle.py from ggml's block structs; exact",
             "// integers in 2^-24 units rounded to binary32 by integer arithmetic. Do not edit."]
    for name, (kind, data, bits) in result.items():
        tag = name.replace("_", "")
        lines.append(f"KQV_{tag}_KIND :: {kind};")
        lines.append(f"KQV_{tag}_BYTES :: [{len(data)}]u8.[")
        for start in range(0, len(data), 24):
            lines.append("    " + ",".join(str(c) for c in data[start:start + 24]) + ",")
        lines.append("];")
        lines.append(f"KQV_{tag}_BITS :: [{len(bits)}]u32.[")
        for start in range(0, len(bits), 8):
            lines.append("    " + ",".join(f"0x{c:08x}" for c in bits[start:start + 8]) + ",")
        lines.append("];")
    return "\n".join(lines + [""])


def main():
    args = sys.argv[1:]
    if args[:1] == ["--grids"]:
        # Extract the tables from a ggml checkout (read as text, never built).
        assert len(args) in (2, 3) and args[2:] in ([], ["--write"]), "usage: kquant_oracle.py --grids HEADER [--write]"
        tables = extract(args[1])
        grid_checks(tables)
        for name, ctype, _, coax, _ in TABLES:
            print(f"{coax}_SHA256 = {hashlib.sha256(table_bytes(ctype, tables[name])).hexdigest()}")
        if args[2:] == ["--write"]:
            GRIDS.write_text(grid_fixture(tables))
        else:
            assert GRIDS.read_text() == grid_fixture(tables), "grid fixture differs from the header"
        return
    checks()
    tables = read_grids()
    grid_checks(tables)
    result = vectors(tables)
    expected = fixture(result)
    if args == ["--write"]:
        TARGET.write_text(expected)
        return
    assert not args, "usage: kquant_oracle.py [--write] | --grids HEADER [--write]"
    assert TARGET.read_text() == expected, "K-quant fixture drifted"
    total = sum(len(bits) for _, _, bits in result.values())
    print(f"K-quant oracle: {len(result)} formats, {total} decoded values match the fixture; "
          f"{len(TABLES)} ggml tables match their pinned SHA-256")


if __name__ == "__main__":
    main()
