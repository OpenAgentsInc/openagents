#!/usr/bin/env python3
"""Independent sorted top-k and Decimal(100) softmax for the tiny MoE profile.

No upstream code or Coax output is imported. Fixtures include the original
32/128-expert, top-four shapes, ties, near ties and extreme finite scores.
"""
from decimal import Decimal, localcontext
from pathlib import Path
import struct
import sys

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / "psionic/fixtures/moe-vectors.coax"


def f32(value):
    return struct.unpack("<f", struct.pack("<f", value))[0]


def bits(value):
    return struct.unpack("<I", struct.pack("<f", value))[0]


def cases():
    inputs = [([0], 1), ([2, 2], 2), ([0, 4, 2, 3, 1, -1], 4),
              ([1000, 1001, 999, 1002, 998], 4),
              ([0, 1, -1, 2, -2], 1), ([1, 1, 1, 1, 1], 4),
              ([1, struct.unpack('<f', struct.pack('<I', 0x3f800001))[0], 0, -1, -2], 4),
              ([3.4028234663852886e38, -3.4028234663852886e38, 0, 1, -1], 4),
              ([i % 7 - 3 for i in range(32)], 4),
              ([0] * 128, 4), ([i / 16 - 4 for i in range(128)], 4),
              ([i % 5 - 2 for i in range(9)], 3)]
    with localcontext() as context:
        context.prec = 100
        for scores, k in inputs:
            scores = list(map(f32, scores))
            ids = sorted(range(len(scores)), key=lambda i: (-scores[i], i))[:k]
            maximum = Decimal.from_float(scores[ids[0]])
            numerators = [(Decimal.from_float(scores[i]) - maximum).exp() for i in ids]
            weights = [float(value / sum(numerators)) for value in numerators]
            rounded = [f32(value) for value in weights]
            # Each native scalar expert computes (id + 1) * 2 + id.
            mixed = f32(sum(Decimal.from_float(w) * (3*i+2) for i,w in zip(ids, rounded)))
            yield scores, k, ids, weights, mixed


def fixture(data):
    lines = ["// Generated by psionic/tests/moe_oracle.py; sorted IDs and Decimal softmax."]
    for number, (scores,k,ids,weights,_) in enumerate(data):
        words = ",".join(f"f32_from_bits(0x{bits(x):08x})" for x in scores)
        lines += [f'#test "independent top-k router fixture {number}" {{',
                  f"    logits:=[{len(scores)}]f32.[{words}];r:=mo_route(logits[..],{k});",
                  f"    #assert r.status==MoStatus.ok && r.count=={k};"]
        for slot,(identity,weight) in enumerate(zip(ids,weights)):
            lines.append(f"    #assert r.ids[{slot}]=={identity} && abs(f64(r.weights[{slot}])-{weight:.17g})<0.00000012;")
        lines.append("}")
    return "\n".join(lines)+"\n"


def main():
    data = list(cases());expected = fixture(data)
    if sys.argv[1:] == ["--write"]:
        TARGET.write_text(expected);return
    assert TARGET.read_text() == expected, "MoE fixture drifted"
    if sys.argv[1:] == ["--header"]:
        print("static const struct {int n,k; uint32_t logits[128]; int ids[4]; double weights[4]; float mixed;} moe_cases[] = {")
        for scores,k,ids,weights,mixed in data:
            mixed_literal = f"{mixed:.9g}"
            if '.' not in mixed_literal and 'e' not in mixed_literal:
                mixed_literal += '.0'
            print("{"+f"{len(scores)},{k},{{"+','.join(f"0x{bits(x):08x}u" for x in scores)+"},{"+
                  ','.join(map(str,ids))+"},{"+','.join(f"{x:.17g}" for x in weights)+"},"+mixed_literal+"f},")
        print("};")
    else:
        assert not sys.argv[1:], "usage: moe_oracle.py [--write | --header]"
        print(f"MoE oracle: {len(data)} independent routing and weighted-expert cases pass")


if __name__ == "__main__":
    main()
