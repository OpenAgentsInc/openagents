#!/usr/bin/env python3
"""Independent E2M1 * power-of-two fixtures, using Python's scalar ldexp.

This owned tool does not import or execute either upstream repository or Coax.
All admitted products are exactly representable in binary32, including zeros
and subnormals. The native header also covers every packed-byte permutation.
"""
import math
from pathlib import Path
import struct
import sys

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / "psionic/fixtures/mxfp4-vectors.coax"
MAGNITUDES = (0.0, 0.5, 1.0, 1.5, 2.0, 3.0, 4.0, 6.0)


def reference(code, scale):
    value = MAGNITUDES[code % 8]
    if code >= 8:
        value = -value
    value = math.ldexp(value, scale - 127)
    return struct.unpack("<I", struct.pack("<f", value))[0]


def values():
    result = [reference(code, scale) for scale in range(253) for code in range(16)]
    assert len(result) == 4048
    assert all((value & 0x7f800000) != 0x7f800000 for value in result)
    assert reference(8, 0) == 0x80000000
    assert reference(1, 0) == 0x00200000
    assert reference(7, 252) == 0x7f400000
    try:
        reference(7, 253)
    except OverflowError:
        pass
    else:
        raise AssertionError("scale 253 cannot admit every E2M1 code as finite f32")
    return result


def fixture(data):
    lines = ["// Generated by psionic/tests/mxfp4_oracle.py; independent scalar ldexp.",
             "MX_GOLD_BITS :: [4048]u32.["]
    for scale in range(253):
        row = data[scale * 16:(scale + 1) * 16]
        lines.append("    " + ",".join(f"0x{x:08x}" for x in row) + ",")
    return "\n".join(lines + ["];", ""])


def main():
    data = values()
    expected = fixture(data)
    if sys.argv[1:] == ["--write"]:
        TARGET.write_text(expected)
        return
    assert TARGET.read_text() == expected, "MXFP4 fixture drifted"
    if sys.argv[1:] == ["--header"]:
        print("static const uint32_t mxfp4_expected[4048] = {")
        for start in range(0, len(data), 16):
            print(",".join(f"0x{x:08x}u" for x in data[start:start+16]) + ",")
        print("};")
    else:
        assert not sys.argv[1:], "usage: mxfp4_oracle.py [--write | --header]"
        print("MXFP4 oracle: all 4,048 admitted code/scale pairs match the fixture")


if __name__ == "__main__":
    main()
