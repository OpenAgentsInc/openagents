#!/usr/bin/env python3
# Firm reason: 2 (independent oracle: recomputes our answer outside Coax, so it must not share our implementation)
"""Independent Decimal(120) fixtures; emits a C header, never runtime code.

Inputs are exact binary32 dyadics from a fixed integer LCG. References use
Decimal sums/products, direct exp(logit) softmax, and E[x*x]-E[x]^2 LayerNorm.
They do not import the Coax implementation or consume its output.
"""
from decimal import Decimal, localcontext
import json
import struct


def f32(x):
    return struct.unpack('<f', struct.pack('<f', x))[0]


def bits(x):
    return struct.unpack('<I', struct.pack('<f', x))[0]


def decimal(x):
    return Decimal.from_float(f32(x))


def fixtures():
    seed = 734

    def values(n):
        nonlocal seed
        result = []
        for _ in range(n):
            seed = (1664525 * seed + 1013904223) & 0xffffffff
            result.append(f32(((seed >> 16) % 65 - 32) / 8))
        return result

    with localcontext() as ctx:
        ctx.prec = 120
        for rows in (1, 2, 3):
            for width in (1, 2, 3, 7):
                for op in range(8):
                    for columns in ((1, 2, 4) if op == 3 else (3,) if op == 4 else (0,)):
                        a = values(rows * width)
                        b = values(width * columns if op == 3 else rows * width if op in (0, 2) else 0)
                        indices = [rows - 1, 0, rows - 1] if op == 4 else []
                        mask = [int(c == r % width or (r + c) % 3 != 0) for r in range(rows) for c in range(width)] if op == 5 else []
                        if op == 5:
                            a = [f32(x + (1000 if (i // width) % 2 == 0 else -1000)) for i, x in enumerate(a)]
                        epsilon = f32(1e-5) if op >= 6 else 0.0
                        da, db = list(map(decimal, a)), list(map(decimal, b))
                        out = []
                        if op == 0:
                            out = [x + y for x, y in zip(da, db)]
                        elif op in (1, 2, 3):
                            for r in range(rows):
                                for c in range(columns if op == 3 else 1):
                                    terms = [da[r * width + k] * (db[k * columns + c] if op == 3 else db[r * width + k] if op == 2 else Decimal(1)) for k in range(width)]
                                    out.append(sum(terms, Decimal(0)))
                        elif op == 4:
                            out = [da[r * width + c] for r in indices for c in range(width)]
                        else:
                            for r in range(rows):
                                x = da[r * width:(r + 1) * width]
                                if op == 5:
                                    # Deliberately direct, high-range Decimal exponentials.
                                    exp = [v.exp() if mask[r * width + c] else Decimal(0) for c, v in enumerate(x)]
                                    denominator = sum(exp)
                                    out.extend(v / denominator for v in exp)
                                else:
                                    mean = sum(x) / width if op == 7 else Decimal(0)
                                    second = sum(v * v for v in x) / width
                                    variance = second - mean * mean
                                    denominator = (variance + decimal(epsilon)).sqrt()
                                    out.extend((v - mean) / denominator for v in x)
                        assert max(len(a), len(b), len(indices), len(mask), len(out)) <= 64
                        yield dict(name=f'op{op}-{rows}x{width}x{columns}', op=op, rows=rows, width=width,
                                   columns=columns, epsilon=bits(epsilon), a=a, b=b, indices=indices, mask=mask, out=out)


def main():
    cases = list(fixtures())
    assert len(cases) == 120
    print('/* Independent Decimal(120), LCG seed 734; generated by ops_oracle.py. */')
    print('static const struct Oracle oracle_cases[] = {')
    for c in cases:
        head = [json.dumps(c['name']), *map(str, (c['op'], c['rows'], c['width'], c['columns'])), f"UINT32_C({c['epsilon']})",
                *map(str, (len(c['a']), len(c['b']), len(c['indices']), len(c['mask']), len(c['out'])))]
        arrays = ['{' + ', '.join(f'UINT32_C({bits(v)})' for v in c[key]) + '}' for key in ('a', 'b')]
        arrays += ['{' + ', '.join(map(str, c[key])) + '}' for key in ('indices', 'mask')]
        arrays += ['{' + ', '.join(f'{v:.80E}L' for v in c['out']) + '}']
        # Standard C requires one initializer even for an unused fixed array.
        arrays = [a if a != '{}' else '{0}' for a in arrays]
        print('  {' + ', '.join(head + arrays) + '},')
    print('};')


if __name__ == '__main__':
    main()
