#!/usr/bin/env python3
"""Chapter 128's independent reference values (pure Python, binary64).

Tooling only; never shipped. It shares no code with
psionic/lib/nanochat/pretrain.coax. It rebuilds the run's initial weights
from the written rule (splitmix64 counter draws, one per flat index, scaled
per tensor kind), then takes the loss and gradient of the first 16 tokens of
the training stream through chapter 127's oracle
(psionic/tests/nanochat_grad_oracle.py, a scalar reverse-mode autodiff over
chapter 125's independent forward pass). It also prints the epoch orders of
the checks' plan, FNV-1a hashes, the block-folded digest and the plan and
data identities, each computed here from its written definition.

It prints psionic/fixtures/nanochat/pretrain-oracle.coax.
"""
import hashlib
import importlib.util
import math
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
spec = importlib.util.spec_from_file_location("nanochat_grad_oracle", ROOT / "psionic/tests/nanochat_grad_oracle.py")
grad = importlib.util.module_from_spec(spec)
spec.loader.exec_module(grad)
oracle = grad.oracle

M64 = (1 << 64) - 1
# The run's model (NP_RUN in the example): 2 blocks of width 32, 2 query heads
# over 1 key-value head, the 320-token vocabulary, windows of 64.
MODEL = dict(sequence_len=64, vocab_size=320, n_layer=2, n_head=2, n_kv_head=1, n_embd=32, window_pattern="L", head=0.0, rounding=None)
INIT = 1281
# The first 16 tokens of the training stream (BOS, then chapter 1's first document).
TOKENS = [319, 35, 32, 49, 46, 32, 76, 101, 274, 110, 296, 257, 285, 117, 109, 98]
STRIDE = 97
PICKS = [0, 1, 4, 5, 6, 7, 1000, 10243, 10244, 11000, 12500, 15000, 20000, 21516, 25000, 31000, 32700, 32780, 35000, 42000, 43000, 43046, 43100, 48169]
# The checks' plan (NP_TEST): its seed and five windows.
TEST_SEED, TEST_WINDOWS = 5, 5


def cr_bits(seed, counter):
    z = (seed + 0x9E3779B97F4A7C15 * (counter + 1)) & M64
    z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & M64
    z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & M64
    return z ^ (z >> 31)


def init(c, seed):
    """offset + scale * (2u - 1) per flat index, by tensor kind."""
    s = math.sqrt(3.0 / c["n_embd"])
    scale = {"wte": math.sqrt(3.0), "lm_head": 0.001 * math.sqrt(3.0), "attn.c_proj": 0.1 * s, "mlp.c_proj": 0.1 * s,
             "ve_gate": 0.1 * s, "smear_gate": 0.1 * s, "c_q": s, "c_k": s, "c_v": s, "c_fc": s, "value_embeds": s}
    fixed = {"resid_lambdas": 1.0, "x0_lambdas": 0.1, "smear_lambda": 0.1, "backout_lambda": 0.2}
    out = []
    for _, kind, shape in oracle.inventory(c):
        for _ in range(math.prod(shape)):
            u = (cr_bits(seed, len(out)) >> 11) / 9007199254740992.0
            out.append(fixed[kind] if kind in fixed else 0.0 + scale[kind] * (2 * u - 1))
    return out


def order(seed, windows, epoch):
    o, c, i = list(range(windows)), epoch * windows, windows - 1
    while i > 0:
        j = cr_bits(seed, c) % (i + 1)
        c += 1
        o[i], o[j] = o[j], o[i]
        i -= 1
    return o


def fnv(b):
    h = 0xCBF29CE484222325
    for x in b:
        h = ((h ^ x) * 0x100000001B3) & M64
    return h


def tagged(tag, msg):
    t = hashlib.sha256(tag.encode()).digest()
    return hashlib.sha256(t + t + msg).digest()


def fold(d, data):
    for at in range(0, len(data), 32768):
        d = tagged("psionic.pretrain-fold.v1", d + data[at:at + 32768])
    return d


def data_id(train, val):
    d = fold(bytes(32), struct.pack("<QQ", len(train), len(val)))
    for s in (train, val):
        for at in range(0, len(s), 8192):
            d = fold(d, b"".join(struct.pack("<I", x) for x in s[at:at + 8192]))
    return d


def f64_bits(x):
    return struct.unpack("<Q", struct.pack("<d", x))[0]


def plan_id():
    # NP_TEST: model fields, batch, steps, warmup, warmdown, then the rates and settings as binary64 bits, seed, init, budget.
    ints = [8, 40, 1, 2, 1, 24, 0, 1, 8, 2, 6, 2, 2]
    floats = [0.5, 0.05, 0.02, 0.02, 0.01, 0.8, 0.95, 1e-10, 1.0]
    words = ints + [f64_bits(x) for x in floats] + [5, 11, f64_bits(1e12)]
    return tagged("psionic.pretrain-plan.v1", b"".join(struct.pack("<Q", w) for w in words))


def coax_list(vals):
    return ",".join(repr(float(v)) for v in vals)


def coax_bytes(d):
    return f"[32]u8.[{','.join(str(x) for x in d)}]"


def main():
    c = MODEL
    w = init(c, INIT)
    loss, g = grad.gradient(c, w, TOKENS)
    d = grad.digests(c, g)
    print("// Generated by psionic/tests/pretrain_oracle.py; do not edit.")
    print("NP_ORACLE_MODEL :: NcConfig.{sequence_len=64,vocab=320,layers=2,heads=2,kv_heads=1,width=32,pattern=0,pattern_len=1,context=64};")
    print(f"NP_ORACLE_PARAMETERS :: {len(w)};")
    print(f"NP_ORACLE_INIT :: {INIT};")
    print(f"NP_ORACLE_TOKENS :: [{len(TOKENS)}]int.[{','.join(map(str, TOKENS))}];")
    print(f"NP_ORACLE_LOSS :: {loss!r};")
    print(f"NP_ORACLE_DIGESTS :: [{len(d)}]f64.[{coax_list(d)}];")
    s = g[::STRIDE]
    print(f"NP_ORACLE_SAMPLES :: [{len(s)}]f64.[{coax_list(s)}];")
    print(f"NP_ORACLE_PICKS :: [{len(PICKS)}]int.[{','.join(map(str, PICKS))}];")
    print(f"NP_ORACLE_WEIGHTS :: [{len(PICKS)}]f64.[{coax_list(w[i] for i in PICKS)}];")
    o = order(TEST_SEED, TEST_WINDOWS, 0) + order(TEST_SEED, TEST_WINDOWS, 1)
    print(f"NP_ORACLE_ORDER :: [{len(o)}]int.[{','.join(map(str, o))}];")
    print(f"NP_ORACLE_FNV :: [2]u64.[{fnv(b'a')},{fnv(b'alpha beta.')}];")
    print(f"NP_ORACLE_FOLD :: {coax_bytes(fold(bytes(32), bytes(i % 251 for i in range(70000))))};")
    print(f"NP_ORACLE_DATA_ID :: {coax_bytes(data_id([i % 320 for i in range(9000)], [7, 8, 9]))};")
    print(f"NP_ORACLE_PLAN_ID :: {coax_bytes(plan_id())};")
    print(f"// {len(w)} parameters, {len(grad.TAPE)} recorded operations", file=sys.stderr)


if __name__ == "__main__":
    main()
