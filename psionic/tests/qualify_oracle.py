#!/usr/bin/env python3
"""Chapter 13 tooling: independent digest vectors and the transcribed Elephant evidence.

The policy and value encodings below are written from the chapter's description,
not from the Coax source. Decimal numbers are copied as the exact text of the
chapter 10 files; Python never converts them. Run with --write to regenerate.
"""
import hashlib, re, struct, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ELEPHANT = ROOT / 'psionic/fixtures/models/elephant'
OUT = ROOT / 'psionic/fixtures/qualify'
FILES = {
    'layer0-token32-psionic.f32': 'bb24840a66cdec253c9626c565ddbbc4c46049aea5c9891f889109125f5c26d5',
    'layer0-token32-transformers.f32': '96355941a92956255f1ad3aabf9a29500a88b6ee173aee55d50eaa74052790be',
    'psionic-reference.txt': '1cf6754f3840f9f8f147ffff03dbc30f85fef4ff543e13c6199d98df946095b9',
    'request-tokens.txt': '3c72fddd8566bdfa0cee7347c29f9e972725005fd3e2c6d5b1a03f5559755226',
    'transformers-reference.json': '2078008cf5b55aafa3c3752b82dcb133755b769ded945e861a626cebdd463361',
}
MODES = {'replay': 2, 'one_block': 3}
UNITS = {'hidden': 1, 'probability': 2}


def name(text):
    raw = text.encode('ascii')
    assert 1 <= len(raw) <= 32 and all(0x20 <= b <= 0x7e for b in raw)
    return raw + bytes(32 - len(raw))


def policy(mode, unit, values, value_abs, distribution, tv_max, top, near_tie, regret_max, profile, reference, dataset):
    raw = b'psionic.qualify.policy.v1' + bytes([MODES[mode], UNITS[unit], int(distribution)])
    raw += struct.pack('<QQdddd', values, top, value_abs, tv_max, near_tie, regret_max)
    raw += name(profile) + name(reference) + dataset
    assert len(raw) == 172
    return hashlib.sha256(raw).hexdigest()


def values(xs):
    raw = b'psionic.qualify.values.v1' + struct.pack('<Q', len(xs)) + b''.join(struct.pack('<d', x) for x in xs)
    return hashlib.sha256(raw).hexdigest()


def coax_string(raw):
    text = raw.decode('ascii')
    assert all(c == '\n' or 0x20 <= ord(c) <= 0x7e for c in text)
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'


def vectors():
    tokens = hashlib.sha256(b'tokens').digest()
    base = ('replay', 'probability', 2, 0.0005, True, 0.0005, 1, 0.001, 0.0005, 'cpu-f32-wide-v1', 'torch-2.10.0-cpu-f32-eager', tokens)
    loose = base[:3] + (0.001,) + base[4:]
    hidden = base[:4] + (False, 0.0) + base[6:]
    text = bytes(range(0x20, 0x7f)) + b'\n' + bytes(range(0x20, 0x7f))
    lines = ['// Generated by psionic/tests/qualify_oracle.py: independent SHA-256 vectors.']
    for key, value in [('POLICY', policy(*base)), ('POLICY_LOOSE', policy(*loose)), ('POLICY_HIDDEN', policy(*hidden)),
                       ('VALUES0', values([])), ('VALUES3', values([1.0, -0.5, 0.0])),
                       ('VALUES100', values([i / 4 for i in range(100)])), ('TEXT_SHA', hashlib.sha256(text).hexdigest())]:
        lines.append(f'QY_VECTOR_{key} :: "{value}";')
    lines.append(f'QY_VECTOR_TEXT :: {coax_string(text)};')
    return '\n'.join(lines) + '\n'


def evidence():
    raw = {}
    for file, digest in FILES.items():
        raw[file] = (ELEPHANT / file).read_bytes()
        assert hashlib.sha256(raw[file]).hexdigest() == digest, file
    line = raw['psionic-reference.txt'].decode('ascii').splitlines()[-1]
    match = re.fullmatch(r'choice=yes p_yes=([0-9.]+) p_no=([0-9.]+) slot_mass=([0-9.]+) confidence=([0-9.]+)', line)
    assert match
    json_text = raw['transformers-reference.json'].decode('ascii')
    decision = json_text[json_text.index('"decision"'):]
    probs = re.search(r'"probabilities": \[\s*([0-9.]+),\s*([0-9.]+)\s*\]', decision)
    mass = re.search(r'"slot_mass": ([0-9.]+)', decision)
    assert probs and mass and '"profile": "float32 eager CPU"' in json_text and '"torch": "2.10.0+cpu"' in json_text
    lines = ['// Generated by psionic/tests/qualify_oracle.py from psionic/fixtures/models/elephant.',
             '// Layer-0 values are the files\' exact f32 bits; decimals are the files\' exact text.']
    for key, file in [('LAYER0_PSIONIC', 'layer0-token32-psionic.f32'), ('LAYER0_TRANSFORMERS', 'layer0-token32-transformers.f32')]:
        bits = struct.unpack('<4096I', raw[file])
        lines.append(f'YE_{key} :: [4096]u32.[' + ','.join(f'0x{b:08x}' for b in bits) + '];')
    lines.append(f'YE_DECISION_PSIONIC :: [2]f64.[{match[1]},{match[2]}];')
    lines.append(f'YE_DECISION_TRANSFORMERS :: [2]f64.[{probs[1]},{probs[2]}];')
    lines.append(f'YE_MASS_PSIONIC :: [1]f64.[{match[3]}];')
    lines.append(f'YE_MASS_TRANSFORMERS :: [1]f64.[{mass[1]}];')
    lines.append(f'YE_PSIONIC_TEXT :: {coax_string(raw["psionic-reference.txt"])};')
    lines.append(f'YE_REQUEST_TOKENS :: {coax_string(raw["request-tokens.txt"])};')
    return '\n'.join(lines) + '\n'


def frozen():
    """The identities qualify-elephant.coax pins, computed independently."""
    raw = {f: (ELEPHANT / f).read_bytes() for f in FILES}
    layer0 = hashlib.sha256(b'baselabs/elephant-1 b3f8a93462fb1051a9de031e94a7ff380e254072 token 32 position 0 layer 0\n').digest()
    request = bytes.fromhex(FILES['request-tokens.txt'])
    pins = {'config.json': 'f26324589d15932e2742dbb13dbc7c561865ce4f80990af3b7dff05efe4dadab',
            'model.safetensors': '682f02348dfe4617dd21bba2915c12e805de8cf16327a61e895a831ea681d0ba',
            'readout.json': '96ea8a5c6ecfc30c20cdd369762db5997c5f4fb9821ce0a0318941343eb5e8ba',
            'tokenizer.json': 'a5cd9732badce41de57e6efce8302930ded1c1188c5f81feb2bd6c24c4a1941f'}
    listing = ''.join(f'{pins[n]}  {n}\n' for n in sorted(pins)).encode()
    f32 = lambda file: [float(x) for x in struct.unpack('<4096f', raw[file])]
    line = raw['psionic-reference.txt'].decode().splitlines()[-1].split()
    got = {k: float(v) for k, v in (w.split('=') for w in line[1:])}
    json_text = raw['transformers-reference.json'].decode()
    import json
    ref = json.loads(json_text)['decision']
    profile, reference = 'cpu-f32-wide-v1', 'torch-2.10.0-cpu-f32-eager'
    return {
        'LAYER0_POLICY': policy('one_block', 'hidden', 4096, 0.000003, False, 0.0, 0, 0.0, 0.0, profile, reference, layer0),
        'DECISION_POLICY': policy('replay', 'probability', 2, 0.0005, True, 0.0005, 1, 0.0005, 0.0005, profile, reference, request),
        'MASS_POLICY': policy('replay', 'probability', 1, 0.0005, False, 0.0, 0, 0.0, 0.0, profile, reference, request),
        'LAYER0_PSIONIC_VALUES': values(f32('layer0-token32-psionic.f32')),
        'LAYER0_TRANSFORMERS_VALUES': values(f32('layer0-token32-transformers.f32')),
        'DECISION_PSIONIC_VALUES': values([got['p_yes'], got['p_no']]),
        'DECISION_TRANSFORMERS_VALUES': values(ref['probabilities']),
        'MASS_PSIONIC_VALUES': values([got['slot_mass']]),
        'MASS_TRANSFORMERS_VALUES': values([ref['slot_mass']]),
        'MODEL': hashlib.sha256(listing).hexdigest(),
    }


if __name__ == '__main__':
    files = {OUT / 'qualify-vectors.coax': vectors(), OUT / 'elephant-evidence.coax': evidence()}
    if sys.argv[1:] == ['--frozen']:
        for key, value in frozen().items():
            print(key, value)
    elif sys.argv[1:] == ['--write']:
        for path, text in files.items():
            path.write_text(text)
    else:
        if sys.argv[1:]:
            raise SystemExit('usage: qualify_oracle.py [--write | --frozen]')
        for path, text in files.items():
            assert path.read_text() == text, f'{path} drifted'
        source = (ROOT / 'psionic/lib/qualify-elephant.coax').read_text()
        for key, value in frozen().items():
            assert f'YE_{key} :: "{value}";' in source, f'YE_{key} differs from its independent value'
        print('chapter 13 digest vectors and transcribed Elephant evidence match their sources')
