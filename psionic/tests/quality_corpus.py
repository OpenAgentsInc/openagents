#!/usr/bin/env python3
"""Validate the frozen chapter 12 held-out request set and emit it as a C table."""
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CORPUS = ROOT / 'psionic/fixtures/quality/heldout-v1.json'
# Frozen with the set: changing a label or a request needs a new name and digest.
SHA256 = '704ae5e25be82587946e4cd13a2effa4297c23f13aa2edee8bbd604d2f619286'
KINDS = {'choice': 0, 'noul': 1, 'score': 2}


def load():
    raw = CORPUS.read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    assert digest == SHA256, f'{CORPUS} changed: {digest}'
    data = json.loads(raw)
    assert data['schema'] == 1 and data['name'] == 'psionic-ch12-heldout-v1'
    items = data['items']
    assert len(items) == len({i['id'] for i in items}) == 12
    for item in items:
        kind = KINDS[item['kind']]
        options = item.get('options', [])
        assert kind != 1 or (not options and item['gold'] in (0, 1))
        assert kind != 0 or (1 <= len(options) <= 8 and len({o['name'] for o in options}) == len(options))
        assert kind != 2 or (1 <= len(options) <= 8 and all('name' not in o for o in options))
        count = 2 if kind == 1 else len(options)
        assert 0 <= item['gold'] < count
        abstain = item.get('abstain')
        assert abstain is None or (kind == 0 and 0 <= abstain < count)
        for text in [item['state'], item['question'], *[o.get('name', '') for o in options], *[o.get('description', '') for o in options]]:
            assert text.isascii() and all(c >= ' ' for c in text)
    return digest, items


def c_string(text):
    return 'NULL' if text is None else json.dumps(text)


def header(items):
    lines = ['/* Generated by psionic/tests/quality_corpus.py from heldout-v1.json. */',
             'typedef struct {const char *id;int kind;const char *state;const char *question;int count;const char *names[8];const char *descriptions[8];int gold;int abstain;} quality_item;',
             'static const quality_item quality_items[] = {']
    for item in items:
        options = item.get('options', [])
        names = ','.join(c_string(o.get('name', '')) for o in options) or 'NULL'
        descriptions = ','.join(c_string(o.get('description')) for o in options) or 'NULL'
        abstain = item.get('abstain')
        lines.append(f' {{{c_string(item["id"])},{KINDS[item["kind"]]},{c_string(item["state"])},{c_string(item["question"])},'
                     f'{len(options)},{{{names}}},{{{descriptions}}},{item["gold"]},{-1 if abstain is None else abstain}}},')
    lines.append('};')
    return '\n'.join(lines)


if __name__ == '__main__':
    digest, items = load()
    if sys.argv[1:] == ['--header']:
        print(header(items))
    else:
        assert not sys.argv[1:], 'usage: quality_corpus.py [--header]'
        print(f'held-out set psionic-ch12-heldout-v1: {len(items)} items, sha256 {digest}')
