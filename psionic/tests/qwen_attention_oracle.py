#!/usr/bin/env python3
"""Owned scalar reference for Qwen's split-half, partial rotary Q/K preparation."""
import math,struct,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
def f(x):return struct.unpack('<f',struct.pack('<f',x))[0]
def bits(x):return struct.unpack('<I',struct.pack('<f',x))[0]
def case():
    h,kv,d,rot=4,2,4,4
    qgate=[f(((i*7)%17-8)/5) for i in range(2*h*d)]
    key=[f(((i*3)%11-5)/4) for i in range(kv*d)]
    value=[f(((i*5)%13-6)/3) for i in range(kv*d)]
    qscale=[f((i-2)/5) for i in range(d)];kscale=[f((2-i)/6) for i in range(d)]
    rope=[f(math.cos(0.7)),f(math.sin(0.7)),f(math.cos(0.2)),f(math.sin(0.2))]
    def norm(a,scale):
        den=math.sqrt(sum(float(x)*x for x in a)/d+0.125)
        return [f(a[i]/den*(1+scale[i])) for i in range(d)]
    def rotate(a):
        a=a[:];half=rot//2
        for i in range(half):
            x,y=a[i],a[half+i];c,s=rope[2*i:2*i+2]
            a[i]=f(x*c-y*s);a[half+i]=f(y*c+x*s)
        return a
    queries=[];gates=[];keys=[]
    for head in range(h):
        row=qgate[head*2*d:(head+1)*2*d];queries+=rotate(norm(row[:d],qscale));gates+=row[d:]
    for head in range(kv):keys+=rotate(norm(key[head*d:(head+1)*d],kscale))
    return qgate+key+value+qscale+kscale+rope,queries+gates+keys+value

def attend_case():
    h,kv,d,tokens=4,2,4,3
    q=[f(((i*7)%19-9)/6) for i in range(h*d)]
    gate=[f(((i*3)%13-6)/5) for i in range(h*d)]
    key=[f(((i*11)%23-11)/8) for i in range(tokens*kv*d)]
    value=[f(((i*5)%17-8)/7) for i in range(tokens*kv*d)]
    mask=[1,0,1];out=[]
    for head in range(h):
        group=head//(h//kv)
        scores=[f(sum(q[head*d+i]*key[t*kv*d+group*d+i] for i in range(d))/math.sqrt(d)) for t in range(tokens)]
        maximum=max(scores[t] for t in range(tokens) if mask[t]);prob=[math.exp(scores[t]-maximum) if mask[t] else 0 for t in range(tokens)];den=sum(prob)
        for i in range(d):
            x=sum(prob[t]/den*value[t*kv*d+group*d+i] for t in range(tokens))
            out.append(f(x/(1+math.exp(-gate[head*d+i]))))
    return q+gate+key+value,mask,out

def fixture():
    inp,out=case()
    def array(name,values):return f'{name}:=[{len(values)}]f32.['+','.join(f'f32_from_bits(0x{bits(x):08x})' for x in values)+'];'
    first = '\n'.join(['// Generated by psionic/tests/qwen_attention_oracle.py.','#test "independent split-half partial rotary query and key fixture" {','    s:=QfShape.{heads=4,kv_heads=2,head_dim=4,rotary_dim=4,epsilon=0.125f32};','    '+array('input',inp),'    '+array('expected',out),f'    out:[{len(out)}]f32;',f'    r:=qf_prepare(s,input[..],out[..],false);#assert r.status==QfStatus.ok && r.written=={len(out)};',f'    for i:0..<{len(out)} {{#assert abs(out[i]-expected[i])<0.000002f32;}}','}'])+'\n'
    inp,mask,out=attend_case()
    second='\n'.join(['#test "independent grouped gated attention and mask fixture" {','    s:=QfShape.{heads=4,kv_heads=2,head_dim=4,rotary_dim=0,epsilon=0.125f32};','    '+array('input',inp),'    '+array('expected',out),'    mask:=[3]u8.[1,0,1];',f'    out:[{len(out)}]f32;scratch:[{len(out)}]f32;',f'    r:=qf_attend(s,3,input[..],mask[..],out[..],scratch[..],false);#assert r.status==QfStatus.ok && r.written=={len(out)};',f'    for i:0..<{len(out)} {{#assert abs(out[i]-expected[i])<0.000002f32;}}','}'])+'\n'
    return first+second
def header():
    prep_in,prep_out=case();att_in,mask,att_out=attend_case();lines=[]
    for name,values in [('prep_in',prep_in),('prep_out',prep_out),('att_in',att_in),('att_out',att_out)]:
        lines.append(f'static const float {name}[] = {{'+','.join(float(x).hex()+'f' for x in values)+'};')
    return '\n'.join(lines)+'\n'
