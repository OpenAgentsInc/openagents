#!/usr/bin/env python3
"""Owned scalar reference for Qwen offset RMS/residual/FFN layer tail."""
import math,struct,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
def f(x):return struct.unpack('<f',struct.pack('<f',x))[0]
def bits(x):return struct.unpack('<I',struct.pack('<f',x))[0]
def example():
    d,hidden=3,2;x=list(map(f,[1.25,-.5,.75]));att=list(map(f,[-.25,.125,.5]));scale=list(map(f,[.25,-.5,.125]));eps=f(.125)
    gate=list(map(f,[-.5,.25,.75, .5,-1,.25]));up=list(map(f,[.5,1,-.25, -.75,.25,.5]));down=list(map(f,[.25,-.5, -.75,.25, .5,1]))
    residual=[f(a+b) for a,b in zip(x,att)];div=math.sqrt(sum(a*a for a in residual)/d+eps)
    norm=[f(residual[i]/div*(1+scale[i])) for i in range(d)]
    def linear(w,rows,cols,a):return [f(sum(w[r*cols+c]*a[c] for c in range(cols))) for r in range(rows)]
    g=linear(gate,hidden,d,norm);u=linear(up,hidden,d,norm)
    product=[f(g[i]/(1+math.exp(-g[i]))*u[i]) for i in range(hidden)]
    z=linear(down,d,hidden,product);out=[f(residual[i]+z[i]) for i in range(d)]
    return (x,att,scale,gate,up,down,out)
def fixture():
    x,att,scale,gate,up,down,out=example()
    def floats(name,values):return f'{name}:=[{len(values)}]f32.['+','.join(f'f32_from_bits(0x{bits(v):08x})' for v in values)+'];'
    def raw(name,values):
        b=b''.join(struct.pack('<f',v) for v in values);return f'{name}:=[{len(b)}]u8.['+','.join(str(x) for x in b)+'];'
    lines=['// Generated by psionic/tests/qwen_block_oracle.py.','#test "independent offset RMS and dense feed-forward fixture" {']
    for name,value in [('x',x),('att',att),('scale',scale),('expected',out)]:lines.append('    '+floats(name,value))
    for name,value in [('gate',gate),('up',up),('down',down)]:lines.append('    '+raw(name,value))
    lines+=['    out:[3]f32;work:[20]f32;', '    r:=qb_finish(QmDtype.f32,3,2,0.125f32,x[..],att[..],scale[..],gate[..],up[..],down[..],out[..],work[..],false);', '    #assert r.status==QmStatus.ok && r.written==3;', '    for i:0..<3 {#assert abs(out[i]-expected[i])<0.000002f32;}', '}']
    return '\n'.join(lines)+'\n'
def header():
    x,att,scale,gate,up,down,out=example();lines=[]
    for name,values in [('fixture_x',x),('fixture_att',att),('fixture_scale',scale),('fixture_gate',gate),('fixture_up',up),('fixture_down',down),('fixture_out',out)]:
        lines.append(f'static const float {name}[] = {{'+','.join(float(v).hex()+'f' for v in values)+'};')
    return '\n'.join(lines)+'\n'
if __name__=='__main__':
    p=ROOT/'psionic/fixtures/hybrid/qwen-block-vectors.coax';value=fixture()
    if sys.argv[1:]==['--write']:p.write_text(value)
    else:
        assert p.read_text()==value,'fixture drifted'
        if sys.argv[1:]==['--header']:print(header(),end='')
        else:assert not sys.argv[1:]
