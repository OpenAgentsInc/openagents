"""Independent small causal Qwen full-attention decoder layer reference."""
import math,struct,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
def f(x):return struct.unpack('<f',struct.pack('<f',x))[0]
def bits(x):return struct.unpack('<I',struct.pack('<f',x))[0]
def case():
    d,ff,h,kv,hd=3,2,2,1,2;q=h*hd;k=kv*hd
    def series(n,o):return [f(((i*7+o)%19-9)/16) for i in range(n)]
    inorm=series(d,1);pnorm=series(d,2);qnorm=series(hd,3);knorm=series(hd,4)
    qw=series(2*q*d,5);kw=series(k*d,6);vw=series(k*d,7);mix=series(d*q,8);gate=series(ff*d,9);up=series(ff*d,10);down=series(d*ff,11)
    inputs=[list(map(f,[1.25,-.5,.75])),list(map(f,[-.25,1,.5])),list(map(f,[.75,.5,-1]))];ropes=[[1.,0.],[0.,1.],[-1.,0.]]
    def norm(x,w):
        div=math.sqrt(sum(float(y)*y for y in x)/len(x)+.125)
        return [f(x[i]/div*(1+w[i])) for i in range(len(x))]
    def linear(w,rows,cols,x):return [f(sum(w[r*cols+j]*x[j] for j in range(cols))) for r in range(rows)]
    def rotate(a,rope):return [f(a[0]*rope[0]-a[1]*rope[1]),f(a[1]*rope[0]+a[0]*rope[1])]
    keys=[];values=[];results=[]
    for pos,x in enumerate(inputs):
        normed=norm(x,inorm);qg=linear(qw,2*q,d,normed);ks=rotate(norm(linear(kw,k,d,normed),knorm),ropes[pos]);val=linear(vw,k,d,normed);keys.append(ks);values.append(val)
        heads=[]
        for head in range(h):
            group=head//(h//kv);row=qg[head*2*hd:(head+1)*2*hd];qq=rotate(norm(row[:hd],qnorm),ropes[pos]);g=row[hd:]
            scores=[f(sum(qq[j]*keys[t][group*hd+j] for j in range(hd))/math.sqrt(hd)) for t in range(pos+1)]
            mx=max(scores);p=[math.exp(v-mx) for v in scores];den=sum(p)
            for i in range(hd):heads.append(f(sum(p[t]/den*values[t][group*hd+i] for t in range(pos+1))/(1+math.exp(-g[i]))))
        att=linear(mix,d,q,heads);res=[f(x[i]+att[i]) for i in range(d)];after=norm(res,pnorm)
        g=linear(gate,ff,d,after);u=linear(up,ff,d,after);prod=[f(g[i]/(1+math.exp(-g[i]))*u[i]) for i in range(ff)]
        proj=linear(down,d,ff,prod);out=[f(res[i]+proj[i]) for i in range(d)];cache=[]
        for t in range(pos+1):cache+=keys[t]+values[t]
        results.append((out,cache))
    return locals()
