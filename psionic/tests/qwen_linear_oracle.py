"""Independent two-step full Qwen-style linear layer reference."""
import math,struct,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
def f(x):return struct.unpack('<f',struct.pack('<f',x))[0]
def bits(x):return struct.unpack('<I',struct.pack('<f',x))[0]
def case():
    d,ff,kh,vh,kd,vd=3,2,1,2,2,2;c=2*kh*kd+vh*vd;v=vh*vd;n=vh*kd*vd
    def series(count,offset=0):return [f(((i*7+offset)%19-9)/16) for i in range(count)]
    qkv=series(c*d,1);z=series(v*d,2);a=series(vh*d,3);b=series(vh*d,4);mixer=series(d*v,5)
    gate=series(ff*d,6);up=series(ff*d,7);down=series(d*ff,8)
    inorm=series(d,9);pnorm=series(d,10);conv=series(4*c,11);alog=series(vh,12);dt=series(vh,13);gamma=[f(.8),f(1.2)]
    history=series(c*3,14);state=series(n,15);initial_history=history[:];initial_state=state[:]
    inputs=[list(map(f,[1.25,-.5,.75])),list(map(f,[-.25,1,.5]))];results=[]
    def norm(x,w):
        div=math.sqrt(sum(float(y)*y for y in x)/len(x)+.125)
        return [f(x[i]/div*(1+w[i])) for i in range(len(x))]
    def linear(w,rows,cols,x):return [f(sum(w[r*cols+j]*x[j] for j in range(cols))) for r in range(rows)]
    for x in inputs:
        normed=norm(x,inorm);qkvv=linear(qkv,c,d,normed);zv=linear(z,v,d,normed);av=linear(a,vh,d,normed);bv=linear(b,vh,d,normed)
        mixed=[]
        for ch in range(c):
            window=history[ch*3:ch*3+3]+[qkvv[ch]];vv=sum(window[t]*conv[ch*4+t] for t in range(4));mixed.append(f(vv/(1+math.exp(-vv))));history[ch*3:ch*3+3]=window[1:]
        output=[];next_state=state[:]
        for head in range(vh):
            group=head//(vh//kh);q=mixed[group*kd:(group+1)*kd];key=mixed[kh*kd+group*kd:kh*kd+(group+1)*kd];value=mixed[2*kh*kd+head*vd:2*kh*kd+(head+1)*vd]
            qdiv=math.sqrt(sum(y*y for y in q)+1e-6)*math.sqrt(kd);kdiv=math.sqrt(sum(y*y for y in key)+1e-6)
            decay=math.exp(-math.exp(alog[head])*math.log1p(math.exp(av[head]+dt[head])));beta=1/(1+math.exp(-bv[head]));raw=[]
            for col in range(vd):
                memory=sum(state[(head*kd+row)*vd+col]*decay*key[row]/kdiv for row in range(kd));delta=(value[col]-memory)*beta
                for row in range(kd):
                    idx=(head*kd+row)*vd+col;next_state[idx]=f(state[idx]*decay+key[row]/kdiv*delta)
                raw.append(f(sum(q[row]/qdiv*next_state[(head*kd+row)*vd+col] for row in range(kd))))
            den=math.sqrt(sum(y*y for y in raw)/vd+.125)
            output += [f(raw[i]/den*gamma[i]*(zv[head*vd+i]/(1+math.exp(-zv[head*vd+i])))) for i in range(vd)]
        state=next_state;att=linear(mixer,d,v,output);res=[f(x[i]+att[i]) for i in range(d)];after=norm(res,pnorm)
        g=linear(gate,ff,d,after);u=linear(up,ff,d,after);product=[f(g[i]/(1+math.exp(-g[i]))*u[i]) for i in range(ff)];downout=linear(down,d,ff,product)
        final=[f(res[i]+downout[i]) for i in range(d)];results.append((final,history[:],state[:]))
    return locals()
