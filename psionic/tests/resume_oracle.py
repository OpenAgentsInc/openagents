#!/usr/bin/env python3
# Firm reason: 2 (independent oracle: recomputes our answer outside Coax, so it must not share our implementation)
"""Independent packing, dataset identity and tiny bigram/AdamW training stream.

Prints the values Coax checks pin (psionic/lib/data/pack.coax,
psionic/lib/checkpoint/resume.coax). --coax prints them as Coax constants.
"""
import argparse, hashlib, math, struct

MASK = (1 << 64) - 1
BOS, V = 15, 16

def bits(seed, counter):
    z = (seed + 0x9e3779b97f4a7c15 * (counter + 1)) & MASK
    z = ((z ^ (z >> 30)) * 0xbf58476d1ce4e5b9) & MASK
    z = ((z ^ (z >> 27)) * 0x94d049bb133111eb) & MASK
    return z ^ (z >> 31)

def fixture():
    lens, ids, docs, tokens = [3, 2, 4, 2, 3], [2, 5, 9, 11, 12], [], []
    splits = ['train', 'train', 'train', 'validation', 'test']
    for i in range(5):
        docs.append(dict(id=ids[i], split=splits[i], tokens=[i * 3 + j for j in range(lens[i])]))
    return docs

def order(docs, seed, epoch):
    out = [i for i, d in enumerate(docs) if d['split'] == 'train']
    for i in range(len(out) - 1, 0, -1):
        u = (bits(seed, epoch * 64 + i) >> 11) / 2.0 ** 53
        j = int(u * (i + 1))
        out[i], out[j] = out[j], out[i]
    return out

def stream(docs, seed):
    epoch = 0
    while True:
        for k in order(docs, seed, epoch):
            yield BOS
            yield from docs[k]['tokens']
        epoch += 1

def identity(docs):
    split = dict(train=0, validation=1, test=2)
    body = b''.join(struct.pack('<IBI', d['id'], split[d['split']], len(d['tokens'])) + bytes(d['tokens']) for d in docs)
    tag = hashlib.sha256(b'psionic.dataset.v1').digest()
    return hashlib.sha256(tag + tag + body).digest()

def train(docs, seed, steps, row, lr=0.1, b1=0.9, b2=0.99, eps=1e-8):
    """One AdamW group, no decay, over a 16x16 logit table from zero."""
    w = [0.0] * (V * V); m = [0.0] * (V * V); v = [0.0] * (V * V); s = stream(docs, seed); losses = []
    for t in range(1, steps + 1):
        r = [next(s) for _ in range(row)]
        pairs = [(a, b) for a, b in zip(r, r[1:]) if b != BOS]
        g = [0.0] * (V * V); loss = 0.0
        for a, b in pairs:
            top = max(w[a * V:(a + 1) * V]); e = [math.exp(x - top) for x in w[a * V:(a + 1) * V]]; z = sum(e)
            loss += math.log(z) + top - w[a * V + b]
            for j in range(V):
                g[a * V + j] += (e[j] / z - (1.0 if j == b else 0.0)) / len(pairs)
        losses.append(loss / len(pairs))
        c1, c2 = 1 - b1 ** t, 1 - b2 ** t
        for i in range(V * V):
            m[i] = b1 * m[i] + (1 - b1) * g[i]; v[i] = b2 * v[i] + (1 - b2) * g[i] * g[i]
            w[i] = w[i] - (lr / c1) * (m[i] / (math.sqrt(v[i]) / math.sqrt(c2) + eps))
    return losses, w

def tagged(tag, body):
    t = hashlib.sha256(tag).digest()
    return hashlib.sha256(t + t + body).digest()

def fixed_record():
    head = b'PSCK' + struct.pack('<HH', 1, 4) + b''.join(bytes([k]) * 32 for k in (1, 2, 3, 4, 5))
    head += struct.pack('<QQQQQQQ', 6, 0x0102030405060708, 2, 1, 3, 5, 1) + struct.pack('<I', 2)
    body = head + struct.pack('<6d', 0.5, -1.25, 0.25, 3.0, 1.0, 2.0)
    record = body + tagged(b'psionic.checkpoint.v1', body)
    pointer = b'PSCP' + struct.pack('<HHQ', 1, 0, 6) + record[-32:]
    return record, pointer + tagged(b'psionic.checkpoint-pointer.v1', pointer)

OUT = __import__('pathlib').Path(__file__).resolve().parents[1] / 'fixtures/resume/reference.coax'

def reference():
    docs = fixture()
    orders = {(7, 0): order(docs, 7, 0), (7, 3): order(docs, 7, 3), (8, 0): order(docs, 8, 0)}
    s = stream(docs, 7); rows = [next(s) for _ in range(48)]
    ident = identity(docs)
    losses, w = train(docs, 7, 12, 8)
    lines = ['// Generated by psionic/tests/resume_oracle.py --write. Independent values; do not edit.']
    for (seed, epoch), o in orders.items():
        lines.append(f"PK_ORDER_{seed}_{epoch} :: [3]int.[{','.join(map(str, o))}];")
    lines.append(f"PK_STREAM_7 :: [48]u8.[{','.join(map(str, rows))}];")
    lines.append(f"PK_IDENTITY :: [32]u8.[{','.join(map(str, ident))}];")
    wide = identity([dict(id=0x12345678, split='train', tokens=[i % 15 for i in range(300)])])
    lines.append(f"PK_IDENTITY_WIDE :: [32]u8.[{','.join(map(str, wide))}];")
    lines.append(f"RS_LOSSES :: [12]f64.[{','.join(repr(x) for x in losses)}];")
    lines.append(f"RS_WEIGHTS :: [256]f64.[{','.join(repr(x) for x in w)}];")
    model = tagged(b'psionic.model.v1', b'bigram vocab=16 logits=binary64 init=zero')
    tokenizer = tagged(b'psionic.tokenizer.v1', b'identity 0..14, BOS 15')
    optimizer = tagged(b'psionic.optimizer.v1', struct.pack('<QQ5d', 0, 256, 0.1, 0.9, 0.99, 1e-8, 0.0) + bytes([0, 0]))
    skip = tagged(b'psionic.optimizer.v1', struct.pack('<QQ5d', 0, 256, 0.1, 0.9, 0.99, 1e-8, 0.0) + bytes([0, 1]))
    for name, d in [('MODEL', model), ('TOKENIZER', tokenizer), ('OPTIMIZER', optimizer), ('OPTIMIZER_SKIP', skip)]:
        lines.append(f"RS_{name} :: [32]u8.[{','.join(map(str, d))}];")
    record, pointer = fixed_record()
    lines.append(f"CK_FIXED :: [{len(record)}]u8.[{','.join(map(str, record))}];")
    lines.append(f"CK_FIXED_POINTER :: [80]u8.[{','.join(map(str, pointer))}];")
    return '\n'.join(lines) + '\n', ident, losses

def main():
    a = argparse.ArgumentParser(); a.add_argument('--write', action='store_true'); a.add_argument('--header', action='store_true'); args = a.parse_args()
    text, ident, losses = reference()
    if args.write:
        OUT.parent.mkdir(parents=True, exist_ok=True); OUT.write_text(text); print('Captured', OUT.name); return
    assert OUT.read_text() == text, 'psionic/fixtures/resume/reference.coax does not reproduce'
    if args.header:
        print(f"static const double rs_losses[]={{{','.join(repr(x) for x in losses)}}};")
    else:
        print(f'resume reference reproduces: dataset {ident.hex()[:16]}, loss {losses[0]:.6f} -> {losses[-1]:.6f} over 12 steps')

if __name__ == '__main__':
    main()
