#!/usr/bin/env python3
# Firm reason: 2 (independent exact-rational discrete-motion oracle, never shipped).
"""Freeze illustrative servo traces without importing product code."""
from fractions import Fraction as F
from pathlib import Path
import json
import sys

ROOT = Path(__file__).resolve().parents[3]
PARAMS = ['inertia', 'kp', 'kd', 'viscous', 'coulomb', 'effort', 'voltage', 'step', 'play']
COLUMNS = ['accepted_target', 'applied_target', 'position', 'rate', 'output_position',
           'output_rate', 'proportional', 'derivative', 'requested', 'limit',
           'delivered', 'passive', 'net', 'acceleration', 'clipped', 'cursor', 'steps']

def traces():
    base = ['.01', '2', '0', '0', '0', '.15', '1', '.002', '0']
    cases = [('cap', base, 0, '0', ['.1'] * 5 + ['-.1'] * 8 + ['0'] * 3),
             ('delay_play', base[:-1] + ['.00005'], 2, '0', ['.1'] * 5 + ['-.1'] * 8 + ['0'] * 3),
             ('losses', ['.01', '2', '.03', '.02', '.001', '.15', '.5', '.002', '.0001'],
              2, '-.2', ['.1'] * 7 + ['-.1'] * 9 + ['0'] * 8)]
    results = []
    for name, values, delay, rate, commands in cases:
        inertia, kp, kd, visc, coul, cap, volts, dt, gap = map(F, values)
        q, v, y = F(0), F(rate), F(0)
        queue, cursor, rows = [F(0)] * delay, 0, []
        for step, incoming in enumerate(map(F, commands), 1):
            target = incoming
            if delay:
                target, queue[cursor] = queue[cursor], incoming
                cursor = (cursor + 1) % delay
            p, d = kp * (target - q), -kd * v
            requested, limit = p + d, cap * volts
            delivered = max(-limit, min(limit, requested))
            passive = -visc * v - coul * ((v > 0) - (v < 0))
            net = delivered + passive
            acceleration = net / inertia
            v += dt * acceleration
            q += dt * v
            previous = y
            y = max(q - gap, min(q + gap, y))
            rows.append([incoming, target, q, v, y, (y - previous) / dt, p, d,
                         requested, limit, delivered, passive, net, acceleration,
                         F(delivered != requested), F(cursor), F(step)])
        results.append(dict(name=name, parameters=values, delay=delay, initial_rate=rate,
                            rows=[[str(x) for x in row] for row in rows]))
    assert results[0]['rows'][0][2:4] == ['3/50000', '3/100']
    assert [r[1] for r in results[1]['rows'][:3]] == ['0', '0', '1/10']
    return results

def artifacts():
    cases = traces()
    doc = dict(profile='scalar-servo-play-f64-v1', provenance='illustrative exact-rational equations; no measured motor',
               tolerance=dict(atol=2e-12, rtol=2e-12), parameters=PARAMS, columns=COLUMNS, cases=cases)
    coax = '// Generated by the independent Fraction oracle; frozen before the product implementation.\n'
    for i, case in enumerate(cases):
        rows = case['rows']
        coax += f'RSA_REFERENCE_{i} :: [{len(rows)}][17]f64.[\n'
        coax += ',\n'.join('  [17]f64.[' + ','.join(repr(float(F(x))) for x in row) + ']' for row in rows) + '\n];\n'
    return [(ROOT/'psionic/fixtures/robotics/actuator/reference.json', json.dumps(doc, indent=2)+'\n'),
            (ROOT/'psionic/lib/robotics/actuator-golden.coax', coax)]

if __name__ == '__main__':
    assert sys.argv[1:] in ([], ['--write'])
    for path, content in artifacts():
        if sys.argv[1:] == ['--write'] and not path.exists():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
        assert path.read_text() == content, f'frozen actuator reference differs: {path}'
    print('actuator Fraction oracle: 56 rows, all 17 columns match')
