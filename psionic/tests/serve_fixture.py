#!/usr/bin/env python3
"""Generate the owned chapter-16 toy decision model: small nonzero BF16 weights.

The model has the Elephant layer schedule (three linear layers, then one full
attention layer) at width 2, a 64-dimensional rotary head and the 268-entry
chapter-5 toy vocabulary. It is deterministic teaching data, not a trained model.
"""
import hashlib,json,math,struct,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]/'psionic/fixtures/models/serve'
VOCAB=268

def bf16(x):
 return struct.pack('<f',x)[2:4]

def values(seed,count,scale):
 state=seed*2654435761%4294967296 or 1;out=[]
 for _ in range(count):
  state=(state*1664525+1013904223)%4294967296
  out.append(((state>>16)%33-16)/scale)
 return out

def build():
 tensors=[]
 for layer in range(4):
  prefix=f'model.language_model.layers.{layer}.'
  entries=[('input_layernorm.weight',[2]),('post_attention_layernorm.weight',[2])]
  if layer!=3:
   entries += [('linear_attn.conv1d.weight',[3,1,4]),('linear_attn.A_log',[1]),('linear_attn.dt_bias',[1]),('linear_attn.norm.weight',[1]),('linear_attn.in_proj_qkv.weight',[3,2]),('linear_attn.in_proj_z.weight',[1,2]),('linear_attn.in_proj_a.weight',[1,2]),('linear_attn.in_proj_b.weight',[1,2]),('linear_attn.out_proj.weight',[2,1]),('mlp.gate_proj.weight',[2,2]),('mlp.up_proj.weight',[2,2]),('mlp.down_proj.weight',[2,2])]
  else:
   entries += [('self_attn.q_norm.weight',[64]),('self_attn.k_norm.weight',[64]),('self_attn.q_proj.weight',[128,2]),('self_attn.k_proj.weight',[64,2]),('self_attn.v_proj.weight',[64,2]),('self_attn.o_proj.weight',[2,64]),('mlp.gate_proj.weight',[2,2]),('mlp.up_proj.weight',[2,2]),('mlp.down_proj.weight',[2,2])]
  tensors += [(prefix+name,dims) for name,dims in entries]
 tensors += [('model.language_model.embed_tokens.weight',[VOCAB,2]),('model.language_model.norm.weight',[2]),('lm_head.weight',[VOCAB,2])]
 assert len(tensors)==56
 header={};offset=0;payload=b''
 for index,(name,dims) in enumerate(tensors):
  count=math.prod(dims);scale=16 if 'embed' in name or 'lm_head' in name else 64
  payload+=b''.join(bf16(v) for v in values(index+1,count,scale))
  size=2*count;header[name]={'dtype':'BF16','shape':dims,'data_offsets':[offset,offset+size]};offset+=size
 raw=json.dumps(header,separators=(',',':')).encode();raw+=b' '*((-len(raw))%8);data=struct.pack('<Q',len(raw))+raw+payload
 specs=[]
 for name,dims in tensors:
  padded=dims+[0]*(5-len(dims));specs.append('P5Spec.{name='+json.dumps(name)+',shape=P5Shape.{rank='+str(len(dims))+',dims=[5]int.['+','.join(map(str,padded))+']}}')
 coax='// Generated by psionic/tests/serve_fixture.py.\nSV_TOY_FILE :: ['+str(len(data))+']u8.['+','.join(map(str,data))+'];\nSV_TOY_SHA :: "'+hashlib.sha256(data).hexdigest()+'";\nSV_TOY_SPECS :: [56]P5Spec.['+','.join(specs)+'];\n'
 return data,coax

def main():
 data,coax=build();files={ROOT/'toy.coax':coax.encode()}
 if sys.argv[1:]==['--write']:
  for path,value in files.items():path.write_bytes(value)
 else:
  assert not sys.argv[1:]
  for path,value in files.items():assert path.read_bytes()==value,f'{path} drifted'
  print(f'serve toy fixture: {len(data)} bytes, sha256 {hashlib.sha256(data).hexdigest()}')
if __name__=='__main__':main()
