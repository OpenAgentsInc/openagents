#!/usr/bin/env python3
# Firm reason: 2 (independent oracle: recomputes our answer outside Coax, so it must not share our implementation)
"""Independent oracle for the /v1/systemone protobuf wire.

Uses the official Python protobuf runtime (proto/tools/requirements.txt, run
with PROTO_PYTHON) and the committed descriptor proto/descriptors/systemone.pb,
not the Coax codecs. Tooling only.

  --coax              Coax checks: request bytes and the NIP-DEC JSON each must become
  --update            rewrite those checks between the markers in psionic/lib/serve-proto.coax
  --header            a C header of JSON answer bodies for psionic/tests/serve_proto.c
  --check-answers F   decode the native harness's protobuf answers in F and compare
"""
import json
import pathlib
import sys

from google.protobuf import descriptor_pb2, descriptor_pool, message_factory

ROOT = pathlib.Path(__file__).resolve().parents[2]
SET = descriptor_pb2.FileDescriptorSet.FromString((ROOT / "proto/descriptors/systemone.pb").read_bytes())
POOL = descriptor_pool.DescriptorPool()
for f in SET.file:
    POOL.Add(f)
PKG = "openagents.decision.v1alpha1."
Request = message_factory.GetMessageClass(POOL.FindMessageTypeByName(PKG + "SystemOneRequest"))
Response = message_factory.GetMessageClass(POOL.FindMessageTypeByName(PKG + "SystemOneResponse"))
Entry = message_factory.GetMessageClass(POOL.FindMessageTypeByName(PKG + "EntryType"))
TYPES = {"noul": 1, "choice": 2, "score": 3}


def entry(value, e=None):
    """A Python value as an EntryType (dict order preserved)."""
    e = e if e is not None else Entry()
    if value is None:
        e.null.SetInParent()
    elif isinstance(value, bool):
        e.boolean = value
    elif isinstance(value, (int, float)):
        e.number = float(value)
    elif isinstance(value, str):
        e.text = value
    elif isinstance(value, list):
        e.array.SetInParent()
        for item in value:
            entry(item, e.array.items.add())
    else:
        e.object.SetInParent()
        for key, item in value.items():
            field = e.object.fields.add()
            field.key = key
            entry(item, field.value)
    return e


def request(model=None, state=None, questions=()):
    r = Request()
    if model is not None:
        r.model = model
    if state is not None:
        entry(state, r.state)
    for qid, kind, instructions, criteria in questions:
        q = r.questions.add()
        q.id = qid
        q.question.type = TYPES.get(kind, 0)
        if instructions is not None:
            entry(instructions, q.question.instructions)
        if criteria is not None:
            entry(criteria, q.question.criteria)
    return r


def as_json(value):
    return json.dumps(value, separators=(",", ":"), ensure_ascii=False)


def expected(model, state, questions):
    """The NIP-DEC body the transcoder must write: absent fields left out, in order."""
    parts = []
    if model is not None:
        parts.append('"model":' + as_json(model))
    if state is not None:
        parts.append('"state":' + as_json(state))
    qs = []
    for qid, kind, instructions, criteria in questions:
        q = '"type":' + as_json(kind)
        if instructions is not None:
            q += ',"instructions":' + as_json(instructions)
        if criteria is not None:
            q += ',"criteria":' + as_json(criteria)
        qs.append(as_json(qid) + ":{" + q + "}")
    parts.append('"questions":{' + ",".join(qs) + "}")
    return "{" + ",".join(parts) + "}"


CASES = [
    ("a noul question", "psionic-toy", "go", [("q", "noul", None, None)]),
    ("choice criteria keep their order", "psionic-toy", "s",
     [("c", "choice", "pick one", {"zeta": None, "alpha": "A", "mid": {"n": [1, -2, True]}})]),
    ("score levels and an object state", "elephant-1", {"user": "x", "turn": 3},
     [("s", "score", None, ["low", {"x": [1]}, None]), ("n", "noul", {"note": "quote \" and back\\slash"}, None)]),
    ("no model: JSON's refusal applies", None, "go", [("q", "noul", None, None)]),
    ("no state: JSON's refusal applies", "m", None, [("q", "noul", None, None)]),
    ("large integers stay exact", "m", {"big": 9007199254740992, "neg": -9007199254740992, "zero": 0}, [("q", "noul", None, None)]),
]
REFUSALS = [
    ("a fractional number is unsupported", request("m", {"x": 0.5}, [("q", "noul", None, None)]), "unsupported_input"),
    ("an integer past 2^53 is unsupported", request("m", {"x": 2.0 ** 54}, [("q", "noul", None, None)]), "unsupported_input"),
    ("an unspecified question type is invalid", request("m", "s", [("q", "none", None, None)]), "invalid_request"),
]


def coax_bytes(b):
    return "[%d]u8.[%s]" % (len(b), ",".join(str(x) for x in b)) if b else "[1]u8.[0]"


def coax_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def coax():
    lines = ["// Generated by psionic/tests/serve_proto_oracle.py --coax with the official protobuf runtime."]
    for i, (name, model, state, questions) in enumerate(CASES):
        wire = request(model, state, questions).SerializeToString()
        lines.append('#test "independent protobuf request %d: %s" {' % (i, name))
        lines.append("    wire:=%s;out:[4096]u8;" % coax_bytes(wire))
        lines.append("    t:=sp_request_json(wire[0..<%d],out[..]);" % len(wire))
        lines.append("    #assert t.code==SvCode.none && cast(string)out[0..<t.at]==%s;" % coax_string(expected(model, state, questions)))
        lines.append("}")
    for i, (name, r, code) in enumerate(REFUSALS):
        wire = r.SerializeToString()
        lines.append('#test "independent protobuf refusal %d: %s" {' % (i, name))
        lines.append("    wire:=%s;out:[4096]u8;" % coax_bytes(wire))
        lines.append("    #assert sp_request_json(wire[0..<%d],out[..]).code==SvCode.%s;" % (len(wire), code))
        lines.append("}")
    def http(wire, accept=True):
        head = ("POST /v1/systemone HTTP/1.1\r\nContent-Type: application/x-protobuf\r\n"
                + ("Accept: application/x-protobuf\r\n" if accept else "")
                + "Content-Length: %d\r\n\r\n" % len(wire)).encode()
        return head + wire
    good = http(request("psionic-toy", "go", [("q", "noul", None, None)]).SerializeToString())
    half = http(request("psionic-toy", {"x": 0.5}, [("q", "noul", None, None)]).SerializeToString(), accept=False)
    lines.append('#test "independent protobuf HTTP request through the toy engine\'s slot" {')
    lines.append("    toy:[1]SvToy;e:=sv_test_toy(toy[..],64);storage:[1]SvTestPools;pools:=sv_test_pools(storage[..]);")
    lines.append("    limits:=SvLimits.{read_ms=100,decide_ms=1000};s:=sv_accept(SvSlot.{},limits,10).slot;scratch:[300000]u8;")
    lines.append("    raw:=%s;n:=%d;" % (coax_bytes(good), len(good)))
    lines.append("    part:=sp_bytes(s,limits,e,pools,cast(string)raw[0..<n-1],raw[0..<n-1],scratch[..],50);")
    lines.append("    #assert part.step.action==SvAction.read && part.proto_out;")
    lines.append("    d:=sp_bytes(s,limits,e,pools,cast(string)raw[0..<n],raw[0..<n],scratch[..],50);")
    lines.append("    #assert d.step.action==SvAction.decide && d.proto_out && d.step.request.questions==1 && d.step.request.model==\"psionic-toy\";")
    lines.append("    #assert d.step.slot.phase==SvPhase.deciding && d.step.slot.epoch==1 && d.step.slot.deadline==1050;")
    lines.append("    late:=sp_bytes(s,limits,e,pools,cast(string)raw[0..<n],raw[0..<n],scratch[..],110);")
    lines.append("    #assert late.step.action==SvAction.refuse && late.step.code==SvCode.request_timeout;")
    lines.append("    #assert sp_bytes(s,limits,e,pools,cast(string)raw[0..<n],raw[0..<n-1],scratch[..],50).step.code==SvCode.internal;")
    lines.append("    #assert sp_bytes(s,limits,e,pools,cast(string)raw[0..<n],raw[0..<n],scratch[0..<16],50).step.code==SvCode.internal;")
    lines.append("    bad:=%s;m:=%d;" % (coax_bytes(half), len(half)))
    lines.append("    r:=sp_bytes(s,limits,e,pools,cast(string)bad[0..<m],bad[0..<m],scratch[..],50);")
    lines.append("    #assert r.step.action==SvAction.refuse && r.step.code==SvCode.unsupported_input && !r.proto_out;")
    lines.append("    // A JSON request takes chapter 16's path unchanged.")
    lines.append('    j:="POST /v1/systemone HTTP/1.1\\r\\nContent-Length: 70\\r\\n\\r\\n{\\"model\\":\\"psionic-toy\\",\\"state\\":\\"go\\",\\"questions\\":{\\"q\\":{\\"type\\":\\"noul\\"}}}";')
    lines.append("    jb:[256]u8;jn:=json_raw(jb[..],0,j);k:=sp_bytes(s,limits,e,pools,cast(string)jb[0..<jn],jb[0..<jn],scratch[..],50);")
    lines.append("    #assert k.step.action==SvAction.decide && !k.proto_out && k.step.request.questions==1;")
    lines.append("}")
    lines.append('#test "independent protobuf refusal: bytes that are not a request" {')
    lines.append("    junk:=[3]u8.[255,255,255];out:[64]u8;#assert sp_request_json(junk[..],out[..]).code==SvCode.malformed;")
    lines.append("}")
    return "\n".join(lines) + "\n"


ANSWERS = [
    '{"model":"psionic-toy","answers":{"b":{"type":"choice","choice":"alpha","confidence":0.4,"probabilities":{"zeta":0.4,"alpha":0.4,"mid":0.2}},'
    '"n":{"type":"noul","noul":0.75},"s":{"type":"score","score":1.25,"confidence":0.5,"selected":"1","legend":{"0":"low","1":{"x":[1]},"2":null},'
    '"probabilities":{"0":0.125,"1":0.5,"2":0.375}}},"usage":null,"service":{"door":"psionic","version":"psionic-serve-v1",'
    '"identity":"psionic-toy@sha256:b6680707750842c489bad8a5524bb1b1393ff04f6917b72cf49c2cf87d633573"},"latency_ms":17}',
    '{"model":"elephant-1","answers":{"q":{"type":"noul","noul":0.757196285}},"usage":null,"service":{"door":"psionic",'
    '"version":"psionic-serve-v1","identity":"elephant-1@sha256:682f0234"},"latency_ms":147}',
]


def header():
    lines = ["/* Generated by psionic/tests/serve_proto_oracle.py --header; do not edit. */",
             "static const char *const answer_bodies[] = {"]
    for body in ANSWERS:
        lines.append("  " + json.dumps(body) + ",")
    lines.append("};")
    return "\n".join(lines)


def legend_value(e):
    which = e.WhichOneof("value")
    if which in (None, "null"):
        return None
    if which == "object":
        return {f.key: legend_value(f.value) for f in e.object.fields}
    if which == "array":
        return [legend_value(i) for i in e.array.items]
    if which == "number":
        return int(e.number) if e.number == int(e.number) else e.number
    return getattr(e, which)


def check_answers(path):
    lines = pathlib.Path(path).read_text().split()
    assert len(lines) == len(ANSWERS), "one protobuf answer per JSON body"
    for body, hexed in zip(ANSWERS, lines):
        want = json.loads(body)
        r = Response.FromString(bytes.fromhex(hexed))
        assert r.model == want["model"] and r.latency_ms == want["latency_ms"] and r.HasField("usage_null")
        assert (r.service.door, r.service.version, r.service.identity) == tuple(want["service"][k] for k in ("door", "version", "identity"))
        assert [a.id for a in r.answers] == list(want["answers"])
        for a in r.answers:
            w = want["answers"][a.id]
            kind = a.answer.WhichOneof("answer")
            assert kind == w["type"]
            if kind == "noul":
                assert a.answer.noul.noul == w["noul"]
            elif kind == "choice":
                c = a.answer.choice
                assert c.choice == w["choice"] and c.confidence == w["confidence"]
                assert [(p.id, p.probability) for p in c.probabilities] == list(w["probabilities"].items())
            else:
                s = a.answer.score
                assert s.score == w["score"] and s.confidence == w["confidence"] and a.answer.selected == w["selected"]
                assert [(p.id, p.probability) for p in s.probabilities] == list(w["probabilities"].items())
                assert [(f.key, legend_value(f.value)) for f in s.legend] == list(w["legend"].items())
    print("serve protobuf oracle: %d answers decode to their JSON, value for value" % len(ANSWERS))


def main():
    if sys.argv[1:] == ["--coax"]:
        sys.stdout.write(coax())
    elif sys.argv[1:] == ["--update"]:
        target = ROOT / "psionic/lib/serve-proto.coax"
        text = target.read_text()
        begin, end = "// begin generated vectors\n", "// end generated vectors\n"
        head, rest = text.split(begin)
        _, tail = rest.split(end)
        target.write_text(head + begin + coax() + end + tail)
    elif sys.argv[1:] == ["--header"]:
        print(header())
    elif len(sys.argv) == 3 and sys.argv[1] == "--check-answers":
        check_answers(sys.argv[2])
    else:
        print("serve protobuf oracle: %d request cases, %d refusals, %d answers" % (len(CASES), len(REFUSALS), len(ANSWERS)))


if __name__ == "__main__":
    main()
