#!/usr/bin/env python3
"""Independent oracle for chapter 172: soft attention reads at a given sharpness
and number format, with exact arithmetic in place of floating-point sums.

Written from the chapter's description, not translated from the Coax unit.
Rounding to binary32 uses struct; bfloat16 rounds binary32 bits to nearest
even; exponentials and sums use Decimal at 60 digits. Tooling only:
`--header` prints a C header for psionic/tests/soft.c.
"""
import decimal
import random
import struct
import sys

decimal.getcontext().prec = 60
D = decimal.Decimal
FORMATS = ["f64", "f32", "bf16"]


def fmt(x, f):
    x = float(x)
    if f == "f64":
        return x
    bits = struct.unpack("<I", struct.pack("<f", x))[0]
    if f == "bf16":
        bits = (bits + 0x7FFF + ((bits >> 16) & 1)) & 0xFFFF0000
    return struct.unpack("<f", struct.pack("<I", bits))[0]


def soft_read(keys, values, q, beta, f):
    """Returns (value, mixed, exact) or None when the key was never written."""
    n = len(keys)
    best = None
    for t, k in enumerate(keys):
        if k == q:
            best = t  # the latest write to q is the hard-max answer
    if best is None:
        return None
    def logit(t):
        score = (2 * keys[t] * q - keys[t] * keys[t]) * (n + 1) + t
        return fmt(beta * fmt(score, f), f)
    top = D(logit(best))
    e = [(D(logit(t)) - top).exp() for t in range(n)]
    z = sum(e)
    mixed = sum(D(fmt(e[t] / z, f)) * D(fmt(values[t], f)) for t in range(n))
    value = int((mixed + D("0.5")).to_integral_value(decimal.ROUND_FLOOR)) if mixed >= 0 else \
        -int((D("0.5") - mixed).to_integral_value(decimal.ROUND_FLOOR))
    return value, mixed, value == values[best]


def scan(near, k, v, beta, f, cap):
    """(last exact length, first failing length or 0) for one adversarial stream."""
    n, until = 1, 0
    while n <= cap:
        if near:
            keys, values = [k] + [k - 1] * (n - 1), [v] + [-v] * (n - 1)
        else:
            keys, values = [k] * n, [-v] * (n - 1) + [v]
        if not soft_read(keys, values, k, beta, f)[2]:
            return until, n
        until, n = n, n * 2
    return until, 0


def read_cases():
    rng = random.Random(172)
    cases = []
    while len(cases) < 160:
        f = rng.choice(FORMATS)
        n = rng.randint(1, 24)
        span = rng.choice([3, 16, 300])
        keys = [rng.randint(-span, span) for _ in range(n)]
        values = [rng.randint(-1000, 1000) for _ in range(n)]
        q = rng.choice(keys)
        beta = rng.choice([0.5, 3.0, 9.3, 12.0, 25.0])
        r = soft_read(keys, values, q, beta, f)
        # Skip reads within 1e-6 of a rounding boundary: there the binary64
        # sums of the unit and the exact sums here may honestly disagree.
        frac = abs(r[1] - r[1].to_integral_value(decimal.ROUND_FLOOR) - D("0.5"))
        if frac < D("0.000001"):
            continue
        cases.append((f, keys, values, q, beta, r))
    return cases


# (largest key, largest value, sharpness above or below the bound, format)
LIMITS = [(16, 1000, 1, "f64"), (16, 1000, 1, "f32"), (256, 1000, 1, "f32"), (4096, 1000, 1, "f32"),
          (16, 1000, 1, "bf16"), (16, 1000, -1, "f64"), (16, 1, None, "f64")]


def header():
    lines = ["/* Generated by psionic/tests/soft_oracle.py; do not edit. */",
             "#include <stdint.h>",
             "typedef struct { int format; int n; int64_t key[24]; int64_t value[24]; int64_t q; double beta;",
             "  int64_t expect; double mixed; int exact; } soft_case;",
             "static const soft_case soft_cases[] = {"]
    for f, keys, values, q, b, (value, mixed, exact) in read_cases():
        lines.append("  {%d, %d, {%s}, {%s}, %dLL, %r, %dLL, %r, %d}," % (
            FORMATS.index(f), len(keys), ",".join("%dLL" % k for k in keys),
            ",".join("%dLL" % v for v in values), q, b, value, float(mixed), int(exact)))
    lines.append("};")
    lines.append("typedef struct { int64_t k; int64_t v; double beta; int format; int64_t same_until; int64_t same_failure;")
    lines.append("  int64_t near_until; int64_t near_failure; } soft_limit;")
    lines.append("static const soft_limit soft_limits[] = {")
    for k, v, shift, f in LIMITS:
        b = 0.4 if shift is None else float(D(4 * v).ln()) + shift
        same, near = scan(False, k, v, b, f, 4096), scan(True, k, v, b, f, 4096)
        lines.append("  {%d, %d, %r, %d, %d, %d, %d, %d}," % (k, v, b, FORMATS.index(f), *same, *near))
    lines.append("};")
    return "\n".join(lines)


def main():
    if sys.argv[1:] == ["--header"]:
        print(header())
        return
    cases = read_cases()
    exact = sum(1 for c in cases if c[5][2])
    print("soft oracle: %d reads (%d exact, %d not)" % (len(cases), exact, len(cases) - exact))


if __name__ == "__main__":
    main()
