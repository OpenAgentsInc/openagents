#!/usr/bin/env python3
"""Chapter 71's independent reference: no reverse mode at all.

Seeded random programs over the tape's operations are evaluated in 60-digit
decimal arithmetic, and each parameter's derivative is a central difference
with step 1e-25, whose error is far below binary64 rounding. A program is kept
only if every operation stays well inside its domain (no division by or log of
a number near zero, no exp past 20) and binary64 evaluation agrees with the
decimal one to 1e-12 relative at every node, so differences measure the tape,
not cancellation. `--header` writes the C expectations the native harness
compares.
"""
import math
import random
import sys
from decimal import Decimal, getcontext

getcontext().prec = 60
OPS = ["param", "constant", "add", "sub", "mul", "div", "neg", "square", "exp", "log", "tanh", "sigmoid", "softplus"]
ARITY = {"param": 0, "constant": 0, "add": 2, "sub": 2, "mul": 2, "div": 2}


def arity(op):
    return ARITY.get(op, 1)


def d_exp(x):
    return x.exp()


def apply(op, a, b, exp, log):
    if op == "add":
        return a + b
    if op == "sub":
        return a - b
    if op == "mul":
        return a * b
    if op == "div":
        return a / b
    if op == "neg":
        return -a
    if op == "square":
        return a * a
    if op == "exp":
        return exp(a)
    if op == "log":
        return log(a)
    if op == "tanh":
        e = exp(-2 * abs(a))
        t = (1 - e) / (1 + e)
        return t if a >= 0 else -t
    if op == "sigmoid":
        return 1 / (1 + exp(-a)) if a >= 0 else exp(a) / (1 + exp(a))
    # softplus
    return max(a, 0 * a) + log(1 + exp(-abs(a)))


def run(nodes, params, exact):
    """Values of every node, or None when an operation is too near its domain's edge."""
    exp = d_exp if exact else math.exp
    log = (lambda v: v.ln()) if exact else math.log
    v = []
    for op, a, b, slot, value in nodes:
        if op == "param":
            x = params[slot]
        elif op == "constant":
            x = Decimal(value) if exact else value
        else:
            va, vb = v[a], (v[b] if arity(op) == 2 else None)
            if op == "div" and abs(vb) < 0.05:
                return None
            if op == "log" and va < 0.05:
                return None
            if op == "exp" and va > 20:
                return None
            x = apply(op, va, vb, exp, log)
        if abs(x) > 1e6:
            return None
        v.append(x)
    return v


def program(rng):
    """2 to 4 parameters, then 6 to 26 operations; the last node is the result."""
    k = rng.randint(2, 4)
    nodes = [("param", 0, 0, s, 0.0) for s in range(k)]
    nodes.append(("constant", 0, 0, 0, rng.choice([0.5, 2.0, -1.5, 3.0])))
    for _ in range(rng.randint(6, 26)):
        op = rng.choice(OPS[2:])
        n = len(nodes)
        pick = lambda: max(0, n - 1 - int(rng.expovariate(0.4)))
        nodes.append((op, pick(), pick() if arity(op) == 2 else 0, 0, 0.0))
    params = [round(rng.uniform(-2, 2), 6) for _ in range(k)]
    return nodes, params


def case(rng):
    while True:
        nodes, params = program(rng)
        exact = [Decimal(repr(p)) for p in params]
        dv = run(nodes, exact, True)
        fv = run(nodes, params, False)
        if dv is None or fv is None:
            continue
        if any(abs(float(d) - f) > 1e-12 * max(1.0, abs(float(d))) for d, f in zip(dv, fv)):
            continue
        h = Decimal("1e-25")
        grads = []
        for s in range(len(params)):
            up, down = list(exact), list(exact)
            up[s] += h
            down[s] -= h
            vu, vd = run(nodes, up, True), run(nodes, down, True)
            grads.append(float((vu[-1] - vd[-1]) / (2 * h)))
        # Keep programs whose result depends on some parameter, with gradients in range.
        if max(abs(g) for g in grads) > 1e6 or max(abs(g) for g in grads) < 1e-3:
            continue
        return nodes, params, float(dv[-1]), grads


def header(count, seed):
    rng = random.Random(seed)
    cases = [case(rng) for _ in range(count)]
    out = ["/* Generated by psionic/tests/tape_oracle.py --header. Do not edit. */",
           "#include <stdint.h>",
           "typedef struct { int n, params; int op[32], a[32], b[32], slot[32]; double value[32]; double p[4]; double result; double grad[4]; } tape_case;",
           f"static const tape_case tape_cases[{count}] = {{"]
    for nodes, params, result, grads in cases:
        cols = list(zip(*nodes))
        out.append("  {%d,%d,{%s},{%s},{%s},{%s},{%s},{%s},%r,{%s}}," % (
            len(nodes), len(params),
            ",".join(str(OPS.index(o)) for o in cols[0]), ",".join(map(str, cols[1])), ",".join(map(str, cols[2])),
            ",".join(map(str, cols[3])), ",".join(repr(float(v)) for v in cols[4]),
            ",".join(repr(p) for p in params), result, ",".join(repr(g) for g in grads)))
    out.append("};")
    print("\n".join(out))


if __name__ == "__main__":
    if "--header" in sys.argv:
        header(300, 71)
    else:
        rng = random.Random(71)
        sizes = [len(case(rng)[0]) for _ in range(300)]
        print(f"300 programs, {min(sizes)} to {max(sizes)} nodes, {sum(sizes)} in all")
