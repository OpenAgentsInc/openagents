#!/usr/bin/env python3
"""Chapter 137's domain corpus: Coax source, pinned by revision.

Tooling only; never shipped. For each chapter in CHAPTERS of psionic/book at
REVISION, in order, it reads the chapter's psionic/lib/*.coax sources named
in psionic/book/chapters.json at that revision (a file listed by an earlier
chapter is skipped), keeps printable ASCII and newlines, and makes one
document per file: the file's leading paragraphs (blank-line separated) up
to DOC_BYTES bytes, a paragraph longer than that cut at its last whole line.
A paragraph already in chapter 128's corpus or earlier in this one is
dropped. A document's source is its chapter number, so the domain split
follows chapter 128's rule: sources divisible by 8 are held out. It prints
psionic/fixtures/continue/domain.coax.
"""
import json
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import pretrain_corpus  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
REVISION = pretrain_corpus.REVISION
CHAPTERS = range(1, 41)
DOC_BYTES = 3600


def show(path):
    return subprocess.run(["git", "show", f"{REVISION}:{path}"], cwd=ROOT, capture_output=True, text=True, check=True).stdout


def sources():
    chapters = json.loads(show("psionic/book/chapters.json"))["chapters"]
    used, out = set(), []
    for c in chapters:
        if c["number"] not in CHAPTERS:
            continue
        for s in c["source"]:
            if s.startswith("psionic/lib/") and s.endswith(".coax") and s not in used:
                used.add(s)
                out.append((c["number"], s))
    return out


def paragraphs(text):
    out, block = [], []
    for line in text.split("\n"):
        line = "".join(c for c in line if 32 <= ord(c) < 127).rstrip()
        if line.strip():
            block.append(line)
        elif block:
            out.append(block)
            block = []
    if block:
        out.append(block)
    return out


def documents():
    seen = set()
    for _, d in pretrain_corpus.documents():
        seen.update(d.split("\n\n"))
    docs = []
    for n, path in sources():
        doc = ""
        for lines in paragraphs(show(path)):
            room = DOC_BYTES - len(doc) - 2
            keep = []
            for line in lines:
                if len("\n".join(keep + [line])) > room:
                    break
                keep.append(line)
            p = "\n".join(keep)
            if p and p not in seen:
                seen.add(p)
                doc += p + "\n\n"
            if len(keep) < len(lines):
                break
        if doc:
            docs.append((n, path, doc))
    return docs


def main():
    docs = documents()
    print(f"// Generated by psionic/tools/continue_corpus.py from the psionic/lib sources of psionic/book chapters")
    print(f"// {CHAPTERS.start} to {CHAPTERS.stop - 1} at revision {REVISION}; do not edit. {len(docs)} documents, {sum(len(d) for _, _, d in docs)} bytes.")
    print("// Files: " + ", ".join(f"{n} {p[len('psionic/lib/'):]}" for n, p, _ in docs) + ".")
    print(f"CT_DOMAIN_SOURCES :: [{len(docs)}]int.[{','.join(str(n) for n, _, _ in docs)}];")
    print(f"CT_DOMAIN :: [{len(docs)}]string.[")
    print(",\n".join("    " + pretrain_corpus.quote(d) for _, _, d in docs))
    print("];")


if __name__ == "__main__":
    main()
