#!/usr/bin/env python3
"""Chapter 128's corpus: the prose of Psionic book chapters, pinned by revision.

Tooling only; never shipped. It reads chapters CHAPTERS of psionic/book at
REVISION through `git show` (so later edits to the book do not change the
corpus), keeps their prose, and prints psionic/fixtures/pretrain/corpus.coax.
Kept: headings and paragraphs. Dropped: fenced code, HTML comments, tables,
status lines, and any character outside printable ASCII. Paragraphs are
deduplicated across the whole corpus (the first copy stays). Each chapter is
cut at paragraph boundaries into documents of at most DOC_BYTES bytes; a
document's source is its chapter number, and a whole source takes one split.
"""
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
REVISION = "cf2bddd202"
CHAPTERS = range(1, 41)
DOC_BYTES = 3600


def chapter_text(n):
    names = subprocess.run(["git", "ls-tree", "--name-only", REVISION, "psionic/book/"], cwd=ROOT, capture_output=True, text=True, check=True).stdout.split()
    name = next(x for x in names if re.match(rf"psionic/book/ch{n:03d}-", x))
    return subprocess.run(["git", "show", f"{REVISION}:{name}"], cwd=ROOT, capture_output=True, text=True, check=True).stdout


def paragraphs(text):
    text = re.sub(r"<!--.*?-->", "", text, flags=re.DOTALL)
    out, block, fence = [], [], False
    for line in text.split("\n"):
        if line.startswith("```"):
            fence = not fence
            continue
        if fence or line.startswith("|") or line.startswith("> **Status"):
            continue
        line = "".join(c for c in line if 32 <= ord(c) < 127).rstrip()
        if line.strip():
            block.append(line)
        elif block:
            out.append("\n".join(block))
            block = []
    if block:
        out.append("\n".join(block))
    return out


def documents():
    seen, docs = set(), []
    for n in CHAPTERS:
        doc = ""
        for p in paragraphs(chapter_text(n)):
            if p in seen or len(p) > DOC_BYTES - 2:
                continue
            seen.add(p)
            if doc and len(doc) + len(p) + 2 > DOC_BYTES:
                docs.append((n, doc))
                doc = ""
            doc += p + "\n\n"
        if doc:
            docs.append((n, doc))
    return docs


def quote(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def main():
    docs = documents()
    print(f"// Generated by psionic/tools/pretrain_corpus.py from psionic/book chapters {CHAPTERS.start} to {CHAPTERS.stop - 1}")
    print(f"// at revision {REVISION}; do not edit. {len(docs)} documents, {sum(len(d) for _, d in docs)} bytes.")
    print(f"NP_CORPUS_SOURCES :: [{len(docs)}]int.[{','.join(str(n) for n, _ in docs)}];")
    print(f"NP_CORPUS :: [{len(docs)}]string.[")
    print(",\n".join("    " + quote(d) for _, d in docs))
    print("];")


if __name__ == "__main__":
    main()
