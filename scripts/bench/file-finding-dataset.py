#!/usr/bin/env python3
"""Build the end-to-end file-finding dataset (issue #11210).

A case is one closed issue whose fix landed on main as exactly one commit
whose subject carries `(#N)` and no other issue number. The ground truth is
the set of files that commit changed, split into:

  hand    hand-written files (the recall target)
  derived lockfiles and generated outputs (reported separately)

and each hand-written file is tagged `existing` (present at the fix's parent,
so a finder can see it) or `added` (created by the fix, so only a plan can
name it).

Input: `gh issue list --state closed --json number,title,body,closedAt,createdAt`
saved to --issues (one call, so this script makes no GitHub requests).
Output: JSON with no file contents, only paths and issue text. Keep it in a
scratch directory anyway: issue bodies are copied verbatim.

    gh issue list -R OpenAgentsInc/openagents --state closed --limit 4000 \
        --json number,title,body,closedAt,createdAt > $S/closed_issues.json
    python3 -I scripts/bench/file-finding-dataset.py --repo . \
        --issues $S/closed_issues.json --out $S/ff-dataset.json --n 100
"""
import argparse, json, re, subprocess
from collections import defaultdict

REF = re.compile(r"#(\d{3,6})\b")
LOCK_NAMES = {"Cargo.lock", "package-lock.json", "pnpm-lock.yaml", "yarn.lock", "bun.lock",
              "bun.lockb", "Package.resolved", "go.sum", "flake.lock", "Gemfile.lock",
              "poetry.lock", "uv.lock"}
GEN_MARKERS = ("@generated", "do not edit", "generated by", "autogenerated", "auto-generated",
               "this file is generated")


def git(repo, *args, check=True):
    return subprocess.run(["git", "-C", repo, *args], check=check, capture_output=True).stdout


def derived_kind(repo, rev, path):
    """'lock', 'generated' or None. Bounded path/header rules only."""
    name = path.rsplit("/", 1)[-1]
    if name in LOCK_NAMES or name.endswith(".lock"):
        return "lock"
    if name in ("tree.json",) or re.search(r"(^|/)openapi[^/]*\.(json|ya?ml)$", path) \
            or name.endswith((".snap", ".min.js", ".pb.go", "_pb2.py")):
        return "generated"
    try:
        head = git(repo, "show", f"{rev}:{path}")[:600].decode("utf-8", "replace").lower()
    except subprocess.CalledProcessError:
        return None
    if any(m in head for m in GEN_MARKERS):
        return "generated"
    return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", default=".")
    ap.add_argument("--issues", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--n", type=int, default=100)
    ap.add_argument("--max-hand", type=int, default=25, help="skip sweeping fixes with more hand-written files")
    ap.add_argument("--rev", default="origin/main")
    ap.add_argument("--multi", action="store_true",
                    help="also take issues fixed by several commits (union of their files), for training")
    ap.add_argument("--max-commits", type=int, default=6)
    ap.add_argument("--max-cases", type=int, default=100000)
    ap.add_argument("--only", help="comma-separated issue numbers (any state; --issues must hold them)")
    a = ap.parse_args()
    issues = {i["number"]: i for i in json.load(open(a.issues))}
    only = {int(x) for x in a.only.split(",")} if a.only else None
    if only:  # open issues with fixes already on main (out-of-sample check)
        issues = {n: v for n, v in issues.items() if n in only}
    log = git(a.repo, "log", a.rev, "--no-merges", "--format=%H%x09%s").decode().splitlines()
    by_issue = defaultdict(list)
    for line in log:
        sha, subj = line.split("\t", 1)
        for n in set(int(x) for x in REF.findall(subj)):
            by_issue[n].append(sha)
    cases, skipped = [], defaultdict(int)
    order = {line.split("\t", 1)[0]: i for i, line in enumerate(log)}  # 0 = newest

    def files_of(shas, parent):
        hand, derived = {}, {}
        for sha in shas:
            status = git(a.repo, "show", "--format=", "--name-status", "--no-renames", sha).decode().splitlines()
            for st in status:
                parts = st.split("\t")
                code, path = parts[0], parts[-1]
                if path in hand or path in derived:
                    continue
                existed = subprocess.run(["git", "-C", a.repo, "cat-file", "-e", f"{parent}:{path}"],
                                         capture_output=True).returncode == 0
                kind = derived_kind(a.repo, parent if existed else sha, path)
                if kind:
                    derived[path] = {"path": path, "kind": kind, "status": code}
                else:
                    hand[path] = {"path": path, "status": code, "existing": existed}
        return list(hand.values()), list(derived.values())

    seen = set()
    for line in log:  # newest first
        sha, subj = line.split("\t", 1)
        refs = sorted(set(int(x) for x in REF.findall(subj)))
        for n in refs:
            if n in seen or n not in issues:
                continue
            shas = by_issue[n]
            single_case = len(refs) == 1 and len(shas) == 1
            if not single_case and not a.multi:
                continue
            if len(shas) > a.max_commits:
                skipped["too many commits"] += 1
                seen.add(n)
                continue
            seen.add(n)
            first = max(shas, key=lambda x: order[x])  # oldest
            parent = git(a.repo, "rev-parse", f"{first}^").decode().strip()
            hand, derived = files_of(sorted(shas, key=lambda x: -order[x]), parent)
            if not hand:
                skipped["only derived files"] += 1
                continue
            if len(hand) > a.max_hand:
                skipped[f"more than {a.max_hand} hand-written files"] += 1
                continue
            iss = issues[n]
            cases.append({"issue": n, "commit": first, "parent": parent, "commits": shas,
                          "last_commit": min(shas, key=lambda x: order[x]),
                          "kind": "single" if single_case else "multi",
                          "subject": subj, "title": iss["title"], "body": iss["body"] or "",
                          "created": iss["createdAt"], "closed": iss["closedAt"],
                          "hand": hand, "derived": derived})
        if len([c for c in cases if c["kind"] == "single"]) >= a.n and not a.multi:
            break
        if len(cases) >= a.max_cases:
            break
    json.dump({"rev": a.rev, "max_hand": a.max_hand, "skipped": skipped, "cases": cases},
              open(a.out, "w"), indent=1)
    nh = sum(len(c["hand"]) for c in cases)
    ne = sum(sum(h["existing"] for h in c["hand"]) for c in cases)
    nd = sum(len(c["derived"]) for c in cases)
    print(f"{len(cases)} cases, {nh} hand-written files ({ne} existing at parent, {nh-ne} added), "
          f"{nd} derived; skipped {dict(skipped)}")
    print("issues", cases[-1]["issue"], "..", cases[0]["issue"])


main()
