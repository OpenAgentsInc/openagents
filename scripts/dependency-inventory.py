#!/usr/bin/env python3
"""Write docs/dependency-inventory.md from the lockfile's resolved graph.

Usage:
  scripts/dependency-inventory.py          # regenerate the inventory
  scripts/dependency-inventory.py --check  # exit 1 if the inventory is stale
"""
import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "dependency-inventory.md"


def inventory() -> str:
    meta = json.loads(
        subprocess.check_output(
            ["cargo", "metadata", "--format-version", "1", "--locked"], cwd=ROOT
        )
    )
    members = set(meta["workspace_members"])
    rows = sorted(
        (p["name"], p["version"], p.get("license") or "(none declared)", source(p))
        for p in meta["packages"]
        if p["id"] not in members
    )
    lines = [
        "# Dependency inventory",
        "",
        "Generated by `scripts/dependency-inventory.py` from `Cargo.lock`; do not",
        "edit by hand. `scripts/dependency-inventory.py --check` fails when this",
        "file is stale. License policy and review notes live in",
        "[dependencies.md](dependencies.md).",
        "",
        f"{len(rows)} external packages.",
        "",
        "| Package | Version | License | Source |",
        "| --- | --- | --- | --- |",
    ]
    lines += [f"| {n} | {v} | {l} | {s} |" for n, v, l, s in rows]
    return "\n".join(lines) + "\n"


def source(p: dict) -> str:
    s = p.get("source") or ""
    if s.startswith("registry+https://github.com/rust-lang/crates.io-index"):
        return "crates.io"
    if s.startswith("git+"):
        return s[4:].split("#")[0]
    return s or "path"


def main() -> int:
    text = inventory()
    if "--check" in sys.argv[1:]:
        if OUT.exists() and OUT.read_text() == text:
            print(f"inventory: {OUT.relative_to(ROOT)} is current")
            return 0
        print(
            f"inventory: {OUT.relative_to(ROOT)} is stale; run scripts/dependency-inventory.py",
            file=sys.stderr,
        )
        return 1
    OUT.write_text(text)
    print(f"inventory: wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
