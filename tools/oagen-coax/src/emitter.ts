export function buildCoaxFiles(spec: ApiSpec, meta: CoaxEmitMeta): GeneratedFile[] {
  const files: GeneratedFile[] = [];
  const header = `// Generated by tools/oagen-coax (@workos/oagen) from @workos/openapi-spec ${meta.specVersion}.\n// Do not edit by hand; regenerate via \`cd tools/oagen-coax && bun run generate\`.`;

  files.push({ path: 'runtime.coax', content: RUNTIME_COAX });

  // 1. Enums (open enum constants + string/parse helpers with unknown=0 fallback)
  const enumNameMap = new Map<string, string>();
  const usedEnumIds = new Set<string>();
  const enumLines: string[] = [header, '#load "runtime.coax";', ''];
  for (const en of spec.enums) {
    const eSnake = uniqueName(usedEnumIds, toSnake(en.name));
    const eUpper = toUpperSnake(eSnake);
    enumNameMap.set(en.name, eSnake);
    enumLines.push(`// OpenAPI enum: ${en.name}`);
    enumLines.push(`WOS_E_${eUpper}_UNKNOWN :: 0;`);
    const usedVals = new Set<string>(['UNKNOWN']);
    const valEntries: { constName: string; wire: string; idx: number }[] = [];
    let idx = 1;
    for (const ev of en.values) {
      const wire = String(ev.value);
      const member = uniqueName(usedVals, toUpperSnake(wire));
      const constName = `WOS_E_${eUpper}_${member}`;
      enumLines.push(`${constName} :: ${idx};`);
      valEntries.push({ constName, wire, idx });
      idx++;
    }
    enumLines.push(`wos_e_${eSnake}_parse :: (s: string) -> u32 #effects(all) {`);
    for (const ve of valEntries) {
      enumLines.push(`  if s == ${coaxStr(ve.wire)} { return ${ve.constName}; }`);
    }
    enumLines.push(`  return WOS_E_${eUpper}_UNKNOWN;`);
    enumLines.push(`}`);
    enumLines.push(`wos_e_${eSnake}_str :: (v: u32) -> string #effects(all) {`);
    for (const ve of valEntries) {
      enumLines.push(`  if v == ${ve.constName} { return ${coaxStr(ve.wire)}; }`);
    }
    enumLines.push(`  return "";`);
    enumLines.push(`}`);
    enumLines.push('');
  }
  files.push({ path: 'enums.coax', content: enumLines.join('\n') });

  // 2. Models (borrowed Jv view structs + presence-aware typed getters + iterators)
  const modelByName = new Map<string, Model>();
  const modelIdMap = new Map<string, { pascal: string; snake: string }>();
  const usedModelSnakes = new Set<string>();
  for (const m of spec.models) {
    modelByName.set(m.name, m);
    const snake = uniqueName(usedModelSnakes, toSnake(m.name));
    const pascal = toPascal(snake);
    modelIdMap.set(m.name, { pascal, snake });
  }

  const MODEL_SHARDS = 8;
  const shardSize = Math.ceil(spec.models.length / MODEL_SHARDS);
  const modelBarrel: string[] = [header, '#load "enums.coax";'];

  for (let shard = 0; shard < MODEL_SHARDS; shard++) {
    const slice = spec.models.slice(shard * shardSize, (shard + 1) * shardSize);
    if (slice.length === 0) continue;
    const shardName = `models_${shard}.coax`;
    modelBarrel.push(`#load "${shardName}";`);
    const lines: string[] = [header, '#load "enums.coax";', ''];
    for (const m of slice) {
      const id = modelIdMap.get(m.name)!;
      lines.push(`// OpenAPI model: ${m.name}`);
      lines.push(`WosM_${id.pascal} :: struct { doc: Jv; node: int; error: u32; }`);
      lines.push(`wos_m_${id.snake}_view :: (doc: Jv, node: int) -> WosM_${id.pascal} #effects(all) {`);
      lines.push(`  if jv_kind(doc, node) != JV_OBJECT { return WosM_${id.pascal}.{doc = doc, node = -1, error = WOS_GEN_BAD_TYPE}; }`);
      lines.push(`  return WosM_${id.pascal}.{doc = doc, node = node, error = WOS_GEN_OK};`);
      lines.push(`}`);

      const usedFields = new Set<string>();
      for (const f of m.fields) {
        const fSnake = uniqueName(usedFields, toSnake(f.name));
        const wireKey = coaxStr(f.name);
        const inner = unwrapNullable(f.type);
        if (inner.kind === 'primitive') {
          if (inner.type === 'boolean') {
            lines.push(`wos_m_${id.snake}_get_${fSnake} :: (v: WosM_${id.pascal}) -> WosBoolResult #effects(all) {`);
            lines.push(`  if v.error != WOS_GEN_OK { return WosBoolResult.{error = v.error}; }`);
            lines.push(`  return wos_jv_get_bool(v.doc, v.node, ${wireKey});`);
            lines.push(`}`);
          } else if (inner.type === 'integer') {
            lines.push(`wos_m_${id.snake}_get_${fSnake} :: (v: WosM_${id.pascal}) -> WosIntResult #effects(all) {`);
            lines.push(`  if v.error != WOS_GEN_OK { return WosIntResult.{error = v.error}; }`);
            lines.push(`  return wos_jv_get_int(v.doc, v.node, ${wireKey});`);
            lines.push(`}`);
          } else if (inner.type === 'number') {
            lines.push(`wos_m_${id.snake}_get_${fSnake} :: (v: WosM_${id.pascal}) -> WosNodeResult #effects(all) {`);
            lines.push(`  if v.error != WOS_GEN_OK { return WosNodeResult.{node = -1, error = v.error}; }`);
            lines.push(`  return wos_jv_get_node(v.doc, v.node, ${wireKey});`);
            lines.push(`}`);
          } else {
            lines.push(`wos_m_${id.snake}_get_${fSnake} :: (v: WosM_${id.pascal}, out: [] u8) -> WosStrResult #effects(all) {`);
            lines.push(`  if v.error != WOS_GEN_OK { return WosStrResult.{error = v.error}; }`);
            lines.push(`  return wos_jv_get_str(v.doc, v.node, ${wireKey}, out);`);
            lines.push(`}`);
          }
        } else if (inner.kind === 'enum') {
          lines.push(`wos_m_${id.snake}_get_${fSnake} :: (v: WosM_${id.pascal}, out: [] u8) -> WosStrResult #effects(all) {`);
          lines.push(`  if v.error != WOS_GEN_OK { return WosStrResult.{error = v.error}; }`);
          lines.push(`  return wos_jv_get_str(v.doc, v.node, ${wireKey}, out);`);
          lines.push(`}`);
          const eSnake = enumNameMap.get(inner.name);
          if (eSnake) {
            lines.push(`wos_m_${id.snake}_get_${fSnake}_enum :: (v: WosM_${id.pascal}) -> u32 #effects(all) {`);
            lines.push(`  if v.error != WOS_GEN_OK { return 0; }`);
            lines.push(`  tmp: [128] u8;`);
            lines.push(`  r := wos_jv_get_str(v.doc, v.node, ${wireKey}, tmp[..]);`);
            lines.push(`  if !r.present || r.error != WOS_GEN_OK { return 0; }`);
            lines.push(`  return wos_e_${eSnake}_parse(cast(string) tmp[0..<r.count]);`);
            lines.push(`}`);
          }
        } else if (inner.kind === 'literal') {
          lines.push(`wos_m_${id.snake}_get_${fSnake} :: (v: WosM_${id.pascal}, out: [] u8) -> WosStrResult #effects(all) {`);
          lines.push(`  if v.error != WOS_GEN_OK { return WosStrResult.{error = v.error}; }`);
          lines.push(`  return wos_jv_get_str(v.doc, v.node, ${wireKey}, out);`);
          lines.push(`}`);
        } else if (inner.kind === 'array') {
          lines.push(`wos_m_${id.snake}_iter_${fSnake} :: (v: WosM_${id.pascal}) -> WosArrayIter #effects(all) {`);
          lines.push(`  if v.error != WOS_GEN_OK { return WosArrayIter.{doc = v.doc, cur = -1, error = v.error}; }`);
          lines.push(`  return wos_jv_iter_field(v.doc, v.node, ${wireKey});`);
          lines.push(`}`);
        } else {
          // model / union / map -> borrowed node view (caller passes to target *_view or reads raw)
          lines.push(`wos_m_${id.snake}_get_${fSnake} :: (v: WosM_${id.pascal}) -> WosNodeResult #effects(all) {`);
          lines.push(`  if v.error != WOS_GEN_OK { return WosNodeResult.{node = -1, error = v.error}; }`);
          lines.push(`  return wos_jv_get_node(v.doc, v.node, ${wireKey});`);
          lines.push(`}`);
        }
      }
      lines.push('');
    }
    files.push({ path: shardName, content: lines.join('\n') });
  }
  files.push({ path: 'models.coax', content: modelBarrel.join('\n') + '\n' });

  // 3. Operations & Wrappers grouped by canonical mountOn service (24 services, 269 ops + 12 wrappers)
  const resolved = resolveOperations(spec, policy.operationHints, policy.mountRules);
  const bySvc = new Map<string, ResolvedOperation[]>();
  for (const r of resolved) {
    const list = bySvc.get(r.mountOn) ?? [];
    list.push(r);
    bySvc.set(r.mountOn, list);
  }

  const svcNamesSorted = [...bySvc.keys()].sort();
  const svcFileList: string[] = [];
  let totalOps = 0;
  let totalWrappers = 0;
  const globalProcs = new Set<string>();

  function emitPathSegments(opPath: string, pathParamMap: Map<string, string>, lines: string[]) {
    const parts = opPath.split(/(\{[^}]+\})/).filter((x) => x.length > 0);
    for (const part of parts) {
      if (part.startsWith('{') && part.endsWith('}')) {
        const rawKey = part.slice(1, -1);
        const field = pathParamMap.get(rawKey) ?? toSnake(rawKey);
        lines.push(`  wos_rb_path_seg(b[..], p.${field});`);
      } else {
        lines.push(`  wos_rb_put(b[..], ${coaxStr(part)});`);
      }
    }
  }

  function collectFlatBodyFields(bodyType: TypeRef | undefined): Field[] {
    if (!bodyType) return [];
    const inner = unwrapNullable(bodyType);
    if (inner.kind === 'model') {
      const m = modelByName.get(inner.name);
      return m ? m.fields : [];
    }
    return [];
  }

  interface StructFieldEmit {
    coaxField: string;
    wireName: string;
    kind: 'str' | 'int' | 'bool' | 'csv_arr' | 'raw_json';
    source: 'path' | 'query' | 'body';
  }

  function paramKind(t: TypeRef): 'str' | 'int' | 'bool' | 'csv_arr' | 'raw_json' {
    const inner = unwrapNullable(t);
    if (inner.kind === 'primitive') {
      if (inner.type === 'integer') return 'int';
      if (inner.type === 'boolean') return 'bool';
      return 'str';
    }
    if (inner.kind === 'enum' || inner.kind === 'literal') return 'str';
    if (inner.kind === 'array') {
      const item = unwrapNullable(inner.items);
      if (item.kind === 'primitive' && item.type === 'string') return 'csv_arr';
      if (item.kind === 'enum') return 'csv_arr';
      return 'raw_json';
    }
    return 'raw_json';
  }

  function isPublicOperation(op: Operation): boolean {
    if (op.security && op.security.length === 0) return true;
    return false;
  }

  for (const svcName of svcNamesSorted) {
    const ops = bySvc.get(svcName)!;
    const svcSnake = toSnake(svcName);
    const svcPascal = toPascal(svcSnake);
    const svcFile = `svc_${svcSnake}.coax`;
    svcFileList.push(svcFile);

    const lines: string[] = [
      header,
      `// WorkOS Service: ${svcName} (${ops.length} operations)`,
      '#load "runtime.coax";',
      '',
    ];

    for (const ro of ops) {
      totalOps++;
      const op = ro.operation;
      const fnName = uniqueName(globalProcs, `wos_${svcSnake}_${toSnake(ro.methodName)}`);
      const paramStruct = `WosP_${toPascal(fnName.slice(4))}`;
      const publicAuth = isPublicOperation(op);

      const fields: StructFieldEmit[] = [];
      const usedF = new Set<string>(['raw_body_json', 'unused']);
      const pathParamMap = new Map<string, string>();

      for (const pp of op.pathParams) {
        const cf = uniqueName(usedF, toSnake(pp.name));
        pathParamMap.set(pp.name, cf);
        fields.push({ coaxField: cf, wireName: pp.name, kind: 'str', source: 'path' });
      }
      for (const qp of op.queryParams) {
        const cf = uniqueName(usedF, toSnake(qp.name));
        fields.push({ coaxField: cf, wireName: qp.name, kind: paramKind(qp.type), source: 'query' });
      }

      const bodyFields = collectFlatBodyFields(op.requestBody);
      const hasBody = Boolean(op.requestBody);
      const isPublicNoSecretBody =
        publicAuth ||
        op.path === '/user_management/authorize/device';

      for (const bf of bodyFields) {
        const wire = bf.name;
        // Never accept client_secret on strictly public-client endpoints.
        if (isPublicNoSecretBody && wire === 'client_secret') continue;
        const cf = uniqueName(usedF, toSnake(wire));
        fields.push({ coaxField: cf, wireName: wire, kind: paramKind(bf.type), source: 'body' });
      }

      lines.push(`// ${op.httpMethod.toUpperCase()} ${op.path} (${op.operationId})`);
      lines.push(`${paramStruct} :: struct {`);
      for (const f of fields) {
        if (f.kind === 'int') {
          lines.push(`  ${f.coaxField}: int; has_${f.coaxField}: bool;`);
        } else if (f.kind === 'bool') {
          lines.push(`  ${f.coaxField}: bool; has_${f.coaxField}: bool;`);
        } else {
          lines.push(`  ${f.coaxField}: string;`);
        }
      }
      if (hasBody) {
        lines.push(`  raw_body_json: string;`);
      } else if (fields.length === 0) {
        lines.push(`  unused: u8;`);
      }
      lines.push(`}`);

      lines.push(`${fnName} :: (base_url: string, p: ${paramStruct}, scratch: [] u8) -> WosReq #effects(all) {`);
      lines.push(`  b: [1] WosReqBuild;`);
      lines.push(`  wos_rb_init(b[..], base_url, scratch);`);
      emitPathSegments(op.path, pathParamMap, lines);
      for (const f of fields) {
        if (f.source !== 'query') continue;
        if (f.kind === 'int') {
          lines.push(`  wos_rb_query_int(b[..], ${coaxStr(f.wireName)}, p.${f.coaxField}, p.has_${f.coaxField});`);
        } else if (f.kind === 'bool') {
          lines.push(`  wos_rb_query_bool(b[..], ${coaxStr(f.wireName)}, p.${f.coaxField}, p.has_${f.coaxField});`);
        } else if (f.kind === 'csv_arr') {
          lines.push(`  wos_rb_query_csv(b[..], ${coaxStr(f.wireName)}, p.${f.coaxField});`);
        } else {
          lines.push(`  wos_rb_query_str(b[..], ${coaxStr(f.wireName)}, p.${f.coaxField});`);
        }
      }

      if (!hasBody) {
        lines.push(`  return wos_req_finish(b[0], ${httpMethodConst(op.httpMethod)}, ${publicAuth}, 0, 0, false);`);
      } else {
        lines.push(`  if b[0].bad { return wos_req_finish(b[0], ${httpMethodConst(op.httpMethod)}, ${publicAuth}, 0, 0, false); }`);
        lines.push(`  body_from := b[0].n;`);
        lines.push(`  if p.raw_body_json.count > 0 {`);
        lines.push(`    wos_rb_put(b[..], p.raw_body_json);`);
        lines.push(`    return wos_req_finish(b[0], ${httpMethodConst(op.httpMethod)}, ${publicAuth}, body_from, b[0].n, true);`);
        lines.push(`  }`);
        lines.push(`  j: [1] Jo;`);
        lines.push(`  jo_start(j[..], scratch[body_from..<scratch.count]);`);
        lines.push(`  jo_obj(j[..]);`);
        for (const f of fields) {
          if (f.source !== 'body') continue;
          if (f.kind === 'int') {
            lines.push(`  if p.has_${f.coaxField} { jo_key(j[..], ${coaxStr(f.wireName)}); jo_int(j[..], p.${f.coaxField}); }`);
          } else if (f.kind === 'bool') {
            lines.push(`  if p.has_${f.coaxField} { jo_key(j[..], ${coaxStr(f.wireName)}); jo_bool(j[..], p.${f.coaxField}); }`);
          } else if (f.kind === 'csv_arr') {
            lines.push(`  wos_jo_csv_array(j[..], ${coaxStr(f.wireName)}, p.${f.coaxField});`);
          } else if (f.kind === 'raw_json') {
            lines.push(`  if p.${f.coaxField}.count > 0 { jo_key(j[..], ${coaxStr(f.wireName)}); jo_raw(j[..], p.${f.coaxField}); }`);
          } else {
            lines.push(`  if p.${f.coaxField}.count > 0 { jo_key(j[..], ${coaxStr(f.wireName)}); jo_str(j[..], p.${f.coaxField}); }`);
          }
        }
        lines.push(`  jo_end(j[..]);`);
        lines.push(`  if j[0].bad { b[0].bad = true; b[0].error = WOS_GEN_CAPACITY; }`);
        lines.push(`  return wos_req_finish(b[0], ${httpMethodConst(op.httpMethod)}, ${publicAuth}, body_from, body_from + j[0].n, true);`);
      }
      lines.push(`}`);
      lines.push('');

      // Emit typed wrappers (e.g. authenticate_with_code, authenticate_with_magic_auth, authenticate_with_device_code, ...)
      for (const w of ro.wrappers ?? []) {
        totalWrappers++;
        emitWrapper(w, ro, svcSnake, lines);
      }
    }

    files.push({ path: svcFile, content: lines.join('\n') });
  }

  function emitWrapper(w: ResolvedWrapper, ro: ResolvedOperation, svcSnake: string, lines: string[]) {
    const op = ro.operation;
    const wFn = uniqueName(globalProcs, `wos_${svcSnake}_${toSnake(w.name)}`);
    const wStruct = `WosP_${toPascal(wFn.slice(4))}`;
    const variantModel = modelByName.get(w.targetVariant);
    const variantFieldMap = new Map<string, Field>();
    if (variantModel) {
      for (const f of variantModel.fields) {
        variantFieldMap.set(f.name, f);
      }
    }

    const infer = w.inferFromClient ?? [];
    const allowsClientSecret = infer.includes('client_secret');
    const allowsClientId = infer.includes('client_id');
    const isAuthEndpoint = op.path === '/user_management/authenticate';

    const wFields: { coaxField: string; wireName: string; kind: 'str' | 'int' | 'bool' | 'csv_arr' | 'raw_json' }[] = [];
    const usedW = new Set<string>(['unused']);
    for (const pName of w.exposedParams) {
      if (!allowsClientSecret && pName === 'client_secret') continue;
      const f = variantFieldMap.get(pName);
      const cf = uniqueName(usedW, toSnake(pName));
      wFields.push({
        coaxField: cf,
        wireName: f?.name ?? pName,
        kind: f ? paramKind(f.type) : 'str',
      });
    }

    lines.push(`// Wrapper for ${op.httpMethod.toUpperCase()} ${op.path} (${w.targetVariant})`);
    lines.push(`${wStruct} :: struct {`);
    for (const f of wFields) {
      if (f.kind === 'int') {
        lines.push(`  ${f.coaxField}: int; has_${f.coaxField}: bool;`);
      } else if (f.kind === 'bool') {
        lines.push(`  ${f.coaxField}: bool; has_${f.coaxField}: bool;`);
      } else {
        lines.push(`  ${f.coaxField}: string;`);
      }
    }
    if (wFields.length === 0) lines.push(`  unused: u8;`);
    lines.push(`}`);

    lines.push(`${wFn} :: (base_url: string, client_id: string, api_key: string, p: ${wStruct}, scratch: [] u8) -> WosReq #effects(all) {`);
    lines.push(`  b: [1] WosReqBuild;`);
    lines.push(`  wos_rb_init(b[..], base_url, scratch);`);
    lines.push(`  wos_rb_put(b[..], ${coaxStr(op.path)});`);
    const pubExpr = isAuthEndpoint ? 'api_key.count == 0' : 'false';
    lines.push(`  if b[0].bad { return wos_req_finish(b[0], ${httpMethodConst(op.httpMethod)}, ${pubExpr}, 0, 0, false); }`);
    lines.push(`  body_from := b[0].n;`);
    lines.push(`  j: [1] Jo;`);
    lines.push(`  jo_start(j[..], scratch[body_from..<scratch.count]);`);
    lines.push(`  jo_obj(j[..]);`);
    for (const [dk, dv] of Object.entries(w.defaults ?? {})) {
      lines.push(`  jo_key(j[..], ${coaxStr(dk)}); jo_str(j[..], ${coaxStr(String(dv))});`);
    }
    if (allowsClientId) {
      lines.push(`  if client_id.count > 0 { jo_key(j[..], "client_id"); jo_str(j[..], client_id); }`);
    }
    // Strictly omit client_secret when api_key is empty (public PKCE/mobile/desktop client)
    // and never emit client_secret at all when inferFromClient omits it (e.g. device_code).
    if (allowsClientSecret) {
      lines.push(`  if api_key.count > 0 { jo_key(j[..], "client_secret"); jo_str(j[..], api_key); }`);
    }
    for (const f of wFields) {
      if (f.kind === 'int') {
        lines.push(`  if p.has_${f.coaxField} { jo_key(j[..], ${coaxStr(f.wireName)}); jo_int(j[..], p.${f.coaxField}); }`);
      } else if (f.kind === 'bool') {
        lines.push(`  if p.has_${f.coaxField} { jo_key(j[..], ${coaxStr(f.wireName)}); jo_bool(j[..], p.${f.coaxField}); }`);
      } else if (f.kind === 'csv_arr') {
        lines.push(`  wos_jo_csv_array(j[..], ${coaxStr(f.wireName)}, p.${f.coaxField});`);
      } else if (f.kind === 'raw_json') {
        lines.push(`  if p.${f.coaxField}.count > 0 { jo_key(j[..], ${coaxStr(f.wireName)}); jo_raw(j[..], p.${f.coaxField}); }`);
      } else {
        lines.push(`  if p.${f.coaxField}.count > 0 { jo_key(j[..], ${coaxStr(f.wireName)}); jo_str(j[..], p.${f.coaxField}); }`);
      }
    }
    lines.push(`  jo_end(j[..]);`);
    lines.push(`  if j[0].bad { b[0].bad = true; b[0].error = WOS_GEN_CAPACITY; }`);
    lines.push(`  return wos_req_finish(b[0], ${httpMethodConst(op.httpMethod)}, ${pubExpr}, body_from, body_from + j[0].n, true);`);
    lines.push(`}`);
    lines.push('');
  }

  // 4. Manifest + executable codec & invariant tests
  const manifestLines: string[] = [
    header,
    '#load "models.coax";',
    ...svcFileList.map((f) => `#load "${f}";`),
    '',
    `WOS_GEN_SPEC_VERSION :: ${coaxStr(meta.specVersion)};`,
    `WOS_GEN_SPEC_SHA256 :: ${coaxStr(meta.specSha256)};`,
    `WOS_GEN_UPSTREAM_SHA :: ${coaxStr(meta.upstreamSha)};`,
    `WOS_GEN_SVC_COUNT :: ${svcNamesSorted.length};`,
    `WOS_GEN_OP_COUNT :: ${totalOps};`,
    `WOS_GEN_WRAPPER_COUNT :: ${totalWrappers};`,
    `WOS_GEN_MODEL_COUNT :: ${spec.models.length};`,
    `WOS_GEN_ENUM_COUNT :: ${spec.enums.length};`,
    '',
    `#test "generated WorkOS SDK covers all 269 endpoints, omits client_secret on public flows, and rejects path traversal" {`,
    `  #assert WOS_GEN_OP_COUNT == 269 && WOS_GEN_SVC_COUNT == 24 && WOS_GEN_WRAPPER_COUNT == 12;`,
    `  scratch: [4096] u8;`,
    ``,
    `  // Public PKCE code exchange omits client_secret when api_key is empty (prevents HTTP 422).`,
    `  r_pub := wos_user_management_authenticate_with_code("", "client_01", "", WosP_UserManagementAuthenticateWithCode.{code = "code_1", code_verifier = "ver_1"}, scratch[..]);`,
    `  #assert r_pub.error == WOS_GEN_OK && r_pub.public_auth && r_pub.method == WOS_METHOD_POST;`,
    `  #assert wos_req_url(r_pub, scratch[..]) == "https://api.workos.com/user_management/authenticate";`,
    `  #assert wos_req_body(r_pub, scratch[..]) == "{\\"grant_type\\":\\"authorization_code\\",\\"client_id\\":\\"client_01\\",\\"code\\":\\"code_1\\",\\"code_verifier\\":\\"ver_1\\"}";`,
    ``,
    `  // Confidential server exchange includes client_secret when api_key is supplied.`,
    `  r_srv := wos_user_management_authenticate_with_code("", "client_01", "sk_test_1", WosP_UserManagementAuthenticateWithCode.{code = "code_1"}, scratch[..]);`,
    `  #assert r_srv.error == WOS_GEN_OK && !r_srv.public_auth;`,
    `  #assert wos_req_body(r_srv, scratch[..]) == "{\\"grant_type\\":\\"authorization_code\\",\\"client_id\\":\\"client_01\\",\\"client_secret\\":\\"sk_test_1\\",\\"code\\":\\"code_1\\"}";`,
    ``,
    `  // Device-code exchange NEVER emits client_secret even if api_key is passed.`,
    `  r_dev := wos_user_management_authenticate_with_device_code("", "client_01", "sk_ignored", WosP_UserManagementAuthenticateWithDeviceCode.{device_code = "dev_1"}, scratch[..]);`,
    `  #assert r_dev.error == WOS_GEN_OK;`,
    `  #assert wos_req_body(r_dev, scratch[..]) == "{\\"grant_type\\":\\"urn:ietf:params:oauth:grant-type:device_code\\",\\"client_id\\":\\"client_01\\",\\"device_code\\":\\"dev_1\\"}";`,
    ``,
    `  // Path-segment traversal guard blocks dot-segments across generated path builders.`,
    `  r_bad := wos_user_management_get_user("", WosP_UserManagementGetUser.{id = ".."}, scratch[..]);`,
    `  #assert r_bad.error == WOS_GEN_BAD_PATH;`,
    `  r_ok := wos_user_management_get_user("http://127.0.0.1:4100", WosP_UserManagementGetUser.{id = "user_01"}, scratch[..]);`,
    `  #assert r_ok.error == WOS_GEN_OK && wos_req_url(r_ok, scratch[..]) == "http://127.0.0.1:4100/user_management/users/user_01";`,
    ``,
    `  // Events API multi-value query encoding.`,
    `  r_ev := wos_events_list_events("", WosP_EventsListEvents.{events = "user.created,user.updated", after = "evt_1", limit = 50, has_limit = true}, scratch[..]);`,
    `  #assert r_ev.error == WOS_GEN_OK;`,
    `  #assert wos_req_url(r_ev, scratch[..]) == "https://api.workos.com/events?after=evt_1&limit=50&events=user.created&events=user.updated";`,
    ``,
    `  // Open enum parsing returns known constants and falls back to 0 (UNKNOWN) on future wire values.`,
    `  #assert wos_e_pagination_order_parse("asc") == WOS_E_PAGINATION_ORDER_ASC && wos_e_pagination_order_str(WOS_E_PAGINATION_ORDER_DESC) == "desc";`,
    `  #assert wos_e_pagination_order_parse("future_wire_value") == WOS_E_PAGINATION_ORDER_UNKNOWN && wos_e_pagination_order_str(9999) == "";`,
    ``,
    `  // Borrowed Jv model view + list pagination metadata.`,
    `  nodes: [64] JvNode; d: [1] Jv;`,
    `  sample := "{\\"object\\":\\"list\\",\\"data\\":[{\\"id\\":\\"user_01\\",\\"email\\":\\"a@example.com\\",\\"email_verified\\":true}],\\"list_metadata\\":{\\"before\\":null,\\"after\\":\\"user_01\\"}}";`,
    `  #assert jv_parse(d[..], sample, nodes[..]);`,
    `  meta := wos_list_meta(d[0], 0);`,
    `  #assert !meta.has_before && meta.has_after && cast(string) meta.after[0..<meta.after_n] == "user_01";`,
    `  iter := [1] WosArrayIter.[wos_list_data_iter(d[0], 0)];`,
    `  el := wos_iter_next(iter[..]);`,
    `  #assert el.present && el.error == WOS_GEN_OK;`,
    `  uv := wos_m_user_view(d[0], el.node);`,
    `  #assert uv.error == WOS_GEN_OK;`,
    `  ebuf: [64] u8;`,
    `  er := wos_m_user_get_email(uv, ebuf[..]);`,
    `  #assert er.present && er.error == WOS_GEN_OK && cast(string) ebuf[0..<er.count] == "a@example.com";`,
    `  evf := wos_m_user_get_email_verified(uv);`,
    `  #assert evf.present && evf.error == WOS_GEN_OK && evf.value;`,
    `  #assert !wos_iter_next(iter[..]).present;`,
    `}`,
    '',
  ];
  files.push({ path: 'manifest.coax', content: manifestLines.join('\n') });

  // 5. Barrel file loading all generated services, models, enums, and manifest
  const allLines: string[] = [
    header,
    '#load "manifest.coax";',
    '',
  ];
  files.push({ path: 'all.coax', content: allLines.join('\n') });

  // 6. Provenance stamp
  const stamp = [
    `openapi_spec_version=${meta.specVersion}`,
    `openapi_spec_sha256=${meta.specSha256}`,
    `upstream_last_synced_sha=${meta.upstreamSha}`,
    `services=${svcNamesSorted.length}`,
    `operations=${totalOps}`,
    `wrappers=${totalWrappers}`,
    `models=${spec.models.length}`,
    `enums=${spec.enums.length}`,
    '',
  ].join('\n');
  files.push({ path: '.last-synced-sha', content: stamp });

  return files;
}

export function createCoaxEmitter(meta: CoaxEmitMeta): Emitter {
  return {
    language: 'coax',
    generateModels(): GeneratedFile[] { return []; },
    generateEnums(): GeneratedFile[] { return []; },
    generateResources(): GeneratedFile[] { return []; },
    generateClient(spec: ApiSpec, _ctx: EmitterContext): GeneratedFile[] {
      return buildCoaxFiles(spec, meta);
    },
    generateErrors(): GeneratedFile[] { return []; },
    generateTests(): GeneratedFile[] { return []; },
    fileHeader(): string {
      return '// Generated by tools/oagen-coax (@workos/oagen). Do not edit.';
    },
  };
}
