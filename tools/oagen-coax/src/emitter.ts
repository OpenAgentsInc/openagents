export function toSnake(raw: string): string {
  const s = raw
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .replace(/([A-Z]+)([A-Z][a-z])/g, '$1_$2')
    .replace(/[^A-Za-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '')
    .toLowerCase();
  const base = s.length === 0 ? 'x' : /^[0-9]/.test(s) ? `n_${s}` : s;
  return COAX_KEYWORDS.has(base) ? `${base}_` : base;
}

export function toUpperSnake(raw: string): string {
  const s = raw
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .replace(/([A-Z]+)([A-Z][a-z])/g, '$1_$2')
    .replace(/[^A-Za-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '')
    .toUpperCase();
  if (s.length === 0) return 'EMPTY';
  return /^[0-9]/.test(s) ? `N_${s}` : s;
}

export function toPascal(raw: string): string {
  const parts = raw
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .replace(/[^A-Za-z0-9]+/g, '_')
    .split('_')
    .filter(Boolean);
  const joined = parts.map((p) => p[0].toUpperCase() + p.slice(1)).join('');
  if (joined.length === 0) return 'X';
  return /^[0-9]/.test(joined) ? `N${joined}` : joined;
}

export function coaxStr(s: string): string {
  let out = '"';
  for (let i = 0; i < s.length; i++) {
    const ch = s[i];
    if (ch === '\\') out += '\\\\';
    else if (ch === '"') out += '\\"';
    else if (ch === '\n') out += '\\n';
    else if (ch === '\r') out += '\\r';
    else if (ch === '\t') out += '\\t';
    else out += ch;
  }
  return out + '"';
}

function unwrapNullable(t: TypeRef): TypeRef {
  let cur = t;
  while (cur.kind === 'nullable') cur = cur.inner;
  return cur;
}

function uniqueName(used: Set<string>, base: string): string {
  if (!used.has(base)) {
    used.add(base);
    return base;
  }
  let k = 2;
  while (used.has(`${base}_${k}`)) k++;
  const chosen = `${base}_${k}`;
  used.add(chosen);
  return chosen;
}

function httpMethodConst(m: string): string {
  switch (m.toLowerCase()) {
    case 'get': return 'WOS_METHOD_GET';
    case 'head': return 'WOS_METHOD_HEAD';
    case 'options': return 'WOS_METHOD_OPTIONS';
    case 'post': return 'WOS_METHOD_POST';
    case 'put': return 'WOS_METHOD_PUT';
    case 'patch': return 'WOS_METHOD_PATCH';
    case 'delete': return 'WOS_METHOD_DELETE';
    default: return 'WOS_METHOD_GET';
  }
}

