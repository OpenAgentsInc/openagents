# Firm reason: 1 (it drives the existing Python retargeter, verse/tools/people.py, whose clip and rig writers it reuses).
"""A clip-only rig: a pack manifest's clips retargeted onto the people's two skeletons and written as
a Coax rig (people.rig_coax), with no parts.

  python3 verse/tools/clip_rig.py verse/packs/everglade-two-hand.json verse/everglade/two-hand-rig.coax TWOHAND

The manifest names "libraries" (the first gives the library rest the clips' pelvis moves are taken
from), "clips" ({name, library, clip}) and the "skeletons" (male, female), as
verse/packs/everglade-animation-preview.json does.
"""
import json, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import people


def main():
    if len(sys.argv) != 4:
        raise SystemExit("usage: clip_rig.py MANIFEST OUT.coax PREFIX")
    manifest = json.loads(Path(sys.argv[1]).read_text())
    skeletons = {k: people.Skeleton(people.load(v)) for k, v in manifest["skeletons"].items()}
    if skeletons["male"].names != skeletons["female"].names:
        raise SystemExit("clip_rig: the male and female skeletons aren't the same joints")
    library_rest = people.Skeleton(people.load(next(iter(manifest["libraries"].values())))).t
    cl = people.clips(manifest, skeletons, library_rest)
    text = people.rig_coax(manifest, (skeletons, cl), [], sys.argv[3])
    lines = text.split("\n")
    lines[0] = f"// Generated by verse/tools/clip_rig.py (verse/tools/people.py) from verse/packs/{manifest['pack']}.json; do not edit."
    # no parts: drop the part tables
    lines = [l for l in lines if not l.startswith(f"{sys.argv[3]}_PART")]
    Path(sys.argv[2]).write_text("\n".join(lines))


main()
